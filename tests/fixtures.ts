import { test as base, type BrowserContext, type Page } from '@playwright/test';

/**
 * ВЛАСНИЙ `test` ПРОЄКТУ: аналітика в тестах глушиться сама, а не за згадкою.
 *
 * ## Дефект, через який цей модуль з'явився — заміряний, а не уявний
 *
 * Гейти E2E піднімають `npm run build && npm run preview`, тобто production-збірку.
 * У ній `dev === false`, і до ревізії 9.4 канону гард аналітики (`browser && !dev`)
 * пропускав кожен прогін тестів у бойовий ресурс GA4: справжні `page_view`,
 * справжні події, місяцями, у дев'ятьох проєктах одразу. Симптому не було ніде —
 * ні в консолі, ні у збірці, ні у звіті гейта; побачити це можна лише в самому
 * GA4, а почистити заднім числом не можна взагалі.
 *
 * Перший рівень захисту стоїть у застосунку (`isTestOrLocal()` у сервісі
 * аналітики). Це — другий, мережевий: він ловить те, чого гард не бачить —
 * сторонній скрипт, контейнер тег-менеджера, і сам гард, якщо його приберуть.
 *
 * ## Чому фікстура, а не виклик `blockAnalytics(page)` у хелпері навігації
 *
 * Перша редакція правила казала кликати глушилку в хелпері переходу й у
 * сетап-проєкті. Так НЕ ПРАЦЮЄ, і це виміряно на цьому ж парку проєктів:
 *
 *   - `page.route()` живе на конкретному об'єкті `Page`. Маршрут, поставлений у
 *     сетап-проєкті, не існує для жодного тесту з іншого файлу — там свій
 *     `page`. У двох проєктах «другий рівень» покривав ОДНУ навігацію з
 *     тридцяти однієї.
 *   - Хелпер покриває лише тих, хто його кличе. Там, де `gotoReady` кличуть 129
 *     разів, поруч лишалося 18 прямих `page.goto` у десяти файлах.
 *
 * Правило, яке треба пам'ятати на кожній точці входу, порушать мовчки. Тому
 * маршрут вішається на `BrowserContext` — разом зі спливними вікнами й тими
 * сторінками, що відкриються пізніше, — і робить це ФІКСТУРА, яку не можна не
 * покликати: вона в тому самому `test`, який імпортує специфікація.
 *
 * ## Чому тут немає жодного `test()`
 *
 * Playwright виконує імпортований модуль у контексті файлу-споживача. Якби цей
 * помічник лежав у `identity.setup.ts`, перший же імпорт звідти зареєстрував би
 * сетап-тест УДРУГЕ, вже в чужому проєкті. Модуль із фікстурами тестів не містить.
 *
 * Гейт: `src/analytics-canon.test.ts` (ANALYTICS-v9 § 5.2, `AN-E2E-BLOCK`).
 */

/**
 * Домени, куди не має піти жоден запит із тестового прогону.
 *
 * Звіряється ХОСТ, а не підрядок адреси: glob на кшталт `**\/*google-analytics.com/**`
 * пропускає `https://example.com/?r=google-analytics.com` і водночас не ловить
 * регіональні `region1.google-analytics.com`, якщо форму патерна трохи змінити.
 */
const ANALYTICS_HOSTS = ['google-analytics.com', 'googletagmanager.com', 'analytics.google.com'];

const isAnalytics = (url: URL) =>
	ANALYTICS_HOSTS.some((host) => url.hostname === host || url.hostname.endsWith(`.${host}`));

/**
 * Глушить аналітику для всього контексту (або однієї сторінки).
 *
 * Експортується окремо для сторінок, створених повз фікстуру — наприклад, із
 * `browser.newContext()` усередині тесту.
 */
export async function blockAnalytics(target: BrowserContext | Page) {
	await target.route(isAnalytics, (route) => route.abort());
}

/**
 * Перевизначено саме `context`, а не додано авто-фікстуру над `page`: так
 * глушилка лишається ЛІНИВОЮ. Тест, що бере лише `request`, браузера не
 * піднімає — авто-фікстура над `page` змусила б його це робити.
 */
export const test = base.extend({
	context: async ({ context }, use) => {
		await blockAnalytics(context);
		await use(context);
	}
});

export { devices, expect } from '@playwright/test';
export type {
	BrowserContext,
	Locator,
	Page,
	Request,
	Response,
	Route,
	TestInfo
} from '@playwright/test';

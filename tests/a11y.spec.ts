import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';
import { A11Y_BASELINE, A11Y_KNOWN } from './a11y-baseline';
import { reduceMotion, settlePage } from './support/settle';

/**
 * Машинно-виявні порушення WCAG (ACCESSIBILITY-v8 § 10, `GATE-A11Y-AXE`).
 *
 * ## Чому цей гейт з'явився лише тепер
 *
 * Аудит канону v8 (прохід 4, 2026-08-23) заміряв: три проєкти з семи не мали
 * E2E ЗОВСІМ, тобто `GATE-A11Y-AXE` у них не був «зелений» — його не існувало.
 * Часткова компенсація була: юніт-перевірка контрасту (`contrast.test.ts`) ловить
 * найдорожчий клас порушень на етапі читання змінних тем. Але контраст — це одне
 * правило з дев'яноста.
 *
 * ## МЕЖА МЕТОДУ, і її треба знати, щоб зелений не читався як «сайт доступний»
 *
 * axe ловить приблизно третину проблем доступності. Порядок фокуса,
 * осмисленість `alt`, логічність заголовків, зрозумілість `aria-label`,
 * працездатність focus trap — він не бачить нічого з цього. Зелений axe означає
 * рівно одне: немає порушень, які видно машині.
 *
 * Друга половина — людина. У цьому проєкті вона не «колись і якось»: сторінка
 * `/beta-test-checklists` містить перелік перевірок із рівнями «покрито
 * автотестом / ще ні / лише людина» (BETA-CHECKLIST-v8). Пункти доступності
 * додані туди тим самим комітом, що й цей файл, — щоб машинна й ручна половини
 * з'явилися разом, а не «машинну зробили, ручну колись».
 *
 * Третя межа (§ 10.2): `analyze()` бачить лише той стан, що є одразу після
 * `goto()`. Модалки, відкриті меню й тости в нього не потрапляють НІКОЛИ.
 */

const TAGS = ['wcag2a', 'wcag2aa', 'wcag22aa'];

/**
 * ЕМУЛЯЦІЯ ЗМЕНШЕНОГО РУХУ — ЯВНО, бо з конфігу вона НЕ ДІЄ.
 *
 * Докблок нижче називає `reducedMotion: 'reduce'` із `playwright.config.ts`
 * «не „щоб швидше“, а умовою ДОСТОВІРНОСТІ заміру» і прямо каже, що без неї
 * гейт плаваючий. Заміряно на Playwright 1.62.1: до сторінки ця настройка не
 * доходить ні з конфігу, ні з `test.use` — `matchMedia` віддає `false` в обох
 * випадках і `true` лише після явного `page.emulateMedia()`.
 *
 * Тобто умова достовірності весь цей час була оголошенням, і зелений результат
 * axe означав «на цій машині цього разу пощастило». Подробиці й числа —
 * у `support/settle.ts`.
 *
 * `beforeEach`, а не рядок у кожному тесті: настройка мусить діяти ДО `goto`,
 * бо анімації входу починаються з першим кадром, і забути її в новому тесті
 * означало б тихо повернути плаваючий гейт.
 */
test.beforeEach(async ({ page }) => {
	await reduceMotion(page);
});

/**
 * Заголовок дограв появу — обов'язкова умова перед заміром.
 *
 * `GameHeader` показує `<h1>` через `in:fade` під `{#key activeTitleKey}`, а це
 * перехід Svelte: він пише інлайн `style.opacity` з JS покадрово, тобто НЕ є
 * CSS-анімацією і `prefers-reduced-motion` його не стосується. axe рахує
 * контраст із обчисленого кольору, тож на напівпрозорому заголовку він міряє
 * колір, змішаний із тлом: заміряно `#436a3d` на `#7fa967` — контраст 2.3 при
 * потрібних 4.5. На дограній сторінці той самий заголовок проходить.
 *
 * Результат при цьому залежав від НАВАНТАЖЕННЯ машини: під двома воркерами
 * порушення було, під одним — ні. Тобто без цього рядка гейт плаваючий, а
 * плаваючий гейт гірший за відсутній.
 *
 * `toHaveCSS` сам перепитує до таймауту, тож це не «зачекати N мілісекунд», а
 * умова на стан. Ширша перевірка «жоден елемент не має проміжної прозорості»
 * тут не годиться: на сторінці є елементи з постійним `opacity` між нулем і
 * одиницею (приглушені стани), і така умова не настає ніколи — перша редакція
 * падала саме з таймауту, нічого не сказавши про доступність.
 */
async function waitForTitleShown(page: Page) {
	/*
	 * Тепер це ПОВНА умова спокою зі `support/settle.ts`, спільна із заміром
	 * контрасту. Очікування лише на `h1` тут було замало з двох причин, і обидві
	 * заміряні: заголовок згасає ДВІЧІ (`claimHeader` в `onMount` міняє ключ
	 * `{#key}`), а обгортка сторінки під ним тримає власний `in:fly` — тобто axe
	 * міг рахувати контраст крізь напівпрозору обгортку.
	 */
	await settlePage(page);
}

async function audit(page: Page, key: string) {
	await waitForTitleShown(page);
	const results = await new AxeBuilder({ page }).withTags(TAGS).analyze();

	// Перевірка, яка захищає перевірку: axe, що не проаналізував нічого, дав би
	// «нуль порушень» на порожній сторінці (AI-AGENT-PITFALLS-v8 § 1).
	expect(
		results.passes.length,
		'axe не виконав жодної перевірки — сторінка порожня чи не завантажилася?'
	).toBeGreaterThan(0);

	const ids = [...new Set(results.violations.map((v) => v.id))].sort();
	expect(ids, `новий тип порушення, якого не було в базі (${key})`).toEqual(
		[...A11Y_KNOWN[key]].sort()
	);
	expect(
		results.violations.length,
		`порушень побільшало (${key}): ${results.violations.map((v) => v.id).join(', ')}`
	).toBeLessThanOrEqual(A11Y_BASELINE[key]);
}

test('головна сторінка не має машинно-виявних порушень WCAG', async ({ page }) => {
	await page.goto('/VetCrewGames/');
	// Очікування конкретного елемента, а не `networkidle`: axe на недомальованій
	// сторінці дав би нуль порушень і зелений результат ні про що.
	//
	// `menu-memory-link`, а не `menu-pairs-link`: другий існує лише під `{#if dev}`,
	// а прогін іде по ЗІБРАНОМУ сайту, де меню віддає `FlatGameMenu`. Перша
	// редакція цього файлу впала саме на цьому — і добре, бо інакше довелося б
	// дізнатися, що dev і збірка мають різні меню, якось інакше.
	await expect(page.getByTestId('menu-memory-link')).toBeVisible();
	await audit(page, 'home');
});

/**
 * ТЕМНА ТЕМА — окремий прогін, а не той самий (ACCESSIBILITY-v8 § 6).
 *
 * Контраст — властивість ПАРИ кольорів, тож зелений результат у світлій темі не
 * говорить про темну взагалі нічого. `colorScheme: 'dark'` б'є в
 * `prefers-color-scheme`, тобто перевіряється саме той шлях, яким тему отримує
 * відвідувач, що ніколи не торкався перемикача.
 */
test.describe('темна тема', () => {
	test.use({ colorScheme: 'dark' });

	test('головна сторінка не має машинно-виявних порушень WCAG', async ({ page }) => {
		await page.goto('/VetCrewGames/');
		await expect(page.getByTestId('menu-memory-link')).toBeVisible();
		await audit(page, 'homeDark');
	});
});

/**
 * Сторінка чеклиста — найщільніша розмітка проєкту: вкладки, кнопки, позначки.
 * Саме там найлегше зламати доступність непомітно, бо дивиться на неї
 * тестувальник, а не відвідувач.
 */
test('сторінка чеклиста не має машинно-виявних порушень WCAG', async ({ page }) => {
	await page.goto('/VetCrewGames/beta-test-checklists/');
	// Чекаємо на самі ПУНКТИ, а не на смугу вкладок. Смуга з'являється раніше за
	// вміст, і замір на ній ловив три `color-contrast`, яких на дограній сторінці
	// немає жодного — тобто гейт червонів би від швидкості машини. Перший
	// видимий пункт означає, що список уже відмальований.
	// `.first()` обов'язковий: `beta-checks-list` тут ТРИ — по одному на кожен
	// рівень покриття (covered / testable / manual). Без нього Playwright падає
	// зі strict mode violation, а не з порушенням доступності.
	await expect(page.getByTestId('beta-checks-list').first()).toBeVisible();
	await expect(page.getByTestId('beta-check-item').first()).toBeVisible();
	await audit(page, 'betaChecklist');
});

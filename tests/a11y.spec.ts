import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';
import { A11Y_BASELINE, A11Y_KNOWN } from './a11y-baseline';
import { APP_PAGES, expectAllRoutesListed } from './support/pages';
import { reduceMotion, settlePage } from './support/settle';

/**
 * Машинно-виявні порушення WCAG (ACCESSIBILITY-v8 § 10, `GATE-A11Y-AXE`).
 *
 * ## Чому цей гейт з'явився лише тепер
 *
 * Аудит канону v8 (прохід 4, 2026-08-23) заміряв: три проєкти з семи не мали
 * E2E ЗОВСІМ, тобто `GATE-A11Y-AXE` у них не був «зелений» — його не існувало.
 * Часткова компенсація була: юніт-перевірка контрасту (`contrast.test.ts`) ловить
 * найдорожчий клас порушень на етапі читання змінних тем. Але контраст — це одне
 * правило з дев'яноста.
 *
 * ## ЧОМУ ТЕПЕР УСІ СТОРІНКИ, А НЕ ДВІ
 *
 * Перша редакція ходила на головну (у двох темах) і на чеклист — три заміри на
 * застосунок із чотирнадцяти сторінок. Відхиленням це записано не було, а сам
 * такий стан `tests/support/pages.ts` називає найдорожчим дефектом контрасту в
 * цьому проєкті: «axe ходив на ДВІ сторінки з одинадцяти, там зашитий білий
 * колір виправили, а на сторінках ігор той самий колір прожив далі».
 *
 * Перелік сторінок при цьому в проєкті вже БУВ, і ним уже ходили дві інші
 * браузерні перевірки. Тобто гейт лишався вибірковим не тому, що список важко
 * скласти, а тому, що ніхто не переніс сюди вже наявний. Тепер джерело одне на
 * всі три перевірки, і нова сторінка потрапляє в аудит без окремої правки —
 * `expectAllRoutesListed()` не дасть їй з'явитися повз перелік.
 *
 * ## Чому темна тема лишилася ЛИШЕ на головній
 *
 * Це свідома межа, а не залишок. Різниця між темами машинно видима рівно в
 * одному правилі — `color-contrast`, — і саме його `tests/contrast-runtime.spec.ts`
 * міряє ЧОТИРМА темами по всіх цих сторінках, ще й складаючи напівпрозорі шари,
 * чого axe не робить. Решта правил (ролі, підписи, порядок заголовків) від теми
 * не залежить, тож другий прохід усіма сторінками подвоїв би найдовший гейт
 * проєкту заради повторення чужого заміру. Головна лишається канаркою на сам
 * механізм теми: якщо `colorScheme: 'dark'` перестане доходити до сторінки, це
 * впаде тут.
 *
 * ## МЕЖА МЕТОДУ, і її треба знати, щоб зелений не читався як «сайт доступний»
 *
 * axe ловить приблизно третину проблем доступності. Порядок фокуса,
 * осмисленість `alt`, логічність заголовків, зрозумілість `aria-label`,
 * працездатність focus trap — він не бачить нічого з цього. Зелений axe означає
 * рівно одне: немає порушень, які видно машині.
 *
 * Друга половина — людина. У цьому проєкті вона не «колись і якось»: сторінка
 * `/beta-test-checklists` містить перелік перевірок із рівнями «покрито
 * автотестом / ще ні / лише людина» (BETA-CHECKLIST-v8).
 *
 * Третя межа (§ 10.2): `analyze()` бачить лише той стан, що є одразу після
 * `goto()`. Модалки, відкриті меню й тости в нього не потрапляють НІКОЛИ.
 */

const TAGS = ['wcag2a', 'wcag2aa', 'wcag22aa'];

/**
 * Ключ бази — з адреси, а не рукою.
 *
 * Рукописний ключ і адреса розходяться тихо: сторінку перейменували, рядок бази
 * лишився, і аудит її більше не міряє — маючи в базі число, яке читається як
 * заміряне. Похідний ключ так не вміє: перевірка повноти нижче звіряє обидва
 * боки й падає на першій же розбіжності.
 */
export function keyFor(url: string): string {
	const rest = url.replace('/VetCrewGames/', '').replace(/\/$/, '');
	return rest === '' ? 'home' : rest;
}

/**
 * ЕМУЛЯЦІЯ ЗМЕНШЕНОГО РУХУ — ЯВНО, бо з конфігу вона НЕ ДІЄ.
 *
 * Докблок `playwright.config.ts` називає `reducedMotion: 'reduce'` «не „щоб
 * швидше“, а умовою ДОСТОВІРНОСТІ заміру» і прямо каже, що без неї гейт
 * плаваючий. Заміряно на Playwright 1.62.1: до сторінки ця настройка не доходить
 * ні з конфігу, ні з `test.use` — `matchMedia` віддає `false` в обох випадках і
 * `true` лише після явного `page.emulateMedia()`.
 *
 * Тобто умова достовірності весь цей час була оголошенням, і зелений результат
 * axe означав «на цій машині цього разу пощастило». Подробиці й числа —
 * у `support/settle.ts`.
 *
 * `beforeEach`, а не рядок у кожному тесті: настройка мусить діяти ДО `goto`,
 * бо анімації входу починаються з першим кадром, і забути її в новому тесті
 * означало б тихо повернути плаваючий гейт.
 */
test.beforeEach(async ({ page }) => {
	await reduceMotion(page);
});

/**
 * Замір після ПОВНОЇ умови спокою зі `support/settle.ts`, спільної з гейтом
 * контрасту.
 *
 * Очікування на один елемент тут було замало, і причина заміряна: `GameHeader`
 * показує `<h1>` через `in:fade` під `{#key activeTitleKey}`, а це перехід
 * Svelte — він пише інлайн `style.opacity` з JS покадрово, тобто НЕ є
 * CSS-анімацією і `prefers-reduced-motion` його не стосується. axe рахує
 * контраст із обчисленого кольору, тож на напівпрозорому заголовку він міряє
 * колір, змішаний із тлом: заміряно `#436a3d` на `#7fa967` — контраст 2.3 при
 * потрібних 4.5. Заголовок при цьому згасає ДВІЧІ (`claimHeader` в `onMount`
 * міняє ключ `{#key}`), а обгортка сторінки під ним тримає власний `in:fly`.
 *
 * Результат без цієї умови залежав від НАВАНТАЖЕННЯ машини: під двома воркерами
 * порушення було, під одним — ні. Плаваючий гейт гірший за відсутній.
 */
async function audit(page: Page, key: string) {
	await settlePage(page);
	const results = await new AxeBuilder({ page }).withTags(TAGS).analyze();

	/*
	 * Перевірка, яка захищає перевірку (AI-AGENT-PITFALLS-v8 § 1).
	 *
	 * Рахуються ВУЗЛИ, а не правила: `results.passes.length` — це кількість
	 * правил, що пройшли, і на майже порожній сторінці вона все одно більша за
	 * нуль (`html-has-lang` і `document-title` виконуються без жодного вмісту).
	 * Тобто попередня умова `passes.length > 0` пропустила б сторінку, яка не
	 * домалювалася, і «нуль порушень» читалося б як результат.
	 */
	const inspected = results.passes.reduce((sum, rule) => sum + rule.nodes.length, 0);
	expect(
		inspected,
		`axe оглянув ${inspected} вузлів — сторінка ${key} порожня чи не завантажилася?`
	).toBeGreaterThan(20);

	const ids = [...new Set(results.violations.map((v) => v.id))].sort();
	expect(ids, `новий тип порушення, якого не було в базі (${key})`).toEqual(
		[...(A11Y_KNOWN[key] ?? [])].sort()
	);

	/*
	 * Рахуються ВУЗЛИ, а не рядки `results.violations`.
	 *
	 * `violations` — це масив ПРАВИЛ: чотири зони «Що їмо?» з однією й тією самою
	 * вадою дають довжину 1. Ратчет на такому числі майже не рухається: виправив
	 * три елементи з чотирьох — число лишилося тим самим, і наступний читач бачить
	 * борг, якого вже на три чверті немає. Гірше інше: додати п'яту таку зону теж
	 * лишить одиницю, тобто гейт пропустить зростання.
	 *
	 * Канон рахує саме вузли — його приклад бази записаний як «dialog-name ×2,
	 * color-contrast ×1» із числом 3 (ACCESSIBILITY-v8 § 10.1.1).
	 */
	const nodes = results.violations.reduce((sum, v) => sum + v.nodes.length, 0);
	expect(
		nodes,
		`порушень побільшало (${key}):\n` +
			results.violations
				.flatMap((v) => v.nodes.map((n) => `  ${v.id}: ${n.html.slice(0, 120)}`))
				.join('\n')
	).toBeLessThanOrEqual(A11Y_BASELINE[key] ?? 0);
}

/**
 * Повнота — з ОБОХ боків, і це різні дефекти.
 *
 * Сторінка без рядка бази проходила б із типовим нулем, тобто новий екран міг би
 * потрапити під гейт непоміченим і одразу його завалити. Рядок без сторінки —
 * прострочений виняток: він тримає число, яке ніхто не міряє, і ховає наступне
 * порушення того самого екрана.
 */
test('база покриває рівно ті сторінки, які аудитуються', () => {
	expectAllRoutesListed();

	const expected = [...APP_PAGES.map(keyFor), 'home@dark'].sort();
	expect(Object.keys(A11Y_BASELINE).sort(), 'A11Y_BASELINE розійшовся з APP_PAGES').toEqual(
		expected
	);
	expect(Object.keys(A11Y_KNOWN).sort(), 'A11Y_KNOWN розійшовся з APP_PAGES').toEqual(expected);
});

for (const url of APP_PAGES) {
	test(`немає машинно-виявних порушень WCAG на ${url}`, async ({ page }) => {
		await page.goto(url);
		await audit(page, keyFor(url));
	});
}

/**
 * ТЕМНА ТЕМА — окремий прогін, а не той самий (ACCESSIBILITY-v8 § 6).
 *
 * Контраст — властивість ПАРИ кольорів, тож зелений результат у світлій темі не
 * говорить про темну взагалі нічого. `colorScheme: 'dark'` б'є в
 * `prefers-color-scheme`, тобто перевіряється саме той шлях, яким тему отримує
 * відвідувач, що ніколи не торкався перемикача. Чому лише головна — у докблоці
 * на початку файлу.
 */
test.describe('темна тема', () => {
	test.use({ colorScheme: 'dark' });

	test('головна сторінка не має машинно-виявних порушень WCAG', async ({ page }) => {
		await page.goto('/VetCrewGames/');
		await audit(page, 'home@dark');
	});
});

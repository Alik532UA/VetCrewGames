import { expect, test } from './fixtures';
import { APP_PAGES } from './support/pages';
import { reduceMotion, settlePage } from './support/settle';

/**
 * ЦІЛИЙ КЛАС ДЕФЕКТІВ, ЯКИЙ ІСНУЄ ЛИШЕ РЯДКОМ У КОНСОЛІ.
 *
 * `AI-AGENT-PITFALLS-v8` § 2.1 називає його прямо: буває, що дефекту не видно
 * НІ в джерелах, НІ у `build/`. І там, і там усе правильно — розмітка на місці,
 * політика присутня, атрибути ті. Симптом існує лише в рантаймі:
 *
 * | Дефект                        | Джерела    | Зібраний HTML | Де видно                     |
 * | ----------------------------- | ---------- | ------------- | ---------------------------- |
 * | немає `media-src` у CSP       | правильний | правильний    | тиша при натисканні + консоль |
 * | немає `frame-src`             | правильний | правильний    | порожній прямокутник         |
 * | інлайновий обробник під CSP   | його немає | він є         | рядок «Refused to execute»   |
 * | вузол не завантажився         | правильний | правильний    | 404 у мережі                 |
 *
 * У цьому проєкті клас уже стріляв двічі, і обидва рази ціна була видима:
 * `script-src` без `https://*.firebasedatabase.app` не давав відкрити кімнату
 * зовсім (нескінченний цикл «вставили тег → CSP відмовив → звʼязок утрачено»),
 * а `apple-mobile-web-app-capable` без стандартного сусіда писав попередження в
 * консоль кожного відвідувача. Обидва тепер під `check:build` — але лише як
 * ІМЕНОВАНІ випадки: перелік у скрипті знає рівно те, що в нього вписали, і
 * наступна директива, якої забракне, у ньому не значиться.
 *
 * Ця перевірка іменованого переліку не має. Вона питає протилежне: чи мовчить
 * консоль на кожній сторінці застосунку — байдуже, з якої причини вона могла б
 * не мовчати.
 *
 * ## Що саме береться
 *
 * Три незалежні джерела, бо це три різні події браузера:
 *
 *  * `console` рівня `error` — сюди Chromium пише відмови CSP;
 *  * `pageerror` — необроблений виняток, який до `console` міг і не дійти;
 *  * `requestfailed` для СВОГО origin — файл, якого немає у збірці.
 *
 * Чужі origin у третьому пункті свідомо не рахуються: GA й шрифти Google
 * залежать від мережі раннера, і прогін, який червоніє від чужого таймауту,
 * вимикають першим (`AI-AGENT-PITFALLS-v8` § 1.1). Їхні відмови все одно
 * лишаються видимими — блокування CSP приходить рядком у `console`, а він тут
 * рахується без жодних винятків.
 *
 * ## Межа методу — та сама, що в сусідів
 *
 * Дивиться стан ОДРАЗУ після переходу: відкрите меню, розпочата партія й запит
 * до бази сюди не потрапляють. Щоб побачити їх, їх треба явно виконати, а це
 * вже сценарний E2E.
 */

/** Чужі домени: їхні мережеві збої залежать від раннера, а не від коду. */
const OWN_ORIGIN = /^http:\/\/(localhost|127\.0\.0\.1):/;

test.describe('консоль мовчить на кожній сторінці', () => {
	for (const url of APP_PAGES) {
		test(`жодної помилки в консолі на ${url}`, async ({ page }) => {
			const problems: string[] = [];

			page.on('console', (message) => {
				if (message.type() === 'error') problems.push(`console.error: ${message.text()}`);
			});
			page.on('pageerror', (error) => problems.push(`необроблений виняток: ${error.message}`));
			page.on('requestfailed', (request) => {
				if (!OWN_ORIGIN.test(request.url())) return;
				problems.push(`запит не пройшов: ${request.url()} — ${request.failure()?.errorText}`);
			});

			await reduceMotion(page);
			const response = await page.goto(url);

			/*
			 * Канарка на сам прогін. Сторінка, яка віддала 404 чи не віддала нічого,
			 * теж «не пише помилок у консоль» — і це був би зелений результат про
			 * порожнечу (AI-AGENT-PITFALLS-v8 § 1).
			 */
			expect(response?.status(), `${url} не віддала 200 — перевіряти нема що`).toBe(200);

			await settlePage(page);

			expect(problems, `${url} пише в консоль:\n${problems.join('\n')}`).toEqual([]);
		});
	}
});

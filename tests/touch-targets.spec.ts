import { expect, test } from '@playwright/test';
import { APP_PAGES, expectAllRoutesListed } from './support/pages';
import { reduceMotion, settlePage } from './support/settle';

/**
 * РОЗМІР СЕНСОРНОЇ ЦІЛІ (ACCESSIBILITY-v8 § 8, перевірка — § 10.3).
 *
 * ## Чому цього гейта не було, хоч правило діяло
 *
 * § 8 — найточніше правило того файлу: 44×44 CSS px власного стандарту, 24×24
 * абсолютної підлоги WCAG 2.2 AA (SC 2.5.8). Воно й виконувалося — рукою:
 * `min-height: 44px` із посиланням на § 8 стоїть у формі входу, у таблиці
 * рекордів, у панелі приватності. Але саме тому, що рукою, `PROJECT-CONTEXT.md`
 * чесно тримав рядок «touch targets» серед того, що не перевіряється
 * автоматично. Правило, яке виконують пам'яттю, виконується доти, доки пам'ятає
 * той, хто його завів.
 *
 * ## ДВА ПОРОГИ, І ВОНИ РІЗНІ ЗА ПРИРОДОЮ
 *
 * 24 px — межа WCAG, і вона БЕЗ реєстру: менше — це порушення рівня AA, а не
 * борг. Реєстру для неї тут немає навмисно, щоб не з'явилося місця, куди таке
 * можна відкласти.
 *
 * 44 px — власний стандарт проєкту, і тут реєстр доречний: він не з WCAG, а з
 * досвіду, і в щільному ряду шапки збільшення цілі до 44 забрало б місце в
 * сусідньої. Тому борг записаний ІМЕНАМИ, а не числом.
 *
 * ## ЧОМУ РЕЄСТР ЗА ЛОКАТОРАМИ, А НЕ ЗА СТОРІНКАМИ
 *
 * Кнопки шапки стоять на ВСІХ чотирнадцяти сторінках. Реєстр «сторінка → скільки
 * маленьких» тримав би сім однакових чисел у чотирнадцяти рядках, і всі вони
 * впали б від однієї правки в одному класі — тобто число говорило б про
 * розкладку сторінок, а не про цілі. Реєстр за іменами називає ПРИЧИНУ рівно
 * один раз, а нова маленька ціль де завгодно валить прогін із власним іменем.
 *
 * ## Що цей гейт бачить, а axe — ні
 *
 * `target-size` в axe міряє тільки межу 24 і знає її винятки (проміжок,
 * рядковість). Власний стандарт 44 він не перевіряє взагалі — і саме він тут
 * записаний як стандарт. Тому два гейти не дублюються: axe тримає підлогу WCAG у
 * `tests/a11y.spec.ts`, цей — власну планку проєкту.
 */

/** Власний стандарт проєкту (§ 8). */
const TOUCH_MIN = 44;

/** Абсолютна підлога WCAG 2.2 AA, SC 2.5.8. Нижче — порушення, а не борг. */
const WCAG_MIN = 24;

/**
 * Цілі, менші за 44 px, які вже є. Ключ — клас, значення — замір і причина.
 *
 * Список може лише СКОРОЧУВАТИСЯ: запис, якого більше не видно на жодній
 * сторінці, валить прогін так само, як нова маленька ціль. Прострочений виняток
 * ховає наступне порушення того самого елемента — той самий довід, що в
 * `OVERSIZED_ALLOWLIST` зі `src/structure.test.ts`.
 *
 * Заміряно 2026-08-27, вікном 390×844 з дотиком. П'ять причин на чотирнадцять
 * сторінок, і ЖОДНА не нижча за підлогу WCAG — тобто це борг перед власним
 * стандартом, а не порушення рівня AA.
 */
const SMALL_TARGET_DEBT: Record<string, string> = {
	/*
	 * Найдорожчий запис: шість кнопок на КОЖНІЙ сторінці — «назад», «головна»,
	 * тема, мова, акаунт, повний екран. Розмір заданий у `global.css` як жорсткі
	 * `width: 36px; height: 36px`, і там-таки пояснено, чому ряд щільний: кнопки
	 * — flex-елементи, і 36px стоїть підлогою, щоб сусіди не стискали одне одного.
	 *
	 * Чому не виправлено разом із появою гейта: на 390px ряд несе шість кнопок,
	 * заголовок і рахунок. 44px замість 36 — це +48px на ряд, тобто рішення про
	 * РОЗКЛАДКУ шапки на телефоні, а його не приймають, не подивившись очима.
	 * Дешевший шлях, який § 8 прямо називає, — лишити 36px намальованими, а зону
	 * натискання довести відступами; але й це змінює відстань між сусідніми
	 * зонами, тобто теж вимагає ока.
	 */
	'.header-btn': '36×36 — шість кнопок шапки, на всіх сторінках',

	/*
	 * «Що їмо?»: три страви-натяки в ряд усередині зони тварини. Висота вже
	 * стандартна, замала САМЕ ШИРИНА — зона ділиться на три, і ширшій кнопці
	 * нема звідки взяти місце, поки страв три в ряд.
	 */
	'.hint': '33×44 — ряд натяків у зоні тварини, замала ширина',
	'.quick': '34×45 — кнопки «кому віддати» під стравою, замала ширина',

	/* Заповідник: смуга показників у HUD, вузька за побудовою. */
	'.hud__stat': '32×47 — показник у смузі заповідника, замала ширина',

	/*
	 * Кнопки ВСЕРЕДИНІ поля вводу — вставити, стерти, показати пароль. Поле має
	 * свої 44px висоти, і кнопка на всю висоту поля виглядала б другим полем;
	 * 32px тут — наслідок того, що ціль вкладена в іншу ціль, а не недогляд
	 * розміру.
	 */
	'.tools__btn': '32×32 — кнопки всередині поля вводу (INPUT-TOOLS-v8 § 3)'
};

interface Target {
	key: string;
	testid: string;
	w: number;
	h: number;
	page: string;
}

/**
 * ЗАМІР ІДЕ ПО ЦІЛІ, А НЕ ПО ЕЛЕМЕНТУ, і три випадки тут різняться.
 *
 * 1. **Поле з підписом.** Свій перемикач малюють `<input>` розміром 1×1 під
 *    підписом — саме так зроблено вибір видимості кімнати. Ціллю пальця там є
 *    `<label>`, бо натискання по ньому вмикає поле; міряти сам `input` означало б
 *    оголосити дефектом узвичаєний і правильний прийом.
 * 2. **Елемент поза екраном.** Посилання «перейти до основного вмісту» живе за
 *    межами вікна, доки не отримає фокус. Пальцем його не існує, і вимагати від
 *    нього розміру сенсорної цілі нема сенсу — воно клавіатурне за призначенням.
 * 3. **Прихований предок.** `aria-hidden` і нульова прозорість означають, що
 *    елемента для людини немає.
 */
async function smallTargets(page: import('@playwright/test').Page, url: string): Promise<Target[]> {
	const raw = await page.evaluate((min) => {
		const selector =
			'button, a[href], input:not([type=hidden]), select, textarea, [role="button"], summary';
		const found: Array<{ key: string; testid: string; w: number; h: number }> = [];

		/*
		 * КЛЮЧ — КЛАС, А НЕ ЛОКАТОР, і це не смак.
		 *
		 * Перша редакція ключувала за `data-testid`, і реєстр вийшов би ПЛАВАЮЧИМ:
		 * у «Що їмо?» локатор несе id страви (`feeding-quick-btn-{food}-{target}`),
		 * а страви на кожну партію інші. Заміряно двома прогонами поспіль — перший
		 * дав `…-eucalyptus`, `…-fruit`, `…-onion`, другий `…-meat`, `…-insects`,
		 * `…-milk`. Тобто реєстр із такими ключами червонів би через раз, і його
		 * вимкнули б — заслужено.
		 *
		 * Клас стабільний і, головне, називає ПРИЧИНУ: шість кнопок шапки — це один
		 * `.header-btn`, і виправляються вони одним правилом. Локатор лишається в
		 * повідомленні поруч, щоб знайти конкретний елемент на сторінці.
		 */
		const keyOf = (el: HTMLElement): string => {
			const cls =
				typeof el.className === 'string'
					? el.className.split(/\s+/).filter((c) => c && !c.startsWith('svelte-'))[0]
					: '';
			if (cls) return `.${cls}`;
			return el.dataset.testid ? `[${el.dataset.testid}]` : el.tagName.toLowerCase();
		};

		for (const el of Array.from(document.querySelectorAll<HTMLElement>(selector))) {
			const style = getComputedStyle(el);
			if (style.visibility === 'hidden' || style.display === 'none') continue;
			if (el.closest('[aria-hidden="true"]')) continue;

			/*
			 * З двох боксів береться той, у кого більша МЕНША СТОРОНА, — і саме ця
			 * міра, а не площа.
			 *
			 * Обидві попередні редакції були неправильні, і обидві — заміром:
			 *
			 *   «завжди підпис» — поле імені кімнати має свої 150×44, а `<label>` над
			 *   ним лише підписує (320×21). Гейт оголосив би дефектом місце, де
			 *   стандарт виконано;
			 *
			 *   «більший за площею» — 320×21 це 6720, а 150×44 це 6600, тобто підпис
			 *   вигравав на сотню пікселів площі, лишаючись удвічі нижчим за поріг.
			 *
			 * § 8 міряє саме меншу сторону («44×44»), тож нею й треба порівнювати. Для
			 * свого перемикача (`input` 1×1 під намальованим підписом) виграє підпис,
			 * для текстового поля — саме поле.
			 */
			let box = el.getBoundingClientRect();
			if (el instanceof HTMLInputElement) {
				const label =
					el.closest('label') ??
					(el.id ? document.querySelector<HTMLElement>(`label[for="${CSS.escape(el.id)}"]`) : null);
				const labelBox = label?.getBoundingClientRect();
				const shorter = (r: DOMRect) => Math.min(r.width, r.height);
				if (labelBox && shorter(labelBox) > shorter(box)) box = labelBox;
			}

			if (box.width === 0 || box.height === 0) continue;
			// Виведений за межі вікна — клавіатурний за призначенням, не сенсорний.
			if (box.right <= 0 || box.bottom <= 0) continue;
			if (box.width >= min && box.height >= min) continue;

			found.push({
				key: keyOf(el),
				testid: el.dataset.testid ?? '',
				w: Math.round(box.width),
				h: Math.round(box.height)
			});
		}
		return found;
	}, TOUCH_MIN);

	return raw.map((r) => ({ ...r, page: url }));
}

/**
 * ВІКНО ТЕЛЕФОНА, І САМЕ З ДОТИКОМ.
 *
 * 390×844 — розмір із § 10.3 канону. `hasTouch` та `isMobile` тут не для
 * достовірності «як у людини», а тому, що від них залежить САМА РОЗКЛАДКА:
 * `global.css` і півдесятка компонентів мають `@media (hover: hover)` та
 * `(pointer: fine)`, тобто на миші й на пальці це різні сторінки. Міряти цілі
 * пальця в розкладці для миші означало б міряти те, чого людина не бачить.
 */
test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });

test.beforeEach(async ({ page }) => {
	await reduceMotion(page);
});

test('розмір сенсорних цілей — 44 px власного стандарту, 24 px підлоги WCAG', async ({ page }) => {
	expectAllRoutesListed();

	const small: Target[] = [];
	let inspected = 0;

	for (const url of APP_PAGES) {
		await page.goto(url);
		await settlePage(page);
		inspected += await page.evaluate(
			() =>
				document.querySelectorAll(
					'button, a[href], input:not([type=hidden]), select, textarea, [role="button"], summary'
				).length
		);
		small.push(...(await smallTargets(page, url)));
	}

	/*
	 * Канарка на сам замір (AI-AGENT-PITFALLS-v8 § 1): порожній прохід дав би
	 * «жодної маленької цілі» і зелений результат ні про що. 250 — це помітно
	 * нижче за заміряні 400+ на чотирнадцяти сторінках, тобто межа не падає від
	 * звичайного росту й скорочення, але порожнечу називає.
	 */
	expect(inspected, 'жодного інтерактивного елемента — замір дивиться не туди').toBeGreaterThan(
		250
	);

	/*
	 * ПІДЛОГА WCAG — окремим твердженням і ПЕРШИМ. Реєстру для неї немає: це
	 * порушення рівня AA, а не борг, і місця, куди його відкласти, тут навмисно
	 * не існує.
	 */
	const belowWcag = small.filter((t) => t.w < WCAG_MIN || t.h < WCAG_MIN);
	expect(
		belowWcag.map((t) => `${t.key} ${t.w}×${t.h} — ${t.testid || ''} ${t.page}`),
		'цілі менші за 24×24 (WCAG 2.2 AA, SC 2.5.8)'
	).toEqual([]);

	const seen = new Map<string, Target>();
	for (const target of small) if (!seen.has(target.key)) seen.set(target.key, target);

	const undeclared = [...seen.values()]
		.filter((t) => !(t.key in SMALL_TARGET_DEBT))
		.map((t) => `'${t.key}': '${t.w}×${t.h} — ${t.testid || t.page}',`);
	expect(
		undeclared,
		`ціль менша за ${TOUCH_MIN}px без запису в реєстрі:\n${undeclared.join('\n')}`
	).toEqual([]);

	const stale = Object.keys(SMALL_TARGET_DEBT).filter((key) => !seen.has(key));
	expect(
		stale,
		`запис у реєстрі, якого вже немає на жодній сторінці — прибрати:\n${stale.join('\n')}`
	).toEqual([]);
});

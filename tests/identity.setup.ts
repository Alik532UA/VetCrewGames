import { expect, test as setup } from '@playwright/test';
import { readFileSync } from 'node:fs';

/**
 * СЕРВЕР НА ТЕСТОВОМУ ПОРТІ — САМЕ ЦЕЙ ПРОЄКТ І САМЕ ЩОЙНО ЗІБРАНИЙ.
 *
 * ## Дефект, через який ця перевірка з'явилася — заміряний, а не уявний
 *
 * `playwright.config.ts` віддавна пояснює, чому порт тут свій (5399), і називає
 * захист: «`--strictPort`: зайнятий порт мусить УПАСТИ, а не тихо з'їхати на
 * наступний» плюс `reuseExistingServer: false`. Так от, цей захист НЕ ПРАЦЮЄ, і
 * ось як це виглядає.
 *
 * 2026-08-27 на 5399 піднявся `vite dev` СУСІДНЬОГО проєкту MindStep (його
 * власний тестовий порт — 5373, тобто це помилка там, а не тут). Прогін пішов
 * на чужий застосунок і впав із «element(s) not found» — тобто повідомленням
 * про КОД, а не про порт.
 *
 * ДІРА НЕ В ТОМУ, ЩО ПОРТ НЕ ПЕРЕВІРЯЄТЬСЯ, А В ТОМУ, КОЛИ. Playwright дивиться
 * на порт ОДИН РАЗ — перед запуском своєї команди; зайнятий на той момент порт
 * він називає прямо («http://localhost:5399 is already used»), і це перевірено
 * тут-таки наступним прогоном. Але команда в цьому проєкті починається зі
 * ЗБІРКИ, а це ~40 секунд, і всі вони — відчинене вікно: чужий сервер, що
 * піднявся всередині нього, забирає порт першим, `vite preview --strictPort`
 * чесно падає з «port is already in use», а Playwright цього падіння вже не
 * бачить. Готовність він визначає за тим, чи ВІДПОВІДАЄ порт, — і порт
 * відповідав.
 *
 *     curl http://localhost:5399/VetCrewGames/app-version.json
 *     → <!doctype html><html lang="uk">   ← SPA-фолбек MindStep, код 200
 *
 * Тобто чужий сервер віддає 200 і HTML на БУДЬ-ЯКУ адресу. Пощастило, що гейт
 * чекав на конкретний елемент і впав. Гейт, який шукає щось загальне (`<h1>`,
 * `button`, «жодного дубліката локатора»), пройшов би ЗЕЛЕНИМ, перевіривши чужий
 * сайт. Саме цей випадок докблок конфіга й називає таким, що вже трапився в
 * сусідньому проєкті з інваріантом унікальності `data-testid`.
 *
 * ## Чому звіряється ВЕРСІЯ, а не «є така сторінка»
 *
 * Маркер на кшталт `data-testid="menu-quiz-link"` довів би лише «це наш HTML».
 * Версія доводить ДВА твердження одразу, і друге не менш дороге:
 *
 *  1. **той проєкт** — чужий сервер на `/VetCrewGames/app-version.json` віддасть
 *     або 404, або HTML, і жодне з двох не розбереться як наш JSON;
 *  2. **та збірка** — `vite preview` будує перелік файлів ОДИН РАЗ, на старті
 *     (записано в AGENTS.md серед локальних пасток). Прев'ю, підняте до
 *     попередньої збірки, віддає старі файли, і гейт міряє вчорашній сайт,
 *     звітуючи про сьогоднішній.
 *
 * `static/app-version.json` для цього годиться точно: `static/` копіюється у
 * `build/` як є, а саме число туди пише гачок бампа на коміт, а не збірка —
 * тому крок `git diff --exit-code` у CI лишається зеленим.
 *
 * ## Чому окремим проєктом `setup`, а не рядком у кожному файлі
 *
 * Перевірка мусить бути ПЕРШОЮ і РІВНО ОДНІЄЮ. Рядок у кожному спеку розмножує
 * той самий запит на п'ятдесят перевірок і все одно не рятує від забудькуватості
 * в наступному файлі. `dependencies` у конфігу дає обидві властивості й НЕ додає
 * другої збірки: `webServer` у Playwright один на прогін, а не на проєкт. Саме
 * тому попередня оцінка в докблоці `testid.spec.ts` («другий проєкт додав би на
 * кожен прогін ще одну збірку прев'ю») тут не справджується — і саме тому цей
 * файл не спек, а `setup`.
 *
 * `--project=chromium` у CI цього не обходить: Playwright виконує залежності
 * обраного проєкту разом із ним.
 */

const LOCAL = readFileSync('static/app-version.json', 'utf8');

setup('на тестовому порті — цей проєкт і щойно зібраний', async ({ request, baseURL }) => {
	const response = await request.get('/VetCrewGames/app-version.json');

	const body = await response.text();
	const head = body.slice(0, 200).replace(/\s+/g, ' ');

	expect(
		response.status(),
		`${baseURL}/VetCrewGames/app-version.json віддав ${response.status()}. ` +
			`На порті чужий сервер або збірки немає. Перше, що варто подивитися: ` +
			`netstat -ano | findstr 5399. Прийшло: ${head}`
	).toBe(200);

	let served: { version?: string };
	try {
		served = JSON.parse(body);
	} catch {
		throw new Error(
			`${baseURL}/VetCrewGames/app-version.json віддав не JSON, а це: ${head}\n` +
				'Так поводиться SPA-фолбек ЧУЖОГО застосунку: він відповідає 200 і HTML на ' +
				'будь-яку адресу, тому Playwright вважає порт готовим і йде тестувати не той сайт.'
		);
	}

	expect(
		served.version,
		`версія на сервері (${served.version}) не збігається з ${JSON.parse(LOCAL).version} на диску. ` +
			"Прев'ю підняте до збірки: `vite preview` складає перелік файлів один раз, " +
			'на старті, тож після нової збірки його треба ПЕРЕЗАПУСТИТИ.'
	).toBe((JSON.parse(LOCAL) as { version: string }).version);
});

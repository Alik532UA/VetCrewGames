import { expect, test } from '@playwright/test';
import { APP_PAGES, expectAllRoutesListed } from './support/pages';
import { reduceMotion, settlePage } from './support/settle';

/**
 * РАНТАЙМ-ДУБЛІКАТИ `data-testid` — інваріант § 1.9.2 канону TESTID-AND-NAMING-v8.
 *
 * ## Чому цієї перевірки бракувало
 *
 * Канон вимагає ДВІ перевірки локаторів, і прямо каже: «Обидві мають бути в CI».
 * Статична (`src/testid-conventions.test.ts`) тут є, і вона покриває всі сім
 * обовʼязкових випадків § 1.9.1 плюс два власних. А рантайм-інваріанта не було
 * зовсім — і, що гірше, у `PROJECT-CONTEXT.md` він не значився й відхиленням, хоч
 * решта прогалин у цьому проєкті записана з причинами. Тобто це була не свідома
 * межа, а діра.
 *
 * ## Що саме ця перевірка бачить, а статична — ні
 *
 * Статична читає ДЖЕРЕЛА, тож вона фізично не може знати, скільки разів компонент
 * відрендерено. Локатор, унікальний у файлі, стає двозначним щойно той компонент
 * поставили на сторінку двічі — і Playwright тоді падає не з «дублікат», а зі
 * `strict mode violation` десь у чужому тесті, за півроку й у геть іншому місці.
 *
 * Приклад із цього проєкту, який робить ризик не теоретичним: `.header-btn` малює
 * і `GameHeader`, і `HeaderControls`, і `HeaderMenu` — три компоненти, одна
 * кнопка, і саме там уже одного разу розійшлися стилі.
 *
 * ## Межа методу, і вона та сама, що назвав канон
 *
 * Перевіряється стан ОДРАЗУ після переходу. Відкрите меню, модалка, екран
 * підсумку гри — ні; щоб їх покрити, їх треба явно відкрити. Тут вони й не
 * відкриваються: така перевірка перестала б бути дешевою й перетворилася б на
 * сценарний E2E, якого в цьому проєкті свідомо мало.
 *
 * ## Чому не окремий проєкт Playwright
 *
 * Канон радить запускати інваріант ПЕРЕД основними E2E окремим проєктом `setup`,
 * щоб падати швидко. Тут цього не зроблено свідомо: у конфігу один проєкт
 * (`chromium`), і другий заради порядку виконання додав би на кожен прогін ще
 * одну збірку прев'ю. Ціна — дублікат локатора видно разом з усіма іншими
 * падіннями, а не першим рядком.
 */

test.describe('локатори унікальні в рантаймі', () => {
	test('перелік сторінок покриває всі маршрути', () => {
		expectAllRoutesListed();
	});

	for (const url of APP_PAGES) {
		test(`жодного дубліката на ${url}`, async ({ page }) => {
			await reduceMotion(page);
			await page.goto(url);
			/*
			 * Умова спокою — та сама, що в решти браузерних перевірок. Тут вона не про
			 * кольори: сторінка під анімацією входу ще домальовується, і частина
			 * компонентів на ній може бути присутня двічі — вихідний вузол іще в DOM,
			 * вхідний уже в DOM. Це не дублікат локатора, а кадр переходу.
			 */
			await settlePage(page);

			const ids = await page.$$eval('[data-testid]', (nodes) =>
				nodes.map((node) => node.getAttribute('data-testid') ?? '')
			);

			// Канарка на сам замір: сторінка без локаторів дала б «нуль дублікатів» і
			// зелений результат ні про що (AI-AGENT-PITFALLS-v8 § 1).
			expect(ids.length, `на ${url} немає жодного локатора — замір дивиться не туди`).toBeGreaterThan(
				5
			);

			const seen = new Map<string, number>();
			for (const id of ids) seen.set(id, (seen.get(id) ?? 0) + 1);
			const dupes = [...seen.entries()]
				.filter(([, count]) => count > 1)
				.map(([id, count]) => `${id} — ${count} разів`);

			expect(dupes, `дублікати локаторів на ${url}:\n${dupes.join('\n')}`).toEqual([]);
		});
	}
});

import { expect, test } from './fixtures';
import { APP_PAGES, expectAllRoutesListed } from './support/pages';
import { reduceMotion, settlePage } from './support/settle';

/**
 * РАНТАЙМ-ДУБЛІКАТИ `data-testid` — інваріант § 1.9.2 канону TESTID-AND-NAMING-v8.
 *
 * ## Чому цієї перевірки бракувало
 *
 * Канон вимагає ДВІ перевірки локаторів, і прямо каже: «Обидві мають бути в CI».
 * Статична (`src/testid-conventions.test.ts`) тут є, і вона покриває всі сім
 * обовʼязкових випадків § 1.9.1 плюс два власних. А рантайм-інваріанта не було
 * зовсім — і, що гірше, у `PROJECT-CONTEXT.md` він не значився й відхиленням, хоч
 * решта прогалин у цьому проєкті записана з причинами. Тобто це була не свідома
 * межа, а діра.
 *
 * ## Що саме ця перевірка бачить, а статична — ні
 *
 * Статична читає ДЖЕРЕЛА, тож вона фізично не може знати, скільки разів компонент
 * відрендерено. Локатор, унікальний у файлі, стає двозначним щойно той компонент
 * поставили на сторінку двічі — і Playwright тоді падає не з «дублікат», а зі
 * `strict mode violation` десь у чужому тесті, за півроку й у геть іншому місці.
 *
 * Приклад із цього проєкту, який робить ризик не теоретичним: `.header-btn` малює
 * і `GameHeader`, і `HeaderControls`, і `HeaderMenu` — три компоненти, одна
 * кнопка, і саме там уже одного разу розійшлися стилі.
 *
 * ## Межа методу, і вона та сама, що назвав канон
 *
 * Перевіряється стан ОДРАЗУ після переходу. Відкрите меню, модалка, екран
 * підсумку гри — ні; щоб їх покрити, їх треба явно відкрити. Тут вони й не
 * відкриваються: така перевірка перестала б бути дешевою й перетворилася б на
 * сценарний E2E, якого в цьому проєкті свідомо мало.
 *
 * ## Чому не окремий проєкт Playwright
 *
 * Канон радить запускати інваріант ПЕРЕД основними E2E окремим проєктом `setup`,
 * щоб падати швидко. Тут цього не зроблено, і ціна названа: дублікат локатора
 * видно разом з усіма іншими падіннями, а не першим рядком.
 *
 * Причина, яка стояла тут доти, була НЕВІРНА: «другий проєкт додав би на кожен
 * прогін ще одну збірку прев'ю». Не додав би — `webServer` у Playwright один на
 * прогін, а не на проєкт, і це заміряно: проєкт `setup` з'явився в конфігу
 * 2026-08-27 (`tests/identity.setup.ts`), збірка лишилася одна, прогін —
 * 1,2 хвилини проти тих самих 1,3.
 *
 * Тобто перенести цю перевірку в `setup` тепер можна, і це окрема робота. Вона
 * не зроблена разом із тим комітом свідомо: `setup` мусить бути дешевим і
 * безумовним, а цей інваріант ходить чотирнадцятьма сторінками — тобто зробив би
 * умову «на порті наш сайт» такою ж довгою, як самі гейти, які вона захищає.
 */

/**
 * АТРИБУТ `id` — ТУТ-ТАКИ, І З ТІЄЇ САМОЇ ПРИЧИНИ.
 *
 * Канон радить будувати звʼязок `label` ↔ `input` на `$props.id()`
 * (SVELTE-CORE-v8 § 1.7, SVELTE-UI-v8 § 2.4): руна гарантує унікальність сама.
 * Тут обрано інше — `id` приходить ПРОПОМ від того, хто малює поле, з тієї
 * самої основи, що й `data-testid`, щоб локатор і підпис не могли розійтися.
 *
 * Рішення записане в `PROJECT-CONTEXT.md`, і разом із ним записана його ціна:
 * проп унікальності не гарантує. Двічі намальований `PasswordInput` з тим самим
 * `id` дасть два елементи з однаковим `id`, і `<label for>` покаже на перший —
 * тобто клік по підпису другого поля сфокусує чуже. Ні `svelte-check`, ні
 * eslint, ні збірка цього не бачать: у ДЖЕРЕЛАХ обидва рази законні.
 *
 * Axe теж не порятунок: `duplicate-id` з нього прибрано в axe-core 4.9, а
 * `duplicate-id-active` і `duplicate-id-aria`, що лишилися, дублікат на парі
 * `label`/`input` не ловлять.
 *
 * Тому замір іде разом із локаторами, у тому самому обході: сторінка вже
 * відкрита й доспокоєна, і другий обхід чотирнадцяти адрес коштував би стільки
 * ж, скільки перший.
 */
test.describe('локатори унікальні в рантаймі', () => {
	test('перелік сторінок покриває всі маршрути', () => {
		expectAllRoutesListed();
	});

	for (const url of APP_PAGES) {
		test(`жодного дубліката локатора чи id на ${url}`, async ({ page }) => {
			await reduceMotion(page);
			await page.goto(url);
			/*
			 * Умова спокою — та сама, що в решти браузерних перевірок. Тут вона не про
			 * кольори: сторінка під анімацією входу ще домальовується, і частина
			 * компонентів на ній може бути присутня двічі — вихідний вузол іще в DOM,
			 * вхідний уже в DOM. Це не дублікат локатора, а кадр переходу.
			 */
			await settlePage(page);

			const ids = await page.$$eval('[data-testid]', (nodes) =>
				nodes.map((node) => node.getAttribute('data-testid') ?? '')
			);

			// Канарка на сам замір: сторінка без локаторів дала б «нуль дублікатів» і
			// зелений результат ні про що (AI-AGENT-PITFALLS-v8 § 1).
			expect(
				ids.length,
				`на ${url} немає жодного локатора — замір дивиться не туди`
			).toBeGreaterThan(5);

			const repeated = (values: string[]) => {
				const seen = new Map<string, number>();
				for (const value of values) seen.set(value, (seen.get(value) ?? 0) + 1);
				return [...seen.entries()]
					.filter(([, count]) => count > 1)
					.map(([value, count]) => `${value} — ${count} разів`);
			};

			const dupes = repeated(ids);
			expect(dupes, `дублікати локаторів на ${url}:\n${dupes.join('\n')}`).toEqual([]);

			const attrIds = await page.$$eval('[id]', (nodes) =>
				nodes.map((node) => node.getAttribute('id') ?? '')
			);

			/*
			 * Друга канарка, окрема від першої: `[data-testid]` і `[id]` — різні
			 * множини вузлів, і порожньою може стати будь-яка з них сама по собі.
			 * Межа низька навмисно — сторінка без жодного поля вводу цілком може
			 * мати кілька `id` на посадкових якорях, і вимагати від неї більшого
			 * означало б червоніти на правильному коді.
			 */
			expect(attrIds.length, `на ${url} немає жодного id — замір дивиться не туди`).toBeGreaterThan(
				0
			);

			const idDupes = repeated(attrIds);
			expect(
				idDupes,
				`однакові id на ${url} — \`label for\` покаже на перший із них:\n${idDupes.join('\n')}`
			).toEqual([]);
		});
	}
});

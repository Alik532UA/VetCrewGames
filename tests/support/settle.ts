import { expect, type Page } from '@playwright/test';

/**
 * Довести сторінку до СПОКОЮ, перш ніж міряти з неї кольори.
 *
 * ## Навіщо окремий модуль
 *
 * Обидва гейти, що міряють намальоване (`a11y.spec.ts` через axe і
 * `contrast-runtime.spec.ts` власним заміром), читають ОБЧИСЛЕНІ значення. Поки
 * йде анімація входу, обчислене значення — це кадр, а не стан: axe рахує
 * контраст із проміжного кольору, а замір контрасту складає проміжну
 * прозорість. Умова спокою в них мусить бути одна, інакше два гейти будуть
 * по-різному правдиві.
 *
 * ## ЗНАЙДЕНИЙ ДЕФЕКТ: `reducedMotion` із конфігу НЕ ДІЄ
 *
 * `playwright.config.ts` ставить `use: { reducedMotion: 'reduce' }`, і докблок
 * `a11y.spec.ts` називає це «не „щоб швидше“, а умовою ДОСТОВІРНОСТІ заміру»,
 * прямо кажучи, що без неї гейт плаваючий. Заміряно на Playwright 1.62.1:
 *
 *     `use` у конфігу        → matchMedia('(prefers-reduced-motion: reduce)') = false
 *     `test.use` у файлі     → false
 *     `page.emulateMedia()`  → true
 *
 * Тобто настройка не доходила до сторінки НІ ЗВІДКИ, крім явного виклику, і
 * умова достовірності весь час була оголошенням. Знайшлося це не оком: замір
 * контрасту почав складати прозорість і видав 281 «дефект» у всіх чотирьох
 * темах, усі з однаковою прикметою — колір тексту, складений майже точно в колір
 * тла, тобто прозорість близько 0.05. Це були кадри анімацій входу.
 *
 * Тому емуляція ставиться ТУТ і ЗАРАЗ ЖЕ перевіряється: настройка, чию дію ніхто
 * не стверджує, одного разу вже перетворилася на слова.
 *
 * ## Чому цього все одно не досить, і чому чекаємо ще й на анімації
 *
 * Емуляція гасить CSS-анімації (`global.css` зводить їх до 0.01 мс під
 * `prefers-reduced-motion`), але НЕ переходи Svelte: `in:fly` у кореневому
 * layout пише інлайновий `opacity` покадрово з JS, і жодна медіа-настройка його
 * не стосується. Плюс `animation-delay` блок зменшення руху не скидає — а з
 * `fill: both` елемент під час затримки тримає початковий кадр.
 *
 * Тому спокій підтверджується трьома незалежними умовами, і кожна закриває свій
 * клас: медіа-емуляція (CSS-анімації), очікування на `opacity` обгортки
 * (переходи Svelte), очікування на завершення всіх анімацій Web Animations API
 * (затримки й стагер).
 */

/**
 * Емуляція зменшеного руху — і твердження, що вона справді діє.
 *
 * Кличеться ДО `goto`: анімації входу починаються з першим кадром, і настройка,
 * увімкнена після завантаження, вже нічого не гасить.
 */
export async function reduceMotion(page: Page) {
	await page.emulateMedia({ reducedMotion: 'reduce' });
}

/**
 * Перевірка, яка захищає перевірку: емуляція мусить бути ВИДИМОЮ зі сторінки.
 *
 * Окремо від `reduceMotion`, бо стверджувати це можна лише після `goto` — на
 * `about:blank` `matchMedia` відповідає, але про наш документ це нічого не каже.
 */
export async function expectMotionReduced(page: Page) {
	const reduced = await page.evaluate(
		() => window.matchMedia('(prefers-reduced-motion: reduce)').matches
	);
	expect(
		reduced,
		'емуляція зменшеного руху не діє — замір побачить кадри анімацій, а не стан сторінки'
	).toBe(true);
}

/**
 * Дочекатися, поки жодна анімація не біжить.
 *
 * `document.getAnimations()` бачить і CSS-анімації, і переходи, разом із їхніми
 * затримками — тобто саме те, чого не покриває ні `reducedMotion` (не скидає
 * `animation-delay`), ні очікування на конкретний елемент (стагер зсуває кожен
 * елемент окремо).
 *
 * Нескінченні пропускаються: на сторінці такі є, і `finished` у них не настає
 * ніколи — очікування на них означало б таймаут замість заміру.
 */
export async function waitForAnimations(page: Page) {
	await page.evaluate(async () => {
		const finite = document
			.getAnimations()
			.filter((animation) => animation.effect?.getTiming().iterations !== Infinity);
		// `catch` обовʼязковий: анімацію, скасовану під час очікування, `finished`
		// відхиляє — а це нормальний перебіг, не збій.
		await Promise.all(finite.map((animation) => animation.finished.catch(() => undefined)));
	});
}

/**
 * Пауза між двома вимірами прозорості. Той самий трейлінг, що у `fitLabel`.
 *
 * 140 мс — помітно більше за кадр (16 мс), тобто перехід, який іде, гарантовано
 * зсунеться між вимірами; і помітно менше за найкоротший перехід у проєкті
 * (300 мс), тобто спокій не буде оголошено посеред згасання.
 */
const FADE_SETTLE_MS = 140;

/**
 * Дочекатися, поки прозорості ПЕРЕСТАНУТЬ ЗМІНЮВАТИСЯ.
 *
 * Переходи Svelte (`in:fade`, `in:fly`) пишуть `opacity` ІНЛАЙНОМ покадрово з JS
 * і прибирають атрибут, скінчившись. Ні `getAnimations()`, ні медіа-емуляція їх
 * не бачать: вони не анімації й не CSS.
 *
 * ЧОМУ НЕ ОЧІКУВАННЯ НА КОНКРЕТНИЙ ЕЛЕМЕНТ. Саме на ньому й спіткнулася перша
 * редакція: `expect(page.locator('h1').first()).toHaveCSS('opacity', '1')`.
 * Заголовок у `GameHeader` згасає ДВІЧІ — спершу типовий, а далі
 * `settings.claimHeader()` в `onMount` міняє ключ `{#key}`, і починається другий
 * `in:fade`. Умова на перший спрацьовувала, замір ішов посеред другого, і в звіті
 * стояв рядок значень 2.11, 2.31, 2.54, 2.79, 3.07, 4.46 — кадри одного згасання.
 *
 * ЧОМУ НЕ «ЖОДНОГО ПРОЗОРОГО», а осідання. Друга редакція вимагала, щоб у
 * документі не лишилося інлайнового `opacity` менше одиниці, — і ця умова не
 * настає НІКОЛИ: на сторінці є елементи, приглушені НАЗАВЖДИ (`utils/transitions.ts`
 * тримає власне значення). Усі чотири теми впали в таймаут на 60 секунд, тобто
 * перевірка перетворилася з невірної на мертву.
 *
 * Осідання правильне й по суті, а не лише зручне: назавжди приглушений елемент
 * СПРАВДІ має нижчий контраст, і замір мусить його побачити таким, як він є, а
 * не чекати, поки той стане іншим.
 */
export async function waitForFadesToSettle(page: Page) {
	const snapshot = () =>
		page.evaluate(() =>
			Array.from(document.querySelectorAll<HTMLElement>('[style]'))
				.map((el, index) => `${index}:${el.style.opacity}`)
				.join('|')
		);

	let previous = await snapshot();
	let stable = 0;
	for (let attempt = 0; attempt < 20; attempt += 1) {
		await page.waitForTimeout(FADE_SETTLE_MS);
		const current = await snapshot();
		/*
		 * ДВА однакові виміри підряд, а не один.
		 *
		 * Один збіг випадає й посеред руху: `[style]` — це набір, що зростає, і
		 * поява елемента з `opacity: 1` поруч зі зникненням іншого дає той самий
		 * рядок. Заміряно наслідок: `h1.game-title` на `/pairs/online/` віддавав
		 * 4.40:1 при потрібних 4.5 — рівно один вузол на одній сторінці, тоді як на
		 * решті десяти той самий елемент проходив. Тобто це був не дефект кольору, а
		 * останній кадр згасання, і ловився він лише там, де сторінка домальовується
		 * довше за інші (з'єднання з базою).
		 */
		if (current === previous) {
			stable += 1;
			if (stable >= 2) return;
			continue;
		}
		stable = 0;
		previous = current;
	}
	/*
	 * Двадцять спроб — це майже три секунди безперервного руху. Довше за це на
	 * сторінці нічого не згасає, тож така сторінка або справді анімується без
	 * кінця, або замір дивиться не туди. Тихо міряти далі не можна: результат
	 * читався б як стан, а був би кадром.
	 */
	throw new Error(
		'прозорості не осіли за 20 вимірів — на сторінці щось згасає безперервно, ' +
			'і замір кольорів дав би кадр анімації замість стану'
	);
}

/**
 * Повна умова спокою після переходу на сторінку.
 *
 * Порядок не довільний. Спершу зникає обгортка-перехід — під нею напівпрозоре
 * все, тож без цього решта умов перевіряла б кадри. Далі шрифти: вони міняють
 * метрики, а з ними й те, який текст вважається великим. Далі анімації окремих
 * елементів (стагер зсуває кожен свій). І лише тоді переходи Svelte: другий
 * `in:fade` заголовка починається вже після `onMount`, тобто після того, як
 * обгортка доїхала, — отже чекати на нього треба останнім.
 */
export async function settlePage(page: Page) {
	await expectMotionReduced(page);
	await expect(page.locator('.page-transition-wrapper')).toHaveCSS('opacity', '1');
	await page.evaluate(() => document.fonts.ready);
	await waitForAnimations(page);
	await waitForFadesToSettle(page);
}

import { defineConfig, devices } from '@playwright/test';

/**
 * Окремий порт саме для тестів, і свій у кожному проєкті.
 *
 * Типовий 5173 у всіх сімох проєктах однаковий. Якщо на ньому вже висить
 * dev-сервер ІНШОГО проєкту, Playwright спокійно бере його й перевіряє чужий
 * застосунок: тест зелений, перевірено не те (AI-AGENT-PITFALLS-v8 § 1). Саме
 * так в одному з сусідніх проєктів інваріант унікальності `data-testid` одного
 * разу «пройшов», дивлячись на інший сайт.
 *
 * Реєстр тестових портів на 2026-08-23: CV 5299, Slovko 5273, MindStep 5373,
 * teatralo4ka 5195, цей проєкт 5399, as5 5499, DigitalWorkshop 5599.
 * `--strictPort` + `reuseExistingServer: false` роблять зіткнення ГОЛОСНИМ.
 */
const TEST_PORT = 5399;

export default defineConfig({
	testDir: './tests',
	timeout: 60 * 1000,
	expect: { timeout: 10_000 },
	fullyParallel: true,
	forbidOnly: !!process.env.CI,
	retries: process.env.CI ? 2 : 0,
	/*
	 * Обмежене число воркерів, а не «скільки дасть машина».
	 *
	 * `undefined` віддає Playwright половину ядер. axe сам по собі важкий для
	 * процесора, і кілька браузерів разом із прев'ю-сервером на цій машині не
	 * вміщаються — падіння тоді не в коді, а в навантаженні. Червоний прогін,
	 * причина якого не в коді, починають ігнорувати (той самий аргумент, що для
	 * `off` в ESLint і для нуля в axe).
	 */
	workers: process.env.CI ? 1 : 2,
	reporter: process.env.CI ? [['list'], ['html', { open: 'never' }]] : 'list',
	use: {
		baseURL: `http://localhost:${TEST_PORT}`,
		trace: 'on-first-retry',
		/*
		 * `reducedMotion: 'reduce'` — не «щоб швидше», а умова ДОСТОВІРНОСТІ заміру.
		 *
		 * axe рахує контраст із обчисленого кольору. Поки йде анімація входу
		 * (`card-enter 400ms` + `blur-in 3s` у `global.css`) або перехід кольорів
		 * на `body *`, колір проміжний — і `color-contrast` бачить пару, якої на
		 * екрані немає ні одного кадру після завершення. Виміряно: та сама
		 * сторінка чеклиста давала 3 порушення при замірі під анімацією і 0 після
		 * неї, причому результат залежав від НАВАНТАЖЕННЯ машини (два воркери
		 * проти одного). Тобто гейт був би плаваючим — а такий гірший за
		 * відсутній, бо на нього перестають дивитися.
		 *
		 * Чому саме ця настройка, а не власне вимкнення стилями: проєкт її вже
		 * підтримує — `global.css` має `@media (prefers-reduced-motion: reduce)`,
		 * який зводить усі анімації й переходи до 0.01 мс. Тобто перевіряється
		 * реальний шлях реального відвідувача, а не штучний стан, зліплений у
		 * тесті. Спроба зробити те саме власним `addStyleTag` тут уже була і не
		 * працювала: переходи Svelte (`in:fade`) пишуть інлайн `opacity` з JS
		 * покадрово, і CSS їх не стосується.
		 *
		 * Ціна: axe не побачить порушення, яке існує ЛИШЕ під анімацією. Це
		 * свідомо — такі кадри не є станом сторінки, і їх оцінює око людини.
		 */
		reducedMotion: 'reduce'
	},
	projects: [
		/*
		 * ПЕРЕВІРКА, ЩО ДИВИТЬСЯ НА САМ ПРОГІН, і вона мусить бути першою.
		 *
		 * Порт свій, `--strictPort` стоїть, `reuseExistingServer: false` теж — і
		 * цього НЕ ДОСИТЬ. Заміряно 2026-08-27: на 5399 висів `vite dev` сусіднього
		 * MindStep, `vite preview --strictPort` чесно впав із «port is already in
		 * use», а Playwright цього не помітив, бо готовність сервера він визначає за
		 * тим, чи відповідає порт. Відповідав — чужий. Увесь прогін пішов на чужий
		 * застосунок, і чужий SPA-фолбек віддавав 200 та HTML на будь-яку адресу.
		 *
		 * Тому окремий крок звіряє, що на порті САМЕ цей проєкт і САМЕ щойно зібраний
		 * (`tests/identity.setup.ts`). Другої збірки він не додає: `webServer` тут
		 * один на прогін, а не на проєкт.
		 */
		{ name: 'setup', testMatch: /identity\.setup\.ts$/ },
		{ name: 'chromium', use: { ...devices['Desktop Chrome'] }, dependencies: ['setup'] }
	],
	webServer: {
		/*
		 * ПРЕВ'Ю ЗІБРАНОГО САЙТУ, а не dev-сервер (CODE-QUALITY-v8 § 5.7).
		 *
		 * Dev і збірка — різні застосунки саме там, де живуть найдорожчі дефекти:
		 * CSP у dev приїжджає заголовком із nonce, у збірці — `<meta>` без нього;
		 * dev рендерить сторінку на запит, збірка віддає prerender із диску.
		 * Порушення доступності теж може бути наслідком prerender — наприклад,
		 * `lang` на `<html>`, який ставить лише зібраний варіант.
		 *
		 * `--strictPort`: зайнятий порт мусить УПАСТИ, а не тихо з'їхати на
		 * наступний, інакше `port` нижче вказував би на чужий сервер.
		 *
		 * ЦЬОГО НЕ ДОСИТЬ, і це заміряно, а не припущено. `vite preview` справді
		 * падає на зайнятому порті — але Playwright цього падіння не бачить: він
		 * чекає, поки порт ВІДПОВІСТЬ, а відповідає той, хто його зайняв. Тобто
		 * `--strictPort` і `reuseExistingServer: false` разом захищають від
		 * «сервер тихо з'їхав на 5400» і НЕ захищають від «на 5399 чужий сервер».
		 * Другий випадок закриває проєкт `setup` вище.
		 */
		command: `npm run build && npm run preview -- --port ${TEST_PORT} --strictPort`,
		port: TEST_PORT,
		reuseExistingServer: false,
		// Збірка входить у команду, тож типових 60 с не вистачає.
		timeout: 180_000
	}
});

<script lang="ts">
	import { dev } from '$app/environment';
	import { t, formatFont } from '$lib/i18n';
	import { page } from '$app/state';
	import { langPath, languageFromParam } from '$lib/i18n/routing';
	import { siblingUrl } from '$lib/siblings';

	/**
	 * Головне меню — РОЗДІЛИ, і тепер однакові в роботі й у збірці для людей.
	 *
	 * ## Що тут було й чому змінилося
	 *
	 * Меню було ДВА. У роботі — три розділи («Заповідник», «Вікторина», «Знайди
	 * пару»), у збірці для людей — плоский перелік із випадкової гри й шести ігор.
	 * Міркування було таке: режимів, які обіцяють розділи, ще немає, тож зайвий
	 * рівень вкладеності відводить від того, що працює.
	 *
	 * Воно застаріло, і автор сказав про це прямо: «в prod геть інше меню ніж в
	 * dev». Обіцянка розділів більше не порожня — спільна гра є і у вікторині, і в
	 * «Знайди пару», а вимкнений пункт «грати з друзями» прибрано (`ModeMenu`).
	 * Тримати два різні меню означало тримати два різні застосунки: те, що автор
	 * перевіряє руками, і те, що бачать люди.
	 *
	 * ## Різниця, яка лишилася, — ОДИН пункт
	 *
	 * «Заповідник» ще будується, і кнопка, за якою недороблена гра, псує враження
	 * від готових. Тому він лишається лише в роботі — рівно доти, доки не буде
	 * готовий: прибрати `{#if dev}` тоді буде однією правкою, і меню зійдуться
	 * повністю.
	 *
	 * Адреси при цьому НЕ змінюються й не змінювалися: розділи лишаються за своїми
	 * URL і в продакшні. Прибирати маршрути означало б ламати посилання, які вже
	 * могли комусь піти.
	 *
	 * ## Куди поділася «Випадкова гра»
	 *
	 * Вона на місці, але на рівень глибше: «Вікторина» → «Грати». Так само, як у
	 * роботі, і так само, як було задумано: випадкова гра пропонує пʼятірку
	 * вікторини, тобто живе всередині неї, а не над усіма розділами.
	 */
	const lang = $derived(languageFromParam(page.params.lang));

	/**
	 * Два зовнішні посилання, і мову несе лише одне з них.
	 *
	 * «Замовити сайт» веде в сусідній DigitalWorkshop, а той на голій адресі
	 * віддає українську — тобто читач англійської сторінки натискав
	 * англійський підпис і потрапляв на український сайт. Тепер адресу будує
	 * `siblingUrl()` із таблиці `src/lib/siblings.ts`: мову, яку сусід кладе в
	 * шлях, називає шлях (`/DigitalWorkshop/en/`), а його ТИПОВУ мову — `?lang=`,
	 * бо `/DigitalWorkshop/uk/` не існує з тієї самої причини, з якої тут не існує
	 * `/VetCrewGames/uk/`.
	 *
	 * Сайт ветеринарної команди на `sites.google.com` мов не має взагалі, тож
	 * передавати туди нема чого — і таблиця про нього нічого не знає.
	 */
	const links = $derived([
		{
			key: 'menu.link.vetcrew' as const,
			href: 'https://sites.google.com/view/vetcrew'
		},
		{
			key: 'menu.link.order' as const,
			href: siblingUrl('digitalworkshop', lang)
		}
	]);
</script>

<div class="menu-page">
	<nav class="menu-grid">
		<!--
			ЗАПОВІДНИК — ЛИШЕ В РОБОТІ, і це остання різниця між двома меню.

			Він ще будується, а кнопка, за якою недороблена гра, псує враження від
			готових. Умова стоїть на самому пункті, а не навколо всього меню: решта
			однакова, і тримати дві копії тих самих двох посилань означало б, що
			наступна правка дійде лише до однієї.

			`anim-stagger-1` лишається за ним і в продакшні: перший крок анімації там
			просто нікого не показує, тобто меню зʼявляється на вісімдесят мілісекунд
			пізніше. Прив'язати затримку до порядку означало б обчислювати клас, а
			разом із ним і `data-testid` — тобто прибрати локатори з очей статичних
			перевірок (`src/testid-conventions.test.ts` збирає їх із розмітки).
		-->
		{#if dev}
			<a
				href={langPath(lang, 'reserve')}
				class="menu-btn menu-btn--game anim-stagger-1"
				data-testid="menu-reserve-link"
			>
				{@html formatFont(t('menu.reserve'))}
			</a>
		{/if}

		<a
			href={langPath(lang, 'quiz')}
			class="menu-btn menu-btn--game anim-stagger-2"
			data-testid="menu-quiz-link"
		>
			{@html formatFont(t('menu.quiz'))}
		</a>

		<a
			href={langPath(lang, 'pairs')}
			class="menu-btn menu-btn--game anim-stagger-3"
			data-testid="menu-pairs-link"
		>
			{@html formatFont(t('menu.game.memory'))}
		</a>

		<!--
			АКАУНТА ТУТ БІЛЬШЕ НЕМА — він переїхав у шапку, іконкою між мовою й
			повним екраном (`HeaderControls`).

			Причина рішення автора: акаунт потрібен там, де людина грає, а не лише
			на першому екрані. Аргумент, що стояв тут доти («у шапці живуть
			перемикачі вигляду»), і сам був слабкий: у шапці вже стоїть наскрізний
			рахунок.
		-->
	</nav>

	<div class="menu-links">
		{#each links as link (link.key)}
			<a href={link.href} class="menu-btn menu-btn--link" target="_blank" rel="noopener noreferrer">
				{@html formatFont(t(link.key))}
			</a>
		{/each}
	</div>
</div>

import { loadAccountText } from '$lib/i18n/account';
import { languageFromParam } from '$lib/i18n/routing';
import type { PageLoad } from './$types';

export { languageEntries as entries } from '$lib/i18n/entries';

/**
 * Словник сторінки приїжджає РАЗОМ ЗІ СТОРІНКОЮ, а не після неї.
 *
 * Доти рядки довантажувалися в `onMount`, і ціна цього була названа в
 * компоненті так: «на мить видно `account.signInTitle`». Заміряно в зібраному
 * сайті — мить виявилася не миттю. У `build/account/index.html` лежало
 * пʼятнадцять сирих ключів: `account.signInTitle`, `account.email`,
 * `account.password`, `account.signIn` — тобто ВЕСЬ підпис форми входу. Це те,
 * що бачить пошуковик, прев'ю посилання в месенджері й кожен, у кого JS ще не
 * виконався. Ті самі пʼятнадцять — у кожній з чотирьох мов.
 *
 * `load` розвʼязує саме це: під час пререндеру він виконується ДО малювання, і
 * в HTML потрапляє готовий текст. На клієнті він виконується перед показом
 * сторінки, тобто першого кадру з ключами немає взагалі.
 *
 * Вибір між «ключі» й «порожні підписи», записаний у компоненті, був вибором із
 * двох поганих: третій варіант — мати текст вчасно — там просто не розглядався.
 * Запобіжник `?? key` лишився на місці й нічого не коштує.
 *
 * Мова береться з АДРЕСИ, а не з налаштувань: під час пререндеру налаштувань
 * ще немає, а `settings.applyRouteLocale()` у layout і так виводить локаль
 * саме з параметра маршруту.
 *
 * Чанк лишається окремим: словник не повертається в головний, тож бюджет
 * кореневого layout не рухається.
 */
export const load: PageLoad = async ({ params }) => ({
	accountText: await loadAccountText(languageFromParam(params.lang))
});

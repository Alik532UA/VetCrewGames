import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';

/**
 * ШТАМП ВЕРСІЇ ПРАВИЛ НЕ ВІДСТАВ ВІД ЇХНЬОГО ВМІСТУ.
 *
 * ## Чому це тест, а не лише крок у CI
 *
 * Забути перештампувати правила легко: правку робиш у `database.rules.json`, а
 * штамп живе там же, тільки в іншому місці, і `npm run check:rules` на це не
 * дивиться — він перевіряє поведінку, а не мітку. Якщо розходження ловить лише
 * CI, то дізнаєшся про нього після пуша; `npm test` автор запускає щоразу, тож
 * тут воно ловиться на місці.
 *
 * ## Чому запуск скрипта, а не власний підрахунок
 *
 * Порахувати хеш тут удруге означало б ДВІ реалізації того самого правила
 * («хешуємо семантику без коментарів і без блока штампа»). Розійшлися б вони
 * тихо: тест лишався б зеленим, а штамп у правилах — неправильним. Тому
 * реалізація одна, а тест її ЗАПУСКАЄ.
 *
 * ## Чому це можна робити в юніт-тесті
 *
 * `rules-stamp.mjs --check` читає два файли й нічого більше: ні емулятора, ні
 * мережі, ні Java. Саме тому він тут, на відміну від `check:rules`, який без
 * живого емулятора або падає, або тихо пропускається — і стає перевіркою, якої не
 * запускає ніхто (AI-AGENT-PITFALLS-v8 § 1.3).
 */
describe('штамп версії правил', () => {
	it('збігається з семантикою правил і з константою в коді', () => {
		let output = '';
		try {
			output = execFileSync('node', ['scripts/rules-stamp.mjs', '--check'], {
				encoding: 'utf8',
				stdio: ['ignore', 'pipe', 'pipe']
			});
		} catch (error) {
			const failure = error as { stdout?: string; stderr?: string };
			expect.fail(
				`штамп розійшовся з правилами:\n${failure.stderr ?? ''}${failure.stdout ?? ''}\n` +
					'Виконати: npm run rules:stamp'
			);
		}
		// Перевірка, яка захищає перевірку: скрипт, що нічого не сказав, міг би
		// «пройти» через порожній вивід.
		expect(output).toContain('збігається з вмістом правил');
	});

	/**
	 * Штамп мусить бути ПРОЧИТНИЙ із правил тим самим виразом, яким його шукають
	 * і зонд (`check-rules-live.mjs`), і гейт (`check-rules.mjs`).
	 *
	 * Три місця читають один рядок однаковою регуляркою. Якщо форма блока
	 * зміниться, зламаються всі три — але зламаються ТИХО: зонд просто не знайде
	 * штампа й скаже «немає блока». Цей тест робить поломку гучною.
	 */
	it('блок штампа має ту саму форму, яку шукають зонд і гейт', () => {
		const rules = readFileSync('database.rules.json', 'utf8');
		const stamp = /\$v === '([0-9a-f]+)'/.exec(rules)?.[1];
		expect(stamp, 'у database.rules.json немає блока __rulesVersion').toBeTruthy();
		expect(stamp).toHaveLength(12);

		const declared = /RULES_VERSION = '([0-9a-f]+)'/.exec(
			readFileSync('src/lib/net/rulesVersion.ts', 'utf8')
		)?.[1];
		expect(declared, 'константа в коді не читається тим самим виразом').toBe(stamp);
	});
});

import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';

/**
 * У РЕПОЗИТОРІЇ НЕМА ПРИВАТНИХ КЛЮЧІВ.
 *
 * ## Чому це потрібно саме тут і саме тепер
 *
 * З появою автоматичного викладання правил у проєкті вперше з'явився ключ, який
 * СПРАВДІ є секретом: приватний ключ сервісного акаунта Firebase. Він обходить
 * правила безпеки цілком — тобто це не «ще один пароль», а повний доступ до бази
 * незалежно від усього, що написано в `database.rules.json`.
 *
 * Firebase віддає його файлом у Downloads, з іменем на кшталт
 * `vet-crew-games-firebase-adminsdk-fbsvc-a1b2c3.json`. Один рух у теку проєкту
 * плюс `git add -A` — і ключ у git НАЗАВЖДИ: історію можна переписати, але
 * вважати ключ скомпрометованим доведеться однаково.
 *
 * `.gitignore` від цього захищає, але лише поки ім'я файлу збігається зі шаблоном.
 * Перейменований, вкладений у підтеку, вставлений у скрипт «на хвилинку» — і
 * шаблон не діє. Тому тут перевіряється не ім'я, а ВМІСТ.
 *
 * ## Чому `git grep`, а не власний обхід файлів
 *
 * `git grep` дивиться на те, що git ВІДСЛІДКОВУЄ, — тобто рівно на те, що
 * поїде в репозиторій. Власний обхід теки додав би `node_modules` і `build/`
 * (де ключа й не мусить бути), а головне — не відрізнив би відстежуване від
 * проігнорованого й червонів би на ключі, який лежить у теці ЗАКОННО, поки
 * `.gitignore` його ховає.
 *
 * ## Що це НЕ ловить
 *
 * Ключ, який уже в історії комітів: `git grep` без ревізії дивиться на робочу
 * копію. Пошук по всій історії (`git log -p -S`) на кожному прогоні тестів
 * коштував би секунд і зростав би з роками. Це названа межа, а не недогляд:
 * перевірка ловить те, що НЕ ДАЄ ключу потрапити в git, а не те, що вже сталося.
 */
describe('приватних ключів у репозиторії немає', () => {
	/**
	 * Ознаки, за якими видно саме приватний ключ, а не згадку про нього.
	 *
	 * Рядки розбиті конкатенацією НАВМИСНО: інакше цей самий тест став би файлом,
	 * що містить шукану ознаку, і перевірка падала б на собі.
	 */
	const MARKERS = [
		{ pattern: '-----BEGIN' + ' PRIVATE KEY', what: 'тіло приватного ключа PEM' },
		{ pattern: '"private' + '_key"', what: 'поле приватного ключа в JSON сервісного акаунта' },
		{ pattern: '"type": "service' + '_account"', what: 'JSON сервісного акаунта' }
	];

	it('жодного маркера приватного ключа у відстежуваних файлах', () => {
		const found: string[] = [];

		for (const { pattern, what } of MARKERS) {
			// Без початкового значення: `continue` у `catch` не дає дійти до читання
			// неприсвоєної змінної, а порожній рядок тут ESLint справедливо вважає
			// зайвим (`no-useless-assignment`).
			let hits: string;
			try {
				hits = execFileSync('git', ['grep', '--fixed-strings', '--files-with-matches', pattern], {
					encoding: 'utf8'
				});
			} catch {
				// `git grep` виходить із кодом 1, коли не знайшов НІЧОГО. Це успіх, а не
				// збій: саме такий результат ми й перевіряємо.
				continue;
			}
			const files = hits
				.split('\n')
				.map((line) => line.trim())
				.filter(Boolean)
				// Цей файл згадує маркери в описі — за побудовою.
				.filter((file) => file !== 'src/no-secrets.test.ts');
			for (const file of files) found.push(`${file} — ${what}`);
		}

		expect(
			found,
			`У РЕПОЗИТОРІЇ ЗНАЙДЕНО ПРИВАТНИЙ КЛЮЧ:\n${found.join('\n')}\n\n` +
				'Ключ сервісного акаунта обходить правила безпеки цілком. Прибрати з робочої ' +
				'копії, покласти в секрет репозиторію, і ВІДКЛИКАТИ його в Firebase Console, ' +
				'якщо він уже потрапив у комміт.'
		).toEqual([]);
	});

	/**
	 * Перевірка, яка захищає перевірку.
	 *
	 * `git grep`, що не працює (немає git, не той каталог), виходить із кодом 1 —
	 * тобто нашою умовою «нічого не знайдено». Зелений результат тоді означав би
	 * «перевірка не виконалася», і виглядав би точно як «усе гаразд». Тому окремо
	 * стверджується, що пошук узагалі щось знаходить.
	 */
	it('пошук живий: знаходить те, що напевно є', () => {
		const hits = execFileSync(
			'git',
			['grep', '--fixed-strings', '--files-with-matches', 'RULES_VERSION'],
			{ encoding: 'utf8' }
		);
		expect(hits).toContain('src/lib/net/rulesVersion.ts');
	});
});

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * НОВИЙ ДЕПЛОЙ НЕ ЛАМАЄ ВІДКРИТУ ВКЛАДКУ.
 *
 * ## Що це стереже
 *
 * Дефект із проду, дослівно з консолі автора:
 *
 *     GET .../_app/immutable/nodes/2.W34Pfrl5.js net::ERR_ABORTED 404
 *     [ERROR] [APP] Unhandled client error {message: 'Internal Error', status: 500}
 *
 * Натиск «дім» зі сторінки результатів. Причина не в кнопці й не в маршруті:
 * сторінку відкрили ДО деплою. Кожна збірка перейменовує частини застосунку за
 * хешем вмісту, тож перелік адрес у відкритій вкладці показує на файли, яких на
 * сервері вже немає. Перевірено на проді: та сама адреса й далі віддає 404, а
 * `_app/version.json` уже інший.
 *
 * ## Чому три пункти, і чому кожен окремо
 *
 * Оборона з трьох частин, і кожна поодинці НІЧОГО не робить:
 *
 *  1. `version.pollInterval` — без нього `updated.current` не стає правдою
 *     ніколи, бо на статичному сайті відповіді сервера, з якої це можна було б
 *     дізнатися, не існує. Тобто без цього рядка пункт 2 — мертвий код;
 *  2. `beforeNavigate` у кореневому layout — переводить перехід на повне
 *     завантаження ДО помилки. Без нього опитування версії ні на що не впливає;
 *  3. запасний шар у `handleError` — ловить деплой, що стався між двома
 *     опитуваннями, тобто саме той випадок, який автор і побачив.
 *
 * Прибрати можна будь-яку з трьох, і зникне вона тихо: помилка вертається лише в
 * рідкому збігу «сторінка відкрита, деплой стався, гравець перейшов».
 *
 * ## Чому по джерелах, а не поведінкою
 *
 * Відтворити це поведінкою означало б підняти мережу, зробити дві збірки й
 * підмінити хеші між ними — тобто перевіряти складання Vite, а не своє рішення.
 * Тут стережуться самі рішення, і кожне ламається одним рядком.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — чотири, кожен червонив
 * рівно свій пункт: `pollInterval` прибрано з конфігу; `beforeNavigate` прибрано з
 * layout; умову `updated.current` знято (тобто повне завантаження на КОЖНОМУ
 * переході); захист від циклу прибрано з `handleError`. Усі чотири зроблені.
 */

const CONFIG = 'svelte.config.js';
const LAYOUT = 'src/routes/+layout.svelte';
const HOOKS = 'src/hooks.client.ts';

const read = (path: string) => readFileSync(path, 'utf8');

/** Коментарі цитують те, чого в коді немає, — знімаємо перед пошуком. */
const code = (path: string) =>
	read(path)
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:])\/\/.*/g, '$1 ');

describe('нова збірка й відкрита вкладка', () => {
	it('версія перепитується — інакше про нову збірку ніхто не дізнається', () => {
		expect(code(CONFIG), 'опитування версії вимкнене').toMatch(/version:\s*\{[^}]*pollInterval/);
	});

	it('перехід при новій версії — повним завантаженням', () => {
		const layout = code(LAYOUT);
		expect(layout, 'перехід не перехоплюється').toContain('beforeNavigate(');
		expect(layout, 'умови «є нова версія» немає — повне завантаження на кожному переході').toMatch(
			/updated\.current/
		);
		expect(layout, 'перехід не віддається браузеру').toMatch(/window\.location\.href =/);
		/*
		 * Вихід зі сторінки не підмінюється: там нема чого рятувати, а присвоєння
		 * `location.href` посеред такого переходу лише скасувало б те, що вже йде.
		 */
		expect(layout, 'вихід зі сторінки теж перехоплюється').toMatch(/willUnload/);
	});

	it('запасний шар ловить те, що прослизнуло між опитуваннями', () => {
		const hooks = code(HOOKS);
		/*
		 * Текст помилки в трьох браузерах різний, і перевіряються всі три: у Firefox і
		 * Safari формулювання інші, ніж у Chromium, — тобто «перевірив у себе» тут
		 * означало б «працює в одному браузері з трьох».
		 */
		expect(hooks, 'помилка «частини немає» не розпізнається').toMatch(
			/dynamically imported module/
		);
		expect(hooks, 'розпізнається лише Chromium').toMatch(/Importing a module script failed/);
		expect(hooks, 'людину вертають не туда, куди вона йшла').toMatch(
			/window\.location\.href = event\.url\.href/
		);
	});

	it('запасний шар не крутить цикл перезавантажень', () => {
		/*
		 * Якщо частина зникла не через деплой, а тому що збірка справді зламана,
		 * перезавантаження нічого не виправить — і без позначки сторінка
		 * перезавантажувалася б вічно. Дефект «не відкривається» перетворився б на
		 * «браузер не відпускає», і це гірше за початковий.
		 *
		 * Позначка живе в СЕСІЙНОМУ сховищі: закрив вкладку — забули, тобто наступна
		 * спроба своя. І пам'ятає саму адресу, а не сам факт: інша сторінка пізніше в
		 * тій самій сесії має право на свою спробу.
		 */
		const hooks = code(HOOKS);
		expect(hooks, 'перезавантаження без захисту від циклу').toMatch(/sessionStore\.get\(/);
		expect(hooks, 'позначка не ставиться — захист не працює').toMatch(/sessionStore\.set\(/);
		expect(hooks, 'позначка не привʼязана до адреси').toMatch(/!== event\.url\.href/);
	});
});

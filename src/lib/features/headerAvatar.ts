/**
 * АВАТАРКА В ШАПЦІ — і чому вона монтується імперативно.
 *
 * ## Бюджет, і чому саме він тут вирішує
 *
 * Шапка лежить у чанку кореневого layout, тобто приїжджає КОЖНОМУ відвідувачеві.
 * Той чанк стоїть рівно на бюджеті (110 КБ gzip зі стелі 110, `npm run
 * check:build`) — і 0,85 КБ із них саме ця аватарка: рахунок по частинах стоїть
 * у самому гейті, там же й причина, чому стелю піднято з 120. `Avatar.svelte`
 * при цьому тягне за собою чотирнадцять значків
 * `lucide-svelte` — по одному на кожен вибір. Заміряно: статичний імпорт у шапці
 * дає 123 КБ, тобто на три кілобайти понад стелю. Платили б ці три кілобайти всі,
 * зокрема ті, хто аватарки не вибирав ніколи.
 *
 * Динамічний імпорт САМОГО КОМПОНЕНТА не помагає: `{#if Cmp}<Cmp />{/if}` тягне в
 * layout помічник Svelte для змінних компонентів, і саме він і є зайва вага —
 * той самий висновок уже записаний у `features/awaitedBanner.ts`.
 *
 * Тому монтуємо самі: у layout лишається один динамічний імпорт цього файлу, а
 * значки приїжджають лише тому, хто аватарку справді вибрав. Той, хто не вибирав,
 * бачить звичайний значок акаунта — і не платить нічого.
 *
 * ## Чому це не «поза застосунком»
 *
 * Плитка малюється ВСЕРЕДИНІ посилання на акаунт, у вузол, який дає шапка. Вона
 * нічого не читає з контексту — ні `page`, ні `settings`, лише свій проп, — тож
 * життя поза деревом компонентів для неї нічим не відрізняється.
 */

/**
 * Намалювати аватарку в переданому вузлі. Повертає прибирання.
 *
 * НЕ КИДАЄ на невдачі імпорту: аватарка — підпис, а не дія. Якщо чанк не
 * приїхав, у шапці лишається звичайний значок акаунта, і це рівно те, що бачить
 * той, хто аватарку не вибирав.
 */
export async function paintAvatar(target: HTMLElement, avatar: string): Promise<() => void> {
	try {
		const [{ mount, unmount }, panel] = await Promise.all([
			import('svelte'),
			import('$lib/components/ui/Avatar.svelte')
		]);
		const app = mount(panel.default, { target, props: { avatar, size: 24 } });
		return () => void unmount(app, { outro: false });
	} catch {
		return () => {};
	}
}

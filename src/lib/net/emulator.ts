/**
 * DEV ІДЕ В ЛОКАЛЬНИЙ ЕМУЛЯТОР FIREBASE, а не в справжню базу (прохання автора 2026-09-27).
 *
 * Доти `npm run dev` ходив у продакшн-проєкт, і кожна нова гілка правил (автоматичний
 * пошук — `seek`) у dev не працювала аж до релізу: CI викладає правила лише після push у
 * `main`. На dev автор чув «нові правила ще не опубліковані», а перевірити зміну міг лише
 * в проді. Емулятор бере правила з цього ж дерева (`firebase.dev.json` →
 * `database.rules.json`), тож правка правил видна в dev одразу. Так само вже зроблено в
 * сусідньому `AudioRemote`.
 *
 * ## Чому прапорець не доживе до збірки
 *
 * Доти тут стояло протилежне рішення — «змішувати не можна навіть через прапорець: саме
 * так прапорець і лишився б увімкненим у збірці» (`emulatorSession.ts`). Воно про прапорець,
 * який ЧИТАЄТЬСЯ в рантаймі. Цей — `import.meta.env.DEV`: збірка підставляє на його місце
 * `false`, і гілка емулятора вирізається разом із демо-проєктом. Що вирізалася, доводить
 * `check:build` на зібраному сайті (у бандлі немає ні `demo-vet-crew-games`, ні портів
 * емулятора), а не лише цей коментар.
 *
 * ## `npm run dev:live` — dev на справжній базі
 *
 * `vite dev --mode live`: той самий dev, але з продакшн-проєктом — коли треба зайти в кімнату
 * з телефона, відкритого на живому сайті. Правила там ті, що викладені, і запис іде в живу
 * базу: це свідомий вибір того, хто цю команду запускає.
 *
 * ## Порти
 *
 * Свої, окремі від `check:rules` (`firebase.json`: 9010/9109): інакше dev-емулятор, що
 * працює, валив би гейт відмовою «порт зайнятий», а гейт — dev. Збіг цих чисел із
 * `firebase.dev.json` і з CSP у `svelte.config.js` тримає `src/dev-emulator.test.ts`.
 */
export const EMULATOR: boolean = import.meta.env.DEV && import.meta.env.MODE !== 'live';

/*
 * ЗНАЧЕННЯ — ЛИШЕ ПІД `EMULATOR`, а не просто константами. Гілки `if (EMULATOR)` у
 * `firebase.ts` мінімізатор вирізає, а ІМПОРТИ констант лишалися: у збірці їхав окремий
 * шматок на 128 байтів — демо-проєкт, `127.0.0.1` і порти (спіймав `check:build`
 * на першій же збірці). Тернарник згортається тут-таки, у самому модулі.
 */

/** Демо-проєкт: префікс `demo-` емулятор приймає без ключів, і в хмарі такого немає. */
export const EMULATOR_PROJECT = EMULATOR ? 'demo-vet-crew-games' : '';

export const EMULATOR_HOST = EMULATOR ? '127.0.0.1' : '';

export const EMULATOR_PORTS = EMULATOR ? { database: 9011, auth: 9110 } : { database: 0, auth: 0 };

/** Чим його запустити — ця команда стоїть і в тості «емулятор не відповідає». */
export const EMULATOR_COMMAND = 'npm run emulators';

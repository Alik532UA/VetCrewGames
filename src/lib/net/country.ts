import { isCountry } from '$lib/config/countries';
import { logService } from '$lib/services/logService.svelte';

/**
 * Країна за IP — ПІДКАЗКА, а не факт.
 *
 * ## Що це і чого це не є
 *
 * Автор просив показувати прапор гравця, визначаючи країну за IP. Я заперечив, і
 * заперечення лишається в силі: IP дає країну ПРОВАЙДЕРА або VPN, а не людини.
 * Діаспора, мобільний оператор, будь-який тунель — і прапор бреше, показуючи це
 * як факт. Прапор при цьому річ політично навантажена: чужий прапор на гравцеві
 * гірший за відсутній.
 *
 * Автор зважив це й обрав середнє: визначення за IP лишається, але ЛИШЕ як
 * початкове значення, яке людина міняє одним вибором. Тобто відповідальність за
 * прапор належить людині, а служба лише пропонує.
 *
 * ## Чому саме `api.country.is`
 *
 * Він віддає РІВНО країну й IP — і нічого більше. Це не дрібниця: решта
 * безкоштовних служб без ключа (`ip-api.com`, `fwd.gr`, `BigDataCloud`) віддають
 * місто, провайдера, координати, часовий пояс. Нам потрібні дві літери, а зайві
 * дані — це зайві дані про дитину, які ми попросили в третьої сторони без
 * потреби.
 *
 * HTTPS і CORS без ключа; домен доданий у `connect-src` політики CSP — інакше
 * браузер заблокував би запит, і прапор просто не з'являвся б.
 *
 * ## ЦІНА, ЯКУ ТРЕБА НАЗВАТИ
 *
 * Це запит до сторонньої служби, і в ньому їдe IP відвідувача. Тому запит
 * робиться ОДИН РАЗ і лише коли країни ще немає у сховищі — тобто рівно на
 * першому відкритті сторінки спільної гри, а не на кожному завантаженні сайту.
 * Хто прапор не хоче, той міняє його на «без прапора», і більше нічого не
 * питається.
 *
 * НЕ КИДАЄ. Прапор — оздоба: без нього гра працює цілком, тож невдача тут
 * означає «прапора не буде», а не «щось зламалося».
 */

/** Куди питати. Одне місце — щоб домен у CSP і в коді не розійшлися. */
export const COUNTRY_API = 'https://api.country.is/';

/**
 * Скільки чекати відповіді. Дві секунди — не «щоб швидко»: форма входу вже на
 * екрані, і прапор доїжджає до неї, а не тримає її. Довше чекання нічого не
 * додає, бо людина за цей час уже читає список кімнат.
 */
const TIMEOUT_MS = 2000;

export async function detectCountry(): Promise<string | null> {
	try {
		const response = await fetch(COUNTRY_API, {
			signal: AbortSignal.timeout(TIMEOUT_MS),
			// Кеш браузера тут доречний: країна за той самий IP не міняється, а
			// повторний запит — це ще одна згадка IP у чужому журналі.
			cache: 'force-cache'
		});
		if (!response.ok) return null;

		const data: unknown = await response.json();
		const code =
			typeof data === 'object' && data !== null && 'country' in data
				? (data as { country: unknown }).country
				: null;

		// Перевіряємо ЧУЖУ відповідь: код, якого немає в наборі прапорів, дав би
		// `<img>` на неіснуючий файл — порожню рамку замість прапора.
		if (!isCountry(code)) return null;
		return String(code).toLowerCase();
	} catch (error) {
		// `warn`, не `error`: не з'явився прапор — не поламалася гра. Причина в
		// журналі потрібна, бо найчастіша з них (заблоковано розширенням чи
		// політикою) виглядає точно як «служба не відповіла».
		logService.warn('network', 'country not detected', { reason: String(error) });
		return null;
	}
}

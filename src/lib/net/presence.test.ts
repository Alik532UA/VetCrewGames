import { describe, expect, it } from 'vitest';
import { othersWaiting } from './presence';

/**
 * ХТО ЧЕКАЄ МЕНЕ В КІМНАТІ — для смуги «вас чекають у грі» (аудит 2026-09-25).
 *
 * Присутність одна на людину, а не на вкладку. Доти друга вкладка (чи інший
 * пристрій) показувала «вас чекають» для партії, яку людина саме грає, і її «піти»
 * викидало живу вкладку з кімнати.
 *
 * Зворотний експеримент: рахувати інших, не дивлячись на себе, — червоніє другий.
 */
describe('хто чекає мене', () => {
	it('перевірка жива: інші є, мене немає — чекають', () => {
		expect(othersWaiting({ 'uid-a': { at: 1 }, 'uid-b': { at: 2 } }, 'uid-me')).toBe(2);
	});

	it('я вже в кімнаті з іншої вкладки — мене ніхто не чекає', () => {
		expect(othersWaiting({ 'uid-a': { at: 1 }, 'uid-me': { at: 2 } }, 'uid-me')).toBe(0);
	});

	it('порожня присутність — нікого', () => {
		expect(othersWaiting(null, 'uid-me')).toBe(0);
	});
});

import { connect } from './firebase';
import { logService } from '$lib/services/logService.svelte';

/**
 * ПЕРЕЛІК ПУБЛІЧНИХ КІМНАТ — `lobby/{code}`.
 *
 * ## Задача, і чому вона довго не мала розв'язку
 *
 * Зайти в спільну партію доти можна було лише за пʼятилітерним кодом, який хтось
 * мусив продиктувати. Тобто гра «з незнайомцем» була неможлива в принципі, і не
 * через недогляд: код кімнати І Є її пароль, тому правила бази прямо забороняють
 * ПЕРЕЛІЧУВАТИ `rooms` — інакше всі коди читалися б одним запитом.
 *
 * ## Рішення: окрема гілка, і ціна названа прямо
 *
 * Ключ тут — той самий код кімнати, а гілка читається списком. Отже запис у
 * `lobby` ВІДДАЄ КОД усім авторизованим: для цієї кімнати код перестає бути
 * паролем. Це не побічний ефект, а весь сенс публічної кімнати — у неї й мусить
 * зайти незнайомець.
 *
 * Тому рішення явне й лишається за господарем: прапорець «закрита кімната» у
 * формі входу означає рівно «не писати сюди». Закрита кімната поводиться так, як
 * поводилися всі до появи цієї гілки, і жодного права в неї не відібрано.
 *
 * Розкриття ВИБІРКОВЕ й ОБОРОТНЕ: зняв запис — кімната знову лише за кодом. Саме
 * цього не дав би дозвіл читати `rooms` списком: там розкриття було б спільним
 * для всіх кімнат і незворотним для тих господарів, які про це не просили.
 *
 * ## Що тут лежить, а чого немає
 *
 * Лише те, що й так побачить кожен, хто зайде: імʼя господаря (воно вже в
 * `members`) і скільки гравців. НЕМАЄ `seed` і `config` — вони визначають
 * роздачу, і читати їх, не заходячи, означало б бачити дошку суперника до
 * першого ходу. Правило бази це не просто не радить, а забороняє (`$other:
 * false`), і негативний випадок «у перелік кладуть зерно роздачі» стоїть у
 * `npm run check:rules`.
 *
 * ## Хто пише
 *
 * Тільки господар, і тільки про свою кімнату. Кількість гравців веде він же: він
 * єдиний, хто підписаний на склад і має право писати сюди. Побічний наслідок
 * названий і прийнятний: якщо господар закрив вкладку, число застигає — але тоді
 * `onDisconnect` уже прибирає й сам запис.
 */

/** Форма запису в переліку. Рівно ті поля, що дозволяє правило. */
export interface LobbyRoom {
	/** Код кімнати. У базі це КЛЮЧ, тут — поле, щоб список був простим масивом. */
	code: string;
	hostUid: string;
	hostName: string;
	/** Прапор господаря. Відсутнє = без прапора; правило дозволяє обидва. */
	hostCountry?: string;
	gameId: string;
	rulesVersion: number;
	players: number;
	/** Серверний час публікації. За ним список упорядковується. */
	at: number;
}

/**
 * Оголосити свою кімнату публічною.
 *
 * `onDisconnect` домовляється ПРИБРАТИ запис — і робиться це ДО самого запису.
 * Порядок не косметика: у зворотному є вікно, де запис уже є, а домовленості про
 * прибирання ще немає, і зникнення вкладки в цю мить лишає в списку привида
 * назавжди. Той самий порядок і з тієї самої причини — у `net/presence.ts`.
 *
 * Повертає функцію «зняти з переліку». Кличеться вона в трьох випадках: партія
 * почалася, господар закрив кімнату, сторінка вивантажилась.
 */
export async function publishRoom(entry: Omit<LobbyRoom, 'at'>): Promise<() => void> {
	const { db } = await connect();
	const { onDisconnect, ref, remove, serverTimestamp, set } = await import('firebase/database');
	const node = ref(db, `lobby/${entry.code}`);

	await onDisconnect(node).remove();
	await set(node, {
		hostUid: entry.hostUid,
		hostName: entry.hostName,
		/*
		 * `...(entry.hostCountry ? { hostCountry: entry.hostCountry } : {})` —
		 * поле або є, або його немає ЗОВСІМ.
		 *
		 * `undefined` усередині обʼєкта `set()` у Firebase КИДАЄ, а порожній
		 * рядок не пройшов би `.validate` (там рівно дві літери). На цьому вже
		 * одного разу зникав хід `peek`.
		 */
		...(entry.hostCountry ? { hostCountry: entry.hostCountry } : {}),
		gameId: entry.gameId,
		rulesVersion: entry.rulesVersion,
		players: entry.players,
		at: serverTimestamp()
	});

	return () => void remove(node);
}

/**
 * Оновити кількість гравців у своєму записі.
 *
 * НЕ КИДАЄ. Список — довідка, а не стан партії: невдале оновлення числа лишає в
 * списку старе значення, і найгірший наслідок цього — хтось зайде в кімнату, де
 * місць уже немає, і стане глядачем. Кинути звідси означало б зламати лобі
 * господаря через несправність довідки.
 */
export async function updatePlayers(code: string, players: number): Promise<void> {
	try {
		const { db } = await connect();
		const { ref, set } = await import('firebase/database');
		await set(ref(db, `lobby/${code}/players`), players);
	} catch (error) {
		logService.warn('network', 'lobby player count not updated', { code, reason: reasonOf(error) });
	}
}

/** Зняти кімнату з переліку. Так само не кидає — і з тієї самої причини. */
export async function unpublishRoom(code: string): Promise<void> {
	try {
		const { db } = await connect();
		const { ref, remove } = await import('firebase/database');
		await remove(ref(db, `lobby/${code}`));
	} catch (error) {
		logService.warn('network', 'lobby entry not removed', { code, reason: reasonOf(error) });
	}
}

/**
 * Скільки записів переліку ПОКАЗУВАТИ.
 *
 * Не про трафік, а про сторінку: список на екрані має бути оглядним, а не
 * прокруткою на сотню рядків. Двадцяти більш ніж досить — публічних кімнат у грі
 * такого розміру одночасно бувають одиниці. Обрізку видно в інтерфейсі окремим
 * рядком, а не мовчки (NO-SILENT-CAPS).
 *
 * ЦЕ ЧИСЛО БІЛЬШЕ НЕ ЄДИНА МЕЖА. Доти стеля жила лише тут, у клієнті, — тобто
 * була ввічливим проханням: той самий SDK із консолі браузера читав гілку цілком.
 * Тепер обмеження вимагає ПРАВИЛО (`query.limitToLast <= 25` у
 * `database.rules.json`), а це число лишається межею ПОКАЗУ.
 */
export const LOBBY_LIMIT = 20;

/**
 * Просимо на один більше, ніж показуємо.
 *
 * Так «є ще» стає ФАКТОМ, а не здогадкою: приїхало 21 — значить двадцять першу
 * ми не показуємо, і про це можна сказати. Точну кількість кімнат при цьому не
 * знає ніхто, і знати не мусить: обмежений запит на те й обмежений.
 */
const LOBBY_FETCH = LOBBY_LIMIT + 1;

/**
 * Підписка на перелік публічних кімнат — ОБМЕЖЕНИМ запитом.
 *
 * ## Що тут було й чому змінилося
 *
 * Доти це було `onValue` на всю гілку з міркуванням «вибірка й так менша за сотню
 * записів, читати її цілком дешевше, ніж тримати індекс». Міркування вірне для
 * ЦІНИ й хибне для МЕЖІ: стеля в 20 записів жила лише в клієнті, тобто той самий
 * SDK із консолі браузера читав гілку цілком незалежно від неї. Ідею взято з
 * `MindStep`, де та сама межа стоїть правилом: `allow list: if
 * request.query.limit <= 50`.
 *
 * Тепер обмеження ВИМАГАЄ правило (`query.orderByChild === 'at' &&
 * query.limitToLast <= 25`), тож запит тут — умова доступу, а не оптимізація. І
 * `.indexOn: "at"` у правилах став обовʼязковим: без нього база віддає гілку
 * цілком і сортує на клієнті, лишивши попередження, якого в продакшні не читає
 * ніхто, — тобто межа діяла б, а економія зникла б.
 *
 * Найновіші СПЕРШУ: свіжа кімната — це та, у якій ще хтось сидить і чекає. База
 * впорядковує зростаюче, тож порядок перевертається на клієнті.
 *
 * ## Чому `hasMore`, а не «усього N»
 *
 * Обмежений запит не знає повної кількості — і клієнт теж. Тому замість «показано
 * 20 із 34» тепер «показано найновіші, є ще»: на питання «чи все я бачу» це
 * відповідає так само, а числа, якого ніхто не знає, не вигадує.
 */
export interface LobbyWatcher {
	/**
	 * `hasMore` замість «усього N»: запит обмежений правилом, тож повної кількості
	 * не знає навіть клієнт. На питання «чи все я бачу» це відповідає так само.
	 */
	onRooms: (rooms: LobbyRoom[], hasMore: boolean) => void;
	/**
	 * Перелік НЕ ЧИТАЄТЬСЯ — окремий обробник, а не порожній список.
	 *
	 * Перша редакція на помилці підписки кликала `onRooms([], 0)`, і сторінка
	 * показувала «Відкритих кімнат поки немає». Тобто «правила не викладені»
	 * виглядало точно як «ніхто не створив кімнату» — і заміряно це було в
	 * браузері саме так: напис про порожній список на сторінці, де насправді
	 * бракує прав. Найгірший різновид повідомлення: воно не бреше про факт, але
	 * веде до хибного висновку.
	 */
	onUnavailable: (reason: string) => void;
}

export async function watchLobby(watcher: LobbyWatcher): Promise<() => void> {
	const { db } = await connect();
	const { limitToLast, off, onValue, orderByChild, query, ref } = await import(
		'firebase/database'
	);
	/*
	 * ЗАПИТ, А НЕ ЧИТАННЯ ГІЛКИ, і без нього правило тепер відмовить.
	 *
	 * `orderByChild('at')` плюс `limitToLast` — обидва названі в правилі, тобто це
	 * не оптимізація, а умова доступу. Побічно зникла й потреба сортувати весь
	 * список: база віддає рівно найновіші.
	 */
	const branch = query(ref(db, 'lobby'), orderByChild('at'), limitToLast(LOBBY_FETCH));

	const handler = onValue(
		branch,
		(snapshot) => {
			const raw = (snapshot.val() ?? {}) as Record<string, Omit<LobbyRoom, 'code'>>;
			const all = Object.entries(raw)
				.map(([code, entry]) => ({ ...entry, code }))
				/*
				 * База впорядкувала за `at` ЗРОСТАЮЧЕ, а показувати треба найновіші
				 * першими — тож порядок перевертається тут.
				 *
				 * `at` може не приїхати, якщо запис саме зараз створюється: серверна
				 * позначка розкривається на сервері, і між записом і підтвердженням
				 * клієнт бачить своє власне значення. Нуль ставить такий запис у кінець,
				 * а не викидає його зі списку.
				 */
				.sort((a, b) => (b.at ?? 0) - (a.at ?? 0));
			// Приїхало більше, ніж показуємо, — отже щось лишилося за межею запиту.
			watcher.onRooms(all.slice(0, LOBBY_LIMIT), all.length > LOBBY_LIMIT);
		},
		(error) => {
			// Майже завжди «правила ще не викладені». Сторінка від цього не ламається:
			// зайти за кодом і створити кімнату можна й без переліку.
			logService.warn('network', 'lobby not readable', { reason: error.message });
			watcher.onUnavailable(error.message);
		}
	);

	return () => off(branch, 'value', handler);
}

const reasonOf = (error: unknown): string =>
	error instanceof Error ? error.message : String(error);

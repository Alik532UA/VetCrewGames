import { connect } from './firebase';
import { RULES_VERSION } from './rulesVersion';
import { logService } from '$lib/services/logService.svelte';

/**
 * ЧИ ВИКЛАДЕНІ В FIREBASE ТІ САМІ ПРАВИЛА, ЩО ЛЕЖАТЬ У ЦІЙ ЗБІРЦІ.
 *
 * ## Навіщо це в застосунку, коли є той самий зонд у CI
 *
 * CI відповідає на питання «чи виклали правила після останнього пуша». А питання
 * «чому в мене не працює список кімнат» ставить людина перед екраном — і доти
 * відповіді на нього не було ніде: сторінка чесно казала «перелік недоступний», а
 * чому саме недоступний (правила не викладені? немає мережі? зламався код?),
 * доводилося вгадувати.
 *
 * Цей рядок відповідає одним словом.
 *
 * ## Чому НА ВИМОГУ, а не при відкритті сторінки
 *
 * Читання вимагає авторизації, а вхід тут анонімний — тобто автоматична перевірка
 * заводила б обліковий запис Firebase кожному, хто просто відкрив сторінку
 * чеклиста. Кнопка лишає це рішення людині: перевірка потрібна рідко, а платити
 * за неї облікованим записом щоразу не варто.
 *
 * ## Чому відповідь ТРИСТАННА
 *
 * `stale` і `unknown` — різні речі, і злити їх в одне означало б збрехати. Немає
 * мережі, база недоступна, вхід не вдався — це «не знаю», а не «правила
 * відстали»; показати «відстали» на впалій мережі означало б відправити людину
 * викладати правила, які вже викладені.
 */
export type LiveRulesState =
	/** Штамп прочитався: у продакшні саме ця редакція. */
	| 'fresh'
	/** Відмова на очікуваному штампі: у продакшні ІНША редакція. */
	| 'stale'
	/** Не вдалося дізнатися: мережа, вхід, недоступна база. */
	| 'unknown';

export interface LiveRulesResult {
	state: LiveRulesState;
	/** Редакція, якої очікує ця збірка. Показується разом зі станом. */
	stamp: string;
}

/**
 * Спитати базу, чи діє редакція `RULES_VERSION`.
 *
 * Читається шлях `__rulesVersion/<штамп>`, за яким НЕМА даних і не мусить бути:
 * правила оцінюються до існування вузла, тож сама відповідь «дозволено/відмова» і
 * є версією. Порожній результат — це успіх, а не порожнеча.
 */
export async function checkLiveRules(): Promise<LiveRulesResult> {
	try {
		const { db } = await connect();
		const { get, ref } = await import('firebase/database');
		await get(ref(db, `__rulesVersion/${RULES_VERSION}`));
		return { state: 'fresh', stamp: RULES_VERSION };
	} catch (error) {
		/*
		 * `PERMISSION_DENIED` — це ВІДПОВІДЬ, а не збій: правила відкинули читання,
		 * отже цієї редакції в продакшні немає. Решта помилок (мережа, вхід,
		 * блокувальник) означає «не знаю», і плутати їх не можна.
		 *
		 * Розрізняється за текстом, бо Firebase SDK для RTDB кидає звичайний
		 * `Error` без коду — на відміну від Firestore, де є `FirebaseError.code`.
		 */
		const message = error instanceof Error ? error.message : String(error);
		const denied = /permission[_ ]denied/i.test(message);
		if (!denied) {
			logService.warn('network', 'live rules check inconclusive', { reason: message });
		}
		return { state: denied ? 'stale' : 'unknown', stamp: RULES_VERSION };
	}
}

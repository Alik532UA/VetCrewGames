import { ROOM_BEAT_MS } from '$lib/config/roomLife';

/**
 * СЕРЦЕБИТТЯ КІМНАТИ: «я тут», поки вона відкрита на екрані.
 *
 * ## Навіщо
 *
 * Без нього список «продовжити партію» не відрізняє покинуту кімнату від тієї, з
 * якої щойно вийшли: про кімнату відомо лише те, що вона існує, а це правда і
 * через тиждень. Присутність на це питання не відповідає — вона гасне разом із
 * вкладкою й забирає з собою час.
 *
 * ## Чому окремим модулем, а не ефектом на сторінці
 *
 * Бо сторінок дві — «Знайди пару» й вікторина, — і це рівно той борг, що вже
 * названий числом у їхніх докблоках: мережева обвʼязка в них повторюється майже
 * дослівно. Тут вона не повторюється: сторінці лишається `return
 * startRoomBeat(code)` в ефекті, тобто чотири рядки замість двадцяти в кожній.
 *
 * ## Що робить із невдачами
 *
 * Нічого. `transport.touch()` не кидає сам (це довідка про кімнату, а не хід), а
 * невдалий такт означає лише те, що кімната зайвий раз повисить у списку.
 */
export function startRoomBeat(code: string): () => void {
	let stopped = false;

	const beat = () => {
		if (stopped) return;
		void import('./rtdbRoom').then((net) => net.roomTransport(code).then((room) => room.touch()));
	};

	// Перший удар — ОДРАЗУ, а не через інтервал: інакше кімната, у яку зайшли й
	// одразу вийшли, лишалася б із позначкою від попереднього заходу.
	beat();
	const timer = setInterval(beat, ROOM_BEAT_MS);

	return () => {
		stopped = true;
		clearInterval(timer);
	};
}

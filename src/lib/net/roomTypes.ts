/**
 * Конверт спільної партії — те, що однакове для ВСІХ ігор проєкту.
 *
 * Тут навмисно немає жодного правила «Знайди пару». Узагальнювати треба конверт,
 * а не стан: кімната, склад учасників і ЖУРНАЛ ХОДІВ спільні, а зміст ходу й
 * правила лишаються свої в кожної гри. Тому нова гра — це адаптер плюс модуль
 * правил, і схема бази не змінюється.
 *
 * **Чому не «поле стану на всю гру».** Альтернатива, до якої тягне: кімната з
 * полем `gameState`, у яке всі учасники пишуть свій погляд на світ. Наслідків
 * три: правило доступу неможливо звузити (власника документа немає), останній
 * запис перетирає чужий, а примирення станів розростається захисними періодами
 * й прапорцями. Журнал ходів усього цього не має: хід — окрема дитина, яку
 * можна лише СТВОРИТИ. Розбір обох моделей — CLOUD-DATABASE-v8 § 8.
 *
 * **Авторитету немає ні в кого.** Стан партії — чиста функція від (`seed`,
 * склад гравців, журнал). Кожен учасник застосовує ті самі ходи в тому самому
 * порядку й отримує той самий стан; сервер для цього не потрібен. Звідси й
 * вимога детермінізму, яку тримають тести кожної гри.
 */

/**
 * Роль у кімнаті.
 *
 * Глядач — це УЧАСНИК із роллю, а не окремий механізм. Він отримує той самий
 * журнал і крутить ті самі правила, просто не має права дописувати. Щойно
 * зʼявився б окремий канал «результати для глядача», це перестало б бути
 * архітектурою й стало б екраном на кожну гру.
 */
export type Role = 'player' | 'spectator';

export interface Member {
	uid: string;
	/** Як його звати на екрані. Вільний рядок, не ключ перекладу. */
	name: string;
	role: Role;
	/**
	 * Порядок входу. Черга ходів рахується З НЬОГО, а не з порядку, у якому
	 * приїхали дані: два учасники могли б отримати склад у різній послідовності й
	 * розійтися на тому, чий зараз хід.
	 */
	order: number;
}

/** Стан кімнати. Партія починається, коли господар переводить її в `playing`. */
export type RoomStatus = 'lobby' | 'playing' | 'over';

export interface RoomInfo {
	/** Яка гра. Одна кімната — одна гра; змішувати їх нема сенсу. */
	gameId: string;
	/**
	 * Версія ПРАВИЛ гри, а не застосунку.
	 *
	 * Сайт роздається з кешу, тож двоє гравців легко опиняються на різних
	 * збірках. Детермінізм при цьому обертається проти нас: із того самого зерна
	 * різні правила дадуть різні світи, і виглядатиме це не як помилка версій, а
	 * як зламана гра. Тому кімната називає версію, а невідповідність — це відмова
	 * зайти, а не тихе розходження.
	 */
	rulesVersion: number;
	/** Зерно партії. Одне число замість усієї розкладки. */
	seed: number;
	status: RoomStatus;
	hostUid: string;
	/**
	 * Налаштування партії. Для конверта це непрозорий обʼєкт: що там усередині,
	 * знає лише адаптер конкретної гри.
	 */
	config: Record<string, number>;
	/**
	 * Коли партію почали — СЕРВЕРНИМ часом.
	 *
	 * Від цієї позначки рахується очікування ПЕРШОГО ходу, далі — від `at`
	 * попереднього. Без неї межа очікування не діяла б рівно там, де вона
	 * найпотрібніша: суперник, який зайшов у кімнату й одразу зник, тримав би
	 * першу чергу назавжди.
	 *
	 * Необовʼязкове: кімнати, створені до появи цього поля, лишаються читаними,
	 * а адаптер трактує відсутність як «межі ще немає».
	 */
	startedAt?: number;
}

/**
 * Один хід у журналі.
 *
 * `seq` — і порядок, і ключ: хід пишеться в `moves/{seq}` правилом «лише
 * створити». Тому повторний запис того самого номера відкидає САМА БАЗА, і
 * ідемпотентність не потребує ні перевірок на клієнті, ні сервера.
 */
export interface Move {
	seq: number;
	/** Хто зробив. Перевіряється при застосуванні — однаково в усіх. */
	by: string;
	/** Що зробив. Рядок, бо перелік ходів свій у кожної гри. */
	type: string;
	/**
	 * Коли зробив — СЕРВЕРНИМ часом, і це не метадані.
	 *
	 * На цій позначці стоїть єдине правило гри, залежне від часу: `yield`
	 * («суперник відпав, віддай чергу») дозволений лише тоді, коли попередній хід
	 * старіший за межу очікування. Час рахує сервер саме тому, що інакше гравець
	 * оголошував би чужий хід простроченим коли завгодно й забирав чергу; правило
	 * бази це й тримає — `at` мусить лягати у вікно навколо `now`.
	 *
	 * Необовʼязкове в ТИПІ, обовʼязкове в базі: підставний транспорт ставить його
	 * сам, а ходи з кімнат старішої версії правил читаються без нього.
	 */
	at?: number;
	/**
	 * Чим саме. Числа й короткі рядки.
	 *
	 * Спершу тут були лише числа — і першій же грі, якій потрібне слово чи літера,
	 * довелося б правити правила в консолі разом із релізом. Межа довжини рядка
	 * лишається у правилі бази: свій власний хід теж не має права нести
	 * мегабайтний рядок.
	 */
	payload?: Record<string, number | string>;
}

/** Знімок кімнати, який приходить із транспорту. */
export interface RoomSnapshot {
	info: RoomInfo;
	members: Member[];
	/** Журнал, відсортований за `seq`. Транспорт зобовʼязаний його впорядкувати. */
	moves: Move[];
}

/**
 * Транспорт кімнати. Дві реалізації: справжня база й підставна для тестів.
 *
 * Інтерфейс тут не для «гнучкості на майбутнє», а тому що правила спільної
 * партії інакше неперевірні: із живою базою кожна перевірка вимагала б мережі,
 * ключів і чужого часу. Із підставним транспортом ті самі правила
 * перевіряються двома учасниками в одному процесі.
 */
export interface RoomTransport {
	/** Підписка на знімки. Повертає функцію відписки. */
	watch(onSnapshot: (snapshot: RoomSnapshot) => void): () => void;
	/**
	 * Дописати хід. `false` означає, що номер уже зайнятий — тобто хтось
	 * зробив хід раніше, а цей ЗНИКАЄ. Це не помилка: журнал і є правда.
	 */
	append(move: Move): Promise<boolean>;
	/**
	 * Перевести кімнату в інший стан. Дозволено господареві.
	 *
	 * Перехід у `playing` заразом ставить `startedAt` серверним часом — одним
	 * записом, бо це та сама подія: партія почалася. Двома записами існувала б
	 * мить, у яку партія вже йде, а межа очікування ще не має від чого рахуватися.
	 */
	setStatus(status: RoomStatus): Promise<void>;
	/**
	 * Нова партія в ТІЙ САМІЙ кімнаті: нове зерно й порожній журнал.
	 *
	 * Одним записом, а не двома. Порядок тут не косметика: якби спершу змінилося
	 * зерно, усі роздали б нову колоду й програли на ній СТАРІ ходи, які ще
	 * лежать у журналі. Атомарна зміна такого проміжку не має.
	 */
	restart(seed: number): Promise<void>;
}

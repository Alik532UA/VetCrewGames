import { connect } from './firebase';
import { logService } from '$lib/services/logService.svelte';
import type { RoomInfo } from './roomTypes';

/**
 * Індекс СВОїх кімнат і прибирання за собою — `myRooms/{uid}/{code}`.
 *
 * **Чому окремий модуль, а не частина кімнати.** З тієї самої причини, що й
 * `presence.ts`: тут інша природа записів. `rtdbRoom.ts` описує кімнату, у якій
 * іде партія; цей файл не знає про партію нічого й існує рівно для однієї
 * задачі — щоб покинута кімната колись зникла. Змішані в одному файлі, вони
 * читаються як одне, і зʼявляється спокуса «прибирати заодно й чуже».
 *
 * **Задача, яку це вирішує.** Кімната, покинута в стані `playing` або `over`,
 * доти не прибиралася НІКИМ. `onDisconnect` знімає лише ту, у яку ніхто не
 * зайшов (лобі); партія, з якої всі просто закрили вкладку, лишалася назавжди.
 * Записано це було боргом із числом («~1 КБ»), і борг був правильний, але код
 * кімнати з пʼяти літер — ресурс скінченний: кожна вічна кімната назавжди
 * забирає з нього одне значення.
 *
 * **Чому індекс, а не запит.** Щоб знайти свої кімнати запитом, довелося б
 * читати `rooms` цілком (`orderByChild('info/hostUid')`) — тобто відкрити
 * перелік усіх кімнат, а це рівно те, що правила забороняють: код кімнати
 * перестав би бути її паролем. Індекс, який веде сам господар, дає ту саму
 * відповідь, не відкриваючи нічого. Заразом він не потребує `.indexOn`:
 * читається він за ключем, а не сортуванням (CLOUD-DATABASE-v8 § 7.4).
 *
 * **Чому це не той збирач, від якого застерігає § 9.3.** Щоб прибирати ЧУЖЕ,
 * потрібне право видаляти чуже — тобто дірка, яка заразом є готовим примітивом
 * «видалити всі кімнати». Тут прав не додано жодних: право «знести свою
 * кімнату» господар мав і без цього файлу, а збирач лише користується ним за
 * власним списком.
 *
 * **Найнадійніший варіант — не цей.** § 9.3 ставить першим заплановане завдання
 * на боці провайдера; воно вимагає тарифу Blaze й лишається записаним у
 * PROJECT-CONTEXT.md. Тут — третій варіант зі списку: власник прибирає своє.
 * Тобто покинуте лишається лише після падіння, а не завжди.
 */

/**
 * Скільки живе покинута кімната, перш ніж її можна знести.
 *
 * Дванадцять годин — не про місце, а про КОД: партія, яку хочуть продовжити
 * після перерви, у цю межу не впирається, а покинута назавжди — впирається.
 */
const ROOM_TTL_MS = 12 * 60 * 60 * 1000;

/**
 * Скільком записам індексу дивитися в очі за один прогін.
 *
 * Прибирання — супутня справа, і воно не має права затримувати створення
 * кімнати на десятки запитів. Двадцяти вистачає з запасом: більше кімнат за раз
 * одна людина не покидає, а якщо покинула — решта прибереться наступного разу.
 */
const PRUNE_LIMIT = 20;

/**
 * Запамʼятати свою кімнату. Невдача тут НЕ скасовує створення.
 *
 * Індекс потрібен лише збирачеві: кімната без запису в ньому працює бездоганно,
 * просто ніхто не прибере її автоматично — тобто найгірший наслідок цієї
 * невдачі дорівнює стану, який був до появи індексу. Кинути звідси означало б
 * не дати створити кімнату через несправність прибирання.
 */
export async function rememberOwnRoom(code: string): Promise<void> {
	try {
		const { uid, db } = await connect();
		const { ref, serverTimestamp, set } = await import('firebase/database');
		await set(ref(db, `myRooms/${uid}/${code}`), { at: serverTimestamp() });
	} catch (error) {
		logService.warn('network', 'own-room index not written', { code, reason: reasonOf(error) });
	}
}

/** Забути свою кімнату — коли її знесли навмисно. */
export async function forgetOwnRoom(code: string): Promise<void> {
	const { uid, db } = await connect();
	const { ref, remove } = await import('firebase/database');
	await remove(ref(db, `myRooms/${uid}/${code}`));
}

/**
 * Знести СВОЇ покинуті кімнати. Кличеться перед створенням наступної.
 *
 * **Чому не в лобі.** § 9.3 забороняє прибирання в клієнті, який відкрив
 * список, — і причина не в місці, а в правах. Тут господар точно є (він щойно
 * попросив кімнату), тож перевірити його власні кімнати саме час; прибирання,
 * привʼязане до відкриття списку, залежало б від того, чи хтось туди зайшов.
 *
 * **Ніколи не кидає.** Людина попросила кімнату, а не прибирання.
 */
export async function pruneOwnRooms(): Promise<void> {
	try {
		const { uid, db } = await connect();
		const { get, ref, remove } = await import('firebase/database');

		const index = await get(ref(db, `myRooms/${uid}`));
		if (!index.exists()) return;

		const codes = Object.keys(index.val() as Record<string, unknown>).slice(0, PRUNE_LIMIT);
		let removed = 0;

		for (const code of codes) {
			const snapshot = await get(ref(db, `rooms/${code}/info`));

			// Кімнати вже немає — отже, її знесли (виходом господаря чи
			// `onDisconnect` у лобі), а запис індексу лишився. Прибираємо запис.
			if (!snapshot.exists()) {
				await remove(ref(db, `myRooms/${uid}/${code}`));
				continue;
			}

			const info = snapshot.val() as Pick<RoomInfo, 'status'> & { createdAt?: number };
			/*
			 * Скінчена партія — одразу; решта — за віком.
			 *
			 * Вік рахується місцевим годинником проти СЕРВЕРНОЇ позначки, і це
			 * свідома неточність: розбіжність годинників на дванадцять годин
			 * неправдоподібна, а навіть якби вона була, під ніж пішла б лише ВЛАСНА
			 * кімната того, хто саме створює наступну.
			 */
			const abandoned =
				info.status === 'over' ||
				(typeof info.createdAt === 'number' && Date.now() - info.createdAt > ROOM_TTL_MS);
			if (!abandoned) continue;

			await remove(ref(db, `rooms/${code}`));
			await remove(ref(db, `myRooms/${uid}/${code}`));
			removed++;
		}

		if (removed > 0) logService.info('network', `abandoned rooms removed: ${removed}`);
	} catch (error) {
		logService.warn('network', 'own-room cleanup skipped', { reason: reasonOf(error) });
	}
}

const reasonOf = (error: unknown): string =>
	error instanceof Error ? error.message : String(error);

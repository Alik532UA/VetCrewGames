import { connect } from './firebase';
import { logService } from '$lib/services/logService.svelte';
import type { RoomInfo } from './roomTypes';

/**
 * Індекс СВОїх кімнат і прибирання за собою — `myRooms/{uid}/{code}`.
 *
 * **Чому окремий модуль, а не частина кімнати.** З тієї самої причини, що й
 * `presence.ts`: тут інша природа записів. `rtdbRoom.ts` описує кімнату, у якій
 * іде партія; цей файл не знає про партію нічого — він знає лише, ЯКІ кімнати
 * мої. Змішані в одному файлі, вони читаються як одне, і зʼявляється спокуса
 * «прибирати заодно й чуже».
 *
 * **Індекс відповідає на ДВА питання, і друге зʼявилося пізніше.** Спершу він
 * існував рівно для того, щоб покинута кімната колись зникла. Тепер із того
 * самого списку читається «партія, у яку можна вернутися»: людина, що вийшла зі
 * сторінки посеред гри, доти не мала дороги назад узагалі — код кімнати жив лише
 * в адресі, і адреса губилася разом із вкладкою.
 *
 * Друге питання нічого не змінило в правах: індекс і далі приватний
 * (`myRooms/{uid}`, читає лише його власник), і далі не дає доступу до чужого.
 * Але воно змінило ЦІНУ записів у ньому — див. `rememberOwnRoom`.
 *
 * **Задача, яку це вирішує.** Кімната, покинута в стані `playing` або `over`,
 * доти не прибиралася НІКИМ. `onDisconnect` знімає лише ту, у яку ніхто не
 * зайшов (лобі); партія, з якої всі просто закрили вкладку, лишалася назавжди.
 * Записано це було боргом із числом («~1 КБ»), і борг був правильний, але код
 * кімнати з пʼяти літер — ресурс скінченний: кожна вічна кімната назавжди
 * забирає з нього одне значення.
 *
 * **Чому індекс, а не запит.** Щоб знайти свої кімнати запитом, довелося б
 * читати `rooms` цілком (`orderByChild('info/hostUid')`) — тобто відкрити
 * перелік усіх кімнат, а це рівно те, що правила забороняють: код кімнати
 * перестав би бути її паролем. Індекс, який веде сам господар, дає ту саму
 * відповідь, не відкриваючи нічого. Заразом він не потребує `.indexOn`:
 * читається він за ключем, а не сортуванням (CLOUD-DATABASE-v8 § 7.4).
 *
 * **Чому це не той збирач, від якого застерігає § 9.3.** Щоб прибирати ЧУЖЕ,
 * потрібне право видаляти чуже — тобто дірка, яка заразом є готовим примітивом
 * «видалити всі кімнати». Тут прав не додано жодних: право «знести свою
 * кімнату» господар мав і без цього файлу, а збирач лише користується ним за
 * власним списком.
 *
 * **Найнадійніший варіант — не цей.** § 9.3 ставить першим заплановане завдання
 * на боці провайдера; воно вимагає тарифу Blaze й лишається записаним у
 * PROJECT-CONTEXT.md. Тут — третій варіант зі списку: власник прибирає своє.
 * Тобто покинуте лишається лише після падіння, а не завжди.
 */

/**
 * Скільки живе покинута кімната, перш ніж її можна знести.
 *
 * Дванадцять годин — не про місце, а про КОД: партія, яку хочуть продовжити
 * після перерви, у цю межу не впирається, а покинута назавжди — впирається.
 */
const ROOM_TTL_MS = 12 * 60 * 60 * 1000;

/**
 * Скільком записам індексу дивитися в очі за один прогін — і в збирача, і в
 * переліку «продовжити партію».
 *
 * Обидва читають індекс по одному запису, тож межа тут про КІЛЬКІСТЬ ЗАПИТІВ, а
 * не про показ. Прибирання — супутня справа, і воно не має права затримувати
 * створення кімнати на десятки запитів; так само й форма входу.
 *
 * Двадцяти вистачає з запасом: більше кімнат за раз одна людина не покидає, а
 * якщо покинула — решта прибереться наступного разу. Межа СПІЛЬНА навмисно:
 * збирач тримає індекс коротким, тож перелік упирається в неї лише тоді, коли
 * прибирання не спрацювало жодного разу.
 */
const PRUNE_LIMIT = 20;

/**
 * Партія, до якої я належу і в яку можна вернутися.
 *
 * `hostUid` тут не для показу, а для збирача: господар має право знести кімнату,
 * гість — лише свій запис індексу.
 */
export interface OwnRoom {
	code: string;
	gameId: string;
	status: 'lobby' | 'playing' | 'over';
	hostUid: string;
	amHost: boolean;
	/**
	 * Коли в кімнаті востаннє хтось був — СЕРВЕРНИЙ час, `info.aliveAt`.
	 *
	 * `undefined` — кімната зі старішої збірки, яка позначки ще не має; такі
	 * вважаються живими (`config/roomLife.ts`).
	 */
	aliveAt?: number;
}

/**
 * Запамʼятати свою кімнату. Невдача тут НЕ скасовує ні створення, ні вхід.
 *
 * **Кличеться і господарем, і гостем.** Спершу — лише при створенні, і саме тому
 * індекс знав кімнати, де я господар, і не знав тих, куди я зайшов. Для збирача
 * цього було досить (знести кімнату однаково може лише господар), а для «вернутися
 * в партію» — ні: пішов зі сторінки найчастіше саме гість.
 *
 * Найгірший наслідок невдачі — немає рядка «продовжити партію», і кімната
 * лишається досяжною за кодом, як і доти. Кинути звідси означало б не дати
 * зайти в гру через несправність довідки про неї.
 */
export async function rememberOwnRoom(code: string): Promise<void> {
	try {
		const { uid, db } = await connect();
		const { ref, serverTimestamp, set } = await import('firebase/database');
		await set(ref(db, `myRooms/${uid}/${code}`), { at: serverTimestamp() });
	} catch (error) {
		logService.warn('network', 'own-room index not written', { code, reason: reasonOf(error) });
	}
}

/** Забути свою кімнату — коли її знесли навмисно. */
export async function forgetOwnRoom(code: string): Promise<void> {
	const { uid, db } = await connect();
	const { ref, remove } = await import('firebase/database');
	await remove(ref(db, `myRooms/${uid}/${code}`));
}

/**
 * Знести СВОЇ покинуті кімнати. Кличеться перед створенням наступної.
 *
 * **Чому не в лобі.** § 9.3 забороняє прибирання в клієнті, який відкрив
 * список, — і причина не в місці, а в правах. Тут господар точно є (він щойно
 * попросив кімнату), тож перевірити його власні кімнати саме час; прибирання,
 * привʼязане до відкриття списку, залежало б від того, чи хтось туди зайшов.
 *
 * **Ніколи не кидає.** Людина попросила кімнату, а не прибирання.
 */
export async function pruneOwnRooms(): Promise<void> {
	try {
		const { uid, db } = await connect();
		const { get, ref, remove } = await import('firebase/database');

		const index = await get(ref(db, `myRooms/${uid}`));
		if (!index.exists()) return;

		const codes = Object.keys(index.val() as Record<string, unknown>).slice(0, PRUNE_LIMIT);
		let removed = 0;

		for (const code of codes) {
			const snapshot = await get(ref(db, `rooms/${code}/info`));

			// Кімнати вже немає — отже, її знесли (виходом господаря чи
			// `onDisconnect` у лобі), а запис індексу лишився. Прибираємо запис.
			if (!snapshot.exists()) {
				await remove(ref(db, `myRooms/${uid}/${code}`));
				continue;
			}

			const info = snapshot.val() as Pick<RoomInfo, 'status' | 'hostUid'> & {
				createdAt?: number;
			};
			/*
			 * Скінчена партія — одразу; решта — за віком.
			 *
			 * Вік рахується місцевим годинником проти СЕРВЕРНОЇ позначки, і це
			 * свідома неточність: розбіжність годинників на дванадцять годин
			 * неправдоподібна, а навіть якби вона була, під ніж пішла б лише ВЛАСНА
			 * кімната того, хто саме створює наступну.
			 */
			const abandoned =
				info.status === 'over' ||
				(typeof info.createdAt === 'number' && Date.now() - info.createdAt > ROOM_TTL_MS);
			if (!abandoned) continue;

			/*
			 * ГІСТЬ ЗНОСИТЬ ЛИШЕ СВІЙ ЗАПИС, а не кімнату.
			 *
			 * Права знести чужу кімнату немає — і не мусить бути: саме цим правом і
			 * була б дірка «видалити всі кімнати» (§ 9.3). Але доти цей рядок
			 * виконувався беззастережно, бо в індексі лежали лише кімнати господаря.
			 * Щойно туди почав писати й гість, той самий рядок став гарантованим
			 * `PERMISSION_DENIED` — а `catch` цього циклу обриває ВЕСЬ прогін, тобто
			 * одна чужа кімната в індексі вимикала прибирання власних.
			 */
			if (info.hostUid === uid) {
				await remove(ref(db, `rooms/${code}`));
				removed++;
			}
			await remove(ref(db, `myRooms/${uid}/${code}`));
		}

		if (removed > 0) logService.info('network', `abandoned rooms removed: ${removed}`);
	} catch (error) {
		logService.warn('network', 'own-room cleanup skipped', { reason: reasonOf(error) });
	}
}

/**
 * Партії, які вже йдуть і до яких я належу. Читається з ВЛАСНОГО індексу.
 *
 * **Чому не з переліку кімнат.** У `lobby` розпочатих партій немає навмисно: там
 * лежить те, куди ще можна ЗАЙТИ, і рядок про партію, що вже йде, обіцяв би гру,
 * а давав роль глядача. Класти їх туди означало б ще й розкрити код розпочатої
 * партії всім авторизованим — тобто зробити зі свого списку чужий.
 *
 * Індекс дає ту саму відповідь, не відкриваючи нічого: він приватний за
 * правилом (`myRooms/{uid}` читає лише власник), а `rooms/{code}/info`
 * читається тим, хто вже знає код, — а я його знаю, бо це моя кімната.
 *
 * **Лише `playing`.** Кімната в `lobby` — це не «партія, у яку вернутися», а
 * та, яку я щойно створив і не почав; вона й так відкрита в переліку. Скінчена
 * (`over`) не потребує повернення взагалі.
 *
 * **НЕ КИДАЄ.** Це довідка: її відсутність лишає сторінку такою, якою вона була
 * до появи цього списку, а кинути звідси означало б зламати форму входу через
 * несправність підказки.
 */
export async function listOwnRooms(): Promise<OwnRoom[]> {
	try {
		const { uid, db } = await connect();
		const { get, ref } = await import('firebase/database');

		const index = await get(ref(db, `myRooms/${uid}`));
		if (!index.exists()) return [];

		const codes = Object.keys(index.val() as Record<string, unknown>).slice(0, PRUNE_LIMIT);
		const rooms: OwnRoom[] = [];

		for (const code of codes) {
			const snapshot = await get(ref(db, `rooms/${code}/info`));
			if (!snapshot.exists()) continue;
			const info = snapshot.val() as RoomInfo;
			if (info.status !== 'playing') continue;
			rooms.push({
				code,
				gameId: info.gameId,
				status: info.status,
				hostUid: info.hostUid,
				amHost: info.hostUid === uid,
				aliveAt: info.aliveAt
			});
		}

		return rooms;
	} catch (error) {
		logService.warn('network', 'own rooms not listed', { reason: reasonOf(error) });
		return [];
	}
}

const reasonOf = (error: unknown): string =>
	error instanceof Error ? error.message : String(error);

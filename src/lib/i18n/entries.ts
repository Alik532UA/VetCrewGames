import { PREFIXED_LANGUAGES } from './routing';

/**
 * Перелік мовних варіантів, які треба ЗГЕНЕРУВАТИ (SVELTEKIT-DATA-v8 § 2.3).
 *
 * Без `entries()` краулер знаходить лише те, на що є посилання зі
 * згенерованих сторінок. Решта отримує SPA-фолбек: адреса відкривається, але
 * до виконання JavaScript показує типовий вміст — і саме його бачить
 * пошуковик та прев'ю в месенджері.
 *
 * `entries` — валідний експорт лише в `+page.ts`, тож кожен маршрут
 * реекспортує цю функцію одним рядком. Спокуса покласти її в `+layout.ts`
 * закінчується помилкою збірки, і це добре: інакше було б неочевидно, для
 * котрих саме сторінок перелік діє.
 *
 * `undefined` — голий шлях, на якому живе типова мова.
 */
export function languageEntries() {
	return [
		{ lang: undefined as string | undefined },
		...PREFIXED_LANGUAGES.map((lang) => ({ lang: lang as string | undefined }))
	];
}

import { loadReserveText } from './index';
import { languageFromParam } from '../routing';

/**
 * `load` для КОЖНОЇ сторінки заповідника: словник приїжджає разом зі сторінкою.
 *
 * ## Навіщо, якщо є `onMount`
 *
 * Доти рядки тягнув `onMount`, і ціна цього була названа в
 * `i18n/reserve/index.ts` так: «між першим кадром і приїздом чанку `t()` віддає
 * ключ». Заміряно в зібраному сайті — перший кадр тут не мить, а НАЗАВЖДИ:
 * пререндер малює сторінку до будь-якого чанку, тож у
 * `build/reserve/index.html` лежав двадцять один сирий ключ (`reserve.budget`,
 * `reserve.day`, `reserve.reputation`, кнопки швидкості), і по двадцять — у
 * кожній із чотирьох ділянок. Помножити на чотири мови.
 *
 * `load` виконується ДО малювання і на сервері, і на клієнті, тож ключів немає
 * ні в HTML, ні в першому кадрі.
 *
 * ## Чому спільна функція, а не пʼять однакових
 *
 * Сторінок пʼять — сама вітрина й чотири ділянки, — і `load` у них дослівно
 * один. Пʼять копій розійшлися б на першій же правці, а шоста сторінка
 * почалася б із копіювання пʼятої.
 *
 * ## Чому нічого не повертається
 *
 * `loadReserveText` ДОДАЄ рядки в той самий реєстр, з якого читає `t()` (на
 * відміну від `i18n/account`, який віддає словник пропом). Тобто повертати
 * нічого й не треба: після `await` двадцять чотири компоненти заповідника вже
 * бачать текст. Заразом це означає, що словник не серіалізується в дані
 * сторінки — 11,7 КБ на мову лишаються окремим чанком, а не в HTML.
 *
 * ## Мова — з АДРЕСИ
 *
 * Під час пререндеру налаштувань ще немає, а `settings.applyRouteLocale()` у
 * кореневому layout і так виводить локаль саме з параметра маршруту.
 */
export const load = async ({ params }: { params: { lang?: string } }): Promise<void> => {
	await loadReserveText(languageFromParam(params.lang));
};

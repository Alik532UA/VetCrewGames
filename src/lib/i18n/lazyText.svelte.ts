/**
 * СИГНАЛ «ДОВАНТАЖЕНІ РЯДКИ ЗМІНИЛИСЯ» — одна руна на весь застосунок.
 *
 * ## Навіщо окремий файл
 *
 * `i18n/index.ts` не може містити рун: його читають юніт-тести під
 * `environment: node`, і `$state` там не існує. Але `t()` мусить стати
 * залежним від довантаження — інакше компонент, намальований до приїзду чанку,
 * лишиться з ключем на екрані назавжди: `settings.locale` міняється лише при
 * зміні мови, а словник приїхав без неї.
 *
 * ## Чому лічильник, а не сам словник у руні
 *
 * Реєстр перекладів — звичайний обʼєкт, і робити його глибоко реактивним
 * означало б проксі на кількох тисячах рядків, які читаються на кожному кадрі.
 * Лічильник дає те саме: зміна числа перемальовує всіх, хто читав `t()`.
 */
class LazyText {
	/** Скільки разів реєстр поповнювався. Саме число нікого не цікавить. */
	version = $state(0);

	bump(): void {
		this.version += 1;
	}
}

export const lazyText = new LazyText();

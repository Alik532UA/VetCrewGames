/**
 * Чеклист бета-тестування: що саме має перевірити людина, яка захотіла допомогти.
 *
 * **Чому це дані, а не сторінка.** Список перевірок живе окремо від того, хто
 * його малює, бо на нього треба навести інваріанти — і саме вони роблять чеклист
 * кращим за текстовий файл. Текстовий файл ніхто не звіряє з кодом; цей —
 * звіряється на кожному `npm test`.
 *
 * **Дві мови в ОДНОМУ обʼєкті, а не у двох файлах.** У сусідньому проєкті
 * (`AndDvergrShallSpeakAI/Checklists`) чеклист лежить двома деревами файлів,
 * `uk/` і `en/`, і там знадобилося окреме правило про міжмовну відповідність:
 * однакові `id`, у тому самому порядку, стільки ж пунктів. Тут така відповідність
 * не потребує ні правила, ні перевірки — її вимагає ТИП: пункт без англійського
 * тексту просто не збереться.
 */

/** Текст, у якого дві мови обовʼязкові. de та nl показують англійський. */
export interface Localized {
	uk: string;
	en: string;
}

/**
 * Чи може цей пункт перевірити машина — і чи перевіряє.
 *
 * Порядок значень тут не алфавітний і не випадковий: це ПРІОРИТЕТ показу.
 * Людина витрачається спершу там, де машини немає, і лише в кінці — там, де
 * автотест уже дивиться. Останній рівень при цьому не зайвий: помилка, знайдена
 * в покритому місці, — це звіт про дефект ТЕСТА, а не гри, і він дорожчий за
 * звичайний баг, бо знецінює всі зелені прогони.
 */
export type Coverage =
	/** Око, палець, друга людина, справжній телефон. Машина цього не вміє. */
	| 'manual'
	/** Автотестом покрити можна — але покриття НЕМА. Тобто це ще й беклог тестів. */
	| 'testable'
	/** Покрито; файл названий у `test` і його існування перевіряє інваріант. */
	| 'covered';

/** Порядок показу: спершу те, чого машина не вміє. */
export const COVERAGE_ORDER: Record<Coverage, number> = { manual: 0, testable: 1, covered: 2 };

/**
 * Відповідь тестувальника.
 *
 * Чотири стани, а не два, і середній — найдорожчий: «працює, але дивно» ловить
 * саме те, що бінарне «так/ні» округляє до «так». Взято з чеклиста сусіднього
 * проєкту, де ці ж чотири стани стоять кнопками під кожним пунктом.
 */
export type Vote = 'none' | 'fail' | 'weird' | 'ok';

export interface BetaCheck {
	/**
	 * Ключ прогресу — тому СТАБІЛЬНИЙ назавжди.
	 *
	 * Перейменувати `reserve_7` означає стерти людині галочку: позначки лежать у
	 * сховищі саме за цим рядком. Нові пункти ДОПИСУЮТЬСЯ з новим номером;
	 * перенумеровувати наявні не можна навіть тоді, коли порядок змінився.
	 */
	id: string;
	/** Розділ усередині вкладки. Непорожній — інакше пункт нікуди не належить. */
	category: Localized;
	/**
	 * Що зробити й що мусить статися. Без слів «працює», «адекватно», «коректно»:
	 * у пункта має бути видимий чи чутний вияв, інакше двоє людей поставлять різні
	 * позначки на тому самому екрані.
	 */
	text: Localized;
	coverage: Coverage;
	/** Файл автотесту. Обовʼязковий для `covered`, заборонений для `manual`. */
	test?: string;
	/**
	 * `data-testid` елемента, про який пункт говорить.
	 *
	 * Не для тестувальника — для інваріанта: він перевіряє, що такий локатор у
	 * коді досі є. Пункт, який просить натиснути кнопку, якої вже немає, падає в
	 * CI, а не доїжджає до людини. Це наша відповідь на найдорожчу пастку
	 * чеклистів: список, що відстав від коду, каже «перевірено» про те, чого
	 * більше не існує.
	 */
	testid?: string;
	/**
	 * Перевірка МЕЖІ: «не мусить», «не має продовжувати».
	 *
	 * Найдорожчі дефекти тихі — ліміт, який перестав діяти, виглядає точно так
	 * само, як ліміт, що діє. Тому в кожної вкладки є хоч один такий пункт, і це
	 * вимагає інваріант.
	 */
	negative?: true;
}

export interface BetaTab {
	id: string;
	title: Localized;
	/**
	 * Які адреси ця вкладка накриває.
	 *
	 * Головне поле всього файлу. Інваріант вимагає, щоб КОЖЕН маршрут із
	 * `LANGUAGE_ROUTES` був заявлений рівно однією вкладкою, — отже нова гра без
	 * пунктів чеклиста валить `npm test`. Правило «як помітити, що чеклист відстав
	 * від коду» перестає бути правилом у документі й стає червоним прогоном.
	 */
	routes: readonly RouteRest[];
	checks: readonly BetaCheck[];
}

/**
 * Порядок вкладок — той, у якому їх варто проходити: спершу спільне (воно
 * ламається одразу в усіх іграх), далі те, де код найсвіжіший.
 */
export const BETA_TABS: readonly BetaTab[] = [
	commonTab,
	onlineTab,
	quizOnlineTab,
	reserveTab,
	memoryTab,
	populationTab,
	habitatTab,
	feedingTab,
	mythTab,
	familyTab
];

/**
 * Маршрути, які чеклист навмисно НЕ накриває.
 *
 * Рівно один — сама сторінка чеклиста. Пункти про інструмент перевірки
 * всередині цього ж інструмента нічого не додають: людина відкрила сторінку,
 * отже сторінка відкривається.
 */
export const BETA_UNCOVERED_ROUTES: readonly RouteRest[] = ['beta-test-checklists'];

/** Усі пункти підряд — для інваріантів і для звіту. */
export const allBetaChecks = (): BetaCheck[] => BETA_TABS.flatMap((tab) => [...tab.checks]);

/**
 * Пункти вкладки в порядку пріоритету.
 *
 * Усередині рівня зберігається порядок оголошення: він тематичний (пункти одного
 * розділу стоять поруч), і сортувати його ще й за чимось означало б розсипати
 * розділи. `sort` у V8 стабільний, тож достатньо сортувати лише за рівнем.
 */
export const sortedChecks = (tab: BetaTab): BetaCheck[] =>
	[...tab.checks].sort((a, b) => COVERAGE_ORDER[a.coverage] - COVERAGE_ORDER[b.coverage]);

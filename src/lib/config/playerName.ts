import { randomCrewName, type Translate } from './crewNames';

/**
 * Яке імʼя стоїть у формі входу — і коли його можна змінити за людину.
 *
 * ## Чому окремо від сторінки
 *
 * Тут два рішення, і жодне з них не видно з коду сторінки, якщо воно там
 * розсипане по `onMount` і callback-у підписки. Обидва — про межу між «наше» і
 * «людське»: підставлене імʼя ми маємо право перекинути, введене — ні. Помилка
 * в цій межі не падає й не помітна на тесті сторінки: вона виглядає як «поле
 * саме перескочило», і побачить її лише той, хто саме друкував.
 *
 * Функції ЧИСТІ й без рун: перекладач і джерело випадковості приходять
 * аргументами з тієї самої причини, що в `crewNames.ts` — `$lib/i18n` тягне
 * `settings`, а той у конструкторі кличе `window.matchMedia`, якого в jsdom
 * немає.
 */

/**
 * Ключ сховища. Імʼя памʼятається між заходами.
 *
 * Не зручність: сторінка заходить у кімнату заново після перезавантаження, і без
 * збереженого імені гравець перетворювався б на когось іншого — сам для себе й
 * для суперника, посеред партії.
 */
export const NAME_KEY = 'pairs.name';

/**
 * Ключ прапора. Поруч із іменем, бо це та сама відповідь «як мене видно».
 *
 * ВІДСУТНІСТЬ ключа й порожнє значення — РІЗНІ стани: `null` означає «ще не
 * питали» (і тоді можна спитати службу за IP), а `''` — «питали, відповіли:
 * без прапора». Без цієї різниці той, хто прапор прибрав, отримував би його
 * назад на кожному відкритті сторінки.
 */
export const COUNTRY_KEY = 'pairs.country';

export interface ChosenName {
	/** Що показати в полі. */
	name: string;
	/**
	 * Що з цього підставили МИ. Порожньо — імʼя обрала людина.
	 *
	 * Порівняння за ЗНАЧЕННЯМ, а не прапорець «авто»: людина могла ввести рівно
	 * те саме, що ми підставили, і тоді заміна була б проти її вибору.
	 */
	assigned: string;
}

/**
 * Імʼя для щойно відкритої сторінки.
 *
 * Поле НЕ буває порожнім: порожнє — це прохання вигадати, а вигадувати нікого не
 * просили. Імʼя тут лише для того, щоб суперник розумів, хто ходить; кому
 * підставлене не до душі, той натисне кубик або впише своє.
 *
 * Збережене імʼя не вважається підставленим, тож його не перекине ніщо: воно вже
 * вибір людини, навіть якщо колись прийшло з кубика.
 */
export function initialName(
	saved: string | null,
	translate: Translate,
	random: () => number,
	taken: readonly string[]
): ChosenName {
	if (saved !== null) return { name: saved, assigned: '' };
	const name = randomCrewName(translate, random, taken);
	return { name, assigned: name };
}

/**
 * Перекинути ПІДСТАВЛЕНЕ імʼя, якщо воно виявилося зайнятим. `null` — не чіпати.
 *
 * Кличеться, коли приїхав перелік кімнат: імʼя підставляється при відкритті
 * сторінки, тобто ДО того, як стало відомо, хто вже онлайн. Тому перша відповідь
 * неминуче може виявитися зайнятою — і виправити її можна лише тут.
 *
 * `null`, а не «те саме імʼя», навмисно: виклик, який завжди щось повертає,
 * читається як «перепиши поле», і сторінка перезаписувала б `name` на кожен
 * оновлений перелік. Порожній результат прямо каже «нічого робити».
 */
export function rerollIfTaken(
	current: string,
	assigned: string,
	translate: Translate,
	random: () => number,
	taken: readonly string[]
): string | null {
	// Не наше — не чіпаємо. Порожній `assigned` означає «імʼя обрала людина».
	if (assigned === '' || current !== assigned) return null;
	if (!taken.includes(current)) return null;
	return randomCrewName(translate, random, taken);
}

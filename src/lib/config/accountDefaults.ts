import { pickOne } from '$lib/utils/seededRandom';
import { CREW_ANIMALS, crewNameKey, type Translate } from './crewNames';

/**
 * ЩО СТОЇТЬ У ПОРОЖНІХ ПОЛЯХ ПРОФІЛЮ — імʼя в грі й @нік для пошуку.
 *
 * ## Чому не з пошти
 *
 * Автор запропонував підставляти в поля початок пошти, і від цього я відмовився з
 * однією причиною: @нік ПУБЛІЧНИЙ. Він стоїть у таблиці лідерів і за ним шукають
 * людей, тож із адреси `okolosov@…` типовим значенням став би `okolosov` — тобто
 * застосунок сам оприлюднив би частину пошти кожному. Саме від цього в проєкті
 * пошта лежить хешем, а не текстом (`net/account.ts`), і підстановка з неї
 * звела б ту роботу на нуль.
 *
 * ## Чому обидва поля з ОДНОГО ключа тварини
 *
 * Ключі імен команди латинські за побудовою (`pairs.crew.<id тварини>`), тож із
 * «Мудрої Сови» виходить `owl_482` — і видно, що це та сама людина. Два
 * незалежних жеребкування дали б «Мудру Сову» з ніком `panda_137`, і зв'язок,
 * заради якого це й робиться, зник би.
 *
 * ## Межі, які тримає сама форма ключа
 *
 * @нік мусить пройти `/^[a-z0-9_]{3,20}$/` — те саме правило, що в базі. Найдовший
 * ідентифікатор тварини — `passenger_pigeon` (16), плюс підкреслення й три
 * цифри — рівно 20. Тому нове імʼя тварини довше за шістнадцять символів
 * зламало б підстановку: перевірка на це стоїть в `accountDefaults.test.ts`.
 */
export interface AccountIdentity {
	/** Імʼя в грі: те, що бачать інші. */
	name: string;
	/** @нік для пошуку: латиниця, унікальний. */
	handle: string;
}

/** Скільки цифр дописується до ніка, щоб зменшити збіги. */
const SUFFIX_DIGITS = 3;

/**
 * Підставити імʼя й @нік для порожнього профілю.
 *
 * `translate` і `random` ПЕРЕДАЮТЬСЯ, а не беруться зсередини — той самий підпис,
 * що в `randomCrewName`, і з тієї самої причини: `Math.random()` усередині робить
 * поведінку неперевірною точно, а лише ймовірно. Плюс інваріант проєкту забороняє
 * `Math.random()` у конфігах.
 */
export function defaultIdentity(translate: Translate, random: () => number): AccountIdentity {
	const animal = pickOne(CREW_ANIMALS, random) ?? CREW_ANIMALS[0];
	const span = 9 * 10 ** (SUFFIX_DIGITS - 1);
	const suffix = Math.floor(random() * span) + 10 ** (SUFFIX_DIGITS - 1);
	return { name: translate(crewNameKey(animal)), handle: `${animal}_${suffix}` };
}

/**
 * Підрежим «Де живем?» за ідентифікатором гри. `null` — це інша гра.
 *
 * Тут, а не в дошці: `ONLINE_GAMES` — джерело правди про склад, і розбір його
 * власних ідентифікаторів належить йому. У компоненті це був би другий розбір
 * тих самих рядків.
 */
export function habitatModeOf(gameId: string): 'continents' | 'biomes' | null {
	if (gameId === 'habitat-continents') return 'continents';
	if (gameId === 'habitat-biomes') return 'biomes';
	return null;
}

/**
 * У РОЗРОБЦІ РАУНД УП'ЯТЕРО ДОВШИЙ.
 *
 * Сім секунд неможливо ні відлагодити, ні навіть прочитати умову, коли поруч
 * відкрита консоль. Множник просив автор саме таким; він діє ЛИШЕ в `dev`, тож
 * зібраний сайт грає з тими числами, що названі вище.
 */
export const DEV_TIME_FACTOR = 5;

/**
 * Скільки триває раунд цієї гри, у мілісекундах.
 *
 * `factor` — параметр, а не читання `dev` усередині: інакше числа неможливо
 * перевірити тестом в обидва боки, і перевірка доводила б лише те, що в тестах
 * `dev === false`.
 */
export function roundLimitMs(gameId: string, factor = 1): number {
	const game = ONLINE_GAMES.find((candidate) => candidate.id === gameId);
	// Невідома гра — кімната з новішої збірки. Беремо найкоротший раунд: партія
	// мусить рухатися далі, а не стояти на кроці, якого нам нічим грати.
	const seconds = game?.seconds ?? ONLINE_GAMES[0].seconds;
	return seconds * 1000 * factor;
}

/**
 * Скільки видно табло між раундами. Чотири секунди — як просив автор.
 *
 * Помножується на той самий `DEV_TIME_FACTOR`: інакше в розробці раунд ішов би
 * пʼять разів довше, а пауза лишалася б людською, і ритм партії розсипався б.
 */
export const REVEAL_MS = 4000;

/**
 * Скільки чекати після ОСТАННЬОЇ відповіді, перш ніж показати табло.
 *
 * Секунда, і вона потрібна: без паузи табло вискакує в ту саму мить, коли
 * останній гравець відпустив кнопку, і він не бачить власної відповіді на
 * дошці — лише те, що екран змінився.
 */
export const SETTLE_MS = 1000;

/**
 * Скільки раундів у партії.
 *
 * Дванадцять — це близько двох-трьох хвилин разом із таблом. Доти було шість
 * КРОКІВ по пʼять раундів, тобто тридцять питань: партія, яку не доводили до
 * кінця.
 */
export const QUIZ_ROUNDS = 12;

/** Найменше й найбільше очок за ПРАВИЛЬНУ відповідь. */
export const SLOW_POINTS = 50;
export const FAST_POINTS = 100;

/**
 * Очки за відповідь: правильність × швидкість.
 *
 * Обидві позначки часу — СЕРВЕРНІ (`at` у ходах), тож швидкість тут не
 * оголошена клієнтом, а порахована з журналу. Це те, що робить множник
 * перевірним; клієнт усе одно оголошує `correct`, і ця половина лишається
 * неперевірною — див. докблок на початку файлу.
 *
 * Миттєва відповідь — 100, на останній мілісекунді — 50, між ними лінійно.
 * Лінійно, а не кривою: гравець мусить розуміти, скільки втрачає, поки думає, а
 * крива робить втрату непередбачуваною саме там, де вона найбільша.
 *
 * `correct` — частка, а не булеве: у «Роздай страви» три страви, і дві з трьох
 * мусять давати дві третини очок, інакше гра стає «усе або нічого».
 */
export function answerPoints(
	answeredAt: number,
	roundStartedAt: number,
	limitMs: number,
	correct: number
): number {
	if (correct <= 0) return 0;
	const share = Math.min(1, correct);

	/*
	 * Відповідь ПОЗА вікном оцінюється як найповільніша, а не як нульова.
	 *
	 * Від'ємна різниця можлива: `at` ставить сервер із вікном у пʼять секунд, і
	 * хід міг отримати позначку раніше за старт раунду. Нуль очок за це був би
	 * покаранням за розсинхрон годинників, а не за повільність.
	 */
	const elapsed = Math.min(Math.max(answeredAt - roundStartedAt, 0), limitMs);
	const speed = limitMs === 0 ? 1 : 1 - elapsed / limitMs;
	return Math.round(share * (SLOW_POINTS + (FAST_POINTS - SLOW_POINTS) * speed));
}



/**
 * Префікс ключів налаштувань кімнати: `game_myths` → 1 або 0.
 *
 * ПІДКРЕСЛЕННЯ, А НЕ ТОЧКА, і це не стиль. Тут стояло `game.`, і Realtime
 * Database такий ключ не приймає взагалі: `.`, `#`, `$`, `/`, `[`, `]`
 * заборонені в іменах вузлів. SDK відкидає запис ще до мережі, тобто правила
 * доступу цього не бачать — `config/$key` вимагає лише `isNumber()`, і форму
 * ключа не перевіряв ніхто.
 *
 * Коштувало це всього режиму спільної вікторини: створення кімнати падало
 * ЗАВЖДИ, а на екрані стояло «Не вдалося зайти в кімнату. Спробуйте ще раз».
 * Причину ховав глухий `catch` у `net/rtdbRoom.ts` — він трактував будь-яку
 * відмову запису як «код зайнятий», тому цикл доростав до чотирьох цифр і
 * здавався. Обидва місця виправлені разом: без другого перше знову сховалося б.
 */
export const GAME_FLAG_PREFIX = 'game_';

/**
 * Налаштування кімнати з переліку вибраних ігор.
 *
 * Форма нав'язана конвертом: `info.config` — це `Record<string, number>`, і
 * правило бази дозволяє в ньому лише числа (`config/$key` → `isNumber`). Тому
 * вибір їде прапорцями 1/0, а не масивом рядків, — і схема бази не змінюється
 * ЗОВСІМ, тобто нової редакції правил ця гра не потребує.
 */
export function gamesToConfig(selected: readonly string[]): Record<string, number> {
	const config: Record<string, number> = {};
	for (const game of ONLINE_GAMES) {
		config[`${GAME_FLAG_PREFIX}${game.id}`] = selected.includes(game.id) ? 1 : 0;
	}
	return config;
}

/**
 * Перелік вибраних ігор із налаштувань кімнати.
 *
 * Порожній результат неможливий у грі, але можливий у ДАНИХ: кімната старішої
 * збірки, чужі руки, помилка в майбутньому. Тому порожнеча трактується як «усі» —
 * партія, що не почалася через порожній набір, виглядала б як поломка, а не як
 * порожній вибір.
 */
export function configToGames(config: Record<string, number>): string[] {
	const chosen = ONLINE_GAMES.filter((game) => config[`${GAME_FLAG_PREFIX}${game.id}`] === 1);
	return (chosen.length > 0 ? chosen : ONLINE_GAMES).map((game) => game.id);
}

/** Один крок програми: яка гра й із яким зерном. */
export interface QuizStep {
	game: string;
	/** Зерно цього кроку. Різне в кожного кроку, але однакове в усіх гравців. */
	seed: number;
}

/**
 * Програма партії — з ЗЕРНА КІМНАТИ, а не з випадковості клієнта.
 *
 * Це те саме міркування, що тримає роздачу в «Знайди пару»: усі учасники
 * отримують той самий список кроків, бо виводять його з того самого числа. Тому
 * тут `randomFor(seed)`, а не `Math.random()` — інваріант проєкту забороняє
 * останній у конфігах саме через це.
 *
 * Ігри чергуються ВИПАДКОВО, а не по колу: за фіксованого порядку шостий крок
 * завжди був би тією самою грою, і партія читалася б як розклад.
 */
export function quizProgramme(
	seed: number,
	games: readonly string[],
	rounds: number = QUIZ_ROUNDS
): QuizStep[] {
	const random = randomFor(seed);
	const pool = games.length > 0 ? games : ONLINE_GAMES.map((game) => game.id);
	return Array.from({ length: rounds }, () => ({
		game: pool[Math.floor(random() * pool.length)],
		/*
		 * Зерно кроку — ціле число з того самого генератора.
		 *
		 * Не `seed + index`: сусідні зерна в лінійному генераторі дають схожі
		 * послідовності, і два кроки тієї самої гри показали б майже ті самі
		 * питання. Тут кожен крок бере наступне число потоку, тож кроки незалежні,
		 * а вся програма однакова в усіх.
		 */
		seed: Math.floor(random() * 2 ** 31)
	}));
}

/**
 * СПІЛЬНА ВІКТОРИНА: які ігри в кімнаті, скільки триває раунд і як рахуються очки.
 *
 * ## Чим це відрізняється від «Знайди пару»
 *
 * Там гравці ходять ПО ЧЕРЗІ по спільній дошці. Тут усі відповідають ОДНОЧАСНО,
 * кожен на своєму екрані, і спільне — не дошка, а ПРОГРАМА (які питання й у
 * якому порядку), ЧАС (спільний дедлайн) і РАХУНОК.
 *
 * Програму дає зерно: усі пʼять ігор проєкту детерміновані за зерном, і це не
 * обіцянка, а перевірка — `controllers/quizSeed.test.ts` прогонює кожну до кінця
 * й порівнює послідовності.
 *
 * ## Які ігри доступні онлайн
 *
 * Не всі пʼять, і причина технічна. Онлайн-раунд вимагає ДОШКИ як компонента:
 * вона малюється всередині кімнати й не має ні власної навігації, ні екрана
 * підсумку. Такі дошки є в `MythCard` і `FeedingBoard` — обидві приймають
 * контролер або питання пропсом.
 *
 * У решти трьох дошка вплетена в сторінку: `HabitatRound` тримає власний
 * контролер без зерна, а «Хто зайвий» і «Хто численніший» компонента не мають
 * зовсім (374 і 1117 рядків розмітки в самих маршрутах). Тому вони тут
 * ВІДСУТНІ, а не вимкнені: `ONLINE_GAMES` — це те, що працює.
 *
 * Автор попросив шість ігор; борг на виніс решти записаний у
 * `PROJECT-CONTEXT.md` числом. Додати гру потім — це один рядок таблиці нижче
 * плюс дошка, яка приймає контролер.
 */

/**
 * ## РАУНД, А НЕ КРОК — і це переписана модель, не налаштування
 *
 * Доти одиницею був КРОК: ціла міні-гра з пʼятьма раундами, яку кожен проходив
 * САМ і у своєму темпі. Спільного моменту не існувало ніде: хто закінчив
 * раніше, дивився на «чекаємо інших», а таймера не було зовсім (перевірено
 * пошуком: ні `setInterval`, ні `deadline` у жодному файлі вікторини).
 *
 * Автор назвав це прямо: «не відповідає базовим принципам алгоритмів в
 * більшості ігор вікторин». Тепер одиниця — РАУНД: усі бачать те саме питання,
 * дедлайн спільний, після нього табло.
 *
 * ## Один раунд — один контролер із `totalRounds = 1`
 *
 * Це те, що зробило переписування дешевим. Усі пʼять контролерів ігор уже
 * приймають `(totalRounds, seed)`, а `quizSeed.test.ts` доводить, що за
 * однакового зерна послідовність однакова. Тобто «одне питання» — це просто
 * контролер на один раунд, і жодної нової механіки роздачі не потрібно.
 *
 * ## Час і рахунок беруться з СЕРВЕРНОГО часу, і нової редакції правил не треба
 *
 * Старт раунду — це ХІД у журналі (`type: 'round'`), а `at` у ходів уже ставить
 * сервер: правило `moves/$seq` вимагає `at` у вікні пʼяти секунд від `now`.
 * Тому швидкість відповіді — це різниця двох СЕРВЕРНИХ позначок, і підробити її
 * клієнт не може.
 *
 * Це й робить рахунок чистою функцією від журналу — тією самою властивістю, на
 * якій стоїть «Знайди пару». Ціна, що лишається: клієнт усе одно оголошує, чи
 * відповів ПРАВИЛЬНО. Ця половина неперевірна, і так і залишається — щоб
 * перевіряти її, дошка мусила б бути спільною, тобто це була б інша гра.
 */

/** Гра, доступна у спільній вікторині. */
export interface OnlineGame {
	/** Ключ у налаштуваннях кімнати. Коротко, бо їде в `info.config`. */
	id: string;
	/**
	 * Ключ назви у словнику — той самий, що в меню.
	 *
	 * `TranslationKey`, а не `string`, і це не педантизм. Перша редакція мала
	 * тут `string`, а компонент писав `t(game.nameKey as TranslationKey)` — і
	 * приведення сховало помилку: у ключах стояло `menu.mythbusters` замість
	 * `menu.game.mythbusters`. `svelte-check` промовчав (його ж і обійшли),
	 * `check:i18n` теж (ключ у словнику є, просто інший), і на екрані
	 * замість назв ігор стояли самі ключі. Знайдено оком у браузері.
	 */
	nameKey: TranslationKey;
	/**
	 * СКІЛЬКИ СЕКУНД НА ОДИН РАУНД ЦІЄЇ ГРИ.
	 *
	 * Число своє на гру, а не спільне, і це не смак. «Міфи» — один тап по
	 * «правда/міф». «Роздай страви» — перетягнути три страви на три мішені,
	 * причому мишею й на телефоні по-різному. Однакові сім секунд зробили б другу
	 * гру не швидкою, а недосяжною: гравець не встигав би фізично, і множник за
	 * швидкість перетворився б на податок на складнішу гру.
	 */
	seconds: number;
}


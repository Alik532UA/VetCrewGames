export const REVEAL_PACE: Record<QuizPace, number> = { fast: 1, normal: 1.75, slow: 3 };

/** Швидкість із налаштувань кімнати. Невідоме число — типова. */
export function paceFromConfig(config: Record<string, number>, key: string): QuizPace {
	return QUIZ_PACES[config[key] ?? -1] ?? DEFAULT_PACE;
}

/**
 * Налаштування кімнати ЦІЛКОМ: і набір ігор, і обидві швидкості.
 *
 * Одна функція, а не дві, і це не зручність. `setConfig` пише обʼєкт ПОВНІСТЮ —
 * тобто зміна набору ігор окремим викликом стерла б швидкість, а зміна швидкості
 * стерла б набір. Складати їх мусить одне місце, інакше кожен новий виклик
 * доводиться згадувати про всі попередні.
 */
export function quizConfig(
	games: readonly string[],
	roundPace: QuizPace,
	revealPace: QuizPace
): Record<string, number> {
	return {
		...gamesToConfig(games),
		[PACE_ROUND_KEY]: QUIZ_PACES.indexOf(roundPace),
		[PACE_REVEAL_KEY]: QUIZ_PACES.indexOf(revealPace)
	};
}

/**
 * ЧИ ПІДХОДИТЬ КІМНАТА ПІД ФІЛЬТР «у що я хочу грати».
 *
 * ## Умова: набір кімнати ⊆ вибраного
 *
 * Не перетин, і це різні речі на екрані. Перетин («хоч одна спільна») пустив би
 * у список кімнату з усіма шістьма іграми за будь-якого фільтра: вибравши одні
 * «Міфи», людина потрапила б у партію, де пʼять раундів із шести — те, що вона
 * щойно зняла. Тобто фільтр працював би, а результат був би той самий.
 *
 * Підмножина читається просто: «покажи кімнати, де НЕ попадеться те, чого я не
 * хочу». Типовий стан фільтра — усі ігри, тож типово він не приховує НІЧОГО, а
 * звужується разом із вибором.
 *
 * ## Кімната без оголошеного набору
 *
 * `configToGames` порожній набір трактує як «усі» (див. вище), і тут це працює
 * саме так, як треба: кімната, яка свій набір не оголосила, може зіграти в що
 * завгодно, тож ховається щойно фільтр звузили. Показувати її при вузькому
 * фільтрі означало б обіцяти те, чого ніхто не обіцяв.
 */
export function roomFitsGames(
	games: Record<string, number> | undefined,
	wanted: readonly string[]
): boolean {
	return configToGames(games ?? {}).every((game) => wanted.includes(game));
}

/** Один крок програми: яка гра й із яким зерном. */
export interface QuizStep {
	game: string;
	/** Зерно цього кроку. Різне в кожного кроку, але однакове в усіх гравців. */
	seed: number;
}

/**
 * Програма ПЕРЕВІРКИ: кожен крок — ІНША гра, без повторів.
 *
 * ## Чим відрізняється від `quizProgramme`
 *
 * Та вибирає гру на кожен крок незалежно, тобто з повтореннями: у партії на
 * дванадцять кроків це правильно — інакше шостий крок завжди був би тією самою
 * грою, і партія читалася б як розклад.
 *
 * Перевірка «зробити самому» в заповіднику коротка — пʼять кроків, — і автор
 * попросив саме різні ігри: «кожне з питань з різних міні ігор». З
 * повтореннями пʼять кроків давали б у середньому три різні гри, а не пʼять, і
 * доволі часто одну й ту саму двічі підряд.
 *
 * ## Що це робить із порогом 70%
 *
 * Нічого. Ціна раунду різна («Правда чи міф» — три очки, «Що їмо» — до
 * чотирьох), але поріг рахується від НАБРАНОГО максимуму (`isSuccess(points,
 * max)`), а не від числа раундів. Тобто набір ігор змінює масштаб обох чисел
 * однаково. Саме через це раніше тут стояла одна гра на всі пʼять кроків — і
 * причина виявилася хибною: пропорція не зсувається.
 *
 * ## Чому перемішування, а не «беремо перші `rounds`»
 *
 * Ігор шість, кроків пʼять — без перемішування одна й та сама гра завжди
 * лишалася б за бортом, а порядок був би той самий у кожній перевірці.
 * Перемішування — Фішер-Йейтс на тому самому зерні, тож перевірка лишається
 * відтворюваною в тестах.
 *
 * Якщо кроків просять більше, ніж є ігор, повтори неминучі — тоді колода
 * перемішується заново, а не добирається випадково: інакше «різні ігри»
 * перестало б бути правдою навіть для перших шести.
 */
export function distinctProgramme(seed: number, rounds: number): QuizStep[] {
	const random = randomFor(seed);
	const steps: QuizStep[] = [];
	let deck: string[] = [];

	while (steps.length < rounds) {
		if (deck.length === 0) {
			deck = ONLINE_GAMES.map((game) => game.id);
			// Фішер-Йейтс: кожна перестановка рівноймовірна, і зерно те саме.
			for (let i = deck.length - 1; i > 0; i--) {
				const j = Math.floor(random() * (i + 1));
				[deck[i], deck[j]] = [deck[j], deck[i]];
			}
		}
		steps.push({
			game: deck.pop() as string,
			// Те саме, що в `quizProgramme`: наступне число потоку, а не `seed + index`.
			seed: Math.floor(random() * 2 ** 31)
		});
	}

	return steps;
}

/**
 * Програма партії — з ЗЕРНА КІМНАТИ, а не з випадковості клієнта.
 *
 * Це те саме міркування, що тримає роздачу в «Знайди пару»: усі учасники
 * отримують той самий список кроків, бо виводять його з того самого числа. Тому
 * тут `randomFor(seed)`, а не `Math.random()` — інваріант проєкту забороняє
 * останній у конфігах саме через це.
 *
 * Ігри чергуються ВИПАДКОВО, а не по колу: за фіксованого порядку шостий крок
 * завжди був би тією самою грою, і партія читалася б як розклад.
 */
export function quizProgramme(
	seed: number,
	games: readonly string[],
	rounds: number = QUIZ_ROUNDS
): QuizStep[] {
	const random = randomFor(seed);
	const pool = games.length > 0 ? games : ONLINE_GAMES.map((game) => game.id);
	return Array.from({ length: rounds }, () => ({
		game: pool[Math.floor(random() * pool.length)],
		/*
		 * Зерно кроку — ціле число з того самого генератора.
		 *
		 * Не `seed + index`: сусідні зерна в лінійному генераторі дають схожі
		 * послідовності, і два кроки тієї самої гри показали б майже ті самі
		 * питання. Тут кожен крок бере наступне число потоку, тож кроки незалежні,
		 * а вся програма однакова в усіх.
		 */
		seed: Math.floor(random() * 2 ** 31)
	}));
}

import { randomFor } from '$lib/utils/seededRandom';
import type { TranslationKey } from '$lib/i18n/translations/uk';

/**
 * СПІЛЬНА ВІКТОРИНА: які ігри в кімнаті й у якому порядку вони йдуть.
 *
 * ## Модель партії, і чому вона інша, ніж у «Знайди пару»
 *
 * У «Знайди пару» гравці ходять ПО ЧЕРЗІ по спільній дошці, тож стан партії —
 * чиста функція від журналу ходів, і дошка в усіх однакова.
 *
 * Вікторина влаштована навпаки: усі відповідають ОДНОЧАСНО, кожен на своєму
 * екрані. Спільного тут не дошка, а ПРОГРАМА (які питання й у якому порядку) і
 * РАХУНОК. Програму дає зерно: усі пʼять ігор проєкту детерміновані за зерном, і
 * це не обіцянка, а перевірка — `controllers/quizSeed.test.ts` прогонює кожну до
 * кінця й порівнює послідовності.
 *
 * Тому в журнал їде лише РЕЗУЛЬТАТ кроку: «гравець X набрав N на кроці K». Дошку
 * ніхто не відтворює — кожен грає свою.
 *
 * ## ЦІНА ЦІЄЇ МОДЕЛІ, названа прямо
 *
 * Результат неперевірний. Той, хто відкрив консоль, може дописати в журнал будь-яке
 * число — і жоден учасник цього не виявить, бо дошки в нього немає. У «Знайди
 * пару» такого не буває: там кожен хід перевіряють усі.
 *
 * Це властивість одночасної гри з приватними дошками, а не недогляд: щоб рахунок
 * став перевірним, дошка мусила б бути спільною — тобто це була б інша гра. Для
 * дитячої освітньої вікторини ціна прийнятна, і вона тут записана, щоб наступний
 * читач не вирішив, що про неї забули.
 *
 * ## Які ігри доступні онлайн
 *
 * Не всі пʼять, і причина технічна, а не задумана. Онлайн-крок вимагає ДОШКИ як
 * компонента: вона малюється всередині кімнати, поруч із рахунком, і не має
 * власної навігації чи екрана підсумку.
 *
 * Такі дошки є в двох ігор — `MythCard` і `FeedingBoard` (обидві приймають
 * контролер або питання пропсом). У решти трьох дошка вплетена в сторінку:
 * `HabitatRound` — це сторінка з навігацією й `GameOverCard`, а «Хто зайвий» і
 * «Хто численніший» узагалі не мають компонента (374 і 1117 рядків розмітки в
 * самих маршрутах).
 *
 * Тому вони тут відсутні, а не вимкнені: `ONLINE_GAMES` — це те, що ПРАЦЮЄ, а
 * борг на виніс решти записаний у `PROJECT-CONTEXT.md`. Додати гру потім — це
 * один рядок таблиці нижче.
 */

/** Гра, доступна у спільній вікторині. */
export interface OnlineGame {
	/** Ключ у налаштуваннях кімнати. Коротко, бо їде в `info.config`. */
	id: string;
	/**
	 * Ключ назви у словнику — той самий, що в меню.
	 *
	 * `TranslationKey`, а не `string`, і це не педантизм. Перша редакція мала
	 * тут `string`, а компонент писав `t(game.nameKey as TranslationKey)` — і
	 * приведення сховало помилку: у ключах стояло `menu.mythbusters` замість
	 * `menu.game.mythbusters`. `svelte-check` промовчав (його ж і обійшли),
	 * `check:i18n` теж (ключ у словнику є, просто інший), і на екрані
	 * замість назв ігор стояли самі ключі. Знайдено оком у браузері.
	 */
	nameKey: TranslationKey;
	/** Скільки раундів цієї гри в одному кроці програми. */
	rounds: number;
}

export const ONLINE_GAMES: readonly OnlineGame[] = [
	{ id: 'myths', nameKey: 'menu.game.mythbusters', rounds: 5 },
	{ id: 'feeding', nameKey: 'menu.game.feeding', rounds: 5 }
];

/**
 * Скільки кроків у партії.
 *
 * Крок — це одна гра з набором раундів. Шість кроків по пʼять раундів — близько
 * десяти хвилин, тобто партія, яку доводять до кінця, а не кидають на середині.
 */
export const QUIZ_STEPS = 6;

/** Префікс ключів налаштувань кімнати: `game.myths` → 1 або 0. */
export const GAME_FLAG_PREFIX = 'game.';

/**
 * Налаштування кімнати з переліку вибраних ігор.
 *
 * Форма нав'язана конвертом: `info.config` — це `Record<string, number>`, і
 * правило бази дозволяє в ньому лише числа (`config/$key` → `isNumber`). Тому
 * вибір їде прапорцями 1/0, а не масивом рядків, — і схема бази не змінюється
 * ЗОВСІМ, тобто нової редакції правил ця гра не потребує.
 */
export function gamesToConfig(selected: readonly string[]): Record<string, number> {
	const config: Record<string, number> = {};
	for (const game of ONLINE_GAMES) {
		config[`${GAME_FLAG_PREFIX}${game.id}`] = selected.includes(game.id) ? 1 : 0;
	}
	return config;
}

/**
 * Перелік вибраних ігор із налаштувань кімнати.
 *
 * Порожній результат неможливий у грі, але можливий у ДАНИХ: кімната старішої
 * збірки, чужі руки, помилка в майбутньому. Тому порожнеча трактується як «усі» —
 * партія, що не почалася через порожній набір, виглядала б як поломка, а не як
 * порожній вибір.
 */
export function configToGames(config: Record<string, number>): string[] {
	const chosen = ONLINE_GAMES.filter((game) => config[`${GAME_FLAG_PREFIX}${game.id}`] === 1);
	return (chosen.length > 0 ? chosen : ONLINE_GAMES).map((game) => game.id);
}

/** Один крок програми: яка гра й із яким зерном. */
export interface QuizStep {
	game: string;
	/** Зерно цього кроку. Різне в кожного кроку, але однакове в усіх гравців. */
	seed: number;
}

/**
 * Програма партії — з ЗЕРНА КІМНАТИ, а не з випадковості клієнта.
 *
 * Це те саме міркування, що тримає роздачу в «Знайди пару»: усі учасники
 * отримують той самий список кроків, бо виводять його з того самого числа. Тому
 * тут `randomFor(seed)`, а не `Math.random()` — інваріант проєкту забороняє
 * останній у конфігах саме через це.
 *
 * Ігри чергуються ВИПАДКОВО, а не по колу: за фіксованого порядку шостий крок
 * завжди був би тією самою грою, і партія читалася б як розклад.
 */
export function quizProgramme(
	seed: number,
	games: readonly string[],
	steps: number = QUIZ_STEPS
): QuizStep[] {
	const random = randomFor(seed);
	const pool = games.length > 0 ? games : ONLINE_GAMES.map((game) => game.id);
	return Array.from({ length: steps }, () => ({
		game: pool[Math.floor(random() * pool.length)],
		/*
		 * Зерно кроку — ціле число з того самого генератора.
		 *
		 * Не `seed + index`: сусідні зерна в лінійному генераторі дають схожі
		 * послідовності, і два кроки тієї самої гри показали б майже ті самі
		 * питання. Тут кожен крок бере наступне число потоку, тож кроки незалежні,
		 * а вся програма однакова в усіх.
		 */
		seed: Math.floor(random() * 2 ** 31)
	}));
}

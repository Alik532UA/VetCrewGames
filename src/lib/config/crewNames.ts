export const CREW_ONLY: readonly string[] = ['wombat'];

/** Скільки імен у списку. Одне джерело — сам список. */
export const CREW_NAME_COUNT = CREW_ANIMALS.length;

/** Ключ імені тварини. Одне джерело форми — щоб тест і генератор не розійшлися. */
export const crewNameKey = (animal: string): string => `pairs.crew.${animal}`;

/** Усі ключі списку, у порядку `CREW_ANIMALS`. */
export const CREW_NAME_KEYS: readonly string[] = CREW_ANIMALS.map(crewNameKey);

/**
 * Випадкове імʼя зі списку, ГАРАНТОВАНО не з числа зайнятих.
 *
 * `taken` — не косметика, і причин дві.
 *
 * Перша: кнопка «інше імʼя». Без виключення поточного вона в одному кидку з
 * вісімдесяти шести нічого не міняє, і виглядає це як зламана кнопка, а не як
 * щасливий збіг: людина натискає ще раз, бо вирішила, що не спрацювало.
 *
 * Друга, і саме через неї це ПЕРЕЛІК, а не один рядок: імена, уже видані тим,
 * хто зараз онлайн. Два «Мудра Сова» в одному переліку кімнат — не поломка
 * (особу несе `uid`), але вибір «до кого зайти» вони роблять неможливим.
 *
 * Реалізовано вибором зі списку БЕЗ зайнятих, а не повтором кидка: цикл «кидай,
 * поки не збіг» не має верхньої межі часу, а коли зайнято все, не завершився б
 * ніколи.
 *
 * **ЯКЩО ЗАЙНЯТО ВСЕ — повторюємося, і це названо.** Резерв тут не «на всяк
 * випадок»: без нього функція мусила б віддати `null`, і в поле імені поїхало б
 * порожнє. Вісімдесят шість імен проти двадцяти кімнат у переліку означає, що
 * дійти до резерву неможливо на живих даних, — але поведінка на цьому краю
 * мусить бути рішенням, а не наслідком.
 *
 * ## Чому джерело випадковості ПЕРЕДАЄТЬСЯ
 *
 * `Math.random()` усередині був — і його впіймав власний інваріант проєкту
 * (`quizSeed.test.ts`: «ні в конфігах, ні в контролерах немає Math.random()»).
 * Той замок стоїть заради спільної партії: випадковість, яка не йде через зерно,
 * розводить дошки двох гравців. Імені це не стосується — воно не входить у стан
 * партії, — але ПРАВИЛЬНА відповідь тут не виняток, а той самий підпис, що вже
 * має `pickOne` у `utils/seededRandom.ts`: джерело віддає той, хто кличе.
 *
 * Вигода не в зеленому гейті. Функція стала детермінованою, тож її поведінку
 * можна стверджувати ТОЧНО — «на 0 віддає перше, на 0.999999 останнє», як і
 * тест самого `pickOne`, — замість сотні кидків, що ловлять помилку лише
 * ймовірно.
 */
export function randomCrewName(
	translate: Translate,
	random: () => number,
	taken: readonly string[] = []
): string {
	const names = CREW_NAME_KEYS.map(translate);
	const busy = new Set(taken);
	const free = names.filter((name) => !busy.has(name));
	// Порожньо буде лише коли зайнято ВСІ імена — тоді повторитися правильніше,
	// ніж віддати нічого.
	const pool = free.length > 0 ? free : names;
	// `pickOne` віддає `null` лише на ПОРОЖНЬОМУ списку, а `pool` порожнім не
	// буває: `CREW_NAME_KEYS` за побудовою непорожній. Резерв усе одно названий,
	// щоб тип не тягнув `null` у поле імені.
	return pickOne(pool, random) ?? names[0];
}

/**
 * Імʼя гравця за замовчуванням — із власного списку, а не «Ти 417».
 *
 * ## Що тут було
 *
 * `guessName()` на сторінці `pairs/online` віддавала `` `${t('memory.you')}
 * ${Math.floor(Math.random() * 900 + 100)}` `` — тобто «Ти 417». Число в імені
 * не називає нікого: у лобі стоять двоє, і обидва «Ти» з різними числами.
 *
 * ## ПРИКМЕТНИК + ТВАРИНА, і чому не роли ветклініки
 *
 * Перша редакція мала «Головний Лікар», «Добра Медсестра» — роли ветклініки.
 * Автор це відкинув: імена мусять бути про тварин («весела корова»). Тварини —
 * ВЛАСНІ назви проєкту з `animals.ts`, тобто ті самі слова, що на картках.
 *
 * Заперечення, яке я тоді мав і яке автор зважив: онлайн-режим тут один, і це
 * «Знайди пару», де КАРТКИ і є тварини — тобто «Весела Корова» ходить у партії,
 * де на дошці лежить корова. Прикметник це й розводить: підпис гравця завжди з
 * двох слів, назва картки — з одного, і сплутати їх ніде.
 *
 * ## Чому ЦІЛІ фрази, а не склеювання в рантаймі
 *
 * Це головне обмеження, і воно не про лінь. Прикметник мусить узгодитися з
 * родом, а рід той самий у різних мовах РІЗНИЙ: «Корова» жіночого роду, `die
 * Kuh` теж, а `het nijlpaard` — середнього, і прикметник при ньому взагалі без
 * закінчення. Склеювання двох списків вимагало б таблиці родів на кожне слово в
 * кожній мові плюс правил відмінювання — тобто саморобної морфології, яку
 * I18N-v8 § 4.2 забороняє прямо (там уже прибрали власну арифметику
 * плюралізації з тієї самої причини).
 *
 * Готова фраза знімає питання цілком: її НАПИСАНО як фразу, і кожна правильна за
 * побудовою. Ціна названа: варіантів рівно 24, а не «прикметники × тварини».
 *
 * ## Чому ключі, а не масив рядків
 *
 * Словник проєкту — плаский `Record<TranslationKey, string>`, іншої форми в
 * ньому немає. Тому імена лежать ключами `pairs.crew1…pairs.crew24`. Побічна
 * вигода: паритет мов стереже наявний `npm run check:i18n`, а не окрема
 * перевірка.
 *
 * ## Чому перекладач ПЕРЕДАЄТЬСЯ, а не імпортується
 *
 * `import { td } from '$lib/i18n'` тут був і був прибраний: цей модуль тягнув би
 * за собою `settings`, а той у конструкторі кличе `window.matchMedia`, якого в
 * jsdom немає. Тобто модуль ставав неімпортовним у тестах — а разом із ним і
 * все, що його імпортує. Тепер `crewNames.ts` не залежить ні від чого, і саме
 * тому властивість «кнопка завжди міняє імʼя» перевіряється підставним
 * перекладачем, а не через справжній словник.
 */

import { pickOne } from '$lib/utils/seededRandom';

/** Як переклад потрапляє сюди. Збігається з підписом `td` із `$lib/i18n`. */
export type Translate = (key: string) => string;

/**
 * Скільки імен у списку.
 *
 * Число тут, а не `Object.keys(...).length`: ключі плаcкі, і порахувати їх у
 * рантаймі означало б перебирати весь словник. Натомість те, що всі 24 ключі
 * справді існують у всіх чотирьох мовах, стверджує `crewNames.test.ts` — тобто
 * розходження цього числа зі словником падає в CI, а не віддає ключ замість
 * імені.
 *
 * ЧОМУ САМЕ 24, і чого це не гарантує. Двоє в кімнаті беруть однакове імʼя з
 * шансом 1/24 — близько 4%. Це не помилка: особу учасника несе `uid`, а не
 * підпис, тож збіг нічого не ламає, а видно його одразу в лобі й міняється одним
 * натиском. Було 16 (6%); список подовжено разом із переходом на «прикметник +
 * тварина», бо цілі фрази не дають комбінаторики, і єдиний важіль різноманіття
 * тут — довжина списку.
 */
export const CREW_NAME_COUNT = 24;

/** Ключ n-го імені. Одне джерело форми — щоб тест і генератор не розійшлися. */
export const crewNameKey = (index: number): string => `pairs.crew${index}`;

/** Усі ключі списку, у порядку словника. */
export const CREW_NAME_KEYS: readonly string[] = Array.from(
	{ length: CREW_NAME_COUNT },
	(_, index) => crewNameKey(index + 1)
);

/**
 * Випадкове імʼя зі списку, ГАРАНТОВАНО не те, що вже стоїть.
 *
 * `exclude` — не косметика. Кнопка «інше імʼя» без нього в одному кидку з
 * двадцяти чотирьох нічого не міняє, і виглядає це як зламана кнопка, а не як щасливий
 * збіг: людина натискає ще раз, бо вирішила, що не спрацювало.
 *
 * Реалізовано вибором зі списку БЕЗ поточного, а не повтором кидка: цикл
 * «кидай, поки не інше» не має верхньої межі часу, а на списку з одного елемента
 * не завершився б ніколи.
 *
 * ## Чому джерело випадковості ПЕРЕДАЄТЬСЯ
 *
 * `Math.random()` усередині був — і його впіймав власний інваріант проєкту
 * (`quizSeed.test.ts`: «ні в конфігах, ні в контролерах немає Math.random()»).
 * Той замок стоїть заради спільної партії: випадковість, яка не йде через зерно,
 * розводить дошки двох гравців. Імені це не стосується — воно не входить у стан
 * партії, — але ПРАВИЛЬНА відповідь тут не виняток, а той самий підпис, що вже
 * має `pickOne` у `utils/seededRandom.ts`: джерело віддає той, хто кличе.
 *
 * Вигода не в зеленому гейті. Функція стала детермінованою, тож її поведінку
 * можна стверджувати ТОЧНО — «на 0 віддає перше, на 0.999999 останнє», як і
 * тест самого `pickOne`, — замість сотні кидків, що ловлять помилку лише
 * ймовірно.
 */
export function randomCrewName(
	translate: Translate,
	random: () => number,
	exclude?: string
): string {
	const names = CREW_NAME_KEYS.map(translate);
	const choices = names.filter((name) => name !== exclude);
	// Список без поточного порожній лише коли ім'я в ньому одне — тоді міняти нема
	// на що, і повернути те саме правильніше, ніж `null`.
	const pool = choices.length > 0 ? choices : names;
	// `pickOne` віддає `null` лише на ПОРОЖНЬОМУ списку, а `pool` порожнім не
	// буває: `CREW_NAME_KEYS` за побудовою має 24 елементи. Резерв усе одно
	// названий, щоб тип не тягнув `null` у поле імені.
	return pickOne(pool, random) ?? names[0];
}

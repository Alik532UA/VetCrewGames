/**
 * ЖИТТЯ КІМНАТИ: коли її ще показувати, коли пропонувати закрити, коли ховати.
 *
 * ## Що було не так
 *
 * У списку «Продовжити партію» висіли три однакові рядки кімнат, у яких давно
 * нікого не було. Причина проста: список питав лише «чи існує кімната й чи вона
 * `playing`», а це правда і за тиждень після того, як звідти всі пішли. Автор
 * сказав це прямо: «у користувача висить три кімнати і там вже давно нікого
 * немає».
 *
 * ## Чому позначка часу, а не присутність
 *
 * Спокуса — питати `presence/{код}`: він гасне сам, коли вкладка зникла. Але він
 * відповідає на «чи є хтось ЗАРАЗ», а не на «скільки вже нікого». Тобто той, хто
 * закрив вкладку тридцять секунд тому й хоче вернутися, виглядав би точно так
 * само, як покинута вчора кімната, — і його рядок зник би в нього з-під носа.
 *
 * Тому кімната сама несе `info.aliveAt` — СЕРВЕРНУ позначку, яку оновлює кожен,
 * хто в ній сидить. Тиша в ній і є відповідь: поки хтось є, вона свіжа; щойно
 * всі вийшли, вона перестає рости. Одне читання замість двох, і жодного
 * вгадування.
 *
 * ## Три стани, а не два
 *
 * Проміжний стан потрібен, і саме його попросив автор: «пропонувати закрити
 * кімнати до 5 хвилин порожньої кімнати, а потім все одно приховувати». Тобто
 * доки ще пам'ятаєш, що це за партія, — тобі дають її закрити; коли вже не
 * пам'ятаєш — вона просто зникає з очей.
 */

/**
 * Як часто кімната каже «я жива», поки хтось у ній сидить.
 *
 * 45 секунд, а не 10: у фоновій вкладці браузер притискає таймери приблизно до
 * одного спрацювання на хвилину, тож частіше просто не вийде, а рідше — зробило
 * б «живу» кімнату схожою на покинуту.
 */
export const ROOM_BEAT_MS = 45_000;

/**
 * ВІДЛІК ДО АВТОМАТИЧНОГО СТАРТУ — п'ять секунд від `info.countdownAt`.
 *
 * Лежить тут, бо це число мусить бути ОДНЕ. Його читають двоє й по-різному:
 * господар ставить на нього таймер («о цій миті починаю»), а екран показує
 * секунди, що лишилися. Розійшовшись, ці два вжитки дали б найгіршу з можливих
 * поломок: партія почалася б не тоді, коли доказав відлік на екрані.
 *
 * Доти копії стояли в обох сторінках спільної гри — це частина боргу, названого
 * в `quiz/online/+page.svelte` числом. Третя копія в компоненті лобі й змусила
 * винести його: там воно вже не «те саме число поруч», а те саме число в іншому
 * файлі.
 */
export const COUNTDOWN_MS = 5000;

/**
 * Скільки тиші означає «зараз там нікого».
 *
 * Дві хвилини — це два пропущені удари з запасом. Менше не можна саме через
 * притиснуті таймери у фоні: вкладка, згорнута на телефоні, інакше оголошувалася
 * б порожньою, поки людина читає повідомлення в сусідньому застосунку.
 */
export const ROOM_IDLE_MS = 120_000;

/**
 * Скільки тиші означає «показувати більше нема чого». Число автора.
 */
export const ROOM_DEAD_MS = 300_000;

/** У якому стані кімната з погляду списку «продовжити партію». */
export type RoomLife = 'alive' | 'idle' | 'dead';

/**
 * Стан кімнати за її позначкою активності.
 *
 * Час передається, а не читається з годинника: інакше поведінку неможливо
 * перевірити тестом — він мусив би чекати справжні хвилини. Той самий підпис, що
 * в фаз раунду вікторини.
 *
 * Позначки немає зовсім (кімната зі старішої збірки) — вважаємо живою: зникнути
 * з очей через те, що застосунок оновився, гірше, ніж зайвий рядок.
 */
export function roomLife(aliveAt: number | undefined, now: number): RoomLife {
	if (aliveAt === undefined) return 'alive';
	const silence = now - aliveAt;
	if (silence > ROOM_DEAD_MS) return 'dead';
	if (silence > ROOM_IDLE_MS) return 'idle';
	return 'alive';
}

/**
 * «Знайди пару».
 *
 * 1 → 2: у ході з'явився серверний час (`at`), у кімнаті — позначка початку
 * партії (`startedAt`), і на них стоїть межа очікування. Стара збірка пише ходи
 * без часу — правило бази їх відкидає, тож змішувати версії не можна, і саме
 * для цього поле й існує.
 *
 * 2 → 3: роздача й черга — із ЗАМОРОЖЕНОГО складу (`info.roster`), а не з
 * поточних `members`. Стара збірка роздає за поточним складом і на першому ж
 * виході гравця посеред партії розійшлася б із новою.
 *
 * 3 → 4: хід `leave` — черга того, хто пішов назовсім, пропускається. Стара
 * збірка такого ходу не знає й чекала б на вибулого — черга розійшлася б.
 *
 * ПЕРЕШТАМПОВАНО БЕЗ НОВОЇ ВЕРСІЇ (2026-09-26, `--same=pairs`): у `PairsMatch`
 * з'явилося поле `avatarSwaps` — хто в складі отримав іншу аватарку, бо його пару
 * вже тримає раніший (`utils/roomAvatars`). Це підпис, а не стан партії: роздача,
 * черга й рахунок із журналу рахуються тими самими рядками, і дві збірки в одній
 * кімнаті розходяться хіба що плиткою біля імені.
 *
 * І вдруге (2026-09-26, шостий аудит): розкладка береться з налаштувань через
 * `roomLayoutOf` — у межах колоди. Для кожної законної кімнати (межі тримає й
 * правило `config`) роздача та сама; інакше — лише там, де доти партія не мала кінця.
 *
 * І втретє (шостий аудит, A4): поля кімнати переїхали з `PairsMatch` у спільний
 * `RoomEnvelopeState` — ті самі поля, той самий розклад знімка, перепрогін не змінився.
 *
 * І вчетверте (хвости A2): у лобі ходи не застосовуються. Журнал там приймає лише `lead`
 * (R1), а старт його стирає, тож дошка партії рахується з тих самих ходів.
 *
 * І впʼяте (шостий аудит, S1): у `utils/roster.ts` змінився `leadCandidates` — хто
 * пробує підхопити ведення. Його читає лише політика перехоплення, а не перепрогін.
 */
export const PAIRS_RULES_VERSION = 4;

/**
 * Спільна вікторина.
 *
 * ДВІЙКА З ПОЯВОЮ ШВИДКОСТІ КІМНАТИ: клієнт першої редакції полів швидкості не
 * читає й порахує собі СВІЙ дедлайн за старими числами — а очки залежать від
 * того, скільки тривав раунд.
 *
 * ТРІЙКА З ПОЯВОЮ «НЕ ОБМЕЖЕНОГО» РАУНДУ (`pace_round` = 3). Клієнт другої
 * редакції читає його як «стандартна»: у нього раунд скінчився б за межею, і
 * «поки кожен не відповість» не настало б ніколи.
 *
 * ЧЕТВІРКА: ПАУЗУ ПИШЕ КОЖЕН ГРАВЕЦЬ, а перепрогін бере НАЙБІЛЬШЕ (аудит
 * 2026-09-24). Клієнт третьої редакції рахував би лише ходи ведучого й ДОДАВАВ
 * їх — тобто в одній кімнаті вийшло б два різні дедлайни, і відповідь, яку один
 * зараховує, другий відкидав би.
 *
 * ПʼЯТІРКА: ТРИ ЗМІНИ ПЕРЕПРОГОНУ, що вийшли під четвіркою (аудит 2026-09-26).
 * Гравці — склад ∪ пізні, ходи до `createdAt` не рахуються, чекання належить
 * раунду, а ведучий після зняття чекання дає доїхати чужим записам. Вкладки двох
 * редакцій в одній кімнаті рахували різних гравців — різні табло й нагороди.
 * Під нею ж — перепрогін за серверним часом, а не за номером ходу: зміна приїхала
 * до викладки пʼятірки, тож окремої версії не потребує. І присутність для партії
 * з поправкою на мить (`settledPresence`): щойно зниклого ведучий ще чекає з
 * відповіддю, а не оголошує раунд без нього. Це рішення ведучого, а не
 * перепрогін, і приїхало воно теж до викладки. І програма партії з колоди
 * кімнати (`config/quizDeck.ts`): питання без повторів, раунди порівну між іграми
 * — за тим самим зерном інший розклад раундів, тобто інші межі часу, — теж до
 * викладки пʼятірки.
 *
 * Відтепер версію стереже штамп коду перепрогону (`scripts/replay-stamp.mjs`):
 * змінився код, з якого рахується партія, — гейт червоніє, доки версію не піднято
 * або не підтверджено, що перепрогін той самий.
 *
 * ПЕРЕШТАМПОВАНО БЕЗ НОВОЇ ВЕРСІЇ (2026-09-26, `--same=quiz`, шостий аудит): стеля
 * номера партії в колоді (`MAX_ROOM_GAMES`). Для кожного зерна в межах (їх тримає й
 * правило `seed`) програма та сама; інакше — лише там, де доти вкладка висла.
 *
 * І вдруге (шостий аудит, S1): `leadCandidates` у `utils/roster.ts` — кандидати на
 * ведення. Це рішення політики перехоплення, а не перепрогін: ведучого партії й далі
 * рахують ходи `lead` у журналі.
 */

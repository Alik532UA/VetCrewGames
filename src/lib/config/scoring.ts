/**
 * Спільний рахунок усіх вікторин — і поріг, за яким дія в заповіднику вдалася.
 *
 * **Навіщо.** П'ять ігор рахували очки чотирма різними способами, і порівняти їх
 * було неможливо: «Правда чи міф» давала 1 за правильну відповідь, «Що їмо» — до
 * 3 за раунд, а «Де живем» карала за частковий успіх НУЛЕМ, тобто гравець, який
 * вибрав чотири зони з п'яти, діставав рівно те саме, що й той, хто не вибрав
 * нічого. Поки ігри жили окремо, це було непослідовністю; відколи вони стали
 * міні-грою всередині заповідника, це стало дефектом: «набрати 70%» не означало
 * нічого, доки максимум у кожної гри свій і рахується по-своєму.
 *
 * **Форма рахунку.** Раунд буває двох видів, і в них різна ціна:
 *
 *  * **Бінарний** — одна відповідь, правильна або ні («Правда чи міф», «Хто чия
 *    дитина»). Правильна дає `BINARY_POINTS`. Одиниця тут була б несумірна з
 *    раундом, де відповідей три.
 *  * **Складений** — кілька частин, кожна зараховується окремо («Що їмо» —
 *    три страви, «Кого більше» — три слоти, «Де живем» — набір зон). По одному
 *    очку за частину, і `PERFECT_BONUS` понад те, якщо не схиблено ЖОДНОЇ.
 *
 * Бонус за бездоганний раунд — те, заради чого й розділені ці два види. Три
 * страви з трьох це не «на одну краще, ніж дві»: це інша якість відповіді, і
 * шкала має її помітити.
 *
 * **Поріг рахується від ОЧОК, а не від відповідей** — і від максимуму САМЕ ЦІЄЇ
 * гри. Через бонус ці два відсотки розходяться (15 правильних страв із 15 дають
 * 100% відповідей і 75% очок), тож обрано один, і він названий тут, а не
 * виводиться на місці виклику.
 */

/** Очки за правильну відповідь у раунді, де відповідь одна. */
export const BINARY_POINTS = 3;

/** Надбавка за раунд без жодної помилки. Лише для складених раундів. */
export const PERFECT_BONUS = 1;

/**
 * Частка очок, ПОНАД яку дія в заповіднику вважається успішною.
 *
 * Строго більше, а не «не менше»: рівні 70% — це не «впорався», а «рівно на
 * межі», і межа має лишатися по один її бік.
 */
export const SUCCESS_SHARE = 0.7;

/**
 * Скільки очок дає раунд.
 *
 * `parts` — на скільки частин ділиться відповідь: 1 для бінарного раунду, 3 для
 * трьох страв. `correct` — скільки з них узято правильно.
 */
export function roundPoints(correct: number, parts: number): number {
	const hit = Math.max(0, Math.min(correct, parts));
	if (parts <= 1) return hit >= 1 ? BINARY_POINTS : 0;
	return hit + (hit === parts ? PERFECT_BONUS : 0);
}

/** Найбільше, що можна взяти за раунд із такою кількістю частин. */
export const maxRoundPoints = (parts: number): number =>
	parts <= 1 ? BINARY_POINTS : parts + PERFECT_BONUS;

/** Найбільше за всю партію. */
export const maxSessionPoints = (parts: number, rounds: number): number =>
	maxRoundPoints(parts) * rounds;

/**
 * Чи вистачило очок, щоб дія в заповіднику зарахувалася.
 *
 * Нульовий максимум дає `false`, а не ділення на нуль: партія без раундів нічого
 * не доводить, і вважати її успіхом означало б віддавати дію задарма.
 */
export function isSuccess(points: number, max: number): boolean {
	if (max <= 0) return false;
	return points / max > SUCCESS_SHARE;
}

/**
 * ОНЛАЙН-БАЛИ ПЕРЕВОДЯТЬСЯ В ЛОКАЛЬНІ ДІЛЕННЯМ, а не додаються як є.
 *
 * Шкали різні на два порядки, і це не недогляд, а різна природа: соло-раунд дає
 * 3–4 очки за правильну відповідь, а онлайн-раунд — 50–100, бо в них закладена
 * ще й швидкість. Дванадцять раундів партії — це 600–1200, тобто одна спільна
 * вікторина коштувала б як двадцять соло-партій.
 *
 * Число вибрав автор: підсумок партії ділиться на 50 і округлюється. Виходить
 * 12–24 бали за партію проти ~30 за соло-партію з десяти раундів — тобто шкали
 * стають порівнянними, а не рівними: спільна гра лишається трохи дорожчою за
 * підхід до однієї гри, і це справедливо, бо вона й довша.
 *
 * Чому це взагалі важливо: наскрізний рахунок — це те, що показує шапка, що
 * їде в хмару і що стоїть у ТАБЛИЦІ ЛІДЕРІВ. Пряме додавання онлайн-балів
 * зробило б таблицю таблицею тих, хто грав онлайн, а не тих, хто грав.
 */
export const ONLINE_TO_LOCAL = 50;


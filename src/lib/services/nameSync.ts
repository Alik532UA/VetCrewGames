import { hasAccount } from './accountFlag';
import { logService } from './logService.svelte';

/**
 * ОДНЕ ІМʼЯ НА ВЕСЬ ЗАСТОСУНОК: профіль — правда, сховище — кеш.
 *
 * ## Що було зламано
 *
 * Імен було ДВА, і синхронізація між ними — однобока й в одній точці: форма
 * профілю писала імʼя у сховище при натиску «Зберегти», і все. Читання профілю
 * кеш не оновлювало, а екран входу в кімнату не писав у профіль ніколи. Тому на
 * новому пристрої (чи після чистки сховища) у профілі стояв «Уважний Олень», а в
 * лобі — «Швидкий Леопард», підставлений кубиком. Автор надіслав знімок саме
 * цього.
 *
 * Був і другий, тонший бік: `forEntry` записує у сховище ПІДСТАВЛЕНЕ нами імʼя, а
 * ознака «це вигадали ми» живе лише в памʼяті сторінки. Тобто після першого входу
 * в кімнату випадкове імʼя ставало для коду «вибором людини» й далі мало
 * перевагу над профілем.
 *
 * ## Правило, і чому саме таке
 *
 * ПРОФІЛЬ ГОЛОВНІШИЙ. Він лежить на сервері, він один для всіх пристроїв, і його
 * людина заповнювала свідомо. Сховище лишається кешем — для першого кадру (щоб
 * поле не блимало порожнім) і як ЄДИНЕ джерело для того, хто акаунта не має:
 * анонімові профілю немає звідки взяти, і «одна змінна замість двох» для нього
 * неможлива в принципі.
 *
 * Назад імʼя їде В МОМЕНТ ВХОДУ В КІМНАТУ — там, де воно вперше стає публічним, і
 * там, де мережа в коді вже є (`createRoom`/`joinRoom`). Запис на кожне
 * натискання клавіші дав би десятки записів за одне імʼя й недописане імʼя в
 * профілі того, кого відірвали від компʼютера.
 *
 * ## Чому читати профіль у лобі тепер МОЖНА
 *
 * У проєкті тричі записано «форма входу в кімнату не читає профіль, бо це
 * мережевий запит на екрані, який мусить відкритися з першого дотику». Це вже не
 * так: та сама сторінка при відкритті підписується на перелік кімнат і читає свої
 * партії (`LobbyFeed.watch`, `LobbyFeed.load`) — тобто SDK там уже піднімається, і
 * читань уже два. Третє, того самого класу й лише для того, хто ввійшов, нічого
 * не змінює в природі екрана.
 */

/**
 * Імʼя, яке ми бачили в профілі. `null` — не читали або профілю немає.
 *
 * Кеш на сесію, і він тут не про швидкість: `load()` контролера перезапускається
 * на кожну зміну мови й переліку зайнятих імен, тобто без кешу профіль читався б
 * знову й знову. Заразом він відповідає на питання «чи є куди писати»: `null`
 * означає, що записувати нікуди — або акаунта немає, або профіль не заповнений.
 */
let known: string | null = null;

/**
 * Імʼя з профілю. Порожньо — акаунта немає, профілю немає або мережа не відповіла.
 *
 * НЕ КИДАЄ: це підпис, а не дія. Невдача означає «лишається те, що в кеші», і
 * саме так виглядає екран у того, хто акаунта не має.
 */
export async function profileName(): Promise<string> {
	if (!hasAccount()) return '';
	if (known !== null) return known;
	try {
		const [{ connect }, account] = await Promise.all([
			import('$lib/net/firebase'),
			import('$lib/net/account')
		]);
		const { uid } = await connect();
		const profile = await account.readProfile(uid);
		known = profile?.name ?? null;
		return known ?? '';
	} catch (error) {
		logService.warn('network', 'profile name not read', { reason: String(error) });
		return '';
	}
}

/**
 * Імʼя поїхало в кімнату — записати його і в профіль.
 *
 * Нічого не робить, коли профілю немає (анонім або незаповнений акаунт): запис у
 * `profile/name` на порожньому місці створив би профіль з одного імені, без
 * @ніка, — і прочитався б він як профіль, якого людина не заповнювала. Ту саму
 * межу тримає `Account.saveAvatar`, і з тієї самої причини.
 *
 * НЕ КИДАЄ: невдача тут не має права ламати вхід у кімнату. Профіль наздожене
 * наступного разу — імʼя вже лежить у кеші сховища.
 */
export async function pushName(name: string): Promise<void> {
	if (name === '' || !hasAccount()) return;
	try {
		// Профіль ще не читали (людина натиснула швидше, ніж приїхала відповідь) —
		// читаємо тепер: інакше перша ж зміна імені загубилася б.
		if (known === null) await profileName();
		if (known === null || known === name) return;

		const account = await import('$lib/net/account');
		await account.saveName(name);
		known = name;

		/*
		 * Рядок у таблиці лідерів несе імʼя — без цього виклику він показував би те,
		 * що було до зміни. Той самий крок робить `Account.save` після профілю.
		 */
		const sync = await import('./playerSync');
		await sync.refreshProfile();
	} catch (error) {
		logService.warn('network', 'profile name not updated', { reason: String(error) });
	}
}

/**
 * Профіль щойно записали самі — кеш мусить це знати.
 *
 * Без цього виклику форма профілю й екран входу в кімнату розійшлися б у памʼяті:
 * `known` лишався б зі старим імʼям, і наступний вхід у кімнату зробив би зайвий
 * запис того самого значення.
 */
export function rememberName(name: string): void {
	known = name;
}

/** Забути кеш. Потрібно виходу з акаунта: далі імʼя належить браузеру, не акаунту. */
export function forgetName(): void {
	known = null;
}

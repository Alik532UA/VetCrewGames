import { browser, dev } from '$app/environment';
import { storage } from './storage';

/**
 * Чи показувати службове табло — і скільки натискань `V` коштує його перемкнути.
 *
 * **Три стани, а не два, і саме тому тут не `boolean`.** Прапорець зі сховища
 * може означати «показати», «сховати» або «нічого не сказано» — і третій стан
 * потрібен, бо ЗА ЗАМОВЧУВАННЯМ у dev і в проді відповідь різна: у dev табло
 * видиме, у проді ні. `boolean` із типовим `false` зробив би dev-табло
 * прихованим, а типовий `true` — показав би його всім відвідувачам проду.
 *
 * ```
 * override === null   → як заведено в цьому середовищі (dev: видиме, prod: ні)
 * override === true   → показане, попри середовище
 * override === false  → сховане, попри середовище
 * ```
 *
 * **Пороги асиметричні, і це не примха.** Показати табло в проді коштує 55
 * натискань, сховати — 5; у dev обидва по 5. Причина в тому, ЩО саме захищає
 * поріг: у проді він тримає службовий елемент від випадкового відвідувача, тож
 * має бути високим. Сховати — дія без наслідків для будь-кого, тож дорогою її
 * робити нема причини. А в dev табло вже видиме за замовчуванням, і ховають його
 * заради чистого скріншоту — 55 натискань для скріншота були б покаранням.
 *
 * **Гідрація в конструкторі, запис у мутаторі.** `$effect` тут кинув би
 * `effect_orphan`: це module-level синглтон. Той самий порядок, що в `settings` і
 * `logService` (AGENTS.md, потік даних § 3).
 */

/** Показати табло в проді. Високий поріг: він тримає службовий елемент від відвідувача. */
export const SHOW_PRESSES_PROD = 55;
/** Сховати — і показати в dev. Дія без наслідків, тож дорогою бути не мусить. */
export const HIDE_PRESSES = 5;

class DebugMode {
	/** `null` — «нічого не сказано»: діє типова відповідь середовища. */
	override = $state<boolean | null>(null);

	constructor() {
		// `browser &&` обовʼязково: під час prerender сховища немає, а фасад, хоч і
		// не кидає, віддав би `null` — читати його там просто нема сенсу.
		if (browser) {
			const stored = storage.get('debug_mode');
			this.override = stored === '1' ? true : stored === '0' ? false : null;
		}
	}

	/** Чи табло показане зараз (без урахування `?debug=1`, який діє поверх). */
	get enabled(): boolean {
		return this.override ?? dev;
	}

	/**
	 * Скільком натисканням `V` перемкнути стан ЗАРАЗ.
	 *
	 * Читається на кожне натискання, бо після спрацювання відповідь інша: щойно
	 * табло стало видимим, наступна серія коштує 5, а не 55.
	 */
	get pressesToToggle(): number {
		if (this.enabled) return HIDE_PRESSES;
		return dev ? HIDE_PRESSES : SHOW_PRESSES_PROD;
	}

	/** Перемкнути. Повертає новий стан — щоб той, хто кличе, міг його залогувати. */
	toggle(): boolean {
		const next = !this.enabled;
		this.override = next;
		/*
		 * Наскрізний запис, і пишеться саме `'0'`, а не видалення ключа.
		 *
		 * Видалення повернуло б стан «нічого не сказано», тобто в dev табло
		 * зʼявилося б знову після перезавантаження — а людина щойно попросила його
		 * сховати. Три стани в сховищі мусять бути тими самими трьома, що в памʼяті.
		 */
		storage.set('debug_mode', next ? '1' : '0');
		return next;
	}
}

export const debugMode = new DebugMode();

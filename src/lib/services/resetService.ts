import { base } from '$app/paths';
import { PREFIX, sessionStore, storage } from './storage';

/**
 * Аварійне скидання: стерти локальні дані ЦЬОГО проєкту й перезавантажитися.
 *
 * **Навіщо воно взагалі.** Стан заповідника й налаштування живуть у сховищі, і
 * коли вони суперечать новій збірці, застосунок відкривається зламаним — а
 * лікується це відкриттям DevTools, чого ні бета-тестувальник, ні дитина не
 * зроблять. Жест на клавіатурі дає той самий результат без інструментів
 * розробника.
 *
 * **Що саме стирається — і чому не більше.** Origin спільний із сусідніми
 * проєктами на GitHub Pages, тож `localStorage.clear()` тут означав би знищення
 * ЧУЖИХ даних. Фасад `storage` видаляє лише ключі з префіксом `vetcrewgames_`, і
 * саме тому скидання ходить через нього, а не через сховище напряму
 * (STORAGE-NAMESPACE-v8 § 2).
 *
 * **PWA тут ще немає — але скидання вже готове до неї, і це не запас «на всяк
 * випадок».** У проєкті немає ні `vite-plugin-pwa`, ні власного
 * `service-worker.js`, тож сьогодні обидві половини нижче не роблять нічого. Але
 * написати їх ПІСЛЯ появи PWA означало б написати їх у поспіху — а саме тут
 * поспіх коштує чужих даних, і в сусідніх проєктах він уже коштував:
 *
 *  - `Slovko` знімає реєстрацію ВСІХ service worker на origin, без фільтра за
 *    scope: `getRegistrations()` віддає реєстрації всього
 *    `alik532ua.github.io`, тож одне натискання `r` у Slovko вбиває service
 *    worker і MindStep, і будь-якого іншого проєкту поруч. Кеші там
 *    відфільтровані за префіксом, а реєстрації — ні;
 *  - `MindStep` фільтрує кеші, але service worker не знімає взагалі — тобто
 *    після скидання сторінка може приїхати з того самого SW і виглядати
 *    незміненою.
 *
 * Тут обидві половини фільтрують: кеші — за префіксом проєкту, реєстрації — за
 * `scope`, який мусить лежати всередині `base`. Обидва переліки походять із
 * ОДНОГО джерела: `PREFIX` зі `storage.ts` і `base` зі `$app/paths`
 * (STORAGE-NAMESPACE-v8 § Крок 5).
 *
 * **Ніколи не кидає.** Це аварійний шлях: людина кличе його тоді, коли вже щось
 * не працює. Виняток усередині означав би «навіть скидання зламане».
 */

/** Скільком натисканням запускати жест. Різні числа — різна ціна помилки. */
export const RESET_PRESSES_DEV = 5;
/**
 * П'ятдесят п'ять у проді — те саме число, що в `MindStep`.
 *
 * Число велике не для складності, а тому що ціна випадкового спрацювання — увесь
 * місцевий прогрес. Плюс підтвердження: разом це два незалежні бар'єри, і жоден
 * не покладається на уважність.
 *
 * `Slovko` має 50, і це розходження лишається: поріг — рішення проєкту з
 * названою ціною, а не магічна константа. Важливо, щоб число було ЗАПИСАНЕ, а не
 * щоб воно було однакове (DEBUGGING-v8 § 5).
 */
export const RESET_PRESSES_PROD = 55;

/**
 * @param askConfirmation питати підтвердження. У проді — обов'язково: без нього
 * жест стирає прогрес без жодного запитання.
 */
export async function hardReset(askConfirmation = true): Promise<void> {
	if (typeof window === 'undefined') return;

	if (askConfirmation && !window.confirm(CONFIRM_TEXT)) return;

	/*
	 * Кожна половина — під власним `try`, а не всі разом.
	 *
	 * Спільний `try` означав би, що збій у першій половині скасовує другу: не
	 * вдалося стерти кукі — і кеші лишилися. Скидання кличуть, коли вже зламано,
	 * тож воно мусить зробити стільки, скільки зможе.
	 *
	 * Порожні `catch` тут не недогляд: повідомляти нема кому й нема куди —
	 * сторінка зараз зникне.
	 */
	try {
		// Лише префіксовані ключі — сусіди по origin не постраждають.
		storage.clear();
		sessionStore.clear();
	} catch {
		/* сховище недоступне — решта скидання все одно потрібна */
	}

	try {
		clearOwnCookies();
	} catch {
		/* кукі заблоковані — не причина не чистити кеші */
	}

	await clearOwnCaches();
	await unregisterOwnWorkers();

	window.location.reload();
}

/**
 * Кеші — лише свої, за префіксом проєкту.
 *
 * `caches.keys()` віддає імена кешів усього ORIGIN, тобто разом із кешами
 * сусідніх проєктів на `alik532ua.github.io`. Без фільтра це «скинути все, що є
 * на домені», а не «скинути свою гру».
 *
 * Умова названа префіксом, а не переліком імен: перелік розійшовся б із тим, що
 * справді створює service worker, а префікс — те саме джерело, що в ключів
 * сховища.
 */
async function clearOwnCaches(): Promise<void> {
	if (!('caches' in window)) return;
	try {
		const names = await caches.keys();
		await Promise.all(names.filter((name) => name.startsWith(PREFIX)).map((name) => caches.delete(name)));
	} catch {
		/* Cache API недоступний або заблокований */
	}
}

/**
 * Реєстрації service worker — лише свої, за `scope`.
 *
 * `getRegistrations()` теж віддає реєстрації всього ORIGIN. Саме на цьому
 * спіткнувся `Slovko`: він проходить по всіх і знімає кожну, тож одне скидання
 * там вбиває service worker сусідніх проєктів. Тут перевіряється `scope` — і
 * порівнюється він як АДРЕСА, а не як рядок: `scope` завжди абсолютний
 * (`https://host/VetCrewGames/`), а `base` — шлях (`/VetCrewGames`), тож пряме
 * `startsWith` не збіглося б ніколи.
 *
 * Без цього зняття скидання лишається неповним: сторінка приїжджає з того самого
 * service worker і виглядає незміненою — так виглядає `MindStep`, який кеші
 * чистить, а реєстрацію не знімає.
 */
async function unregisterOwnWorkers(): Promise<void> {
	if (!('serviceWorker' in navigator)) return;
	try {
		const registrations = await navigator.serviceWorker.getRegistrations();
		const scopePrefix = new URL(`${base || ''}/`, window.location.origin).href;
		await Promise.all(
			registrations
				.filter((registration) => registration.scope.startsWith(scopePrefix))
				.map((registration) => registration.unregister())
		);
	} catch {
		/* реєстрації недоступні — решта скидання вже виконана */
	}
}

/**
 * Текст підтвердження свідомо НЕ через i18n.
 *
 * `confirm()` — це блокуючий діалог браузера, і він може знадобитися саме тоді,
 * коли зламалося завантаження словників: тоді `t()` віддав би ключ замість
 * тексту, тобто людина побачила б «reset.confirm» перед знищенням прогресу.
 * Єдине місце в проєкті, де жорсткий рядок правильніший за переклад.
 */
const CONFIRM_TEXT =
	'Це видалить усі локальні дані цієї гри: прогрес, налаштування, збережені партії. Продовжити?';

/**
 * Кукі — лише свого шляху.
 *
 * `path` мусить збігатися з тим, під яким кукі поставлені, інакше запис не
 * видаляється, а дублюється. `base` тут і є той шлях: у продакшні
 * `/VetCrewGames`, у dev — порожньо.
 */
function clearOwnCookies(): void {
	const path = base || '/';
	for (const raw of document.cookie.split(';')) {
		const name = raw.split('=')[0]?.trim();
		if (!name) continue;
		document.cookie = `${name}=;expires=Thu, 01 Jan 1970 00:00:00 GMT;path=${path}`;
	}
}

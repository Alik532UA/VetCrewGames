import { LANGUAGE_ROUTES, type RouteRest } from '$lib/i18n/routing';

/**
 * Випадкова гра з головного меню.
 *
 * **Перелік виводиться з маршрутів, а не пишеться руками.** Другий список
 * розійшовся б із першим на наступній грі: додав маршрут — і забув додати його
 * у «випадкову». Тут навпаки: щойно гра з'явилася в `LANGUAGE_ROUTES`, вона
 * одразу може випасти.
 */

/**
 * Що НЕ може випасти у «Випадковій грі».
 *
 * Перелік виводиться з маршрутів, а не пишеться руками, тож нова гра
 * зʼявляється тут сама. Але не кожен маршрут — гра, і кожне виключення нижче
 * має свою причину:
 *
 *  * `''`, `quiz`, `quiz/play`, `pairs` — це МЕНЮ. Кнопка обіцяє гру, а не ще
 *    один вибір;
 *  * `game-habitat` — вибір підрежиму, теж меню. Самі підрежими
 *    (`game-habitat/continents` і `.../biomes`) у переліку є й випадають;
 *  * `game-memory` — окремий розділ зі своєю спільною партією, і «Випадкова
 *    гра» живе всередині вікторини, тобто пропонує саме її п'ятірку;
 *  * `beta-test` — службова сторінка. «Випадкова гра», яка приводить у чеклист
 *    перевірок, — це не жарт, а зламана обіцянка кнопки.
 */
const NOT_A_GAME = new Set<RouteRest>([
	'',
	'quiz',
	'quiz/play',
	'pairs',
	'game-habitat',
	'game-memory',
	'beta-test'
]);

export const PLAYABLE_ROUTES = (Object.keys(LANGUAGE_ROUTES) as RouteRest[]).filter(
	(route): route is Exclude<RouteRest, ''> => !NOT_A_GAME.has(route)
);

/**
 * Те саме плюс «Знайди пару» — для головного меню збірки для людей.
 *
 * Там усі шість ігор стоять рівними пунктами, тож і випадкова гра мусить давати
 * будь-яку з шести. Усередині вікторини «Знайди пару» лишається за межами: у неї
 * власний розділ.
 */
export const MENU_POOL: readonly Exclude<RouteRest, ''>[] = [...PLAYABLE_ROUTES, 'game-memory'];

/**
 * Набір — ПАРАМЕТР, а не модульна стала.
 *
 * У вікторині випадкова гра пропонує її пʼятірку; у головному меню збірки для
 * людей — усі шість, разом зі «Знайди пару», бо там вона стоїть поруч рівним
 * пунктом. Один список на два різні обіцяння давав би або зайву гру, або
 * відсутню.
 */
export function pickRandomRoute(
	random: () => number = Math.random,
	pool: readonly Exclude<RouteRest, ''>[] = PLAYABLE_ROUTES
): Exclude<RouteRest, ''> {
	return pool[Math.floor(random() * pool.length)];
}

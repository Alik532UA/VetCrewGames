import { LANGUAGE_ROUTES, type RouteRest } from '$lib/i18n/routing';

/**
 * Випадкова гра з головного меню.
 *
 * **Перелік виводиться з маршрутів, а не пишеться руками.** Другий список
 * розійшовся б із першим на наступній грі: додав маршрут — і забув додати його
 * у «випадкову». Тут навпаки: щойно гра з'явилася в `LANGUAGE_ROUTES`, вона
 * одразу може випасти.
 */

/**
 * Що НЕ може випасти у «Випадковій грі».
 *
 * Перелік виводиться з маршрутів, а не пишеться руками, тож нова гра
 * зʼявляється тут сама. Але не кожен маршрут — гра, і кожне виключення нижче
 * має свою причину:
 *
 *  * `''`, `quiz`, `quiz/play`, `pairs` — це МЕНЮ. Кнопка обіцяє гру, а не ще
 *    один вибір;
 *  * `game-habitat` — вибір підрежиму, теж меню. Самі підрежими
 *    (`game-habitat/continents` і `.../biomes`) у переліку є й випадають;
 *  * `game-memory` — окремий розділ зі своєю спільною партією, і «Випадкова
 *    гра» живе всередині вікторини, тобто пропонує саме її п'ятірку;
 *  * `beta-test-checklists` — службова сторінка. «Випадкова гра», яка привела б у
 *    чеклист перевірок, — це не жарт, а зламана обіцянка кнопки.
 */
const NOT_A_GAME = new Set<RouteRest>([
	'',
	'quiz',
	'quiz/play',
	'pairs',
	'game-habitat',
	'game-memory',
	'beta-test-checklists'
]);

export const PLAYABLE_ROUTES = (Object.keys(LANGUAGE_ROUTES) as RouteRest[]).filter(
	(route): route is Exclude<RouteRest, ''> => !NOT_A_GAME.has(route)
);

/*
 * «MENU_POOL» І ПАРАМЕТР `pool` ТУТ БІЛЬШЕ НЕ ПОТРІБНІ.
 *
 * Другий набір існував для головного меню збірки для людей: там усі шість ігор
 * стояли рівними пунктами, тож випадкова гра мусила давати будь-яку з шести.
 * Тепер головне меню однакове в роботі й у продакшні — це розділи, а не ігри, —
 * і «Випадкова гра» лишилася там, де завжди й була за задумом: усередині
 * вікторини, тобто пропонує саме її пʼятірку.
 *
 * Прибрано разом із набором і параметр: жоден виклик його не передавав, а шлях,
 * який лишається лише для тесту, — це фальшивий борг, не гнучкість.
 */
export function pickRandomRoute(random: () => number = Math.random): Exclude<RouteRest, ''> {
	return PLAYABLE_ROUTES[Math.floor(random() * PLAYABLE_ROUTES.length)];
}

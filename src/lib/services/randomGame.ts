import { LANGUAGE_ROUTES, type RouteRest } from '$lib/i18n/routing';
import { QUIZ_GAMES } from '$lib/config/menu-games';

/**
 * Випадкова гра з меню «Вікторина».
 *
 * ## Перелік — ДОЗВОЛЕНИЙ, з ігор меню, а не «усі маршрути, крім винятків»
 *
 * Доти тут стояв перелік винятків: усі адреси сайту мінус меню, «Знайди пару» й
 * чеклист. Він працював, поки кожна нова адреса була грою. Потім зʼявилися
 * заповідник із чотирма ділянками, акаунт, «Грати», «Грати онлайн» і дві сторінки
 * кімнат — і жодну з них у винятки не дописали. Кнопка вибирала з шістнадцяти
 * адрес, і лише шість із них були іграми: у десяти натисках із шістнадцяти вона
 * вела в заповідник, вікно входу чи іншу сторінку (скарга автора 2026-09-28).
 * Тест цього не бачив, бо сам рахував «усі, крім винятків», — тобто повторював ту
 * саму помилку, а не перевіряв обіцянку кнопки.
 *
 * Тепер кнопка бере РІВНО ті ігри, що стоять у меню під нею (`QUIZ_GAMES`). Нова
 * сторінка сайту сюди не потрапить сама, а нова гра меню — потрапить: список у меню
 * й у кнопці один.
 *
 * ## Гра з підрежимами — це її підрежими
 *
 * Кнопка обіцяє ГРУ, а не ще один вибір. «Де живем?» (`game-habitat`) — сторінка
 * вибору підрежиму, тож випадає не вона, а самі підрежими: адреси під нею
 * (`game-habitat/continents`, `…/biomes`). Звідси шість варіантів на пʼять ігор меню.
 */

/** Підрежими гри — адреси під її адресою; гра без них — сама собі варіант. */
function playableOf(route: Exclude<RouteRest, ''>): Exclude<RouteRest, ''>[] {
	const modes = (Object.keys(LANGUAGE_ROUTES) as RouteRest[]).filter(
		(rest): rest is Exclude<RouteRest, ''> => rest.startsWith(`${route}/`)
	);
	return modes.length > 0 ? modes : [route];
}

export const PLAYABLE_ROUTES: readonly Exclude<RouteRest, ''>[] = QUIZ_GAMES.flatMap((game) =>
	game.route === '' ? [] : playableOf(game.route)
);

/*
 * «MENU_POOL» І ПАРАМЕТР `pool` ТУТ БІЛЬШЕ НЕ ПОТРІБНІ.
 *
 * Другий набір існував для головного меню збірки для людей: там усі шість ігор
 * стояли рівними пунктами, тож випадкова гра мусила давати будь-яку з шести.
 * Тепер головне меню однакове в роботі й у продакшні — це розділи, а не ігри, —
 * і «Випадкова гра» лишилася там, де завжди й була за задумом: усередині
 * вікторини, тобто пропонує саме її пʼятірку.
 *
 * Прибрано разом із набором і параметр: жоден виклик його не передавав, а шлях,
 * який лишається лише для тесту, — це фальшивий борг, не гнучкість.
 */
export function pickRandomRoute(random: () => number = Math.random): Exclude<RouteRest, ''> {
	return PLAYABLE_ROUTES[Math.floor(random() * PLAYABLE_ROUTES.length)];
}

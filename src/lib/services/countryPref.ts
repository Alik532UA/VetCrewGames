import { COUNTRY_KEY } from '$lib/config/playerName';
import { isCountry } from '$lib/config/countries';
import { detectCountry } from '$lib/net/country';
import { storage } from './storage';

/**
 * ЯКИЙ ПРАПОР ПОКАЗУВАТИ, поки людина не вибрала свій.
 *
 * ## Навіщо окремий модуль
 *
 * Правило тут не одне, а три, і кожне має причину: вибір людини головніший за
 * будь-яку підказку; служба питається РІВНО РАЗ (у запиті їде IP); відповідь
 * запамʼятовується, зокрема відсутність вибору. Доти ці три правила жили в
 * `controllers/playerIdentity` — тобто лише в лобі, — а сторінці акаунта прапор
 * не діставався зовсім: там він починався з «без прапора», хоч у грі та сама
 * людина вже давно під своїм. Саме про це скарга автора: «прапор за
 * замовчуванням: без прапору, хоча в грі правильно детектить країну».
 *
 * ## Чому функції, а не сервіс зі станом
 *
 * Стан прапора вже є в двох місцях, і в кожного своя роль: у лобі це поле, яке
 * їде в кімнату, на сторінці акаунта — поле форми, яке чекає на «Зберегти».
 * Третій, «спільний», лише додав би питання, котрий із трьох правдивий. Тут
 * лишилися самі правила, і саме тому вони перевіряються без браузера.
 */

/**
 * Прапор, з якого починати: свій вибір, підказка служби або нічого.
 *
 * Порожній рядок означає «без прапора» — і це може бути ВІДПОВІДЬ, а не
 * відсутність відповіді: людина, яка вибрала «без прапора», записала у сховище
 * порожньо, і питати службу ще раз ми не маємо права.
 */
export async function preferredCountry(): Promise<string> {
	const saved = storage.get(COUNTRY_KEY);
	// `null` — ключа немає, тобто не питали. `''` — вибрали «без прапора».
	if (saved !== null) return isCountry(saved) ? saved : '';

	const guess = await detectCountry();
	if (guess === null) return '';

	/*
	 * Підказку памʼятаємо ТЕЖ, і це не кеш заради швидкості: без запису служба
	 * питалася б на кожному відкритті сторінки, тобто IP відвідувача їхав би в
	 * чужий журнал щоразу.
	 */
	storage.set(COUNTRY_KEY, guess);
	return guess;
}

/** Запамʼятати вибір людини. Порожньо — «без прапора», і це теж вибір. */
export function rememberCountry(code: string): void {
	storage.set(COUNTRY_KEY, isCountry(code) ? code : '');
}

import { dev } from '$app/environment';

/**
 * Відкрито чи ні службове меню розробника.
 *
 * Стан живе ОКРЕМО від обох сторін, і це єдиний спосіб їх не зв'язати: кнопка —
 * це номер версії в кореневому layout, а редагує меню партію заповідника.
 * Кореневий layout не має знати про заповідник (він спільний для всіх ігор), а
 * заповідник не має знати, де на екрані стоїть номер версії. Спільним лишається
 * рівно один прапорець.
 *
 * У продакшні меню немає взагалі: `dev` — це константа збірки, тож умова
 * `if (!dev) return` дає збирачеві прибрати й саме меню, і його код.
 */
class DevPanel {
	open = $state(false);

	toggle(): void {
		if (!dev) return;
		this.open = !this.open;
	}

	close(): void {
		this.open = false;
	}
}

export const devPanel = new DevPanel();

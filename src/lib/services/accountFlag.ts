import { storage } from './storage';

/**
 * «ЧИ Є АКАУНТ» — питання, на яке відповідають БЕЗ мережі.
 *
 * ## Навіщо окремий модуль на три рядки
 *
 * Тому що його імпортує кореневий layout, тобто КОЖНА сторінка. Усе, що лежить у
 * тому чанку, приїжджає кожному відвідувачеві, і бюджет цього чанку — гейт
 * (`npm run check:build`, 110 КБ gzip): один статичний імпорт `net/play` уже
 * вивів його за межу. Тут же layout дізнається відповідь ціною трьох рядків і
 * лише тоді вантажить синхронізацію — тобто той, хто просто грає, не тягне ні
 * модуля обміну, ні SDK бази.
 *
 * ## Чому не `auth.currentUser`
 *
 * Бо це вже мережа: `currentUser` є лише після того, як SDK піднявся й
 * анонімний вхід відбувся. Питання «варто взагалі під'єднуватися» мусить мати
 * відповідь ДО під'єднання, і сховище — єдине джерело, яке її дає одразу.
 *
 * Ключ живе тут, а не в двох місцях: доти прапорець ставив один модуль, а читав
 * інший, і рядок `'linked'` існував би двічі — розходження таких пар мовчазне.
 */
const KEY = 'linked';

/** Чи цей браузер уже входив в акаунт. `false` — мережі не потрібно. */
export function hasAccount(): boolean {
	return storage.get(KEY) === '1';
}

/** Акаунт з'явився: далі рахунок належить йому, а не браузеру. */
export function rememberAccount(): void {
	storage.set(KEY, '1');
}

/** Вийшли з акаунта. Разом із цим стирається й усе, що набрано (`playerData`). */
export function forgetAccount(): void {
	storage.remove(KEY);
}

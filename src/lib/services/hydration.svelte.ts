/**
 * ЧИ СКІНЧИЛАСЯ ГІДРАЦІЯ пререндереної сторінки — один прапорець на весь застосунок.
 *
 * Читає його `ui/DynamicIcon.svelte` (там і розписано, від чого це захищає): значок,
 * вибраний зі стану клієнта, після гідрації перестворюється з нуля й не несе в собі вузлів
 * пререндера. Ставить кореневий layout в `onMount`, тобто коли гідроване все дерево, — і
 * лише він (гейт `src/hydration-safe.test.ts`). Компоненти, створені ПІСЛЯ гідрації
 * (перехід усередині застосунку, відкрите вікно), бачать `true` одразу й нічого не
 * перестворюють. На сервері прапорець не ставиться ніколи.
 *
 * Та сама мить позначається й у DOM — `data-hydrated` на `<html>`. Її чекає умова спокою
 * e2e (`tests/support/settle.ts`, `waitForHydration`): пререндер виглядає осілим, і без
 * ознаки замір міряв сторінку ДО гідрації, коли модулі приходили повільно (флейк
 * `contrast-runtime` 2026-09-28, «назад» і «додому» шапки посеред `in:fade`).
 *
 * Функції, а не клас: модуль їде в чанк кореневого layout, чий бюджет коду (22 КБ gzip,
 * `scripts/check-build.mjs`) клас із геттером і сеттером перевищував на 32 байти.
 */
let done = $state(false);

/** `true`, щойно змонтувався кореневий layout: усе дерево вже гідроване. */
export const hydrated = () => done;

export const finishHydration = () => {
	done = true;
	document.documentElement.dataset.hydrated = '';
};

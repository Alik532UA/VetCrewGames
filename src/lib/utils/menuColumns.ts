/**
 * Геометрія БАГАТОКОЛОНКОВОЇ панелі: сусід у колонці й розмір, що вміщається.
 *
 * ## Навіщо окремий модуль
 *
 * `CountryMenu.svelte` стоїть на 292 SLOC при межі 300 (`structure.test.ts`
 * § 7), і колонки додають туди дві речі, які до розмітки не мають стосунку:
 * пошук сусіда за координатами й вимір вільного місця. Перше з них ще й
 * ЧИСТА ФУНКЦІЯ від списку координат — тобто його можна перевірити в `npm test`
 * без браузера, чого в компоненті не зробити ніяк: у jsdom
 * `getBoundingClientRect()` віддає нулі для всього.
 *
 * ## Чому координати, а не арифметика по індексах
 *
 * У CSS multicol номер колонки НЕ вивести з номера пункта: колонки заповнюються
 * по черзі, але скільки пунктів увійшло в кожну — вирішує браузер, і залежить це
 * від `break-inside: avoid` на розділах, від висоти заголовків і від того, чи
 * перенеслася довга назва в два рядки. Тобто «плюс N» не існує як число.
 * Координати ж є завжди й точні — їх і питаємо.
 */

/** Пункт, зведений до того, що потрібно для сусідства: ліворуч і вгору. */
export interface Spot {
	left: number;
	top: number;
}

/**
 * Скільки пікселів різниці ще вважається «та сама колонка».
 *
 * Один піксель, а не нуль: `getBoundingClientRect()` віддає дроби, і два пункти
 * однієї колонки можуть розійтися на 0,5px через масштаб сторінки. Колонки при
 * цьому стоять на ~190px одна від одної, тож помилитися нема на чому.
 */
const SAME_COLUMN = 1;

/**
 * Пункт, на який має перейти стрілка ВПРАВО або ВЛІВО.
 *
 * Правило в два кроки, і порядок кроків важливий: спершу знаходиться НАЙБЛИЖЧА
 * колонка в потрібний бік, і лише серед її пунктів — найближчий за висотою. Одна
 * зважена сума тут не годиться: колонка заввишки чотири тисячі пікселів, тобто
 * будь-яка вага, підібрана для одного набору країн, перевернеться на іншому —
 * далекий пункт сусідньої колонки почне вигравати в близького через дві.
 *
 * Немає колонки в цей бік — повертається той самий індекс, тобто нічого не
 * відбувається. Закільцьовувати горизонталь навмисно не стали: «вправо» з
 * останньої колонки на першу — це стрибок через увесь екран, і людина, яка
 * тримає стрілку, втратила б місце, замість дійти до краю й спинитися.
 */
export function columnNeighbour(spots: Spot[], from: number, by: number): number {
	const start = spots[from];
	if (!start) return from;

	let best = from;
	let bestGap = Infinity;
	let bestRow = Infinity;

	for (let i = 0; i < spots.length; i += 1) {
		const shift = spots[i].left - start.left;
		// Не той бік (або та сама колонка) — далі.
		if (by > 0 ? shift <= SAME_COLUMN : shift >= -SAME_COLUMN) continue;

		const gap = Math.abs(shift);
		const row = Math.abs(spots[i].top - start.top);

		// Дальша колонка — не цікавить, хоч би як близько був рядок.
		if (gap - bestGap > SAME_COLUMN) continue;
		// Ближча колонка — забирає вибір разом зі своїм рядком.
		if (bestGap - gap > SAME_COLUMN) {
			best = i;
			bestGap = gap;
			bestRow = row;
			continue;
		}
		// Та сама колонка: перемагає ближчий рядок.
		if (row < bestRow) {
			best = i;
			bestRow = row;
		}
	}

	return best;
}

/**
 * Те саме, але координати беруться з ЖИВОЇ панелі.
 *
 * Читання DOM живе тут, а не в компоненті, з тієї самої причини, що й решта
 * модуля: у `CountryMenu.svelte` лишається намір («перейти в сусідню колонку»), а
 * не спосіб. Плюс `columnNeighbour` вище залишається чистим — тобто перевірним
 * без браузера.
 *
 * `count` — довжина списку, у якому компонент тримає порядок пунктів. Розійшлася
 * з розміткою — повертається той самий індекс, тобто стрілка вбік не діє. Це
 * навмисно: вибрати НЕ ТУ країну гірше, ніж не зробити нічого.
 *
 * Усі коробки читаються одним проходом: браузер порахує розкладку раз, на
 * першому `getBoundingClientRect()`, і віддасть решту 262 з того самого стану.
 */
export function columnNeighbourIn(
	panel: HTMLElement | null,
	count: number,
	from: number,
	by: number
): number {
	const spots = spotsIn(panel, count, from);
	return spots ? columnNeighbour(spots, from, by) : from;
}

/**
 * Пункт у СУСІДНЬОМУ РЯДКУ — стрілка вниз або вгору в СІТЦІ прапорів.
 *
 * ## Навіщо, якщо є лінійний крок
 *
 * У колонках лінійний крок і є «вниз»: multicol заповнює спершу всю першу
 * колонку, потім другу, тож наступний пункт лежить під поточним. У сітці
 * (`.menu__group--flags` у `CountryMenu.svelte`) порядок документа йде РЯДКАМИ —
 * той самий наступний пункт лежить праворуч. Тобто без цієї функції «вниз»
 * означало б «вправо», і 262 прапори проходилися б по одному.
 *
 * ## Чому це та сама арифметика, тільько повернута
 *
 * «Найближчий рядок у потрібний бік, а в ньому — найближча колонка» — це
 * дослівно `columnNeighbour` із переставленими осями. Тому тут не другий
 * алгоритм, а транспонування: одна правда про сусідство, і зламати її можна
 * лише в одному місці.
 */
export function rowNeighbourIn(
	panel: HTMLElement | null,
	count: number,
	from: number,
	by: number
): number {
	const spots = spotsIn(panel, count, from);
	if (!spots) return from;
	const turned = spots.map((spot) => ({ left: spot.top, top: spot.left }));
	return columnNeighbour(turned, from, by);
}

/**
 * Координати всіх пунктів панелі — одним проходом.
 *
 * Браузер порахує розкладку раз, на першому `getBoundingClientRect()`, і віддасть
 * решту 262 з того самого стану.
 *
 * `null` означає «питати нема про що»: розмітка розійшлася з порядком, який
 * тримає компонент. Тоді стрілка не робить нічого — вибрати НЕ ТУ країну гірше,
 * ніж не зробити нічого.
 */
function spotsIn(panel: HTMLElement | null, count: number, from: number): Spot[] | null {
	const items = panel?.querySelectorAll<HTMLElement>('[role="option"]');
	if (!items || items.length !== count || from < 0) return null;
	return [...items].map((item) => {
		const box = item.getBoundingClientRect();
		return { left: box.left, top: box.top };
	});
}

/**
 * Відступ від краю вікна, який панель лишає собі за спиною.
 *
 * Не нуль: панель із тінню, притулена впритул до краю, читається як обрізана, а
 * на телефоні під нею ще й системна смуга.
 */
const GUTTER = 8;

/**
 * Проміжок між кнопкою й панеллю. Доти стояв у CSS як `calc(100% + 6px)`.
 *
 * Переїхав у JS разом із положенням: у `<body>` немає предка, від якого CSS
 * відкладав би ці 6px.
 */
const STEP = 6;

/**
 * Дія: сказати панелі, СКІЛЬКИ місця в неї є — праворуч і вниз.
 *
 * ## Що було не так
 *
 * Панель мала `max-width: min(88vw, 24rem)` і `max-height: min(60vh, 22rem)`.
 * Обидва числа не знають, ДЕ стоїть кнопка, і саме тому обидва помилялися:
 * заміряно на `/pairs/online/` — при вікні 1280×800 праворуч від кнопки лишалося
 * 800px, а панель брала 256; вниз лишалося 570px, а список брав 352 (бо `22rem`
 * менше за `60vh` при будь-якій висоті вікна більшій за 587px — тобто друга межа
 * не діяла ніколи). Вісім країн із 262 на екрані шириною в 1280 — це наслідок
 * саме цих двох чисел, а не розкладки.
 *
 * ## Чому вимір, а не CSS
 *
 * Праву межу панелі задає її власне положення на екрані, а CSS свого положення
 * не знає: `88vw` однакові й тоді, коли кнопка на початку рядка, і тоді, коли
 * вона під правим краєм. Тобто будь-яке число, вибране без виміру, або
 * недобирає ширини (як було), або вилазить за екран. Anchor positioning це
 * вміє, але його немає у Firefox.
 *
 * Записується РІВНО ДВА числа, а розкладку з них робить CSS: скільком колонкам
 * бути — вирішує `columns` за шириною, і в JS цього числа немає взагалі.
 *
 * ## ЧОМУ ПАНЕЛЬ ПЕРЕЇЖДЖАЄ В `<body>`
 *
 * Бо всередині картки її НЕМОЖЛИВО підняти над сусідніми картками — жодним
 * `z-index`. Скарга автора зі знімком: панель вибору країни на сторінці акаунта
 * лежить ПІД картками «Приватність», «Мої підписки» й «Таблиця лідерів».
 *
 * Причина не в числі, а в тому, що число ні з чим не порівнюється. Глобальний
 * `.text-panel` має `backdrop-filter: blur(10px)`, а непорожній `backdrop-filter`
 * створює ВЛАСНИЙ КОНТЕКСТ НАКЛАДАННЯ. Тобто `z-index: 9500` панелі порівнюється
 * лише з сусідами ВНУТРІ тієї самої картки, а самі картки — рівноправні шари,
 * складені в порядку документа: кожна наступна малюється поверх попередньої
 * ЦІЛКОМ, разом із усім, що з неї вилазить.
 *
 * ЗАМІРЯНО В БРАУЗЕРІ, а не виведено з міркувань: дві `.text-panel` поспіль,
 * усередині першої — коробка з `z-index: 9500`, і `elementFromPoint` у місці
 * перетину віддає ДРУГУ картку. Обчислені властивості першої при цьому:
 * `backdrop-filter: blur(10px)`, `filter: none`, `transform: none`,
 * `isolation: auto` — тобто винуватець рівно один.
 *
 * Підняти саму картку — не вихід: `z-index` картки мусив би перевищити 8000
 * (`PageScrollbar`), і тоді її ТЛО накрило б і смугу прокрутки, і шапку, щойно
 * сторінку прокрутять. Тому панель іде в `<body>`: там її 9500 знову
 * порівнюється з тим, із чим і калібрувався, — зі смугою (8000) і меню шапки
 * (9501).
 *
 * ## Ціна переїзду: положення тепер треба ставити самому
 *
 * У `<body>` немає кнопки, під якою панель стояла `absolute`. Тому координати —
 * із заміру кнопки, а `position` у стилях — `fixed`. Звідси й слухач прокрутки,
 * якого тут раніше НАВМИСНО не було: доти панель їхала разом зі сторінкою сама,
 * бо лежала в ній. Сторінка акаунта прокручується (панелей більше, ніж екрана),
 * тож без цього слухача панель відклеїлася б від кнопки.
 *
 * `capture: true` — бо подія прокрутки не булькає, а прокручувати можуть і
 * вікно, і внутрішній контейнер.
 */
/**
 * Предки, які прокручуються, плюс саме вікно.
 *
 * Разом це повний перелік того, від чого панель може «відклеїтися»: рухає її на
 * екрані будь-хто з них, а подія прокрутки не булькає, тож на кожного потрібен
 * свій слухач.
 */
function scrollParents(from: HTMLElement | null): EventTarget[] {
	const found: EventTarget[] = [window];
	for (let node = from?.parentElement ?? null; node; node = node.parentElement) {
		const style = getComputedStyle(node);
		if (/auto|scroll|overlay/.test(`${style.overflowY} ${style.overflowX}`)) found.push(node);
	}
	return found;
}

export function fitMenu(node: HTMLElement, anchor: HTMLElement | null) {
	/*
	 * Переїзд — саме тут, а не в окремій дії: розмір і положення панелі — одне
	 * питання («де вона вміщається»), і рознесені по двох файлах вони розійшлися б
	 * порядком виконання. Вимір нижче читає `box.left` уже переставленої панелі.
	 *
	 * ФОКУС ПЕРЕЖИВАЄ ПЕРЕЇЗД ЛИШЕ ЯВНО. Перенесення вузла — це виймання з дерева,
	 * і браузер знімає фокус із усього, що було всередині: він іде на `<body>`.
	 * Заміряно тут же — поле пошуку відкритої панелі втратило фокус, тобто панель,
	 * відкрита кнопкою, лишалася без клавіатури: ні `Escape`, ні стрілок.
	 *
	 * Саме так, а не порядком ефектів: фокус ставить вкладення на самому полі
	 * (`focusSearch`), і покладатися на те, чий ефект спрацює першим, означало б
	 * тримати клавіатуру на невидимій умові.
	 */
	const focused = node.contains(document.activeElement) ? document.activeElement : null;
	document.body.appendChild(node);
	if (focused instanceof HTMLElement) focused.focus();

	function measure() {
		/*
		 * Кнопка задає ліву межу, низ і НАЙМЕНШУ ширину: доти цим займався
		 * `min-width: 100%`, тобто ширина коробки-предка, якої в `<body>` немає.
		 */
		const button = anchor?.getBoundingClientRect();
		if (button) {
			node.style.top = `${Math.round(button.bottom + STEP)}px`;
			node.style.left = `${Math.round(button.left)}px`;
			node.style.setProperty('--menu-least', `${Math.round(button.width)}px`);
		}

		/*
		 * МІРЯТИ ТРЕБА ЗІ СТИСНУТОЮ ПАНЕЛЛЮ, інакше вимір бачить власний наслідок.
		 *
		 * Заміряно й спершу зроблено неправильно: панель ширша за екран розсуває
		 * сторінку, а сторінка тут центрована — тобто вміст їде ВЛІВО. При вікні
		 * 375px кнопка стояла на 28px, панель бралася за запасні 24rem (384px),
		 * вилазила на 37px за край, і в мить виміру кнопка була вже на −5px. Панель
		 * отримувала 372px замість 339 і впиралася в правий край рівно нулем зазору.
		 *
		 * Нуль у змінній робить ширину меншою за кнопку, а `min-width: 100%` не дає
		 * їй зникнути; читання нижче тут же примушує розкладку, тож обидва рядки
		 * лежать в одному такті — між ними браузер не малює, і миготіння немає. Той
		 * самий приом і з тієї самої причини — у `fitToViewport`.
		 */
		node.style.setProperty('--menu-room', '0px');
		const box = node.getBoundingClientRect();
		node.style.setProperty('--menu-room', `${Math.round(window.innerWidth - box.left - GUTTER)}px`);
		node.style.setProperty('--menu-tall', `${Math.round(window.innerHeight - box.top - GUTTER)}px`);
	}

	measure();
	window.addEventListener('resize', measure);

	/*
	 * ПРОКРУТКУ СЛУХАЄМО НА КОЖНОМУ ПРЕДКОВІ, ЩО ПРОКРУЧУЄТЬСЯ, а не лише на вікні.
	 *
	 * Подія прокрутки не булькає. На вікні її ще можна впіймати в фазі
	 * перехоплення, але сторінку тут прокручує не вікно: заміряно на
	 * `/pairs/online/` — прокручується `div.page-transition-wrapper` з
	 * `overflow-y: auto`, тобто ВНУТРІШНІЙ контейнер, і таких обгорток на шляху
	 * буває більше однієї. Перелічити їх від кнопки — єдиний спосіб не залежати від
	 * того, як саме браузер проводить подію до вікна.
	 */
	const scrollers = scrollParents(anchor);
	for (const target of scrollers) {
		target.addEventListener('scroll', measure, { passive: true });
	}

	return () => {
		window.removeEventListener('resize', measure);
		for (const target of scrollers) target.removeEventListener('scroll', measure);
		/*
		 * Знімаємо вузол САМІ: Svelte більше не знає, де він лежить, а перевірка
		 * `toHaveCount(0)` після закриття мусить лишатися правдою.
		 */
		node.remove();
	};
}

/**
 * Геометрія БАГАТОКОЛОНКОВОЇ панелі: сусід у колонці й у рядку.
 *
 * ## Навіщо окремий модуль
 *
 * `CountryMenu.svelte` стоїть близько межі 300 SLOC (`structure.test.ts` § 7), а пошук
 * сусіда за координатами до розмітки не має стосунку. Він ще й ЧИСТА ФУНКЦІЯ від списку
 * координат — тобто його можна перевірити в `npm test`
 * без браузера, чого в компоненті не зробити ніяк: у jsdom
 * `getBoundingClientRect()` віддає нулі для всього.
 *
 * ## Чому координати, а не арифметика по індексах
 *
 * У CSS multicol номер колонки НЕ вивести з номера пункта: колонки заповнюються
 * по черзі, але скільки пунктів увійшло в кожну — вирішує браузер, і залежить це
 * від `break-inside: avoid` на розділах, від висоти заголовків і від того, чи
 * перенеслася довга назва в два рядки. Тобто «плюс N» не існує як число.
 * Координати ж є завжди й точні — їх і питаємо.
 *
 * Розміру панелі тут більше немає: доти `fitMenu` ставив її під кнопку й міряв вільне місце,
 * а тепер вона заповнює вікно вибору (`CountryPicker`, прохання автора 2026-09-29).
 */

/** Пункт, зведений до того, що потрібно для сусідства: ліворуч і вгору. */
export interface Spot {
	left: number;
	top: number;
}

/**
 * Скільки пікселів різниці ще вважається «та сама колонка».
 *
 * Один піксель, а не нуль: `getBoundingClientRect()` віддає дроби, і два пункти
 * однієї колонки можуть розійтися на 0,5px через масштаб сторінки. Колонки при
 * цьому стоять на ~190px одна від одної, тож помилитися нема на чому.
 */
const SAME_COLUMN = 1;

/**
 * Пункт, на який має перейти стрілка ВПРАВО або ВЛІВО.
 *
 * Правило в два кроки, і порядок кроків важливий: спершу знаходиться НАЙБЛИЖЧА
 * колонка в потрібний бік, і лише серед її пунктів — найближчий за висотою. Одна
 * зважена сума тут не годиться: колонка заввишки чотири тисячі пікселів, тобто
 * будь-яка вага, підібрана для одного набору країн, перевернеться на іншому —
 * далекий пункт сусідньої колонки почне вигравати в близького через дві.
 *
 * Немає колонки в цей бік — повертається той самий індекс, тобто нічого не
 * відбувається. Закільцьовувати горизонталь навмисно не стали: «вправо» з
 * останньої колонки на першу — це стрибок через увесь екран, і людина, яка
 * тримає стрілку, втратила б місце, замість дійти до краю й спинитися.
 */
export function columnNeighbour(spots: Spot[], from: number, by: number): number {
	const start = spots[from];
	if (!start) return from;

	let best = from;
	let bestGap = Infinity;
	let bestRow = Infinity;

	for (let i = 0; i < spots.length; i += 1) {
		const shift = spots[i].left - start.left;
		// Не той бік (або та сама колонка) — далі.
		if (by > 0 ? shift <= SAME_COLUMN : shift >= -SAME_COLUMN) continue;

		const gap = Math.abs(shift);
		const row = Math.abs(spots[i].top - start.top);

		// Дальша колонка — не цікавить, хоч би як близько був рядок.
		if (gap - bestGap > SAME_COLUMN) continue;
		// Ближча колонка — забирає вибір разом зі своїм рядком.
		if (bestGap - gap > SAME_COLUMN) {
			best = i;
			bestGap = gap;
			bestRow = row;
			continue;
		}
		// Та сама колонка: перемагає ближчий рядок.
		if (row < bestRow) {
			best = i;
			bestRow = row;
		}
	}

	return best;
}

/**
 * Те саме, але координати беруться з ЖИВОЇ панелі.
 *
 * Читання DOM живе тут, а не в компоненті, з тієї самої причини, що й решта
 * модуля: у `CountryMenu.svelte` лишається намір («перейти в сусідню колонку»), а
 * не спосіб. Плюс `columnNeighbour` вище залишається чистим — тобто перевірним
 * без браузера.
 *
 * `count` — довжина списку, у якому компонент тримає порядок пунктів. Розійшлася
 * з розміткою — повертається той самий індекс, тобто стрілка вбік не діє. Це
 * навмисно: вибрати НЕ ТУ країну гірше, ніж не зробити нічого.
 *
 * Усі коробки читаються одним проходом: браузер порахує розкладку раз, на
 * першому `getBoundingClientRect()`, і віддасть решту 262 з того самого стану.
 */
export function columnNeighbourIn(
	panel: HTMLElement | null,
	count: number,
	from: number,
	by: number
): number {
	const spots = spotsIn(panel, count, from);
	return spots ? columnNeighbour(spots, from, by) : from;
}

/**
 * Пункт у СУСІДНЬОМУ РЯДКУ — стрілка вниз або вгору в СІТЦІ прапорів.
 *
 * ## Навіщо, якщо є лінійний крок
 *
 * У колонках лінійний крок і є «вниз»: multicol заповнює спершу всю першу
 * колонку, потім другу, тож наступний пункт лежить під поточним. У сітці
 * (`.menu__group--flags` у `CountryMenu.svelte`) порядок документа йде РЯДКАМИ —
 * той самий наступний пункт лежить праворуч. Тобто без цієї функції «вниз»
 * означало б «вправо», і 262 прапори проходилися б по одному.
 *
 * ## Чому це та сама арифметика, тільько повернута
 *
 * «Найближчий рядок у потрібний бік, а в ньому — найближча колонка» — це
 * дослівно `columnNeighbour` із переставленими осями. Тому тут не другий
 * алгоритм, а транспонування: одна правда про сусідство, і зламати її можна
 * лише в одному місці.
 */
export function rowNeighbourIn(
	panel: HTMLElement | null,
	count: number,
	from: number,
	by: number
): number {
	const spots = spotsIn(panel, count, from);
	if (!spots) return from;
	const turned = spots.map((spot) => ({ left: spot.top, top: spot.left }));
	return columnNeighbour(turned, from, by);
}

/**
 * Координати всіх пунктів панелі — одним проходом.
 *
 * Браузер порахує розкладку раз, на першому `getBoundingClientRect()`, і віддасть
 * решту 262 з того самого стану.
 *
 * `null` означає «питати нема про що»: розмітка розійшлася з порядком, який
 * тримає компонент. Тоді стрілка не робить нічого — вибрати НЕ ТУ країну гірше,
 * ніж не зробити нічого.
 */
function spotsIn(panel: HTMLElement | null, count: number, from: number): Spot[] | null {
	const items = panel?.querySelectorAll<HTMLElement>('[role="option"]');
	if (!items || items.length !== count || from < 0) return null;
	return [...items].map((item) => {
		const box = item.getBoundingClientRect();
		return { left: box.left, top: box.top };
	});
}

/**
 * АДРЕСА КІМНАТИ: `?room=` як єдине джерело правди про те, де я.
 *
 * ## Навіщо окремий модуль на два рядки
 *
 * Бо ці два рядки стоять у ЧОТИРЬОХ місцях: обидві сторінки онлайну ставлять
 * параметр при вході в кімнату й знімають його на «назад». Копії розійшлися б на
 * першій же правці, і розійшлися б непомітно — кожна виглядає правильною окремо.
 *
 * ## Чому саме параметр, а не окремий маршрут
 *
 * Бо кімната — це СТАН тієї самої сторінки, а не інша сторінка: форма входу й
 * кімната читають той самий матч, ту саму присутність і той самий перелік ігор.
 * Заразом адресу з кімнатою можна надіслати другові, і вона працює як посилання.
 */

/**
 * Та сама адреса з кімнатою. Новий обʼєкт: `page.url` правити не можна.
 *
 * `?from` ЗНІМАЄТЬСЯ (аудит 2026-09-26): він живе рівно до входу в кімнату —
 * переїзд у стару кімнату оголошено при створенні нової (`utils/crossGame.ts`).
 * Доти він лишався в адресі й після «назад», і КОЖНЕ наступне створення
 * оголошувало переїзд у стару кімнату знову — туди, куди група вже не йшла.
 */
export function withRoom(url: URL, code: string): URL {
	const next = new URL(url);
	next.searchParams.set('room', code);
	next.searchParams.delete('from');
	// `?move` теж відслужив: він потрібен лише до входу (`RoomInvite.check`).
	next.searchParams.delete('move');
	return next;
}

/**
 * Та сама адреса без кімнати — крок «назад» із кімнати на форму входу.
 *
 * Саме крок, а не окремий вихід: сторінка слухає адресу, тож зняття параметра
 * розбирає кімнату тим самим шляхом, яким її й збирали.
 */
export function withoutRoom(url: URL): URL {
	const next = new URL(url);
	next.searchParams.delete('room');
	return next;
}

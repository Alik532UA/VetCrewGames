import type { QuizPhase } from '$lib/controllers/quizMatch.svelte';

/**
 * ТАБЛО ОСТАННЬОГО РАУНДУ І Є ФІНАЛ (прохання автора 2026-09-26).
 *
 * Доти після останнього раунду йшло звичайне табло з заголовком «Наступний
 * раунд» — хоч наступного немає, — а за ним маленька панель «Гру завершено!» з
 * тими самими числами дрібним шрифтом. Два екрани поспіль з однаковим рахунком —
 * зайвий крок, і саме головний екран партії виходив найменшим.
 *
 * Тепер фінал — це табло останнього раунду: великим, із «+балами» цього раунду, що
 * докочуються в підсумок, і з кнопками під ним. Автор вибрав це з варіантів:
 * просто пропустити табло означало б загубити єдиний драматичний момент партії —
 * хто кого обігнав на останньому питанні.
 *
 * Фінал настає ще ДО того, як партію записано скінченою: ведучий закриває
 * останній раунд окремим ходом, коли табло простояло свій час, — і лише тоді
 * кнопки оживають (`QuizRoom`). Ця мить і табло — один і той самий екран, тож
 * анімація не повторюється, коли партія стає `over`.
 */
export function isFinalTable(
	over: boolean,
	phase: QuizPhase,
	round: number,
	total: number
): boolean {
	return over || (total > 0 && phase === 'reveal' && round >= total - 1);
}

/**
 * Скільки раундів малювати зіграними на смужках табло.
 *
 * На таблі раунд, що щойно скінчився, — теж зіграний: доти він лишався білим
 * «поточним», хоча його результат уже на екрані. У фіналі — усі.
 */
export function playedRounds(final: boolean, round: number, total: number): number {
	return final ? total : Math.min(total, Math.max(0, round + 1));
}

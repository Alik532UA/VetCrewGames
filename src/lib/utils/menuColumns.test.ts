// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { columnNeighbour, type Spot } from './menuColumns';

/**
 * Стрілка ВБІК у багатоколонковій панелі вибору країни.
 *
 * ## Чому це перевіряється тут, а не тільки в браузері
 *
 * Браузер перевіряє інше й потрібен для іншого: що колонки взагалі є, що розділ
 * не розрізаний і що поле пошуку не віддає каретку (`tests/country-menu.spec.ts`).
 * Саме ПРАВИЛО сусідства — арифметика над координатами, і в браузері його не
 * перевірити чесно: `getBoundingClientRect()` віддає те, що склалося, тобто
 * випадковий набір чисел, а не випадки, які мусять працювати.
 *
 * Числа тут узяті з заміру справжньої панелі при вікні 1280×800: колонки
 * стоять на 485, 673, 860 і 1048, тобто крок 187–188px, а рядок — 44px.
 */

/** Колонка з `n` пунктів: та сама абсциса, крок 44px по ординаті. */
function column(left: number, n: number, from = 0): Spot[] {
	return Array.from({ length: n }, (_, i) => ({ left, top: from + i * 44 }));
}

describe('сусід у колонці', () => {
	const left = column(485, 5); // 0..4, top 0..176
	const middle = column(673, 5); // 5..9
	const right = column(860, 5); // 10..14
	const spots = [...left, ...middle, ...right];

	it('перевірка жива: вправо з першої колонки переходить у другу', () => {
		expect(columnNeighbour(spots, 0, 1)).toBe(5);
	});

	it('вправо тримає ВИСОТУ, а не номер у списку', () => {
		// Третій пункт першої колонки (top 88) → третій пункт другої, не наступний.
		expect(columnNeighbour(spots, 2, 1)).toBe(7);
	});

	it('вліво повертає туди, звідки прийшли', () => {
		const aside = columnNeighbour(spots, 2, 1);
		expect(columnNeighbour(spots, aside, -1)).toBe(2);
	});

	/**
	 * НАЙГОЛОВНІШИЙ ВИПАДОК, і саме через нього правило — не одна зважена сума.
	 *
	 * Він не вигаданий: `break-inside: avoid` лишає в кінці колонок порожнє місце
	 * (заміряно — близько четвертої частини площі), тож стоячи внизу першої
	 * колонки, ти цілком можеш мати найближчий пункт другої на 400px нижче, а
	 * третю колонку — з пунктом рівно на своїй висоті. Правильна відповідь —
	 * друга: «вправо» означає сусідню колонку, а не найближчу точку на екрані.
	 *
	 * Зважена сума тут відповідає ТРЕТЮ: 188 + 400 більше за 375 + 0. Саме цим
	 * прогоном перша редакція тесту й показала себе непридатною — вона проходила
	 * і на зваженій сумі, бо в ній зсув був 176px, тобто менший за крок колонки.
	 */
	it('ближча колонка перемагає ближчий рядок', () => {
		const uneven = [...column(485, 1, 400), ...column(673, 5, 800), ...column(860, 5, 400)];
		expect(columnNeighbour(uneven, 0, 1)).toBe(1);
	});

	it('з крайньої колонки вбік не веде НІКУДИ — і не закільцьовується', () => {
		expect(columnNeighbour(spots, 12, 1)).toBe(12);
		expect(columnNeighbour(spots, 2, -1)).toBe(2);
	});

	/**
	 * Одна колонка — це телефон, і там стрілка вбік не мусить робити нічого:
	 * інакше вона перестрибувала б по списку, і людина не зрозуміла б, куди.
	 */
	it('в одній колонці стрілка вбік нічого не змінює', () => {
		const alone = column(8, 20);
		expect(columnNeighbour(alone, 7, 1)).toBe(7);
		expect(columnNeighbour(alone, 7, -1)).toBe(7);
	});

	it('дробові координати не роблять із однієї колонки двох', () => {
		// Той самий стовпчик, але з дробами від масштабування сторінки.
		const jittered: Spot[] = [
			{ left: 485, top: 0 },
			{ left: 485.4, top: 44 },
			{ left: 484.6, top: 88 }
		];
		expect(columnNeighbour(jittered, 0, 1)).toBe(0);
	});

	it('порожній список і неможливий індекс не кидають', () => {
		expect(columnNeighbour([], 0, 1)).toBe(0);
		expect(columnNeighbour(spots, 99, 1)).toBe(99);
	});
});

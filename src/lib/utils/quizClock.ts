import type { QuizAnswer } from './quizReplay';

/**
 * ЧАС СПІЛЬНОЇ ВІКТОРИНИ: коли раунд кінчається, що на екрані, що показує смуга.
 *
 * ## Чому окремим модулем
 *
 * `QuizMatch` уперся в межу розміру вдруге (315 рядків коду при межі 300), а канон
 * межу піднімати забороняє. Але розріз тут не через це: контролер уже оголошував —
 * «у ньому немає жодного таймера навмисно, час приходить аргументом, інакше
 * перевірка мусила б чекати справжні секунди». Виніс — це логічне завершення тієї
 * самої думки: якщо час лише аргумент, то й усі відповіді про час — чисті функції.
 *
 * Ні `$state`, ні годинника, ні мережі. Контролер віддає СЕБЕ: усі поля знімка в
 * нього вже публічні, тож окремий адаптер лише переписував би їхні імена — і
 * розходився б з інтерфейсом при кожній правці.
 *
 * ## ТРИ РІЗНІ ЧИСЛА, які легко сплутати
 *
 * Найважливіше, що тут закріплено, — вони РІЗНІ, і кожне відповідає на своє
 * питання:
 *
 *  * `limitLeftMs` — скільки лишилося до самої МЕЖІ ЧАСУ. На нього дивиться
 *    автовідповідь: «скільки в мене лишилося, щоб підтвердити»;
 *  * `barLeftMs` — що показує СМУГА. Те саме, але застигає, щойно відповіли всі:
 *    інакше вона стрибала б із половини на майже нуль, коли дедлайн переїжджає;
 *  * `deadlineAt` — коли раунд справді кінчається. На ньому тримається фаза.
 *
 * Сплутати їх — не абстрактна небезпека: смугу вже одного разу привʼязали до
 * дедлайну, і автор побачив стрибок.
 */

/** Знімок стану, з якого виводиться все про час. Лише дані й одна функція. */
export interface QuizClockView {
	/** Серверний час початку кожного раунду. */
	startedAt: Record<number, number>;
	/** Номер поточного раунду. `-1` — раунду ще немає. */
	round: number;
	/** Скільки триває поточний раунд, мс — уже зі швидкістю кімнати. */
	limitMs: number;
	/** Час, відданий за чекання, до моменту `now`. */
	heldMs: (now: number) => number;
	/** Відповіді: раунд → гравець → коли й наскільки правильно. */
	answers: Record<number, Record<string, QuizAnswer>>;
	/** Чи відповіли всі, кого партія чекає. */
	everyoneAnswered: boolean;
	/** Скільки чекати після останньої відповіді — зі швидкістю кімнати. */
	settleMs: number;
	/** Скільки видно табло між раундами — зі швидкістю кімнати. */
	revealMs: number;
}

/** Коли виходить сам ЧАС раунду — без затримок на розбір. `null` — раунду немає. */
function limitAt(view: QuizClockView, now: number): number | null {
	const start = view.startedAt[view.round];
	if (start === undefined) return null;
	return start + view.limitMs + view.heldMs(now);
}

/** Коли відповіли ОСТАННІМ у цьому раунді. `null` — ще ніхто. */
function lastAnswerAt(view: QuizClockView): number | null {
	const times = Object.values(view.answers[view.round] ?? {}).map((answer) => answer.at);
	return times.length === 0 ? null : Math.max(...times);
}

/**
 * Коли поточний раунд мусить закінчитися, за серверним часом. `null` — раунду немає.
 *
 * ПІСЛЯ ОСТАННЬОЇ ВІДПОВІДІ — затримка, ЩОБ ЇЇ ПОБАЧИТИ, і в обидві сторони.
 *
 * Тут стояло `Math.min(byTime, last + settle)`, тобто затримка вміла лише
 * СКОРОЧУВАТИ раунд: відповіли всі — не чекаємо решти. Але та сама умова зʼїдала
 * розбір, коли відповідь приходила в кінці, і саме це автор побачив: «відповідь
 * зʼявляється на мікросекунду, а потім вже табло результатів». Найгостріше — з
 * автовідповіддю, яка за побудовою спрацьовує за 300 мс до межі.
 *
 * Тепер правило одне на два випадки: раунд не кінчається раніше, ніж через `settle`
 * після останньої відповіді. Відповіли всі — рахуємо від неї (раунд може
 * скінчитися задовго до межі); відповіли не всі — межа, але не раніше за той самий
 * `settle`.
 *
 * Продовження ОБМЕЖЕНЕ одним `settle` поверх межі. Без цієї стелі кожна відповідь
 * під кінець зсувала б дедлайн наступній, і в кімнаті на дванадцять гравців раунд
 * тягнувся б на дванадцять затримок довше.
 */
export function deadlineAt(view: QuizClockView, now: number): number | null {
	const byTime = limitAt(view, now);
	if (byTime === null) return null;

	const last = lastAnswerAt(view);
	if (last === null) return byTime;

	const settle = last + view.settleMs;
	const end = view.everyoneAnswered ? settle : Math.max(byTime, settle);
	return Math.min(end, byTime + view.settleMs);
}

/**
 * Раунд іде чи вже табло. Час передається, а не читається з годинника.
 *
 * «Партія скінчилася» тут не вирішується навмисно: це стан КІМНАТИ (`status`), а не
 * висновок про час. Знімок його не бачить, і саме тому в ньому немає жодного поля,
 * яке не про час.
 */
export function phaseAt(view: QuizClockView, now: number): 'round' | 'reveal' {
	const deadline = deadlineAt(view, now);
	if (deadline === null) return 'round';
	return now >= deadline ? 'reveal' : 'round';
}

/**
 * Скільки лишилося до самої МЕЖІ ЧАСУ — без затримок на розбір і без застигання.
 *
 * На це число дивиться автовідповідь: воно й є «скільки в мене лишилося, щоб
 * підтвердити». Смуга для цього не годиться — вона застигає; дедлайн теж — він
 * уміє зʼїхати вперед на час розбору.
 */
export function limitLeftMs(view: QuizClockView, now: number): number {
	const limit = limitAt(view, now);
	return limit === null ? 0 : Math.max(0, limit - now);
}

/**
 * Що показує СМУГА. Застигає, щойно відповіли всі.
 *
 * Скарга автора: «коли всі відповіли, візуально таймер перестрибує на останні 1–2
 * секунди… нехай таймер зупиняється де був на момент відповіді останнього гравця».
 * Так і було, і саме через правильну логіку: дедлайн переїжджає на затримку після
 * останньої відповіді, а смуга рахувалася від дедлайну.
 *
 * Застигає саме ПОКАЗНИК, не правило: раунд однаково кінчається через `settle`,
 * просто ці секунду-дві смуга стоїть на місці, а не добігає.
 */
export function barLeftMs(view: QuizClockView, now: number): number {
	if (!view.everyoneAnswered) return limitLeftMs(view, now);
	const last = lastAnswerAt(view);
	if (last === null) return 0;
	const limit = limitAt(view, last);
	return limit === null ? 0 : Math.max(0, limit - last);
}

/** Чи час господареві оголошувати наступний раунд. */
export function nextDue(view: QuizClockView, now: number): boolean {
	const deadline = deadlineAt(view, now);
	if (deadline === null) return false;
	return now >= deadline + view.revealMs;
}

/**
 * Скільки лишилося ТАБЛУ між раундами. Нуль — табла немає або воно вже минуло.
 *
 * Скарга автора: «між раундами, там де показує рахунок, немає таймера — невідомо,
 * скільки чекати наступний раунд». Число для цього вже існувало, але лише як
 * умова: `nextDue` відповідає «пора чи ні», а на екрані потрібне «скільки ще».
 *
 * Та сама пара, що й у раунді: одна функція вирішує, коли фаза кінчається, а друга
 * віддає залишок для смуги. Виводяться обидві з `deadlineAt`, тож розійтися не
 * можуть — а два незалежні відліки на одному екрані розійшлися б обовʼязково.
 */
export function revealLeftMs(view: QuizClockView, now: number): number {
	const deadline = deadlineAt(view, now);
	if (deadline === null) return 0;
	return Math.max(0, deadline + view.revealMs - now);
}

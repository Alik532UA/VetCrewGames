/**
 * Наскільки зменшити підпис картки, щоб він умістився — чиста арифметика.
 *
 * Винесено окремо від DOM з тієї самої причини, що й `fitZoom`: тут живуть усі
 * рішення, які легко зробити неправильно, і всі вони перевіряються без браузера.
 *
 * ## Чому тут НЕ потрібна мертва зона, а в `fitZoom` потрібна
 *
 * Різниця принципова, і без неї цей файл виглядав би як недоробка сусіднього.
 *
 * `fitZoom` бореться зі ЗВОРОТНИМ ЗВ'ЯЗКОМ: масштаб сторінки міняє розкладку, а
 * розкладка міняє потрібний масштаб — і система дрижить. Тут такого зв'язку
 * НЕМА: ширина картки задана слотом (`max-width: 110px` і `aspect-ratio`), і від
 * розміру шрифту вона не залежить нітрохи. Тобто «доступно» — величина
 * незалежна, і другий вимір дасть те саме число, що перший.
 *
 * Крок усе одно є, і не для стабільності, а щоб різні назви однакової довжини
 * отримували однаковий розмір: без нього два підписи по 15 символів відрізнялися
 * б на пів відсотка, і в одному рядку карток це видно.
 */

/**
 * Дно масштабу. Нижче підпис перестає читатися з відстані витягнутої руки —
 * а це саме та відстань, з якої дитина дивиться на планшет.
 *
 * Коли й на дні не вміщається, підпис НЕ обрізається: він переходить у два
 * рядки (див. `fitLabel`). Обрізане «Reuzenmierenet…» у грі, де тварину треба
 * впізнати за назвою, гірше за дрібний шрифт у два рядки.
 */
export const MIN_LABEL_SCALE = 0.7;

/** Крок масштабу: 5% від 16px — це 0.8px, тобто помітна, але не груба щабель. */
export const LABEL_STEP = 0.05;

/**
 * Запас у пікселях. Без нього підпис, який «рівно вміщається», у наступному
 * кадрі вже виїжджає: округлення ширини й курсив-подібні відступи гліфів дають
 * розбіжність у частку пікселя (FLUID-SIZING-v8 § 8.1).
 */
export const LABEL_SLACK_PX = 1;

export interface LabelFit {
	/** Множник до базового розміру шрифту. `1` — не зменшувати. */
	scale: number;
	/**
	 * Чи дозволити перенос у два рядки.
	 *
	 * `true` лише тоді, коли навіть на дні масштабу текст не вміщається в рядок.
	 * Це не «або-або»: масштаб при цьому все одно стоїть на дні.
	 */
	wrap: boolean;
}

/**
 * Який масштаб дати підпису, знаючи природну й доступну ширину.
 *
 * `needed` — ширина тексту В ОДИН РЯДОК при масштабі 1. Міряти її треба саме при
 * масштабі 1: вимір під уже застосованим масштабом дає значення, з якого
 * наступне обчислення виводить нове, — і підпис повзе з кожним перерахунком.
 *
 * Текст, який вміщається, НЕ зменшується — це вимога, а не оптимізація: підпис
 * мусить бути однаковим у всіх карток, де він і так уміщався.
 */
export function labelFit(needed: number, available: number): LabelFit {
	// Ще не заміряно (елемент прихований або нульової ширини) — не чіпаємо.
	if (needed <= 0 || available <= 0) return { scale: 1, wrap: false };

	if (needed <= available - LABEL_SLACK_PX) return { scale: 1, wrap: false };

	const raw = (available - LABEL_SLACK_PX) / needed;

	// Округлення ВНИЗ: 0.83 → 0.80, а не 0.85. Догори могло б не вміститися, і
	// весь замір був би марний.
	const stepped = Math.floor(raw / LABEL_STEP) * LABEL_STEP;
	const scale = Number(Math.max(MIN_LABEL_SCALE, Math.min(1, stepped)).toFixed(4));

	// Дно не врятувало — далі рятує перенос, а не дальше зменшення.
	return { scale, wrap: raw < MIN_LABEL_SCALE };
}

/**
 * НАЙБІЛЬШИЙ КРОК, ЗА ЯКОГО ТЕКСТ СПРАВДІ ВМІЩАЄТЬСЯ, — вимір, а не пропорція.
 *
 * `labelFit` рахує пропорцією: кегль на 10% менший — рядок на 10% вужчий. Так і є, поки
 * ширини гліфів дробові (Windows). Chromium на Linux округлює їх до цілих пікселів, і той
 * самий рядок меншим кеглем буває ширшим за пропорцію на кілька пікселів — рівно стільки,
 * скільки підпису на картинці й забракло в CI (2026-09-28). Тож пропорція тут — лише
 * перша спроба: від неї крок униз, поки не вміститься, або вгору, поки вміщається. Текст
 * меншає рівно настільки, щоб стати в рядок, — і не більше.
 *
 * Масштаб 1 не пробується: сюди приходять, коли за нього вже НЕ вмістилося.
 *
 * @param first Перша спроба — `labelFit(...).scale`.
 * @param fits Чи вміщається текст за цього масштабу — вимір на сторінці.
 */
export function largestFittingScale(first: number, fits: (scale: number) => boolean): number {
	const onGrid = (scale: number) => {
		const clamped = Math.min(1, Math.max(MIN_LABEL_SCALE, scale));
		return Number((Math.round(clamped / LABEL_STEP) * LABEL_STEP).toFixed(4));
	};

	let scale = onGrid(first);
	if (fits(scale)) {
		for (let up = onGrid(scale + LABEL_STEP); up < 1 && fits(up); up = onGrid(up + LABEL_STEP)) {
			scale = up;
		}
		return scale;
	}
	while (scale > MIN_LABEL_SCALE) {
		scale = onGrid(scale - LABEL_STEP);
		if (fits(scale)) return scale;
	}
	// І дно не врятувало — далі рятує перенос.
	return MIN_LABEL_SCALE;
}

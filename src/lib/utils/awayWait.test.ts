// @vitest-environment node
import { describe, expect, it } from 'vitest';
import {
	AWAY_GRACE_FLOOR_MS,
	AWAY_GRACE_MS,
	awaySecondsLeft,
	awayStamps,
	goOnDecided,
	pauseSecondsLeft,
	shouldHoldRound,
	votesNeeded,
	waitView,
	type WaitSource
} from './awayWait';
import type { Member } from '$lib/net/roomTypes';
import { readFileSync } from 'node:fs';

/**
 * ОЧІКУВАННЯ ЗНИКЛОГО: скільки чекаємо й коли партія справді стоїть.
 *
 * ## Що тут доводиться
 *
 * Вимога автора: «зʼявляється по центру екрану вікно що перекриває гру з
 * очікуванням гравця, поки чекаєте гравця, то у грі зупиняється таймер і до
 * таймера додається +3 секунди, бо це відволікаючий фактор».
 *
 * Пауза без межі перетворює вихід одного гравця на зупинку всіх — тому межі тут
 * дві, і кожна перевіряється окремо: пільговий час і «зниклий уже відповів». Друга
 * важливіша за першу: без неї той, хто відповів і закрив вкладку, тримав би раунд
 * на паузі, а присутні отримували б чужий час у подарунок.
 *
 * Сам зсув дедлайну живе в `controllers/quizMatch` (`setHold`) — там же й
 * надбавка в три секунди.
 */

const member = (uid: string): Member =>
	({ uid, name: uid, country: '', avatar: null }) as unknown as Member;

describe('пільговий час', () => {
	it('рахується від НАЙПІЗНІШОГО зникнення', () => {
		const now = 100_000;
		const since = { a: now - 10_000, b: now - 2_000 };

		// Якби рахувалося від найранішого, лишилося б 5 с; від найпізнішого — 13.
		expect(awaySecondsLeft([member('a'), member('b')], since, now)).toBe(
			Math.ceil((AWAY_GRACE_MS - 2_000) / 1000)
		);
	});

	it('без зниклих — нуль, а не пільга', () => {
		expect(awaySecondsLeft([], {}, 100_000)).toBe(0);
	});

	it('вичерпаний час не стає відʼємним', () => {
		const now = 100_000;
		expect(awaySecondsLeft([member('a')], { a: now - AWAY_GRACE_MS - 5_000 }, now)).toBe(0);
	});
});

describe('чи стоїть партія', () => {
	it('стоїть, поки зниклий не відповів і рішення не ухвалене', () => {
		expect(shouldHoldRound([member('a')], [], [], 2)).toBe(true);
	});

	/**
	 * Головна межа: зниклий, що вже відповів, раунду не тримає. Інакше «відповів і
	 * закрив вкладку» дарувало б присутнім чужий час.
	 */
	it('не стоїть, якщо зниклий уже відповів', () => {
		expect(shouldHoldRound([member('a')], ['a'], [], 2)).toBe(false);
	});

	/**
	 * ПІЛЬГОВИЙ ЧАС БІЛЬШЕ НЕ ЗНІМАЄ ПАУЗУ — і це головна зміна правила.
	 *
	 * Доти партія йшла далі сама за 15 секунд. Вимога автора: «після таймеру
	 * автоматично НЕ зникає вікно і не продовжується гра, а кнопка
	 * розблоковується». Причина в житті: гравець перезавантажує комп'ютер, і
	 * рішення чекати чи ні належить тим, хто грає.
	 */
	it('стоїть і після пільгового часу, поки не проголосували', () => {
		expect(shouldHoldRound([member('a')], [], [], 2)).toBe(true);
	});

	it('не стоїть, коли голосів досить', () => {
		// Двоє присутніх — треба два голоси.
		expect(shouldHoldRound([member('a')], [], ['b'], 2)).toBe(true);
		expect(shouldHoldRound([member('a')], [], ['b', 'c'], 2)).toBe(false);
	});

	it('не стоїть, коли всі на місці', () => {
		expect(shouldHoldRound([], [], [], 2)).toBe(false);
	});

	it('двоє зниклих: досить одного, хто не відповів', () => {
		expect(shouldHoldRound([member('a'), member('b')], ['a'], [], 3)).toBe(true);
	});
});

describe('скільки голосів потрібно', () => {
	it('більшість присутніх', () => {
		expect(votesNeeded(2)).toBe(2);
		expect(votesNeeded(3)).toBe(2);
		expect(votesNeeded(4)).toBe(3);
		expect(votesNeeded(5)).toBe(3);
	});

	/**
	 * Один присутній — один голос. Це не помилка округлення: коли решта пішла,
	 * рішення нема з ким ділити, і вимагати двох означало б замкнути людину в
	 * кімнаті назавжди.
	 */
	it('один присутній вирішує сам', () => {
		expect(votesNeeded(1)).toBe(1);
		expect(goOnDecided(['a'], 1)).toBe(true);
	});

	it('свій голос рахується один раз — це вже забезпечує журнал', () => {
		expect(goOnDecided(['a'], 2)).toBe(false);
		expect(goOnDecided(['a', 'b'], 2)).toBe(true);
	});
});

describe('мить зникнення', () => {
	it('тримає попередню мітку, а не переставляє її щоразу', () => {
		const players = [member('a'), member('b')];
		const first = awayStamps(players, ['b'], {}, 1_000);
		expect(first).toEqual({ a: 1_000 });

		// `a` і далі відсутній — мітка мусить лишитися першою, інакше пільговий час
		// поновлювався б на кожному знімку присутності й не закінчувався б ніколи.
		const later = awayStamps(players, ['b'], first, 9_000);
		expect(later).toEqual({ a: 1_000 });
	});

	it('той, хто повернувся, зникає з переліку', () => {
		const players = [member('a')];
		expect(awayStamps(players, ['a'], { a: 1_000 }, 9_000)).toEqual({});
	});
});

describe('стан чекання одним викликом', () => {
	const NOW = 50_000;

	const source = (over: Partial<WaitSource> = {}): WaitSource => ({
		away: [member('a')],
		answered: [],
		goOn: [],
		present: ['b', 'c'],
		players: [member('a'), member('b'), member('c')],
		pausedBy: null,
		pausedAt: 0,
		graceSpent: () => 0,
		pauseReadyAt: () => 0,
		...over
	});

	it('збирає паузу, межу голосів і відлік', () => {
		const view = waitView(source(), { a: NOW }, NOW, 'b');
		expect(view.hold).toBe(true);
		expect(view.needed).toBe(2);
		expect(view.left).toBe(AWAY_GRACE_MS / 1000);
		expect(view.pausedBy).toBeNull();
	});

	it('досить голосів — партія не стоїть', () => {
		expect(waitView(source({ goOn: ['b', 'c'] }), {}, NOW, 'b').hold).toBe(false);
	});

	/** Матчу ще немає — чекати нема на що, і це не «пауза за замовчуванням». */
	it('без матчу партія не стоїть', () => {
		expect(waitView(null, {}, NOW, 'b')).toEqual({
			hold: false,
			needed: 1,
			left: 0,
			pausedBy: null,
			canPause: false
		});
	});

	/** Пауза й зникнення дають ОДИН відлік: на екрані це одне вікно. */
	it('під паузою відлік рахується від ходу, а не від пільги зникнення', () => {
		const view = waitView(
			source({ away: [], pausedBy: 'a', pausedAt: NOW }),
			{},
			NOW + 5_000,
			'b'
		);
		expect(view.pausedBy?.uid).toBe('a');
		expect(view.left).toBe(AWAY_GRACE_MS / 1000 - 5);
		expect(view.hold, 'паузу знімає людина або голос, а не відлік').toBe(true);
	});

	/**
	 * ВИТРИМКА після своєї паузи — щоб кнопкою не смикали партію. Вимога автора:
	 * «після того як зняли паузу той самий гравець не може ставити паузу протягом
	 * хвилини».
	 */
	it('своя витримка закриває кнопку паузи', () => {
		const ready = { pauseReadyAt: (uid: string) => (uid === 'b' ? NOW + 10_000 : 0) };
		expect(waitView(source({ away: [], ...ready }), {}, NOW, 'b').canPause).toBe(false);
		expect(waitView(source({ away: [], ...ready }), {}, NOW, 'c').canPause).toBe(true);
		expect(waitView(source({ away: [], ...ready }), {}, NOW + 10_000, 'b').canPause).toBe(true);
	});

	it('під паузою кнопки паузи немає ні в кого', () => {
		expect(waitView(source({ pausedBy: 'a' }), {}, NOW, 'b').canPause).toBe(false);
	});
});

/**
 * ВІКНО ОЧІКУВАННЯ ІСНУЄ, ЛИШЕ ПОКИ ПАРТІЯ ЧЕКАЄ.
 *
 * У першій редакції я зробив другий стан — ту саму панель смугою вгорі, коли
 * чекати вже нема на що. Вийшла нелогіка, яку автор назвав точно: проголосувавши,
 * гравець бачив «Чекаємо на нього. Продовжити без нього?» і поруч «Ваш голос
 * враховано 1/1». Питання ставилося після того, як на нього вже відповіли, а
 * панель висіла над грою без причини.
 *
 * Правило звідси таке: вікно існує, щоб ЗАПИТАТИ. Є відповідь — вікна немає. Хто
 * офлайн, показує сірий рядок у переліку гравців, і це інша річ: вона показує
 * стан, а не питає.
 *
 * Поведінкову половину перевіряє `shouldHoldRound` вище: щойно голосів досить,
 * пауза знята. Тут — проводка: що компонент справді залежить від неї, а питання
 * ставиться лише тому, хто ще не голосував.
 */
describe('вікно очікування', () => {
	const source = readFileSync('src/lib/components/quiz/QuizAway.svelte', 'utf8');

	it('малюється лише поки партія чекає', () => {
		expect(source, 'вікно мусить залежати від `waiting`, а не лише від складу').toContain(
			'{#if waiting && listed.length > 0}'
		);
	});

	/**
	 * ДВІ ПРИЧИНИ, ОДНЕ ВІКНО: зникнення й пауза. Тримати два майже однакові вікна
	 * означало б розійтися в них першою ж правкою — а стан на екрані один і той
	 * самий: «партія стоїть, і ось чому».
	 */
	it('те саме вікно показує й паузу', () => {
		expect(source, 'рядок мусить називати причину').toContain(
			"pausedBy ? 'quiz.pauseBy' : 'quiz.awayWait'"
		);
		expect(source, 'автор паузи знімає її сам і без відліку').toContain(
			'data-testid="quiz-pause-resume-btn"'
		);
	});

	/**
	 * Напис на кнопці — єдине, що змінюється після мого голосу. Питання зникло
	 * разом із заголовком і списком: чотири блоки про одне автор назвав шумом, і
	 * мав рацію.
	 */
	it('кнопка каже, чи мій голос уже врахований', () => {
		expect(source, 'без цього гравець не бачить, чи натиск дійшов').toContain(
			"iVoted ? 'quiz.awayVoted' : 'quiz.awayGoOn'"
		);
	});

	/**
	 * ІМЕНА, А НЕ ЗАЙМЕННИКИ. «Чекаємо на нього» брехало щоразу, коли зникала
	 * жінка: імена в проєкті випадкові з обох родів.
	 */
	it('вікно називає зниклих імʼям', () => {
		expect(source, 'імʼя мусить бути в рядку очікування').toContain('member.name');
		expect(source, 'займенникових ключів більше немає').not.toContain('quiz.awayDecide');
		expect(source, 'заголовка «немає звʼязку» більше немає').not.toContain('quiz.awayTitle');
	});

	/**
	 * Обрізане імʼя ховає саме те, заради чого вікно існує.
	 *
	 * Дивимося в САМЕ ПРАВИЛО, а не в текст файлу: слова «max-width: 12ch» стоять і
	 * в коментарі, який пояснює цю правку, — і перевірка на підрядок падала на
	 * власному поясненні.
	 */
	it('імʼя не обрізається', () => {
		const rule = source.slice(source.indexOf('.away__name {'));
		const body = rule.slice(0, rule.indexOf('}'));
		expect(body, 'обмеження ширини на імені ріже його трьома точками').not.toContain('max-width');
	});
});

/**
 * НАКОПИЧУВАЛЬНА ПІЛЬГА: наступне зникнення починається з решти, а не з нуля.
 *
 * Дефект, який описав автор: «можна відключатися на 14 секунд і повертатися, і
 * знову буде таймер на 15 секунд». Так і було — позначка зникнення зникала разом
 * із поверненням, тобто повний відлік вертався щоразу, і чекати можна було
 * безкінечно.
 *
 * Витрачене тепер приходить із журналу (`quizMatch.graceSpent`), тобто однакове в
 * усіх — це вибір автора (варіант B): ціна в записі на кожне зникнення, зате
 * ніхто не бачить свого власного відліку.
 */
describe('накопичувальна пільга', () => {
	const NOW = 100_000;
	const gone = { a: NOW };

	it('без витраченого — повна пільга', () => {
		expect(awaySecondsLeft([member('a')], gone, NOW, () => 0)).toBe(AWAY_GRACE_MS / 1000);
	});

	it('витрачене відрізається від наступного відліку', () => {
		// Витратив 3 с із 15 — лишається 12.
		expect(awaySecondsLeft([member('a')], gone, NOW, () => 3000)).toBe(12);
	});

	/**
	 * ПІДЛОГА В ТРИ СЕКУНДИ — захист від протилежного зловживанню: у гравця з
	 * поганим звʼязком пільга скінчилася б за пʼять коротких обривів, і далі його
	 * виключали б МИТТЮ.
	 */
	it('вичерпана пільга лишає три секунди', () => {
		expect(awaySecondsLeft([member('a')], gone, NOW, () => AWAY_GRACE_MS)).toBe(
			AWAY_GRACE_FLOOR_MS / 1000
		);
		expect(awaySecondsLeft([member('a')], gone, NOW, () => AWAY_GRACE_MS * 10)).toBe(
			AWAY_GRACE_FLOOR_MS / 1000
		);
	});

	it('у кожного своя решта: чекаємо доти, доки чекає хоч один', () => {
		const two = [member('a'), member('b')];
		const since = { a: NOW, b: NOW };
		const spent = (uid: string) => (uid === 'a' ? AWAY_GRACE_MS : 0);

		// `a` витратив усе (лишилося 3 с), `b` не витратив нічого (15 с) — чекаємо 15.
		expect(awaySecondsLeft(two, since, NOW, spent)).toBe(AWAY_GRACE_MS / 1000);
	});
});

/**
 * ПАУЗА: той самий стан, що зникнення, лише з іншою причиною.
 *
 * Легального способу спинити партію доти не було — лише «вийти, щоб зупинити»,
 * як назвав це автор. Тому пауза бере ту саму механіку: ті самі п'ятнадцять
 * секунд, той самий накопичувальний запас, те саме вікно поверх гри.
 *
 * Різниця, яку перевіряють ці випадки: пауза тримає раунд БЕЗЗАСТЕРЕЖНО. Зникнення
 * можна не чекати, якщо зниклий уже відповів; паузу поставили навмисно, і зняти її
 * може або автор, або голосування.
 */
describe('пауза', () => {
	it('тримає раунд, навіть коли всі відповіли', () => {
		expect(shouldHoldRound([], ['a', 'b'], [], 2, 'a')).toBe(true);
	});

	it('знімається голосуванням присутніх', () => {
		// Один голос із двох потрібних — пауза тримається.
		expect(shouldHoldRound([], [], ['b'], 2, 'a')).toBe(true);
		expect(shouldHoldRound([], [], ['b', 'c'], 2, 'a')).toBe(false);
	});

	it('без паузи правило працює як доти', () => {
		expect(shouldHoldRound([member('a')], [], [], 2, null)).toBe(true);
		expect(shouldHoldRound([], [], [], 2, null)).toBe(false);
	});

	/** Відлік паузи — той самий запас, що в зникнення, і та сама підлога. */
	it('відлік паузи зменшується витраченим', () => {
		const now = 100_000;
		expect(pauseSecondsLeft(now, 0, now)).toBe(AWAY_GRACE_MS / 1000);
		expect(pauseSecondsLeft(now, 3000, now)).toBe(12);
		expect(pauseSecondsLeft(now, AWAY_GRACE_MS, now)).toBe(AWAY_GRACE_FLOOR_MS / 1000);
	});

	/**
	 * НУЛЬ НЕ ЗНІМАЄ ПАУЗУ. Він лише відкриває решті кнопку — саме тому автор і
	 * просив, щоб пауза працювала й без запасу: «інші можуть ОДРАЗУ зняти паузу».
	 */
	it('нуль на відліку не знімає паузу сам', () => {
		expect(shouldHoldRound([], [], [], 2, 'a')).toBe(true);
	});
});

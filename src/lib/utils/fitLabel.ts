import { labelFit, MIN_LABEL_SCALE } from './labelScale';

export { MIN_LABEL_SCALE };

/**
 * Дія: зменшити підпис картки РІВНО настільки, щоб він умістився — і не більше.
 *
 * ## Що було не так
 *
 * Довга назва робила КАРТКУ ШИРШОЮ за її слот. Заміряно на скріншотах автора:
 * слот 110px, картка в ньому 118.78px — тобто картка визирала з-під рамки, а в
 * рядку з трьох штовхала сусідів. Причина в тому, що картка — це елемент сітки,
 * а елемент сітки типово не може стати вужчим за свій `min-content`, і для
 * нерозривного слова `Reuzenmiereneter` цей мінімум і є ширина слова.
 *
 * ## Дві половини рішення, і CSS-половина головніша
 *
 * **CSS гарантує, що картка НЕ РОСТЕ, і робить це без JS.** `min-width: 0` на
 * картці знімає той мінімум, а `overflow: hidden` на підписі робить його власний
 * внесок у мінімальну ширину нульовим. Це не оздоба: якщо цей скрипт не
 * виконається, картка все одно лишиться в межах слота — просто підпис буде
 * обрізаний. Напрямок відмови має дивитися сюди.
 *
 * **JS робить підпис читабельним.** Він міряє й зменшує шрифт — але лише коли
 * текст справді не вміщається. Назва, що вміщалася, лишається того самого
 * розміру, що й раніше: інакше всі картки в рядку мали б різний кегль, і це
 * читалося б як дефект.
 *
 * ## Шрифти
 *
 * Перший вимір відкладений до `document.fonts.ready`. Проєкт вантажить власний
 * шрифт, а в запасному ті самі 16 символів займають іншу ширину — тобто вимір до
 * завантаження дає масштаб для чужого шрифта. Помітно це саме на межі: підпис,
 * який мусив лишитися цілим, приїжджає зменшеним.
 */

/**
 * ІМЕНА ЗМІННИХ ПИШУТЬСЯ ЛІТЕРАЛАМИ в місці виклику, а не через константи.
 *
 * Це вимога інваріанта `src/css-variables.test.ts`: він знаходить рантаймові
 * оголошення грепом по `setProperty('--x', …)`. Через константу він їх не бачить
 * і звітує «посилання на неоголошену змінну» — і має рацію, бо сенс перевірки
 * саме в тому, щоб людина й греп могли знайти, ЗВІДКИ береться значення.
 * Непряме звернення через константу це й ламає.
 *
 * Змінних чотири, і вони працюють парами:
 *   `--label-scale`   — множник до базового кегля;
 *   `--label-wrap`, `--label-break`, `--label-hyphens` — СТАН ПЕРЕНОСУ,
 *   потрібний лише тоді, коли навіть на дні масштабу текст не вміщається в
 *   рядок. Типові значення в CSS означають «в один рядок».
 *
 * Чому саме інлайнові стилі, а не клас: клон під пальцем — це `cloneNode(true)`
 * картки, який живе в `<body>` і не успадковує нічого від слота. `cloneNode`
 * копіює інлайнові стилі, тож і масштаб, і стан переносу їдуть разом із ним.
 * Заодно це знімає «Unused CSS selector»: селектор під атрибут, який ставить
 * лише скрипт, компілятор Svelte не бачить.
 */

/**
 * Скільки чекати, поки розкладка вгамується. Те саме число, що у
 * `fitToViewport`, і з тієї самої причини: довше за кадр і коротше за людське
 * «одразу».
 */
const SETTLE_MS = 140;

/**
 * @param node Елемент із текстом підпису. Мусить мати `overflow: hidden` і
 *   `white-space: nowrap` у типовому стані — саме на них тримається і вимір, і
 *   гарантія без JS.
 * @param _text Текст підпису. Значення не використовується: він тут лише щоб
 *   Svelte викликав `update` при зміні назви, якщо елемент перевикористали.
 */
export function fitLabel(node: HTMLElement, _text?: string) {
	if (typeof ResizeObserver === 'undefined') return;

	let pending: ReturnType<typeof setTimeout> | null = null;
	let alive = true;

	/** Прибрати все своє — і перед виміром, і при знищенні дії. */
	function reset() {
		node.style.removeProperty('--label-scale');
		node.style.removeProperty('--label-wrap');
		node.style.removeProperty('--label-break');
		node.style.removeProperty('--label-hyphens');
	}

	function measure() {
		/*
		 * Скидаємо ДО виміру: природну ширину рядка можна прочитати лише при
		 * масштабі 1. Скидання й читання в одному такті — браузер між ними не
		 * малює, тож стрибка розміру не видно.
		 */
		reset();

		/*
		 * «СКІЛЬКИ МІСЦЯ Є» ПИТАЄМО В БАТЬКА, а не в самого підпису — і це не
		 * дрібниця, а причина, через яку перша редакція зменшувала все підряд.
		 *
		 * Підпис — flex-елемент, тож його власна ширина дорівнює ширині ТЕКСТУ,
		 * поки текст коротший за доступне місце. Отже для «Hert» `clientWidth` і
		 * `scrollWidth` — те саме число, умова «не вміщається» спрацьовує на
		 * рівності, і назва з чотирьох літер приїжджала зменшеною на 5%. Заміряно в
		 * браузері: `scale: 0.95` там, де мусила бути одиниця.
		 *
		 * Батько (`.game-card__name`) розтягнутий на всю ширину картки, тож його
		 * `clientWidth` і є справжнє доступне місце.
		 */
		const available = node.parentElement?.clientWidth ?? node.clientWidth;

		// `scrollWidth` — природна ширина рядка: текст `nowrap`, коробка з
		// `overflow: hidden`, тож перенесення не спотворює вимір.
		const fit = labelFit(node.scrollWidth, available);

		/*
		 * РЕЗУЛЬТАТ ПИШЕТЬСЯ ЗАВЖДИ, і саме тут була моя помилка.
		 *
		 * Перша редакція мала «оптимізацію»: якщо число не змінилося — виходимо, не
		 * торкаючись стилю (як у `fitToViewport`). Але тут вихід стояв ПІСЛЯ
		 * `reset()`, тобто стиль уже був стертий, і дострокове повернення лишало
		 * підпис БЕЗ масштабу. Заміряно в Playwright: після звуження слота до 40px
		 * атрибут `style` існував і був ПОРОЖНІЙ, а кегль лишався 16px.
		 *
		 * Циклу «запис → подія спостерігача → запис» це не створює: `reset()` і
		 * запис відбуваються синхронно в одному такті, а `ResizeObserver` порівнює
		 * розмір у кінці кадру з останнім, про який повідомляв. Якщо результат той
		 * самий, різниці немає — і повідомлення не буде. Якщо інший, наступний
		 * прохід дасть те саме число, і на ньому все стане.
		 */
		if (fit.scale !== 1) node.style.setProperty('--label-scale', String(fit.scale));
		if (fit.wrap) {
			node.style.setProperty('--label-wrap', 'normal');
			node.style.setProperty('--label-break', 'anywhere');
			node.style.setProperty('--label-hyphens', 'auto');
		}
	}

	/**
	 * ВИМІР ВІДКЛАДЕНИЙ, доки розкладка не вгамується — і це не оптимізація.
	 *
	 * Перша редакція міряла негайно, і тест ловив на цьому справжній дефект:
	 * підпис, який вміщається, приїжджав зменшеним до дна (11.2px замість 16px).
	 * Причина — перший вимір потрапляв у мить, коли картка ще не мала своєї
	 * ширини: до застосування `zoom` із `fitToViewport`, до розкладки зображень.
	 * `parentElement.clientWidth` тоді дає одиниці пікселів, і масштаб виходить
	 * для неіснуючого стану.
	 *
	 * `SETTLE_MS` і сам прийом узяті з `fitToViewport`: таймер перезаводиться на
	 * кожну подію, тож поки розкладка рухається, вимір не настає взагалі. Ціна —
	 * приблизно кадр, у якому задовгий підпис уже обрізаний `overflow: hidden`,
	 * але ще не зменшений.
	 *
	 * Таймер, а не `requestAnimationFrame`: черга кадрів не йде в прихованих
	 * вкладках і панелях, тобто саме там, де це й перевіряють
	 * (AI-AGENT-PITFALLS-v8 § 2). Заміряно сьогодні ж: `ResizeObserver` у
	 * прихованій панелі не спрацьовує зовсім, а мікрозадача з `fonts.ready` —
	 * спрацьовує.
	 */
	function schedule() {
		if (!alive) return;
		if (pending) clearTimeout(pending);
		pending = setTimeout(() => {
			pending = null;
			measure();
		}, SETTLE_MS);
	}

	/*
	 * СПОСТЕРІГАЄМО ЗА БАТЬКОМ, А НЕ ЗА САМИМ ПІДПИСОМ — і це не однаково.
	 *
	 * Підпис — flex-елемент, тож для короткої назви його ширина дорівнює ширині
	 * ТЕКСТУ: обмеження `max-width: 100%` при цьому не діє. Отже коли картка
	 * РОЗШИРЮЄТЬСЯ, ширина підпису не змінюється зовсім, спостерігач не
	 * спрацьовує, і зменшений кегль залипає назавжди.
	 *
	 * Заміряно в Playwright: після повернення слота зі 40px до 103px підпис
	 * лишався 11.2px, і поверталося воно лише тоді, коли назва була досить довгою,
	 * щоб обмеження діяло. Тобто дефект залежав від довжини слова — саме той
	 * різновид, який в одному прогоні є, а в іншому немає.
	 *
	 * Батько (`.game-card__name`) має `width: 100%`, тож його ширина завжди йде за
	 * карткою: і при зміні вікна, і при `zoom`, який ставить `fitToViewport`.
	 * Окремий слухач `resize` після цього не потрібен.
	 */
	const sizes = new ResizeObserver(schedule);
	sizes.observe(node.parentElement ?? node);

	/*
	 * Перший вимір — після шрифтів, і теж через `schedule`.
	 *
	 * `?? Promise.resolve()` для середовищ без Font Loading API (jsdom у
	 * юніт-прогоні): там вимір просто станеться одразу, і це коректно — власного
	 * шрифта там немає взагалі.
	 */
	const ready = document.fonts?.ready ?? Promise.resolve();
	void ready.then(() => {
		if (alive) schedule();
	});

	return {
		update() {
			// Нова назва в тому самому елементі — природна ширина інша.
			schedule();
		},
		destroy() {
			alive = false;
			if (pending) clearTimeout(pending);
			sizes.disconnect();
			reset();
		}
	};
}

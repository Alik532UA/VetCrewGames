import { fitZoom, MIN_ZOOM, ZOOM_STEP } from './fitZoom';

export { MIN_ZOOM };

/**
 * Дія: зменшити ВЕСЬ екран гри рівно настільки, щоб він умістився.
 *
 * Не картки, не шрифт, не відступи поокремо — усе разом, одним коефіцієнтом.
 * Поелементне стискання завжди лишає щось незачепленим: підганяєш варіанти
 * відповіді, а кнопка «Перевірити» так і стоїть за краєм. Тут стискається
 * сторінка цілком, тож або вміщається все, або нічого — третього стану немає.
 *
 * **Чому `zoom`, а не `transform: scale()`.** `transform` малює інакше, але
 * розкладку лишає ту саму: висота елемента для прокрутки не змінюється, і під
 * зменшеною сторінкою повисає порожнє місце заввишки з відрізане. `zoom` міняє
 * саме розкладку. Заміряно тут-таки: сторінка з `flex: 1` у вікні на 596px при
 * `zoom: 0.8` дістає 745 власних пікселів — рівно 596/0.8.
 *
 * **Дно 0.75.** Нижче інтерфейс перестає бути придатним для пальця: кнопка в
 * 44px стає 33px. Коли й цього замало, повертається чесна прокрутка — гортати
 * гірше, ніж не влучати.
 *
 * ## Чому воно дрижало
 *
 * Масштаб — зворотний зв'язок: він міняє розкладку, а розкладка міняє потрібний
 * масштаб. Три речі замикали це в цикл, і всі три вилікувані тут:
 *
 *  1. **Перерахунок на кожну зміну розміру.** Поки під питанням розкривався
 *     розбір, висота дитини мінялася щокадру — і щокадру мінявся масштаб. Тепер
 *     вимір відкладений на `SETTLE_MS`: рахуємо ОДИН раз, коли все стало на
 *     місце, а не двадцять разів поки воно ставало.
 *  2. **Коефіцієнт без кроку.** Кожен піксель вікна давав нове число, і система
 *     не мала на чому зупинитися. Тепер крок 2%, а зона нечутливості асиметрична:
 *     звужуємо одразу, розтягуємо лише з запасом у два кроки — див. `fitZoom`.
 *  3. **Запис того самого значення.** Стиль переписувався навіть коли число не
 *     змінилося, а кожен запис — це нова розкладка й новий виклик спостерігача.
 *     Тепер пишемо лише різницю.
 */

/**
 * Скільки чекати, поки розкладка вгамується.
 *
 * Довше за кадр і коротше за людське «одразу». Переходи Svelte тут тривають
 * 200–400 мс, а адресний рядок на телефоні ховається приблизно стільки ж; за
 * 140 мс тиші можна вважати, що рух скінчився.
 */
const SETTLE_MS = 140;

export function fitToViewport(node: HTMLElement) {
	if (typeof ResizeObserver === 'undefined') return;

	let pending: ReturnType<typeof setTimeout> | null = null;
	/** Масштаб, який стоїть у стилі. Саме з ним порівнюється новий. */
	let applied = 1;

	function measure() {
		pending = null;

		/*
		 * Міряти треба БЕЗ зуму: інакше кожен вимір бачить наслідок попереднього і
		 * коефіцієнт повзе. Скидання й читання йдуть в одному такті, тож браузер
		 * між ними не малює — миготіння не буде.
		 */
		const before = node.style.zoom;
		node.style.zoom = '1';

		/*
		 * Скільки місця Є — питаємо в ПРОКРУТНИКА, не в самої сторінки.
		 *
		 * Сторінка росте разом із вмістом, тож її власні `scrollHeight` і
		 * `clientHeight` завжди рівні між собою — заміряно: додаєш 900px вмісту,
		 * обидва стають 1454. Умова «не вміщається» на цих числах не спрацювала б
		 * ніколи, хоч прокрутка й з'явилася б на 858 пікселів.
		 */
		const viewport = node.parentElement;
		const needed = node.scrollHeight;
		const available = viewport ? viewport.clientHeight : node.clientHeight;

		const next = fitZoom(needed, available, applied);

		if (next === applied) {
			// Нічого не змінилося — і стиль лишається тим самим рядком, який був.
			node.style.zoom = before;
			return;
		}
		applied = next;
		// Порожній рядок, а не `1`: так у стилі не лишається сліду там, де
		// масштабувати не було чого.
		node.style.zoom = next === 1 ? '' : String(next);
	}

	/*
	 * Зміни приходять пачками — і хвіст пачки важливіший за її початок.
	 *
	 * Таймер перезаводиться на кожну подію, тож поки розкладка рухається, вимір не
	 * настає взагалі. Саме це й прибирає дрижання: масштаб міняється раз, коли рух
	 * скінчився.
	 *
	 * Таймер, а не `requestAnimationFrame`: черга кадрів не йде у фонових вкладках
	 * і в прихованих панелях, тобто саме там, де цю поведінку й перевіряють. З rAF
	 * перерахунок після відповіді просто ніколи не настав би, і дефект був би
	 * невидимий для вимірювання (AI-AGENT-PITFALLS-v8 § 2).
	 */
	function schedule() {
		if (pending) clearTimeout(pending);
		pending = setTimeout(measure, SETTLE_MS);
	}

	/*
	 * Спостерігач за ДІТЬМИ, а не за самою сторінкою: сторінка розтягнута на всю
	 * висоту вікна (`flex: 1`), тож її власна коробка не змінюється ніколи —
	 * навіть коли під питанням розкривається розбір. А саме це й треба ловити.
	 */
	const sizes = new ResizeObserver(schedule);
	const watchChildren = () => {
		sizes.disconnect();
		for (const child of node.children) sizes.observe(child);
	};

	/*
	 * Стежимо за структурою ВСЬОГО піддерева, а не лише за прямими дітьми.
	 *
	 * Партія починається в `onMount`, тобто вже після цієї дії: у мить першого
	 * виміру сторінка майже порожня, а картки з'являються глибоко всередині
	 * панелей. Прямі діти при цьому не міняються взагалі, тож спостерігач за ними
	 * мовчав — заміряно: сторінка просила 648px при 596 доступних, а зум лишався
	 * одиницею.
	 *
	 * `attributes` тут НЕ вмикаємо: під час перетягування картці щокадру
	 * переписують `transform`, і перерахунок ішов би на кожен рух пальця.
	 */
	const structure = new MutationObserver(() => {
		watchChildren();
		schedule();
	});
	structure.observe(node, { childList: true, subtree: true });

	watchChildren();
	window.addEventListener('resize', schedule);
	// Перший вимір — одразу: сторінка не мусить показуватися завеликою й осідати.
	measure();

	return {
		destroy() {
			if (pending) clearTimeout(pending);
			sizes.disconnect();
			structure.disconnect();
			window.removeEventListener('resize', schedule);
			node.style.zoom = '';
		}
	};
}

export { ZOOM_STEP };

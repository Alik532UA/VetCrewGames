/**
 * ТЕЛЕФОН — МЕНШИЙ БІК ЕКРАНА ВУЖЧИЙ ЗА 560px, у будь-якому положенні.
 *
 * Доти рахувалася лише ширина, і телефон боком (844×390) діставав повну колоду
 * «Знайди пару» на сім колонок — чотири ряди в екран заввишки 390px не влазили.
 * Мірило одне на гру й на кімнату: соло вибирає за ним розкладку, а учасник
 * кімнати пише його у свій рядок складу, щоб спільну сітку вибрав найменший екран
 * (рішення автора 2026-09-26).
 */
export const COMPACT_SCREEN_QUERY = '(max-width: 559px), (max-height: 559px)';

/** Чи це телефон. Поза браузером (prerender, тести без `matchMedia`) — ні. */
export function isCompactScreen(): boolean {
	return (
		typeof window !== 'undefined' &&
		window.matchMedia?.(COMPACT_SCREEN_QUERY).matches === true
	);
}

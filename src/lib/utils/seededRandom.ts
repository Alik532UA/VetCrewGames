/**
 * Передбачуваний генератор випадкових чисел — mulberry32.
 *
 * Тридцять два біти стану, одна функція, жодних залежностей. Потрібен саме
 * передбачуваний, і не заради тестів: те саме зерно має давати ту саму гру в
 * усіх учасників спільної партії, інакше довелося б пересилати весь стан
 * замість одного числа.
 *
 * Один на проєкт навмисно. Доти він лежав копією в `config/memory-game.ts`, і
 * друга копія в симуляції означала б два генератори, які колись розійдуться —
 * а розійшовшись, дадуть двом гравцям різні світи з однакового зерна.
 */
export function seededRandom(seed: number): () => number {
	let state = seed >>> 0;
	return () => {
		state = (state + 0x6d2b79f5) >>> 0;
		let t = state;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

/** Тасування Фішера — Йетса на заданому генераторі. */
export function shuffle<T>(items: readonly T[], random: () => number): T[] {
	const out = [...items];
	for (let i = out.length - 1; i > 0; i--) {
		const j = Math.floor(random() * (i + 1));
		[out[i], out[j]] = [out[j], out[i]];
	}
	return out;
}

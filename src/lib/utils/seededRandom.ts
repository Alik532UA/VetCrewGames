/**
 * Передбачуваний генератор випадкових чисел — mulberry32.
 *
 * Тридцять два біти стану, одна функція, жодних залежностей. Потрібен саме
 * передбачуваний, і не заради тестів: те саме зерно має давати ту саму гру в
 * усіх учасників спільної партії, інакше довелося б пересилати весь стан
 * замість одного числа.
 *
 * Один на проєкт навмисно. Доти він лежав копією в `config/memory-game.ts`, і
 * друга копія в симуляції означала б два генератори, які колись розійдуться —
 * а розійшовшись, дадуть двом гравцям різні світи з однакового зерна.
 */
export function seededRandom(seed: number): () => number {
	let state = seed >>> 0;
	return () => {
		state = (state + 0x6d2b79f5) >>> 0;
		let t = state;
		t = Math.imul(t ^ (t >>> 15), t | 1);
		t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}

/**
 * Джерело випадковості ПАРТІЇ: із зерна — однакове в усіх, без зерна — своє.
 *
 * Одні двері замість `if (seed)` у пʼятьох контролерах. Соло-партія зерна не має
 * й не потребує: кожен захід має бути іншим. Спільна — має, і саме тому досить
 * переслати одне число замість набору раундів.
 *
 * `undefined`, а не `0`: нуль — цілком законне зерно, і трактувати його як
 * «зерна немає» означало б мати одну партію, яка мовчки грає інакше.
 */
export const randomFor = (seed?: number): (() => number) =>
	seed === undefined ? Math.random : seededRandom(seed);

/**
 * Один елемент зі списку. Порожній список — `null`, а не виняток: «усі набори
 * вичерпані» — це звичайний стан партії, а не помилка.
 *
 * Окремою функцією, бо той самий рядок стояв копією в чотирьох іграх — і в
 * кожній був місцем, де можна помилитися на одиницю.
 */
export function pickOne<T>(items: readonly T[], random: () => number): T | null {
	if (items.length === 0) return null;
	return items[Math.floor(random() * items.length)];
}

/** Тасування Фішера — Йетса на заданому генераторі. */
export function shuffle<T>(items: readonly T[], random: () => number): T[] {
	const out = [...items];
	for (let i = out.length - 1; i > 0; i--) {
		const j = Math.floor(random() * (i + 1));
		[out[i], out[j]] = [out[j], out[i]];
	}
	return out;
}

/**
 * Скільки масштабу потрібно сторінці — чиста арифметика, без DOM.
 *
 * Винесено окремо саме тому, що тут живе вся боротьба з ДРИЖАННЯМ. Масштаб —
 * зворотний зв'язок: він міняє розкладку, розкладка міняє потрібний масштаб. На
 * телефоні цей цикл видно оком: адресний рядок ховається й з'являється, `dvh`
 * зменшується й росте, і сторінка смикається сама собою, коли гравець нічого не
 * робить.
 *
 * Проти цього тут дві речі, і жодна з них не косметична.
 *
 * **Крок.** Масштаб округлюється до 2%. Дрібне гуляння висоти впирається в те
 * саме округлене число — а те саме число не переписується, тобто розкладка не
 * рухається, тобто цикл не має чим продовжитися. Без кроку кожен піксель вікна
 * давав новий коефіцієнт, і зупинитися системі було ні на чому.
 *
 * **Мертва зона — АСИМЕТРИЧНА, і це головне.** Звужуємо одразу, щойно сторінка
 * перестала вміщатися: тут помилка видна як обрізаний вміст, і терпіти її не
 * можна. А розширюємо лише коли зʼявився запас у два кроки. Симетрична зона
 * шириною в один крок не боронила б нічого: сусідні кратні числа відрізняються
 * рівно на крок, тож «менше за крок» не блокує жодного переходу — саме на цьому
 * перша версія й дрижала.
 */

/** Далі зменшувати нема сенсу: сенсорні цілі стають меншими за палець. */
export const MIN_ZOOM = 0.75;

/**
 * СТЕЛЯ РОСТУ (прохання автора 2026-09-27: «95% порожнє, а ми мілким елементом пишемо»).
 *
 * Доти масштаб ішов лише вниз: гра, що на ноутбуці займала шосту частину екрана, так і
 * лишалася маленькою посеред лісу. Тепер той самий один коефіцієнт росте, доки вміст не
 * заповнить висоту чи ширину.
 *
 * Стеля — та сама, що в одиниці решти застосунку (`--fill-u` у global.css: від 1 до
 * 2,125 rem), бо друге прохання автора було саме про це: «масштабування не пропорційне».
 * Зі стелею 1,6 на 1920×1080 шапка росла вдвічі, а вибір режиму «Де живем?» лише в 1,6
 * раза й займав 20% екрана.
 */
export const MAX_ZOOM = 2.125;

/** Крок масштабу. Дрібніше око не бачить, а цикл на дрібнішому не спиняється. */
export const ZOOM_STEP = 0.02;

/**
 * Наскільки має побільшати вільного місця, щоб масштаб РОЗТЯГНУВСЯ назад.
 *
 * Два кроки, а не один: між сусідніми кратними числами рівно крок, тож зона
 * шириною в крок не блокує нічого. Чотири відсотки — це та різниця, за якої
 * розтягування вже варте перемальовування.
 */
export const GROW_BAND = 2 * ZOOM_STEP;

/**
 * ЯКУ ЧАСТКУ ВИСОТИ ЗАЙМАЄ ВМІСТ — 90%, і в обидва боки (правило автора 2026-09-27: «треба
 * триматися правила для всіх випадків так, щоб елементи разом на 90% екрану»).
 *
 * Доти ціль була 100%: сторінка стискалася лише тоді, коли вже не вміщалася, і росла, доки
 * не впиралася в край. Звідси обидві скарги того самого дня — вікно пошуку на телефоні
 * займало 105% екрана (вікна не масштабувалися зовсім), а до плиток — 60%. Тепер і стискання,
 * і ріст цілять у 90% висоти під шапкою: десята частина лишається полями, а не прокруткою
 * чи порожнечею.
 */
export const FILL_SHARE = 0.9;

/**
 * Скільки місця лишити під краєм. Без запасу сторінка, яка «рівно вміщається»,
 * у вужчому вікні вже віддає прокрутку через смугу (FLUID-SIZING-v8 § 8.1).
 */
export const SLACK_PX = 2;

/**
 * Який масштаб ставити, знаючи потрібну й доступну висоту.
 *
 * `current` потрібен, щоб відповісти «нічого не міняти»: функція повертає його ж,
 * коли різниця в межах мертвої зони. Саме це повернене значення й читає той, хто
 * викликав, — і не пише в стиль нічого.
 *
 * `max` — наскільки дозволено РОСТИ. Типово 1, тобто рівно те, що було: лише вниз. Той,
 * хто кличе, дає більше, коли знає, що сторінці є куди рости й ушир (`fitToViewport`).
 *
 * `min` — наскільки дозволено СТИСКАТИСЯ. Типово дно для пальця (`MIN_ZOOM`); 1 — не
 * стискатися зовсім: так масштабують сторінки, яким на телефоні природно прокручуватися
 * (лобі, хаб), а не зменшуватися.
 *
 * `share` — ціль, частка висоти (`FILL_SHARE`). Параметром — лише для тестів арифметики.
 */
export function fitZoom(
	needed: number,
	available: number,
	current: number,
	max = 1,
	min = MIN_ZOOM,
	share = FILL_SHARE
): number {
	if (needed <= 0 || available <= 0) return 1;

	const room = available * share;
	const ceiling = Math.max(1, max);
	let raw = needed > room + SLACK_PX ? (room - SLACK_PX) / needed : 1;
	// Ріст — лише коли його дозволили і вміст справді нижчий за ціль.
	if (ceiling > 1 && needed < room - SLACK_PX) {
		raw = Math.min(ceiling, (room - SLACK_PX) / needed);
	}

	/*
	 * Поточний масштаб лишається, поки він РОБОЧИЙ: сторінка при ньому вміщається,
	 * не вищий за стелю, і вільного місця не набралося на два кроки. Саме ця умова й
	 * глушить дрижання — дрібне гуляння висоти жодну з її частин не перевертає.
	 */
	const fits = needed * current <= room - SLACK_PX;
	if (fits && current <= ceiling && raw - current < GROW_BAND) return current;

	// Округлення ВНИЗ: 0.951 → 0.94, а не 0.96. Догори могло б не вміститися.
	const stepped = Math.min(ceiling, Math.max(min, Math.floor(raw / ZOOM_STEP) * ZOOM_STEP));
	return Number(stepped.toFixed(4));
}

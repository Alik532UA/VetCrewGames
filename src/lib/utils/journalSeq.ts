/**
 * ВІЛЬНИЙ НОМЕР У ЖУРНАЛІ ХОДІВ — `skip`-тий, рахуючи від ПЕРШОЇ ДІРКИ.
 *
 * ## Чому дірка, а не «найбільший плюс один»
 *
 * «Найбільший плюс один» віддає будь-кому, хто може дописати хід, право вирішити,
 * яким буде наступний номер. Один хід із `seq: 1e20` (правило бази доти
 * перевіряло лише, що це число) робив наступний номер недосяжним: `1e20 + k` у
 * числах із рухомою комою — те саме `1e20` для будь-якої спроби, і кімната
 * вікторини переставала приймати ходи (аудит 2026-09-23). Перша дірка від чужого
 * далекого номера не залежить зовсім.
 *
 * ## Навіщо `skip`
 *
 * За номер борються: автопідтвердження стріляє в усіх у ту саму серверну мить.
 * Якщо знімок із номером суперника ще не приїхав, наступна спроба не мусить
 * битися в той самий номер — вона бере наступний вільний. Дірка, яку це лишає,
 * нічого не ламає: вікторина перепрогонює журнал цілком.
 *
 * @param taken зайняті номери, ЗА ЗРОСТАННЯМ
 * @param skip скільки вільних номерів пропустити (номер спроби)
 */
export function freeSeq(taken: readonly number[], skip = 0): number {
	let seq = 1;
	let skipped = 0;
	for (const busy of taken) {
		while (seq < busy) {
			if (skipped === skip) return seq;
			skipped += 1;
			seq += 1;
		}
		if (busy === seq) seq += 1;
	}
	return seq + (skip - skipped);
}

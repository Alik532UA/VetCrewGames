import type { Member } from '$lib/net/roomTypes';
import { rankedBy } from './standings';

/**
 * ПОРЯДОК РЯДКІВ НА ТАБЛІ МІЖ РАУНДАМИ — дві фази, а не одна.
 *
 * ## Що було не так
 *
 * Рядки стояли на КІНЦЕВИХ місцях від першого кадру. У коді була записана
 * причина — інакше вони стрибали б місцями протягом набору чисел, — і вона
 * правильна. Але рішення викидало половину сенсу: числа рухалися, а на питання
 * «як змінилося моє становище» табло не відповідало ніяк.
 *
 * Скарга автора саме про це: «не видно на якому місці був гравець до цього раунду
 * і як змінилось його положення».
 *
 * ## Чому це окрема функція
 *
 * Бо це ПРАВИЛО, а не оформлення, і його можна перевірити без браузера: у jsdom
 * немає ні `requestAnimationFrame` із реальним часом, ні `animate:flip`, тобто
 * сам переїзд перевірити нічим. А порядок — можна, і саме в ньому дефект і був.
 */

/** Рахунок ДО цього раунду. Виводиться з підсумку й приросту, без нового джерела. */
export const scoreBefore = (
	uid: string,
	scores: Record<string, number>,
	gains: Record<string, number>
): number => (scores[uid] ?? 0) - (gains[uid] ?? 0);

/**
 * Рахунок, за яким стоїть рядок у поточній фазі.
 *
 * `moved === false` — фаза набору: рахунок МИНУЛОГО раунду, і порядок не
 * міняється, поки біжать числа. `moved === true` — після паузи: підсумок, і всі
 * рядки їдуть разом, один раз. Той самий рахунок дає і порядок, і номер місця
 * (`utils/standings.ts`): інакше номер показав би нове місце на старому рядку.
 */
export const phaseScore =
	(scores: Record<string, number>, gains: Record<string, number>, moved: boolean) =>
	(uid: string): number =>
		moved ? (scores[uid] ?? 0) : scoreBefore(uid, scores, gains);

/**
 * Склад у порядку показу для поточної фази.
 *
 * Рівний рахунок розводить `order` — порядок входу в кімнату. Без нього два
 * гравці з однаковими очками могли б переставлятися місцями від перемалювання до
 * перемалювання, бо `sort` не обіцяє стабільності для рівних елементів.
 */
export function rankedByPhase(
	players: readonly Member[],
	scores: Record<string, number>,
	gains: Record<string, number>,
	moved: boolean
): Member[] {
	return rankedBy(players, phaseScore(scores, gains, moved));
}

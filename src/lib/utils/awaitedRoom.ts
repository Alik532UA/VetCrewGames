import type { OwnRoom } from '$lib/net/ownRooms';
import { roomLife } from '$lib/config/roomLife';

/**
 * ЯКА З МОЇХ КІМНАТ СПРАВДІ ЧЕКАЄ НА МЕНЕ — і чи взагалі якась.
 *
 * ## Задача
 *
 * Гравець вийшов зі сторінки партії й пішов у меню. Партія при цьому йде, решта
 * бачить «немає зв'язку» й не знає, чи він вернеться, чи пішов назовсім. Автор
 * описав вихід так: сповіщення «вас чекають у грі» з кнопками «повернутися» й
 * «вийти з кімнати» — тобто система нарешті розрізняє випадковий вихід від
 * свідомого.
 *
 * ## Чому це окремий модуль
 *
 * Бо це ПРАВИЛО, а не показ: «чекає» — не те саме, що «моя кімната існує». Дві
 * межі, і обидві потрібні:
 *
 *  * `playing` — у лобі ніхто нікого не тримає, а скінчена партія не чекає нікого
 *    (сам перелік уже віддає лише `playing`, перевірка тут — від майбутніх змін);
 *  * ЖИВА — тобто хтось у кімнаті тримає її відкритою. Позначку `aliveAt`
 *    оновлює кожен, хто там сидить; тиша в ній означає, що чекати мене нема кому.
 *    Без цієї межі сповіщення нагадувало б про партію, з якої всі пішли ще вчора.
 */

/** Кімната, у яку варто вернутися, або `null`. Найсвіжіша, якщо їх кілька. */
export function roomAwaitingMe(rooms: readonly OwnRoom[], now: number): OwnRoom | null {
	const waiting = rooms.filter(
		(room) => room.status === 'playing' && roomLife(room.aliveAt, now) === 'alive'
	);
	if (waiting.length === 0) return null;

	/*
	 * Найсвіжіша за `aliveAt`. Кімната без позначки (старіша збірка) лишається
	 * придатною, але стає останньою в черзі: справжній свіжий час — краща підстава,
	 * ніж його відсутність.
	 */
	return waiting.reduce((best, room) => ((room.aliveAt ?? 0) > (best.aliveAt ?? 0) ? room : best));
}

/**
 * ЯКА СТОРІНКА ОНЛАЙНУ належить цій кімнаті — ключ типізованої таблиці маршрутів.
 *
 * Саме ключ, а не готовий шлях: шлях складає `langPath()` через `resolve()`, і
 * лише він знає і мову, і базовий шлях сайту (`/VetCrewGames` у продакшні).
 * Склеєний рядок працював би в розробці й вів у нікуди на хостингу — у
 * `i18n/routing.ts` це записано прямо: «внутрішнє посилання — через типізований
 * `resolve()`, а не склеюванням».
 */
export const roomRoute = (room: OwnRoom): 'quiz/online' | 'pairs/online' =>
	room.gameId === 'pairs' ? 'pairs/online' : 'quiz/online';

/**
 * Хвіст адреси з кодом кімнати.
 *
 * Код їде в `?room=`, бо саме його читають обидві сторінки онлайну — і та сама
 * адреса працює як посилання, надіслане другові.
 */
export const roomQuery = (room: OwnRoom): string => `?room=${encodeURIComponent(room.code)}`;

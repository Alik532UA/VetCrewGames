import type { ReserveBiome } from './species';

/**
 * ПОДІЇ ДОБИ: те, що сталося саме собою, поки гравець нічого не робив.
 *
 * ## Навіщо цей файл узагалі
 *
 * Скарга автора: «взяв тварину, а наступний день вона зникла, без сповіщення і
 * без пояснень». Так і було, і причин зникнення виявилося ДВІ, а на екрані вони
 * виглядали однаково — тобто ніяк:
 *
 *  * здоровʼя дійшло нуля, і тварина померла (`siteDay`);
 *  * її вкрали браконьєри — і не обовʼязково на очах: наліт, на який не
 *    відповіли, `expireRaid` розвʼязує сам, як «ігнорувати».
 *
 * Слідів лишалося рівно стільки, скільки в реєстрі показників: рядок «−30
 * користі, причина `death`» у розкладі доби. Це правда, але не відповідь: щоб її
 * дістати, треба знати, що така причина існує, і навести на потрібний показник.
 *
 * ## Чому ПОДІЇ, а не запис у сховище чи виклик тостів на місці
 *
 * Симуляція чиста: у `src/lib/reserve/` немає ні `Date.now()`, ні сервісів, ні
 * i18n — і саме тому та сама доба, прожита двічі з того самого зерна, дає той
 * самий світ. Викликати звідси `toast` або `logService` означало б зламати цю
 * властивість заради повідомлення.
 *
 * Тому доба лише ОГОЛОШУЄ, що сталося, а ким і як це буде показано, вирішує
 * контролер: він логує, а екран показує сповіщення. Одне джерело на дві потреби —
 * інакше журнал і сповіщення розповідали б різні історії.
 *
 * ## Чому це НЕ частина стану
 *
 * Події не описують світ, вони описують ПЕРЕХІД. Складені в стан, вони поїхали б
 * у сейв, вимагали б міграції формату й ставили б питання, що робити зі
 * «непоказаними» подіями через тиждень. Тут вони живуть рівно один крок часу:
 * `tick()` віддає їх тому, хто його викликав, і на цьому все.
 */

/**
 * Що саме сталося. Один тип на всі види, бо всі вони — один потік.
 *
 * `speciesId`, а не готовий текст: перекладати — не справа симуляції, а показ
 * може захотіти й назву виду, і саму подію без неї (тост каже «тварина померла
 * від хвороби», журнал — яка саме).
 */
export type ReserveEvent =
	/** Здоровʼя дійшло нуля. Єдина смерть від власної недбалості. */
	| { kind: 'death'; speciesId: string; biome: ReserveBiome }
	/** Здоровʼя дійшло повного: тварина одужала. */
	| { kind: 'healed'; speciesId: string; biome: ReserveBiome }
	/** Прийшли браконьєри — рішення потрібне до кінця доби. */
	| { kind: 'raid'; speciesId: string; biome: ReserveBiome }
	/** Наліт відбито, тварина лишилася. */
	| { kind: 'raid-held'; speciesId: string; biome: ReserveBiome }
	/** Наліт провалено: тварину забрали. */
	| { kind: 'raid-lost'; speciesId: string; biome: ReserveBiome }
	/**
	 * На наліт не відповіли, і терпіння вийшло — розвʼязано як «ігнорувати».
	 *
	 * Окремо від `raid-lost`, хоч наслідок той самий: людині важливо знати, що
	 * рішення ухвалив ЧАС, а не вона. Саме цей випадок і виглядав як «тварина
	 * зникла без причини».
	 */
	| { kind: 'raid-expired'; speciesId: string; biome: ReserveBiome }
	/** Комусь не дісталося корму: `count` — скільком саме. */
	| { kind: 'hunger'; count: number }
	/** Спонсор пропонує контракт. */
	| { kind: 'contract-offered'; contractId: number }
	/** Термін контракту вийшов, умову не виконано. */
	| { kind: 'contract-missed'; contractId: number }
	/** Пропозицію не взяли, і спонсор пішов до інших. */
	| { kind: 'offer-expired'; contractId: number }
	/** «Користь планеті» лишалася відʼємною надто довго: партія скінчилася. */
	| { kind: 'collapse' };

/**
 * Кому розповідати. `undefined` означає «нікому» — і це нормальний випадок:
 * тести симуляції прогонюють сотні діб, і слухач їм не потрібен.
 */
export type EventSink = (event: ReserveEvent) => void;

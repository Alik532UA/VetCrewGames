import type { Enclosure, Module } from './types';

/**
 * Суб-модулі вольєра: водойма, насадження, укриття.
 *
 * Доти вольєр описували два числа — розмір і якість, — і обидва були про
 * КІЛЬКІСТЬ. Гра про антизоопарк на цьому впиралася: великий дорогий вольєр
 * однаково годився і боброві, і леву, тож рішення «кому що потрібно» не існувало.
 * Модуль — це те, що робить місце придатним для конкретного виду: бобер без води
 * страждає в будь-якому вольєрі, хоч би він був на пів карти.
 *
 * Три модулі, а не десять, і жоден вид не потребує всіх трьох. Інакше вибір
 * зникає: купуй усе завжди — і це вже не рішення, а податок.
 *
 * **Водойма може дістатися безкоштовно.** Вольєр, поставлений біля річки чи
 * озера, закриває цю потребу самим місцем (`byWater`, рахується при будівництві).
 * Саме тому рельєф у грі не декорація: карту варто читати ДО того, як платиш.
 */

export const MODULES = ['water', 'plants', 'shelter'] as const;

/**
 * Ціна модуля росте ЛІНІЙНО з розміром вольєра.
 *
 * Не квадратично, як сама будівля: водойму на пів гектара копати не треба —
 * треба одну водойму, просто в більшому вольєрі до неї довше йти. Двісті за
 * клітинку: у вольєрі на пʼять це тисяча проти шести з половиною тисяч самої
 * будівлі, тобто помітно, але не так, щоб модуль коштував дорожче за вольєр.
 */
export const MODULE_PRICE_PER_CELL = 200;

export const modulePrice = (size: number) => MODULE_PRICE_PER_CELL * size;

/** Чи закрито цю потребу в цьому вольєрі — купленим модулем або природою. */
export function equipped(enclosure: Enclosure, module: Module): boolean {
	if (module === 'water' && enclosure.byWater) return true;
	return enclosure.modules.includes(module);
}

/**
 * Потреби виду, які цей вольєр НЕ закриває.
 *
 * Приймає список потреб, а не сам вид: інакше `species.ts` і цей файл
 * імпортували б одне одного по колу. Тип `Module` живе в `types.ts` — там, де
 * лежить і саме поле `modules`.
 */
export const unmetNeeds = (needs: readonly Module[], enclosure: Enclosure): Module[] =>
	needs.filter((need) => !equipped(enclosure, need));

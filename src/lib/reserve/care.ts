/**
 * Числа ДОГЛЯДУ: одужання, стрес, голод, корм.
 *
 * Окремо від `constants.ts` за предметом, а не заради розміру файлу. Там межі й
 * ціни світу — скільки днів у мінусі означають крах, скільки коштує вольєр; тут
 * усе про те, як живеться ОКРЕМІЙ тварині. Разом вони перестали вміщатися в межу
 * розміру рівно з появою корму й суб-модулів, і межа не збрехала: два різні
 * словники в одному файлі доводилося читати цілком, щоб знайти будь-що з них.
 *
 * Реекспорт стоїть у `constants.ts` — щоб переїзд не тягнув правку десятка
 * імпортів. Числа тут нікого не імпортують, тож кола не буде ніколи.
 */

/**
 * Скільки коштує день утримання однієї тварини БЕЗ корму.
 *
 * Було 60 і покривало все разом, включно з їжею. Тепер корм — окреме рішення
 * гравця (`larder.ts`), тож із шістдесяти тут лишилося двадцять пʼять: ліки,
 * прибирання, вода. Порція корму коштує 35, і разом виходять ті самі шістдесят —
 * ціна не зросла, вона РОЗДІЛИЛАСЯ на обовʼязкове й вирішуване.
 */
export const UPKEEP_PER_ANIMAL = 25;

/**
 * Скільки одужання додає ветеринар одній тварині за день, у частках від повного.
 *
 * Десять днів на тварину — і саме на ТВАРИНУ, а не на всіх разом.
 */
export const RECOVERY_PER_VET_DAY = 0.1;

/**
 * Скільком тваринам один ветеринар устигає лікувати.
 *
 * **Це виправлення справжнього вузького місця, а не полегшення.** Доти зусилля
 * ветеринара ДІЛИЛОСЯ між усіма, кого він лікує: `(vet × 0.1) / recovering`.
 * Тобто один ветеринар на трьох тварин витягував кожну тридцять днів, на шістьох
 * — шістдесят. Одужання сповільнювалося квадратично від того, що фонд росте, і
 * жодна кількість грошей цього не лікувала швидше, ніж лінійно.
 *
 * Наслідків було два, і обидва виміряні. Контракт «випустити двох за 25 днів»
 * лишався невиконанним у принципі. А таймер краху (тоді 30 діб) вичерпувався
 * рівно тієї доби, коли перша тварина нарешті одужувала, — гравець програвав у
 * ту саму мить, коли гра вперше давала йому плюс.
 *
 * Тепер модель та сама, що вже була в доглядача: не ділення, а ЄМНІСТЬ. Один
 * ветеринар веде трьох тварин на повній швидкості; четверта чекає, поки
 * найматимуть другого. Два різні числа під одним ім’ям «скільки людей на тварин»
 * читалися як несумісні саме тому, що були несумісні.
 *
 * Трійка збігається з `ANIMALS_PER_KEEPER` навмисно: у гравця одне правило на
 * весь штат, а не два схожі. Хто понад ємність — не одужує зовсім, як понад
 * ємність доглядача стрес не спадає, а росте.
 */
export const ANIMALS_PER_VET = 3;

/**
 * Стрес росте щодня, поки в тварини немає доглядача, і сповільнює одужання.
 *
 * Один доглядач заспокоює трьох тварин. Понад це стрес росте, і при повному
 * випуск блокується — тварина, яка боїться людей і не вміє добувати їжу, у
 * природі не виживе.
 */
export const ANIMALS_PER_KEEPER = 3;

export const STRESS_PER_DAY = 0.08;

export const STRESS_RELIEF_PER_DAY = 0.12;

/** Вище за це випуск неможливий, хоч би яким здоровим було тіло. */
export const STRESS_BLOCKS_RELEASE = 0.7;

/**
 * ДНО стресу за кожну незакриту потребу вольєра.
 *
 * Не надбавка за день, а межа, нижче за яку тварину не заспокоїти. Перша версія
 * додавала 0.08 на добу — і тест показав, що це не працює: доглядач знімає 0.12,
 * тобто наймом потреба перебивалася повністю. Виходило, що гроші заміняють
 * знання, а це прямо суперечить тому, чого гра навчає.
 *
 * Тепер доглядач може довести тварину лише до тієї межі, яку лишає їй вольєр:
 * лисиця без нори завмирає на 25% стресу, хоч скільком людям за неї плати. Це не
 * смертельно — випуск блокується на 70%, — але одужання йде повільніше, і запасу
 * до межі майже немає. Дві незакриті потреби складаються в 50%.
 */
export const STRESS_FLOOR_PER_UNMET = 0.25;

/**
 * Скільки стресу додає день голоду — і чому саме стільки.
 *
 * Утричі більше за будь-яку іншу причину. Голод не «одна з незручностей»: він
 * єдиний, що ще й повністю спиняє одужання. Забути купити корм має бути дорожче,
 * ніж забути найняти доглядача, бо виправляється це одним натисканням.
 */
export const STRESS_PER_HUNGER = 0.24;

/** Скільки порцій корму зʼїдає одна тварина за добу. */
export const FEED_PER_ANIMAL = 1;

/**
 * Скільки корму лежить у коморі на початку.
 *
 * Двадцять порцій — приблизно тиждень на трьох тварин. Нуль означав би, що перша
 * ж доба нової партії проходить у голоді за правилом, про яке гравець ще не знає.
 */
export const STARTING_FEED = 20;

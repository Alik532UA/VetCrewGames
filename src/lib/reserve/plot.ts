import { REPUTATION_MAX, REPUTATION_MIN } from './constants';

/**
 * Межа ділянки: наскільки далеко від центру можна будувати.
 *
 * Живе окремо від решти чисел, бо це не стала, а ФУНКЦІЯ — єдине правило гри,
 * де одна шкала керує іншою. Тримати її серед констант означало б, що файл
 * «числа гри» починає щось обчислювати.
 *
 * Ділянка — КВАДРАТ, а не коло: будують по клітинках, і кругла межа різала
 * кутові навпіл — вольєр, який «майже влазить», відмовлявся ставитися з причини,
 * якої не видно.
 *
 * Землю не купують грошима — її дає ГРОМАДА. Фонд, якого ніхто не знає, тримає
 * клапоть; фонд із іменем отримує дозвіл на сусідні гектари. Межа рухається в
 * обидва боки, бо репутація щодня спадає; уже збудований вольєр за нею не
 * зникає — зносити збудоване за чужий спад було б покаранням за те, чого гравець
 * не робив.
 */

/*
 * Числа — та сама частка радіуса світу, що й до його зростання (1/6 і ~0.43).
 * Рахувати від `WORLD_RADIUS` прямо тут не можна: рельєф уже читає межу ділянки,
 * і вийшло б коло імпортів. 130 півсторони — це 118 клітинок у поперек, тобто
 * чотири найбільші вольєри або кількадесят звичайних.
 */
export const RESERVE_HALF_MIN = 50;
export const RESERVE_HALF_MAX = 130;

export const reserveHalf = (reputation: number): number =>
	RESERVE_HALF_MIN +
	((RESERVE_HALF_MAX - RESERVE_HALF_MIN) * (reputation - REPUTATION_MIN)) /
		(REPUTATION_MAX - REPUTATION_MIN);

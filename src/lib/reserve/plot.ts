import { CELL_WORLD } from './grid';
import { REPUTATION_MAX, REPUTATION_MIN } from './constants';

/**
 * Межа ділянки: наскільки далеко від центру можна будувати.
 *
 * Живе окремо від решти чисел, бо це не стала, а ФУНКЦІЯ — єдине правило гри, де
 * одна шкала керує іншою. Тримати її серед констант означало б, що файл «числа
 * гри» починає щось обчислювати.
 *
 * Ділянка — КВАДРАТ, а не коло: будують по клітинках, і кругла межа різала кутові
 * навпіл — вольєр, який «майже влазить», відмовлявся ставитися з причини, якої не
 * видно.
 *
 * Землю не купують грошима — її дає ГРОМАДА, і це двобічна угода. Фонд, про який
 * ніхто не чув, отримує десять клітинок на десять. Фонд із іменем — сто вісімнадцять.
 * А фонд, якого СОРОМЛЯТЬСЯ, землю втрачає: на самому дні шкали від неї лишається
 * одна клітинка. Уже збудований вольєр за межею не зникає — зносити збудоване було
 * б покаранням, якого гравець не обирав, — але поставити новий там уже не вийде.
 */

/** Півсторона на самому дні шкали: одна клітинка, і та навпіл. */
export const RESERVE_HALF_MIN = CELL_WORLD / 2;

/**
 * Півсторона на нулі репутації: десять клітинок на десять.
 *
 * Це і є «клапоть землі у невідомого фонду»: шість вольєрів по три або один на
 * десять — і місця більше немає. Доти тут стояло 50 одиниць (45 клітинок), і
 * стартова ділянка була така, що репутація ще довго ні на що не впливала.
 */
export const RESERVE_HALF_START = 5 * CELL_WORLD;

/** Півсторона при повній репутації: 118 клітинок у поперек. */
export const RESERVE_HALF_MAX = 130;

/**
 * Дві вітки, а не одна пряма — бо нуль репутації це не середина шкали, а її
 * ЗВИЧАЙНИЙ стан. Вище нуля громада дає землю поступово, нижче — забирає швидко:
 * від нуля до дна шкали лишається одна клітинка, і саме тому мінус репутації
 * відчувається як подія, а не як цифра.
 */
export const reserveHalf = (reputation: number): number => {
	if (reputation >= 0) {
		return (
			RESERVE_HALF_START + ((RESERVE_HALF_MAX - RESERVE_HALF_START) * reputation) / REPUTATION_MAX
		);
	}
	const depth = Math.max(0, 1 - reputation / REPUTATION_MIN);
	return RESERVE_HALF_MIN + (RESERVE_HALF_START - RESERVE_HALF_MIN) * depth;
};

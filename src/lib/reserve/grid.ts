/**
 * Сітка заповідника: де стоїть кожен вольєр.
 *
 * Розкладка — чиста функція від `id`, а не від порядку в масиві. Це не
 * дрібниця: коли тварину випускають, сусіди НЕ мають зсуватися на її місце.
 * Заповідник, у якому будівлі перестрибують після кожної події, читається як
 * збій, а не як гра.
 *
 * Живе в `reserve/`, а не в компонентах, бо на неї спирається ще й рельєф: він
 * мусить знати, які клітинки лишити під забудову. Дерево, що росте крізь
 * будівлю, читається як помилка, а не як природа.
 */

/** Крок сітки у світових одиницях. Вольєр — одиничний куб. */
export const CELL_WORLD = 2.2;

/**
 * Клітинка спіралі за порядковим номером: 0 — центр, далі кільцями.
 *
 * Спіраль, а не рядки: заповідник росте від центру навсібіч, і камера, наведена
 * на початок координат, лишається наведеною на нього й на двадцятому вольєрі.
 */
export function spiralCell(index: number): { x: number; z: number } {
	let x = 0;
	let z = 0;
	let dx = 0;
	let dz = -1;

	for (let i = 0; i < index; i++) {
		// Кут кільця: там напрямок повертає на 90°.
		if (x === z || (x < 0 && x === -z) || (x > 0 && x === 1 - z)) {
			[dx, dz] = [-dz, dx];
		}
		x += dx;
		z += dz;
	}
	return { x, z };
}

/**
 * Світові координати клітинки, яку колись давала СПІРАЛЬ за `id`.
 *
 * Лишається лише для міграції старих сейвів: доти вольєри ставилися автоматично
 * по спіралі, а тепер їх ставить гравець. Для нових партій ця функція не
 * викликається — саме тому вона й не називається `placeOf`.
 */
export const spiralPlaceOf = (id: number) => {
	const cell = spiralCell(id - 1);
	return { x: cell.x * CELL_WORLD, z: cell.z * CELL_WORLD };
};

/** Світові координати центру клітинки. */
export const worldOf = (cell: Cell) => ({ x: cell.x * CELL_WORLD, z: cell.z * CELL_WORLD });

/** Клітинка, у яку влучає точка світу. */
export const cellOf = (x: number, z: number): Cell => ({
	x: Math.round(x / CELL_WORLD),
	z: Math.round(z / CELL_WORLD)
});

export interface Cell {
	x: number;
	z: number;
}

/**
 * Скільки клітинок займає вольєр цього розміру: рівно `size × size`.
 *
 * Розмір і є сторона — інших відповідей у гри бути не може. Доти тут стояло
 * `1 + floor(size / 3)`, і числа розходилися з очима: «2» давало той самий
 * квадрат 1×1, що й «1», а «3», «4» і «5» — однакові 2×2. Гравець вибирав різні
 * числа й діставав ту саму землю, тобто розмір був підписом, а не рішенням.
 *
 * Ціна цього рішення названа прямо: земля витрачається квадратично. Вольєр на 50
 * займає 2500 клітинок — саме тому ділянка й виросла разом зі світом.
 */
export const footprintOf = (size: number) => size;

/** Усі клітинки, які накриває вольєр, поставлений у `cell`. */
export function cellsOf(cell: Cell, size: number): Cell[] {
	const side = footprintOf(size);
	const out: Cell[] = [];
	for (let dx = 0; dx < side; dx++) {
		for (let dz = 0; dz < side; dz++) out.push({ x: cell.x + dx, z: cell.z + dz });
	}
	return out;
}

export const cellKey = (cell: Cell) => `${cell.x},${cell.z}`;

/**
 * Сітка заповідника: де стоїть кожен вольєр.
 *
 * Розкладка — чиста функція від `id`, а не від порядку в масиві. Це не
 * дрібниця: коли тварину випускають, сусіди НЕ мають зсуватися на її місце.
 * Заповідник, у якому будівлі перестрибують після кожної події, читається як
 * збій, а не як гра.
 *
 * Живе в `reserve/`, а не в компонентах, бо на неї спирається ще й рельєф: він
 * мусить знати, які клітинки лишити під забудову. Дерево, що росте крізь
 * будівлю, читається як помилка, а не як природа.
 */

/** Крок сітки у світових одиницях. Вольєр — одиничний куб. */
export const CELL_WORLD = 2.2;

/**
 * Клітинка спіралі за порядковим номером: 0 — центр, далі кільцями.
 *
 * Спіраль, а не рядки: заповідник росте від центру навсібіч, і камера, наведена
 * на початок координат, лишається наведеною на нього й на двадцятому вольєрі.
 */
export function spiralCell(index: number): { x: number; z: number } {
	let x = 0;
	let z = 0;
	let dx = 0;
	let dz = -1;

	for (let i = 0; i < index; i++) {
		// Кут кільця: там напрямок повертає на 90°.
		if (x === z || (x < 0 && x === -z) || (x > 0 && x === 1 - z)) {
			[dx, dz] = [-dz, dx];
		}
		x += dx;
		z += dz;
	}
	return { x, z };
}

/** Світові координати вольєра за його `id`. */
export const placeOf = (id: number) => {
	const cell = spiralCell(id - 1);
	return { x: cell.x * CELL_WORLD, z: cell.z * CELL_WORLD };
};

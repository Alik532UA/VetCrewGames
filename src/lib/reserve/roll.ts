import { seededRandom } from '$lib/utils/seededRandom';
import type { ReserveState } from './types';

/**
 * Кидок кістки: одна дія, яка потрібна і правилам, і добі.
 *
 * Жив у `simulation.ts`, поки випадковість була потрібна лише при надходженні
 * тварини. Браконьєри кидають кістку в кінці доби — а `day.ts` не може імпортувати
 * `simulation.ts`, бо той імпортує його: вийшло б коло. Тому переїхав сюди.
 *
 * Репутація жила поруч і поїхала в `ledger.ts`: відколи кожна зміна показника
 * пишеться з причиною, це вже не сусідня дрібниця, а частина реєстру.
 */

/**
 * Місце, на якому спинився генератор кожного стану.
 *
 * **Чому окремо від стану, а не полем у ньому.** Бо `ReserveState` мусить
 * лишатися звичайними даними: його серіалізують у сейв, порівнюють і копіюють.
 * Функція туди не лягає — `JSON.stringify` мовчки її викине, і сейв відрізнявся
 * б від того, що в памʼяті.
 *
 * `WeakMap`, а не `Map`: ключ — сам обʼєкт стану, і коли партію закрито, запис
 * зникає разом із нею. Інакше кожна створена партія лишалася б у памʼяті
 * назавжди — а тести створюють їх тисячами.
 */
const cursors = new WeakMap<ReserveState, { seed: number; rolls: number; next: () => number }>();

/**
 * Черговий кидок генератора.
 *
 * **Кількість кидків — частина стану.** Тому будь-яка нова випадковість мусить
 * кидати кістку ЗАВЖДИ, а не лише коли результат потрібен: інакше два однакові
 * сейви розійшлися б залежно від того, чи стався кидок, якого не було видно.
 *
 * **Чому тут курсор, а не просто перемотка.** Доти цей рядок стояв так:
 *
 * ```
 * const random = seededRandom(state.seed);
 * for (let i = 0; i < state.rolls; i++) random();
 * ```
 *
 * тобто генератор створювався наново й проганявся `rolls` разів НА КОЖНОМУ
 * кидку. Це O(n) на кидок і O(n²) на партію: виміряно на 8000 кидків — 241 мс
 * проти 5 мс на тисячі, і далі гірше. Ціна росте там, де її найменше видно: у
 * довгій партії, у якої вже накопичилася історія.
 *
 * Перемотка лишається — але лише тоді, коли курсор НЕ на місці: партію щойно
 * створено, стан прийшов із сейва, або `rolls` перемотали руками. У звичайному
 * ході (кидок за кидком) генератор просто продовжує з того, де спинився, і
 * послідовність чисел від цього не міняється жодним бітом — те саме зерно, ті
 * самі виклики, той самий порядок. Це стереже `roll.test.ts`, звіряючи вихід із
 * наївною перемоткою.
 *
 * `seed` у курсорі теж перевіряється: стан із заміненим зерном — це інша партія,
 * і продовжувати в ній чужу послідовність не можна.
 */
export function roll(state: ReserveState): number {
	let cursor = cursors.get(state);

	if (!cursor || cursor.seed !== state.seed || cursor.rolls !== state.rolls) {
		const next = seededRandom(state.seed);
		for (let i = 0; i < state.rolls; i++) next();
		cursor = { seed: state.seed, rolls: state.rolls, next };
		cursors.set(state, cursor);
	}

	state.rolls += 1;
	cursor.rolls += 1;
	return cursor.next();
}

/**
 * Показники, їхні причини й історія — самі типи, без жодного правила.
 *
 * Окремим файлом, бо це СЛОВНИК, а не частина стану. `types.ts` описує партію:
 * тварин, вольєри, ходи; тут — те, чим партію МІРЯЮТЬ. Разом вони перестали
 * вміщатися в межу розміру рівно тоді, коли в кожної зміни зʼявилася причина, і
 * межа не збрехала: два різні словники в одному файлі доводилося читати цілком,
 * щоб знайти будь-що з них.
 *
 * Файл нічого не імпортує — і тому його може імпортувати будь-хто, включно з
 * `types.ts`. Кільця не виникає ні з реєстром, ні з журналом.
 */

/**
 * Показники, які показує шапка. Зріз, а не події: журнал міряє РІЗНИЦЮ між двома
 * зрізами, тому обидва мусять мати однакову форму.
 */
export interface MetricSet {
	budget: number;
	/** Порції корму в коморі. Показник, бо його забувають — і бачити це треба. */
	feed: number;
	impact: number;
	reputation: number;
	inReserve: number;
	inWild: number;
}

/** Який саме показник змінився. Ключі збігаються з полями `MetricSet`. */
export type LedgerMetric = keyof MetricSet;

/**
 * За що змінився показник. Кожне значення — ключ у словнику: `reserve.why.<r>`.
 *
 * Список закритий навмисно. Вільний рядок дозволив би написати причину, якої
 * немає в перекладі, і в підказці зʼявився б сирий ідентифікатор — на трьох мовах
 * із чотирьох. Тут же нова причина без рядка не збереться (`check:i18n`).
 */
export type LedgerReason =
	| 'wage.vet'
	| 'wage.keeper'
	| 'wage.ranger'
	| 'upkeep.animals'
	| 'upkeep.enclosures'
	| 'donations'
	/** Корм куплено. */
	| 'feed'
	/** Корм зʼїдено. */
	| 'eaten'
	/** Суб-модуль вольєра: водойма, насадження, укриття. */
	| 'module'
	| 'build'
	| 'repair'
	| 'upgrade'
	| 'intake'
	| 'campaign'
	| 'contract'
	| 'penalty'
	| 'drone'
	| 'injury'
	| 'enclosure'
	| 'heal'
	| 'release'
	| 'noVet'
	| 'decay'
	| 'raidSaved'
	| 'raidLost'
	/** Тварина померла в заповіднику: здоровʼя дійшло до нуля. */
	| 'death'
	/** Різниця між сумою записів і виміряною зміною: місце, яке забули підписати. */
	| 'other';

/** Один рядок розкладу: показник, причина, скільки. */
export interface JournalNote {
	metric: LedgerMetric;
	reason: LedgerReason;
	/** Зі знаком: витрата відʼємна, надходження додатне. */
	amount: number;
}

/** Один день історії: на скільки змінився кожен показник — і за що. */
export interface JournalDay extends MetricSet {
	day: number;
	/**
	 * Розклад дня. Порожній означає «партія приїхала з версії 1, де причин ще не
	 * записували» — і підказка тоді показує саме різницю, без розкладу.
	 */
	notes: JournalNote[];
}

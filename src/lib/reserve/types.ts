import type { AnimalOrigin, Quality, StaffRole } from './constants';
import type { ContractGoal } from './contracts';
import type { ReserveBiome } from './species';
import type { JournalDay, JournalNote, MetricSet } from './metrics';
import type { RejectReason } from './rejects';

/**
 * Стан заповідника й ходи, якими його змінюють.
 *
 * Хід тут — ДАНІ, а не виклик методу. Це не стилістика: у спільній партії той
 * самий обʼєкт має прийти мережею й дати той самий результат. Та сама причина
 * стоїть за `MemoryGameController`, і там вона вже виправдалася.
 */

export type AnimalStage = 'recovering' | 'healthy' | 'released';

/** Суб-модуль вольєра. Навіщо саме три й чому не всі — у `modules.ts`. */
export type Module = 'water' | 'plants' | 'shelter';

export interface Enclosure {
	id: number;
	/**
	 * Де стоїть, у клітинках сітки. Ставить ГРАВЕЦЬ, а не гра.
	 *
	 * Доти місце визначалося `id` по спіралі, і питання «де будувати» просто не
	 * існувало. Тепер земля — обмежений ресурс, а біля річки місце цінніше за
	 * місце в глухому куті.
	 */
	cell: { x: number; z: number };
	/** 1–10. Від нього залежить і ціна, і кого сюди можна поселити. */
	size: number;
	/** 1–3. Розмір вирішує ХТО поміститься, якість — наскільки йому тут добре. */
	quality: Quality;
	/** 1 — щойно збудований, 0 — руїна. Спадає щодня, підіймається ремонтом. */
	durability: number;
	/** Які суб-модулі вже стоять. Незакрита потреба виду підіймає стрес. */
	modules: Module[];
	/**
	 * Чи стоїть вольєр біля ПРИРОДНОЇ води.
	 *
	 * Рахується ОДИН раз, коли вольєр ставлять, і лежить у стані. Не щодня: щоб
	 * дізнатися це, треба згенерувати рельєф — шістсот сімдесят фігур, шість
	 * мілісекунд, — і робити це на кожному тіку заради незмінного факту було б
	 * марнотратством. Заразом місце на карті стає рішенням: біля річки водойму
	 * купувати не треба.
	 */
	byWater: boolean;
}

export interface Animal {
	id: number;
	/** Вид із `species.ts`. Вирішує, який вольєр підходить. */
	speciesId: string;
	origin: AnimalOrigin;
	stage: AnimalStage;
	/**
	 * Де живе. Вольєр займається на весь час перебування й звільняється лише
	 * випуском — тварина не «стоїть у черзі», вона або має місце, або її немає.
	 */
	enclosureId: number;
	/** 0 → 1. Дійшовши до одиниці, тварина стає здоровою. */
	health: number;
	/** 0 → 1. Вище за поріг випуск блокується. */
	stress: number;
	/**
	 * Чи придатна ця особина до життя в дикій природі. Вирішується ОДИН раз,
	 * при надходженні, зерновим генератором — щоб та сама партія розгорталася
	 * однаково в усіх учасників.
	 */
	releasable: boolean;
	/** Якого дня випустили. `null`, доки тварина в заповіднику. */
	releasedOnDay: number | null;
}

export interface Contract {
	id: number;
	goal: ContractGoal;
	titleKey: import('$lib/i18n/translations/uk').TranslationKey;
	/** Скільки треба зробити ПОНАД зроблене на момент видачі. */
	amount: number;
	/**
	 * Знімок лічильника на момент видачі. Без нього «випустити двох» означало б
	 * двох за всю партію, і контракт приходив би вже виконаним.
	 */
	startedAt: number;
	/** До якого дня включно. Після нього — провал і мінус репутації. */
	dueDay: number;
	reward: number;
	penalty: number;
}

/*
 * Показники, причини змін і історія переїхали в `metrics.ts` — там словник, тут
 * партія. Реекспорт лишається, щоб не переписувати два десятки імпортів заради
 * переїзду: `from './types'` і далі дає все, що давав.
 */
export type { JournalDay, JournalNote, LedgerMetric, LedgerReason, MetricSet } from './metrics';

/** Тактика проти браконьєрів. Три рішення з технічного завдання. */
export type RaidTactic = 'drone' | 'ambush' | 'ignore';

/** Наліт, який чекає на рішення. */
export interface Raid {
	/** Кого прийшли крати. */
	animalId: number;
	/** На яку ділянку прийшли: вікно мусить назвати місце, а не лише тварину. */
	biome: ReserveBiome;
	/** Якого дня прийшли: за ним рахується терпіння події. */
	day: number;
}

/**
 * Одна ділянка: те, що стоїть на ЦІЙ землі.
 *
 * Грошей і шкал тут немає навмисно — вони спільні на весь фонд. Ділянка знає
 * лише про своїх мешканців, свої вольєри й свій штат: ветеринар із савани не
 * лікує ведмедя в лісі, бо він у савані.
 */
export interface Site {
	animals: Animal[];
	enclosures: Enclosure[];
	staff: Record<StaffRole, number>;
}

/**
 * ФОНД: одна каса, одні шкали, один годинник — і чотири ділянки.
 *
 * Доти кожен біом був окремою грою з власним бюджетом. Тепер гроші, «Користь
 * планеті» й репутація спільні, а тварини, вольєри й персонал — у кожної землі
 * свої. Наслідки й були потрібні: витрати савани з'їдають ліс, репутація одного
 * випуску розширює ділянки ВСЮДИ, а крах трапляється з фондом, не з клаптем.
 */
export interface ReserveState {
	/**
	 * Логічний час — ОДИН на весь фонд.
	 *
	 * Чотири лічильники означали б, що ділянка, у яку не заходили, стоїть у
	 * минулому: повернувшись, гравець побачив би день 3 при дні 40 у сусідній.
	 * Один час — це й відповідь на «чи йде життя там, де мене немає»: іде.
	 */
	ticks: number;
	budget: number;
	impact: number;
	/**
	 * Публічне ім'я фонду, 0–100. Керує пожертвами. Окрема від `impact`, бо
	 * розходиться з ним там, де це щось означає, — див. докблок у `constants`.
	 */
	reputation: number;
	/** Чотири землі фонду. Ключ — біом: він же адреса сторінки. */
	sites: Record<ReserveBiome, Site>;
	/**
	 * Скільки днів поспіль «Користь планеті» в мінусі. Скидається на нуль,
	 * щойно показник вийшов у плюс, — саме тому 30 днів із перервою не
	 * призводять до кінця гри.
	 */
	collapseDays: number;
	gameOver: boolean;
	/** Якого дня востаннє була кампанія. −1 — жодної. Тримає межу «раз на день». */
	lastCampaignDay: number;
	/**
	 * Режим антикризової субсидії: бюджет у мінусі. Годування й ліки тривають,
	 * розширення заблоковане. Це НЕ програш — програш лише за «Користю планеті».
	 */
	subsidy: boolean;
	/** Стан генератора. Зберігається зі станом, інакше сейв не відтворюється. */
	seed: number;
	rolls: number;
	/** Чинні контракти: обіцянки з дедлайном. */
	contracts: Contract[];
	/** Пропозиція, яку ще не прийняли й не відхилили. */
	offered: Contract | null;
	/** Якого дня востаннє пропонували контракт. */
	lastOfferDay: number;
	/**
	 * Історія змін по днях — для підказок над показниками, не для правил.
	 *
	 * У стані, а не в контролері: інакше вона зникала б при перезавантаженні, а
	 * властивість «те саме зерно й ті самі ходи дають той самий стан» перестала б
	 * охоплювати те, що гравець бачить.
	 */
	journal: JournalDay[];
	/**
	 * Корм у коморі, у порціях. Одна порція — одна тварина на добу.
	 *
	 * Спільний на весь фонд, як і гроші: комора одна, і саме тому четверта ділянка
	 * — рішення, а не безкоштовний додаток.
	 */
	feed: number;
	/** Зріз показників на початку поточної доби. З ним порівнюється кінець. */
	dayStart: MetricSet;
	/**
	 * Причини змін ПОТОЧНОЇ, ще не закритої доби.
	 *
	 * У стані, а не в контролері: закрита вкладка не має стирати розклад половини
	 * дня. На межі доби переїжджає в `journal` разом із виміряною різницею.
	 */
	today: JournalNote[];
	/**
	 * Наліт браконьєрів, який чекає на рішення. `null` — тихо.
	 *
	 * У стані, а не в інтерфейсі: наліт — це подія симуляції з дедлайном, і
	 * закрита вкладка не має її скасовувати.
	 */
	raid: Raid | null;
	/** Наступні вільні `id`. */
	nextAnimalId: number;
	nextEnclosureId: number;
	nextContractId: number;
}

/**
 * Хід ділянки чи хід фонду.
 *
 * Одні ходи неможливо зрозуміти без місця — «побудувати» треба знати ДЕ, —
 * а інші належать фондові цілком: кампанія в соцмережах не буває «лісовою».
 * Тому адреса ходу передається окремо від нього самого: у мережу колись
 * поїде пара «`at` + команда», а не команда з полем, яке половина ходів
 * ігнорує.
 */
export type ReserveCommand =
	| { type: 'build'; size: number; quality: Quality; cell: { x: number; z: number } }
	| { type: 'demolish'; enclosureId: number }
	/** Поставити суб-модуль: водойму, насадження або укриття. */
	| { type: 'equip'; enclosureId: number; module: Module }
	/** Купити корму в комору. `portions` — скільки порцій. */
	| { type: 'restock'; portions: number }
	| { type: 'repair'; enclosureId: number }
	| { type: 'upgrade'; enclosureId: number; quality: Quality }
	| { type: 'acquire'; origin: AnimalOrigin; speciesId: string; enclosureId: number }
	| { type: 'release'; animalId: number }
	| { type: 'hire'; role: StaffRole }
	| { type: 'dismiss'; role: StaffRole }
	| { type: 'campaign' }
	| { type: 'accept'; contractId: number }
	| { type: 'claim'; contractId: number }
	| { type: 'raid'; tactic: RaidTactic };

/*
 * Перелік відмов живе в `rejects.ts` — там він читається разом зі словником
 * перекладу. Реекспорт лишається, щоб не правити два десятки імпортів.
 */
export type { RejectReason } from './rejects';

export type CommandResult = { ok: true } | { ok: false; reason: RejectReason };

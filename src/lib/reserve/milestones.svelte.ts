import { milestonesReached } from './milestones';

/**
 * Сторож віх: чи перетнули щойно наступну сходинку.
 *
 * Окремим модулем, а не `$effect` у компоненті, з простої причини:
 * `ReserveGame.svelte` стояв на 299 рядках при межі 300, тобто запасу не було
 * зовсім. Нова відповідальність у такому файлі мусить іти НАЗОВНІ — інакше межа
 * розміру перетворюється на формальність, яку обходять списком винятків.
 *
 * Фабрика, а не синглтон рівня модуля: стан належить одному екрану заповідника й
 * має вмирати разом із ним. Модульний лічильник пережив би перехід між ділянками
 * й привітав би гравця чужою віхою.
 *
 * Розширення `.svelte.ts` обовʼязкове: усередині руна `$state`, і у звичайному
 * `.ts` компілятор її не обробить — код виглядав би правильним і мовчки не
 * реагував ні на що (PROJECT-STRUCTURE-v8, анти-патерни, CRITICAL).
 */
export function createMilestoneWatch() {
	/**
	 * `null` — ще не дивилися жодного разу.
	 *
	 * Саме тому перший виклик нічого не святкує: інакше відкриття сейва, у якому
	 * віха взята минулого тижня, вітало б гравця з тим, що він давно зробив.
	 */
	let celebrated = $state<number | null>(null);

	return (impact: number): boolean => {
		const reached = milestonesReached(impact);
		const crossed = celebrated !== null && reached > celebrated;
		/*
		 * Присвоєння й при СПАДІ: наліт відбирає 30 користі й може опустити фонд
		 * нижче порога. Взяту вдруге віху варто відсвяткувати вдруге — вона знову
		 * коштувала роботи.
		 */
		celebrated = reached;
		return crossed;
	};
}

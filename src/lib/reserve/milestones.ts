/**
 * Віхи «Користі планеті»: нагороди замість фінішу.
 *
 * **Партія більше не виграється.** Доти був поріг `IMPACT_TO_WIN = 10 000`, і
 * при `RELEASE_IMPACT = 50` це означало ДВІСТІ випусків — при тому, що таймер
 * програшу міряв 30 діб. Дві величини з різних ігор: виграти було неможливо
 * арифметично, а сам поріг перевірявся рівно в одному місці — у момент випуску.
 *
 * Замість фінішу — сходинки по степенях десяти. Заповідник triває, скільки
 * хочеться, а кожна віха каже, що зроблено насправді: тисяча користі це двадцять
 * повернених у природу тварин, мільярд — уже не гра, а жарт, і хай він там буде.
 *
 * **Стану тут немає навмисно.** Досягнуте — чиста функція від `impact`, тож
 * нічого не треба ні зберігати, ні мігрувати, ні тримати в синхроні: сейв, що
 * приїхав із будь-якої версії, покаже правильні віхи одразу. Момент ПЕРЕТИНУ
 * контролер ловить порівнянням двох зрізів, а не полем у стані.
 */

/**
 * Пороги. Степені десяти, бо шкала росте на порядки: між першим випуском (+50) і
 * тисячею лежать двадцять тварин, а між тисячею й десятьма — ще сто вісімдесят.
 * Рівномірна сітка тут дала б або сорок віх, або жодної в перші дві години.
 */
export const IMPACT_MILESTONES = [
	1_000, 10_000, 100_000, 1_000_000, 10_000_000, 100_000_000, 1_000_000_000
] as const;

/** Скільки віх уже взято. Нуль — жодної; довжина масиву — усі. */
export const milestonesReached = (impact: number): number =>
	IMPACT_MILESTONES.filter((threshold) => impact >= threshold).length;

/**
 * Наступний поріг — або `null`, коли взято все.
 *
 * `null`, а не «остання віха ще раз»: шапка мусить показати «зроблено все», а не
 * недосяжну мету, до якої вже дійшли.
 */
export function nextMilestone(impact: number): number | null {
	return IMPACT_MILESTONES.find((threshold) => impact < threshold) ?? null;
}

/**
 * Репутація — друга шкала, вона керує ГРІШМИ, і дно в неї НИЖЧЕ нуля.
 *
 * «Користь планеті» лишається моральним підсумком і єдиною умовою програшу;
 * репутація вирішує, скільки жертвують. Розділені вони не заради складності, а
 * тому що розходяться в конкретних місцях: узяв хвору тварину без ветеринара —
 * репутація впала, а планеті ти таки допоміг. Випуск підіймає ОБИДВІ, інакше
 * найбільша нагорода гри була б суто оборонною.
 *
 * Нуль — це «про фонд ніхто не чув», і на ньому гра починається; туди ж упирається
 * спад (`REPUTATION_DECAY_RATE`). Мінус — це «про фонд чули погане», і вести туди
 * може лише ВЧИНОК: чорний ринок, тварина без ветеринара, зірваний контракт,
 * украдений браконьєрами мешканець. У мінуса є ціна: громада ЗАБИРАЄ землю
 * (`plot.ts`), і на самому дні від ділянки лишається одна клітинка. Пожертв у
 * мінусі немає — але й з каси ніхто не виносить: ненависть просто нічого не
 * приносить.
 */

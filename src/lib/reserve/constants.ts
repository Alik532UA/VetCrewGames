/** Звідки береться тварина. Від цього залежить усе інше в її долі. */
export type AnimalOrigin = 'official' | 'black-market' | 'rescue';

export interface OriginTerms {
	/** Ціна самої тварини. */
	price: number;
	/** Логістика чи транспортування — платиться завжди, навіть за порятунок. */
	logistics: number;
	/** Одразу до «Користі планеті»: мінус за попит на ринку, плюс за порятунок. */
	impact: number;
	/**
	 * Шанс, що тварину колись удасться випустити. Народжена в неволі майже
	 * ніколи не повернеться в природу — і саме це робить дешеву покупку
	 * дорогою: випуск дає +150, а купленій він недоступний.
	 */
	releaseChance: number;
}


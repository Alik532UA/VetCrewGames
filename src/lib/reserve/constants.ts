/** Звідки береться тварина. Від цього залежить усе інше в її долі. */
export type AnimalOrigin = 'official' | 'black-market' | 'rescue';

export interface OriginTerms {
	/** Ціна самої тварини. */
	price: number;
	/** Логістика чи транспортування — платиться завжди, навіть за порятунок. */
	logistics: number;
	/** Одразу до «Користі планеті». Порятунок дає нуль — див. докблок нижче. */
	impact: number;
	/** Одразу до репутації: публіка бачить вчинок, а не його наслідки. */
	reputation: number;
	/**
	 * Шанс, що тварину колись удасться випустити. Народжена в неволі майже
	 * ніколи не повернеться в природу — і саме це робить дешеву покупку
	 * дорогою: випуск дає +50, а купленій він недоступний.
	 */
	releaseChance: number;
	/**
	 * Межі здоровʼя, з яким тварина ПРИЇЖДЖАЄ: кидок раз, при надходженні. Це й є
	 * те, за що платять гроші — куплена приїжджає майже здоровою, врятована при
	 * смерті. Пороги — у docblock `HEALTH_SELF_RECOVERY_ABOVE` (care.ts).
	 */
	healthMin: number;
	healthMax: number;
}


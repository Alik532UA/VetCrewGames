/**
 * З чого складається силует мешканця на карті.
 *
 * Доти мешканець був капсулою — однією й тією самою для їжака й слона, — і
 * заповідник читався як склад пігулок. Тепер кожен вид має власний силует.
 *
 * **Жодного ЗОБРАЖЕННЯ тварини тут немає й бути не може.** Дорожня карта прямо
 * забороняє агентові вигадувати, шукати чи вставляти зображення тварин, а чужі
 * моделі з інтернету до того ж не мають перевірної ліцензії. Силует складається
 * з тих самих примітивів, що й дерева в `DecorPiece`: конус, куля, циліндр.
 *
 * **Чому таблиця пропорцій, а не чотирнадцять моделей.** Модель кожного виду
 * окремо — це чотирнадцять місць, де можна помилитися однаково, і жодного
 * способу перевірити їх разом. Тут вид задає два головні числа — довжину тулуба
 * й висоту ноги, — а решта виводиться з них пропорціями. Тому голова не може
 * відірватися від тулуба через недогляд у дев'ятому виді, а перевірка «чи
 * влазить у найменший дозволений вольєр» рахується для всіх однією формулою.
 * Окремо задається лише те, чим вид справді відрізняється: слонові — товщина
 * тулуба, носорогові — низько опущена голова.
 *
 * **Пізнаваність тримається на трьох речах**, і всі три тут є: пропорція (в
 * оленя ноги вищі за тулуб, у їжака ніг не видно), прикмета (роги, хобот,
 * грива, колючки, смуги) і колір.
 *
 * **Масштаб навмисно НЕ метричний.** Слон утридцятеро довший за їжака, а тут —
 * усьомеро. Метрична правда зробила б їжака точкою в двох метрах паркана:
 * розмір вольєра в грі рахується від потреби у ПРОСТОРІ, а не від розмірів
 * тіла. Тому силует міряється часткою свого найменшого дозволеного вольєра —
 * кожен займає від чверті до половини його ширини, і кожного видно однаково
 * добре. Це перевірено тестом, а не на око.
 *
 * Тут лише ЯКІ тварини бувають. Де в них яка частина — у `figure.ts`: додати вид
 * і посадити голову інакше — дві різні правки з різних причин.
 */

export type Tail = 'bushy' | 'flat' | 'stub' | 'fan' | 'none';
export type Ear = 'pointed' | 'round' | 'wide' | 'tuft' | 'none';
export type Mark = 'antlers' | 'horn' | 'trunk' | 'mane' | 'spines' | 'stripes' | 'spots' | 'none';

export interface Beast {
	/** Скільком ногам стояти: чотирилапий тулуб лежить, пташиний — стоїть. */
	stance: 'four' | 'two';
	/** Довжина тулуба. У двоногих — його ВИСОТА: тулуб стоїть. */
	len: number;
	/** Висота тулуба. У двоногих — глибина, від грудей до хвоста. */
	tall: number;
	wide: number;
	/** Від землі до низу тулуба. Майже нуль — ніг не видно (їжак). */
	leg: number;
	shin: number;
	head: number;
	/** Наскільки центр голови вище за спину. Від'ємне — нижче (носоріг). */
	lift: number;
	/** Наскільки центр голови далі за передній край тулуба. */
	reach: number;
	/** Писок або дзьоб; 0 — немає. */
	muzzle: number;
	tail: Tail;
	ear: Ear;
	mark: Mark;
	coat: string;
	/** Колір прикмети: гриви, колючок, рогів, білої голови орла. */
	trim: string;
}

/**
 * Чотирилапий за двома числами. Решта — пропорції від висоти тулуба, і саме
 * тому силует не може вийти внутрішньо суперечливим.
 */
function beast(coat: string, len: number, leg: number, over: Partial<Beast> = {}): Beast {
	const tall = over.tall ?? len * 0.36;
	return {
		stance: 'four',
		len,
		leg,
		tall,
		wide: tall * 0.8,
		shin: tall * 0.22,
		head: tall * 0.6,
		lift: tall * 0.15,
		reach: tall * 0.35,
		muzzle: 0,
		tail: 'stub',
		ear: 'round',
		mark: 'none',
		coat,
		trim: coat,
		...over
	};
}

/** Птах: тулуб стоїть яйцем, ніг дві, замість писка дзьоб. */
function bird(coat: string, len: number, leg: number, over: Partial<Beast> = {}): Beast {
	return beast(coat, len, leg, {
		stance: 'two',
		tall: len * 0.72,
		wide: len * 0.6,
		shin: 0.035,
		head: len * 0.32,
		lift: 0,
		reach: 0,
		muzzle: len * 0.17,
		tail: 'fan',
		ear: 'none',
		...over
	});
}


<script lang="ts">
	import { T } from '@threlte/core';
	import type { Beast } from './anatomy';
	import { headY } from './figure';

	/**
	 * ЗДОРОВʼЯ Й СТРЕС — ПРЯМО НАД ТВАРИНОЮ, а не лише у вікні про неї.
	 *
	 * ## Що було не так
	 *
	 * Скарга автора: «видно стан тварини тільки у вікні інформації». Не зовсім:
	 * стан на карті БУВ — кільце під ногами, зелене чи руде. Але воно бінарне
	 * (`stage === 'healthy'`), тобто «60% здоровʼя, 25% стресу» показати не могло,
	 * а саме ці числа й вирішують, чи потрібен лікар і чи можна випускати.
	 *
	 * ## Чому смужки — КОРОБКИ, а не площини з поворотом за камерою
	 *
	 * У `AnimalFigure` записано, чому кільце лежить на землі: «підпис у повітрі
	 * довелося б повертати за камерою». Для площини це правда, для коробки — ні:
	 * її видно з будь-якого боку без жодного повороту.
	 *
	 * Але один фіксований поворот усе-таки є, і він не про камеру, а про ЧИТАННЯ.
	 * Камера тут не обертається ніколи (`isoCamera.ts`: «обертати камеру тут НЕ
	 * можна»), і напрямок «праворуч по екрану» у світі дорівнює `(1, 0, −1)/√2`.
	 * Смужка вздовж місцевої X після повороту на 45° лягає саме туди — тобто
	 * виглядає горизонтальною й на повну довжину, а не вкороченою навскіс.
	 *
	 * ## Чому `MeshBasicMaterial`
	 *
	 * Смужка — це показник, а не предмет у світі: у сутінках вона мусить читатися
	 * так само, як опівдні. `MeshStandardMaterial` темнів би разом із рештою.
	 *
	 * ЦІНА НАЗВАНА: кольори тут ЛІТЕРАЛИ, а не токени теми — у WebGL змінних CSS
	 * немає. Отже гейт контрасту (`src/contrast.test.ts`) цих трьох кольорів не
	 * бачить, і підбирати їх довелося оком на всіх чотирьох темах: тло під ними —
	 * не панель, а сама земля ділянки.
	 */
	interface Props {
		body: Beast;
		/** 0…1 — від смерті до повного здоровʼя. */
		health: number;
		/** 0…1 — від спокою до межі, за якою випуск неможливий. */
		stress: number;
		/**
		 * Курсор на тварині або вона вибрана.
		 *
		 * Дві причини, а не одна: наведення на телефоні НЕ ІСНУЄ, тож без вибору
		 * смужки лишалися б там напівпрозорими назавжди. Тап — це вибір, і він
		 * працює скрізь.
		 */
		attention: boolean;
	}

	let { body, health, stress, attention }: Props = $props();

	const b = $derived(body);

	/**
	 * Довжина смужки. Не стала: у їжака тулуб 45 см, і смужка на 0.6 накрила б
	 * його цілком, а в слона та сама виглядала б наліпкою.
	 */
	const span = $derived(Math.max(0.7, b.len));

	/** Висота, з якої смужки не налазять ні на голову, ні на роги. */
	const lift = $derived(headY(b) + b.head + 0.3);

	/*
	 * Товщина й проміжок ЗАМІРЯНІ на знімку, а не вибрані на око: при 0.055 і 0.085
	 * дві смужки на екрані зливалися в один подвійний волосок, і сказати, котра з
	 * них здоровʼя, було нічим.
	 */
	const THICK = 0.09;
	/** Проміжок між смужками: менше — злипаються, більше — читаються як дві речі. */
	const ROW = 0.16;
	/** Товщина по глибині: коробку видно збоку, і саме це заміняє білборд. */
	const DEPTH = 0.04;

	const TRACK = '#1d2b1f';
	/*
	 * Здоровʼя міняє колір на порогах, а не плавно: гравець реагує на «щось не
	 * так», і сходинка це каже, а плавний градієнт — ні. Числа ті самі, що в
	 * панелі мешканців: нижче половини — тривога, нижче чверті — біда.
	 */
	const healthColour = $derived(health > 0.5 ? '#4caf50' : health > 0.25 ? '#e0a72c' : '#d1493c');
	/** Стрес — навпаки: чим більше, тим гірше. */
	const stressColour = $derived(stress > 0.6 ? '#d1493c' : stress > 0.3 ? '#e0a72c' : '#6ba7d8');

	const alpha = $derived(attention ? 1 : 0.3);

	/**
	 * Заповнення росте ВЛІВО-ВПРАВО від лівого краю, тож і центр його їде.
	 *
	 * Порожня смужка не малюється зовсім: коробка нульової довжини лишає на екрані
	 * піксель-артефакт на стику.
	 */
	const fill = (value: number) => ({
		width: Math.max(0, Math.min(1, value)) * span,
		shift: (Math.max(0, Math.min(1, value)) - 1) * span * 0.5
	});

	const rows = $derived([
		{ y: lift + ROW / 2, colour: healthColour, ...fill(health) },
		{ y: lift - ROW / 2, colour: stressColour, ...fill(stress) }
	]);
</script>

<!--
	Поворот на 45° — той самий для всіх смужок: він робить їх горизонтальними на
	екрані. Причина — у докблоці вище; камера в цій сцені не обертається.
-->
<T.Group position={[0, 0, 0]} rotation.y={Math.PI / 4}>
	{#each rows as row, index (index)}
		<!-- Жолоб: він і показує, скільки НЕ набрано. -->
		<T.Mesh position={[0, row.y, 0]}>
			<T.BoxGeometry args={[span, THICK, DEPTH]} />
			<!--
				Жолоб такий самий напівпрозорий, як заповнення: 30% — це прохання
				автора про ВСЮ смужку. Гасити жолоб додатково означало б, що на світлій
				землі від показника лишається сама лише кольорова риска без межі.
			-->
			<T.MeshBasicMaterial transparent opacity={alpha} color={TRACK} />
		</T.Mesh>

		{#if row.width > 0}
			<!-- Заповнення трохи товще жолоба — інакше на стику видно мерехтіння. -->
			<T.Mesh position={[row.shift, row.y, 0]}>
				<T.BoxGeometry args={[row.width, THICK * 0.8, DEPTH * 1.4]} />
				<T.MeshBasicMaterial transparent opacity={alpha} color={row.colour} />
			</T.Mesh>
		{/if}
	{/each}
</T.Group>

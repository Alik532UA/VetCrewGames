import { DEFAULT_ZOOM } from './isoCamera';

/**
 * Куда дивиться камера — знане й ПОЗА сценою.
 *
 * Мінікарта мусить знати те саме, що камера, і навпаки: тап по мінікарті рухає
 * камеру, перетягування сцени рухає рамку на мінікарті. Тримати ці числа
 * всередині сцени означало б, що мінікарту доведеться малювати тривимірним
 * рушієм, — а вона потрібна саме тому, що рушій показує лише клаптик.
 *
 * Тому стан живе тут, у чистому файлі без `three`: сцена його ЗВІТУЄ, мінікарта
 * читає, обидві можуть наказати. Наказ не міняє числа сам — їх присилає назад
 * сцена, уже обрізані по межах панорамування. Інакше рамка на мінікарті
 * заїжджала б туди, куди камера поїхати не може.
 */
export class MapView {
	/** Центр огляду у світових одиницях. */
	x = $state(0);
	z = $state(0);
	zoom = $state(DEFAULT_ZOOM);
	/**
	 * Скільки світу вміщається у вікно — уже поділене на масштаб.
	 *
	 * Два числа, а не одне: вікно телефона вище за широке, а вікно ноутбука
	 * навпаки, і рамка мусить показувати те, що видно НАСПРАВДІ.
	 */
	spanX = $state(0);
	spanY = $state(0);

	/** Сцена, яка вміє виконати наказ. `null`, поки полотно не змонтоване. */
	#drive: ((x: number, z: number, zoom: number) => void) | null = null;

	/** Сцена підключається й повертає собі відключення — просто в `$effect`. */
	attach(drive: (x: number, z: number, zoom: number) => void): () => void {
		this.#drive = drive;
		return () => {
			this.#drive = null;
		};
	}

	/** Звіт сцени: камера поїхала ось так. Єдине місце, де числа змінюються. */
	report(x: number, z: number, zoom: number, spanX: number, spanY: number): void {
		this.x = x;
		this.z = z;
		this.zoom = zoom;
		this.spanX = spanX;
		this.spanY = spanY;
	}

	/** Наказ: дивитися сюди. Без сцени наказ просто нікуди не йде. */
	look(x: number, z: number, zoom = this.zoom): void {
		this.#drive?.(x, z, zoom);
	}
}

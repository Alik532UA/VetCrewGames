/**
 * ЖИТТЯ ТВАРИНИ У ВОЛЬЄРІ: ходить, стоїть, плаває, ховається в укриття.
 *
 * ## Що було не так
 *
 * Скарга автора: «тварини стоять по центру вольєра; очікуваний результат —
 * симуляція життя, іноді стоять, іноді плавають, іноді ходять, іноді заходять в
 * укриття». Так і було: `AnimalFigure` малювався в центрі групи вольєра, а
 * повернений був на `(id % 8) × 45°` — тобто нерухома фігура з випадковим, але
 * назавжди тим самим напрямком погляду.
 *
 * ## ЧОМУ ЦЕ НЕ СИМУЛЯЦІЯ, А ВИГЛЯД
 *
 * Найважливіше рішення файлу, і воно про те, ЧОГО тут немає.
 *
 * `src/lib/reserve/` — чистий шар: без годинника, без `Math.random()`, бо та сама
 * послідовність ходів мусить давати той самий світ. Якби координати блукання
 * лежали там, вони поїхали б у сейв (кілька чисел на кожну тварину, що
 * змінюються двадцять разів на секунду), вимагали б міграції формату й
 * потрапили б у майбутній журнал спільної партії — тобто мережа везла б
 * прогулянку лева.
 *
 * Тому це `components/`: чиста функція від `(зерно, id, фаза)` до пози. Стан не
 * зберігається зовсім, а сцена лишається відтворюваною — після перезавантаження
 * той самий лев ходить тим самим маршрутом.
 *
 * ## Чому свій хеш, а не `seededRandom`
 *
 * `seededRandom` дає ПОТІК: щоб узяти сто двадцятий крок, треба пройти сто
 * дев'ятнадцять. Тут же потрібне протилежне — прочитати відразу той крок, у
 * якому тварина зараз, бо фаза приходить із годинника й ніколи не починається з
 * нуля. Тобто потрібен хеш (адресоване значення), а не генератор.
 *
 * ## Розклад одного «кроку»
 *
 * Крок — це «дійти й постояти»: перші 60% часу тварина йде до цілі, решту стоїть
 * на місці. Саме тому окремого стану «стоїть» тут немає: він і є хвіст кожного
 * кроку, а разом вони дають те, чого просив автор, — то рух, то спокій.
 *
 * Куди йти, вирішує хеш: звичайна точка всередині паркана, водойма (якщо
 * куплена) або укриття (якщо куплене). Тобто на карті видно ще й те, ЩО гравець
 * поставив: у вольєрі без водойми ніхто не плаває.
 */

/** Скільки триває один крок «дійти й постояти», у секундах фази. */
export const LEG_SECONDS = 6;

/** Яку частку кроку тварина ЙДЕ. Решту — стоїть на цілі. */
const WALK_SHARE = 0.6;

/** Скільки з місця в кожен бік лишається під ногами: далі паркан. */
const MARGIN = 0.78;

/**
 * Наскільки часто тварина йде до водойми чи укриття, коли вони є.
 *
 * Не половина: істота, що ходить лише по двох точках, читається як механізм.
 * Кожна третя ціль — особлива, решта — випадкова точка вольєра.
 */
const SPECIAL_SHARE = 0.34;

/** Що робить тварина на цілі цього кроку. */
export type Doing = 'walk' | 'rest' | 'swim' | 'shelter';

export interface Pose {
	/** Зсув від центру вольєра у світових одиницях. */
	x: number;
	z: number;
	/** Куди дивиться, у радіанах. Під час ходьби — уперед; на стоянці — як прийшла. */
	turn: number;
	/** Що саме робить ЗАРАЗ (на ходу це завжди `walk`). */
	doing: Doing;
}

export interface Habitat {
	/** Півсторона вольєра у світових одиницях: далі паркан. */
	half: number;
	/** Куплена водойма — можна плавати. */
	water: boolean;
	/** Куплене укриття — можна зайти всередину. */
	shelter: boolean;
}

/**
 * Хеш трьох цілих у [0, 1). Дрібний мікс на кшталт `splitmix32`.
 *
 * Три доданки з різними великими простими: без них сусідні `id` давали б сусідні
 * значення, і два леви в сусідніх вольєрах ходили б синхронно, як танцюристи.
 */
function hash(a: number, b: number, c: number): number {
	let x = (a * 374761393 + b * 668265263 + c * 2246822519) | 0;
	x = (x ^ (x >>> 15)) * 2246822507;
	x = (x ^ (x >>> 13)) * 3266489909;
	x = x ^ (x >>> 16);
	return ((x >>> 0) % 100000) / 100000;
}

/** Куди тварина йде на кроці `leg` і що там робитиме. */
function targetOf(seed: number, id: number, leg: number, place: Habitat) {
	const pick = hash(seed, id, leg * 3 + 1);
	const special: Doing[] = [];
	if (place.water) special.push('swim');
	if (place.shelter) special.push('shelter');

	if (special.length > 0 && pick < SPECIAL_SHARE) {
		/*
		 * Координати особливих цілей ті самі, що в `EnclosureShape`: водойма стоїть
		 * у `[half * 0.45, _, half * 0.45]`, укриття — у `[-half * 0.45, _, half *
		 * 0.5]`. SYNC: якщо там переставлять, тварина плаватиме поруч із водоймою.
		 */
		const doing = special[Math.floor(hash(seed, id, leg * 3 + 2) * special.length)] ?? special[0];
		return doing === 'swim'
			? { x: place.half * 0.45, z: place.half * 0.45, doing }
			: { x: -place.half * 0.45, z: place.half * 0.5, doing };
	}

	const reach = place.half * MARGIN;
	return {
		x: (hash(seed, id, leg * 3 + 2) * 2 - 1) * reach,
		z: (hash(seed, id, leg * 3 + 3) * 2 - 1) * reach,
		doing: 'rest' as Doing
	};
}

/**
 * Поза тварини в момент `phase` (секунди від початку спостереження).
 *
 * Чиста: ті самі аргументи — та сама поза, скільки б разів не спитати. Саме тому
 * її можна перевіряти тестом, а не оком, і саме тому сцена після перезавантаження
 * виглядає так само.
 */
export function poseAt(seed: number, id: number, phase: number, place: Habitat): Pose {
	const leg = Math.floor(phase / LEG_SECONDS);
	const t = (phase - leg * LEG_SECONDS) / LEG_SECONDS;

	const from = targetOf(seed, id, leg - 1, place);
	const to = targetOf(seed, id, leg, place);

	/** Куди дивиться: уздовж руху. Стоячи — так, як прийшла. */
	const turn = Math.atan2(to.x - from.x, to.z - from.z);

	if (t >= WALK_SHARE) return { x: to.x, z: to.z, turn, doing: to.doing };

	// Плавна частка ходьби: `smoothstep` замість прямої — тварина не смикається
	// на початку й у кінці кроку, а розганяється й спиняється.
	const raw = t / WALK_SHARE;
	const eased = raw * raw * (3 - 2 * raw);
	return {
		x: from.x + (to.x - from.x) * eased,
		z: from.z + (to.z - from.z) * eased,
		turn,
		doing: 'walk'
	};
}

// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * СТАН ТВАРИНИ ВИДНО НА КАРТІ, а не лише у вікні про неї.
 *
 * ## Чому перевірка структурна, а не по знімку
 *
 * Знімок сцени Threlte порівнювати нічим: `MeshBasicMaterial` світла не питає,
 * зате все навколо — питає, а освітлення тут добове. Тому перевіряються рішення,
 * які цю смужку й роблять смужкою, і кожне з них ламається одним словом.
 *
 * ## Що саме тут вирішено, і чому це варто стерегти
 *
 * 1. **`MeshBasicMaterial`, а не `Standard`.** Смужка — показник, а не предмет
 *    світу: у сутінках вона мусить читатися так само, як опівдні. Одна літера в
 *    назві матеріалу — і показник темніє разом із землею.
 * 2. **30% у спокої, 100% під увагою** — дослівне прохання автора. Число легко
 *    «підправити на око», і тоді смужки або з'їдають карту, або зникають.
 * 3. **Увага — це наведення АБО вибір.** Половина цього правила критична:
 *    наведення на телефоні НЕ ІСНУЄ, тож без `selected` смужки лишалися б там
 *    напівпрозорими назавжди, і повного стану з карти не побачити ніяк.
 * 4. **Поворот тварини гаситься.** Група фігури повернена на `turn` — куди
 *    тварина дивиться; смужка мусить читатися однаково з будь-якого боку.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — пʼять, кожен червонив
 * рівно свій пункт: матеріал замінено на `Standard`; прозорість у спокої піднято
 * до 1; прибрано `|| selected` з `attention`; прибрано `-turn`; прибрано
 * порівняння `next === hovered`, тобто кадр на кожен рух курсора.
 *
 * ПЕРШИЙ ПРОГІН ЦЬОГО ГЕЙТА УПАВ САМ, і це варто знати: пункт про матеріал шукав
 * `MeshStandardMaterial` по сирому тексту й знаходив його у ВЛАСНОМУ докблоці
 * `AnimalVitals`, де той цитується як «те, чого тут немає». Звідси `code()`
 * нижче.
 */

const VITALS = 'src/lib/components/reserve/AnimalVitals.svelte';
const FIGURE = 'src/lib/components/reserve/AnimalFigure.svelte';
const SHAPE = 'src/lib/components/reserve/EnclosureShape.svelte';
const SCENE = 'src/lib/components/reserve/SceneBody.svelte';

const read = (path: string) => readFileSync(path, 'utf8');

/**
 * Коментарі знімаються ПЕРЕД пошуком, і це не охайність.
 *
 * Докблок `AnimalVitals` пояснює, чому матеріал саме `Basic`, — і цитує при цьому
 * `MeshStandardMaterial`. Пошук по сирому тексту звинувачував би файл у тому, що
 * той робить правильно, і саме так перший прогін цього гейта й упав. Той самий
 * дефект уже був у переліку медіазапитів і в обліку накладок.
 */
const code = (path: string) =>
	read(path)
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:])\/\/.*/g, '$1 ');

describe('смужки стану над твариною', () => {
	const vitals = code(VITALS);

	it('перевірка жива: компонент смужок знайдено й він у фігурі', () => {
		expect(vitals, 'розбір джерела зʼїв усе').toContain('BoxGeometry');
		expect(code(FIGURE), 'фігура не малює смужок').toContain('<AnimalVitals');
	});

	it('обидві шкали, а не одна', () => {
		// Здоровʼя без стресу відповідає лише на половину питання: випуск блокує
		// саме стрес, і побачити його треба так само з карти.
		expect(vitals).toMatch(/health:\s*number/);
		expect(vitals).toMatch(/stress:\s*number/);
	});

	it('матеріал не залежить від освітлення', () => {
		expect(vitals, 'показник мусить читатися і в сутінках').toContain('MeshBasicMaterial');
		expect(vitals, 'MeshStandardMaterial темнів би разом із землею').not.toContain(
			'MeshStandardMaterial'
		);
	});

	it('30% у спокої, 100% під увагою', () => {
		expect(vitals, 'прозорість у спокої не 0.3').toMatch(/attention\s*\?\s*1\s*:\s*0\.3/);
		// Прозорість мусить іти В МАТЕРІАЛ, а не лишитися невжитою змінною.
		expect(vitals).toMatch(/opacity=\{alpha\}/);
	});

	it('увага — це наведення АБО вибір', () => {
		/*
		 * Друга половина обовʼязкова: `@media (hover: none)` — це кожен телефон, і
		 * там перша половина не спрацює жодного разу.
		 */
		expect(code(SHAPE), 'вибір не піднімає прозорість').toMatch(/hovered \|\| selected/);
		expect(code(SCENE), 'у сцені немає підсвітки наведенням').toMatch(/hovered = next/);
	});

	it('поворот тварини гаситься', () => {
		// Інакше смужка крутилася б разом із твариною й ставала б до глядача боком.
		expect(code(FIGURE), 'поворот фігури не скасовано').toMatch(/rotation\.y=\{-turn\}/);
	});

	it('промінь наведення не питається на кожен рух курсора', () => {
		/*
		 * `pointermove` приходить під сотню разів на секунду, а промінь шукає по
		 * всій сцені — шістсот сімдесят фігур рельєфу плюс вольєри. Без обмеження
		 * це найдорожча річ на сторінці, і платить за неї той, хто просто веде
		 * мишею.
		 */
		const scene = code(SCENE);
		expect(scene, 'немає межі частоти променя').toMatch(/HOVER_EVERY_MS/);
		expect(scene, 'кадр малюється навіть коли підсвітка не змінилася').toMatch(
			/if \(next === hovered\) return;/
		);
	});
});

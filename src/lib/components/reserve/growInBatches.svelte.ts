/**
 * Довга робота ПОРЦІЯМИ: скільком елементам уже дано місце.
 *
 * Рельєфу в заповіднику шістсот сімдесят фігур, і разом вони блокували головний
 * потік однією задачею — виміряно 2663 мс. Під час такої задачі браузер не малює
 * нічого: ні кадру, ні смужки поступу, ні реакції на дотик. Сторінка виглядала
 * завислою тому, що вона й була зависла. Порціями та сама робота триває приблизно
 * стільки ж, але між ними керування повертається браузерові: карта показується з
 * першої порції, поступ видно, дотик працює. Виміряно після: найдовша задача 95 мс.
 *
 * **Пауза між порціями — `MessageChannel`, і це не забаганка.**
 *
 * `requestAnimationFrame` не годиться: черга кадрів не йде у фонових вкладках і в
 * прихованих панелях, тобто сцена в такій вкладці не добудувалася б НІКОЛИ, а
 * дефект був би невидимий для вимірювання (AI-AGENT-PITFALLS-v8 § 2).
 *
 * `setTimeout` не годиться теж, і це виміряно: у прихованому документі браузер
 * клампить його до секунди, тож замість двох із половиною секунд сцена росла б
 * десять хвилин — за шість секунд доїхало 9%.
 *
 * `MessageChannel` віддає керування через чергу задач і клампу не має. Тим самим
 * трюком користується планувальник React — і з тієї самої причини.
 *
 * Живе окремим файлом, бо це РЕЖИМ РОБОТИ, а не деталь сцени: та сама потреба
 * зʼявиться в будь-якому місці, де за раз створюється сотня обʼєктів.
 */

/** Скільки часу віддаємо одній порції: кадр при 60 Гц — 16 мс. */
const FRAME_BUDGET_MS = 12;

/** З чого починаємо, поки ціна одного елемента невідома. */
const FIRST_BATCH = 4;

/** Межі порції: одна фігура — щоб не застрягти, шістдесят чотири — щоб не блокувати. */
const MIN_BATCH = 1;
const MAX_BATCH = 64;

export interface Growing {
	/** Скільком елементам уже дано місце. Читати в розмітці як межу зрізу. */
	readonly shown: number;
}

/**
 * Викликається під час створення компонента — саме тому це функція, а не клас:
 * `$effect` усередині мусить належати компонентові, який його ж і прибере.
 *
 * @param total скільки елементів усього; функція, бо число приходить із `$derived`
 * @param onProgress частка зробленого, 0 → 1
 */
export function growInBatches(total: () => number, onProgress: (done: number) => void): Growing {
	let shown = $state(0);

	$effect(() => {
		// Єдина залежність — КІЛЬКІСТЬ. Читати тут `shown` означало б перезапускати
		// цикл на кожній порції, а він і сам себе рухає.
		const count = total();

		if (count === 0) {
			onProgress(1);
			return;
		}
		if (shown >= count) {
			onProgress(1);
			return;
		}

		/*
		 * Розмір порції підбирається НА ХОДУ.
		 *
		 * Стале число довелося б рахувати під найслабший пристрій, і на настільному
		 * екрані воно витрачало б секунди на порожні поступки. Тут розмір виводиться
		 * з того, скільки коштувала попередня порція.
		 */
		let batch = FIRST_BATCH;
		let posted = 0;
		let stopped = false;

		const channel = new MessageChannel();

		channel.port1.onmessage = () => {
			if (stopped) return;

			if (posted > 0) {
				const perItem = Math.max((performance.now() - posted) / batch, 0.05);
				batch = Math.max(MIN_BATCH, Math.min(MAX_BATCH, Math.round(FRAME_BUDGET_MS / perItem)));
			}

			shown = Math.min(count, shown + batch);
			onProgress(shown / count);

			if (shown < count) {
				posted = performance.now();
				channel.port2.postMessage(null);
			}
		};

		posted = performance.now();
		channel.port2.postMessage(null);

		return () => {
			stopped = true;
			channel.port1.close();
			channel.port2.close();
		};
	});

	return {
		get shown() {
			return shown;
		}
	};
}

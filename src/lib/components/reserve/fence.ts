import type { Quality } from '$lib/reserve/constants';

/**
 * ПАРКАН ПОКАЗУЄ ЯКІСТЬ ВОЛЬЄРА — і доти не показував нічого.
 *
 * ## Що було не так
 *
 * Скарга автора: «паркан для всіх трьох якостей вольєрів виглядає нормально але
 * однаково». Так і було: `EnclosureShape` малював два бруси на висотах 0.22 і
 * 0.42 та стовпчики 0.08×0.56 незалежно від `quality`.
 *
 * Це не лише про красу. Якість — це друга з двох осей, якими гравець платить
 * (перша — розмір), і вона коштує втричі більше за просту (`QUALITY_PRICE`).
 * Купивши «відмінну», людина не бачила на карті НІЧОГО іншого — тобто найдорожче
 * рішення в грі не мало видимого наслідку.
 *
 * ## І про знос — те, чого канон уже вимагав
 *
 * У `constants.ts` над порогами зносу стоїть: «сходинки, а не плавний множник,
 * щоб гравець БАЧИВ, що вольєр став гіршим». Побачити було нічим. Тому паркан
 * бере `effectiveQuality`, а не `enclosure.quality`: зношена «відмінна» виглядає
 * як «добра», а руїна — як «проста». Обіцянка того коментаря виконується саме
 * тут.
 *
 * ## Чому окремий модуль, а не числа в компоненті
 *
 * Бо це три набори по сім чисел, і саме такі набори розповзаються по гілках
 * `{#if}`. Тут вони поруч, їх видно одним поглядом — і їх перевіряє
 * `fence.test.ts`: різниця мусить бути ВИДНОЮ, а не просто існувати.
 *
 * ## Чим саме різняться три паркани
 *
 * Не одним параметром, а чотирма — і це рішення. Один (скажімо, колір) на карті
 * з висоти пташиного льоту читався б як освітлення, а не як інший паркан.
 *
 *  * **висота** — 0.44 / 0.60 / 0.82: найпомітніше з висоти;
 *  * **кількість брусів** — два / два / три;
 *  * **матеріал** — сіра вивітрена деревина / свіжа деревина / світлий камінь із
 *    металевим верхом;
 *  * **накривка на стовпчику** — лише у «відмінної»: дрібна деталь, зате саме
 *    вона робить паркан «доглянутим» зблизька.
 */
export interface Fence {
	/** Висоти брусів у світових одиницях, від землі. */
	rails: number[];
	/** Товщина бруса. */
	railThickness: number;
	/** Повна висота стовпчика: центр рахується як половина. */
	postHeight: number;
	/** Сторона перетину стовпчика. */
	postWidth: number;
	/** Колір стовпчика. */
	post: string;
	/** Колір бруса. */
	rail: string;
	/** Накривка на стовпчику — лише в найдорожчого паркана. */
	cap: boolean;
	/**
	 * Скільки стовпчиків додати до сторони сліду.
	 *
	 * Не абсолютне число: великий вольєр із трьома стовпчиками читався б як гола
	 * рамка незалежно від якості. Тому це надбавка до `span`, а сама формула
	 * лишається в компоненті — він знає, скільки клітинок займає слід.
	 */
	extraPosts: number;
}

/**
 * ПРОСТА — жердини. Низько, сіро, рідко: огорожа «щоб не вийшло», а не будівля.
 *
 * Колір навмисно вивітрений (сірий підмішаний у брунатний): свіжа деревина
 * читалася б як нова й доглянута, тобто протилежно до того, що це найдешевший
 * вибір.
 */
const SIMPLE: Fence = {
	rails: [0.16, 0.32],
	railThickness: 0.03,
	postHeight: 0.44,
	postWidth: 0.07,
	post: '#7a6a55',
	rail: '#8d7f6b',
	cap: false,
	extraPosts: 1
};

/**
 * ДОБРА — те, що стояло тут для всіх трьох: свіжа деревина, два бруси.
 *
 * Середню лишено без змін навмисно: вона й була «нормально» за словами автора,
 * тож рухати її означало б міняти те, на що скарги не було.
 */
const GOOD: Fence = {
	rails: [0.22, 0.42],
	railThickness: 0.04,
	postHeight: 0.6,
	postWidth: 0.09,
	post: '#8a6f4a',
	rail: '#a88a5e',
	cap: false,
	extraPosts: 2
};

/**
 * ВІДМІННА — камінь із металевим верхом, три бруси, накривки.
 *
 * Холодний тон, а не «яскравіша деревина»: різниця мусить читатися як ІНШИЙ
 * матеріал. Три бруси й висота 0.82 роблять її вищою за будь-яку тварину, яку
 * малює `AnimalFigure` у дрібному масштабі, — тобто «звідси не вийдуть».
 */
const EXCELLENT: Fence = {
	rails: [0.24, 0.46, 0.68],
	railThickness: 0.045,
	postHeight: 0.82,
	postWidth: 0.11,
	post: '#9aa3a8',
	rail: '#c2cbd0',
	cap: true,
	extraPosts: 3
};

const BY_QUALITY: Record<Quality, Fence> = { 1: SIMPLE, 2: GOOD, 3: EXCELLENT };

/**
 * Паркан для якості. Приймати сюди треба `effectiveQuality`, а не поле сейва:
 * знос мусить бути видним, і це половина сенсу цього модуля.
 */
export const fenceOf = (quality: Quality): Fence => BY_QUALITY[quality];

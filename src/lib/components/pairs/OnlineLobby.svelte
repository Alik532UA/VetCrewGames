	}

	/*
	 * ДВА СТОВПЦІ, щойно їм є де стати: запросити | хто тут.
	 *
	 * Межа 44rem — два стовпці по 20rem плюс проміжок: нижче підпис гравця й
	 * сегменти «Автостарт | Підтвердження готовності» почали б тиснутися.
	 *
	 * Налаштування гри тут ідуть НИЖЧЕ, на всю ширину, а не третім вузьким
	 * стовпцем: на 44–64rem третина — це 14–20rem, і шість ігор у ній стали б
	 * стовпчиком по одній. На всю ширину вони лягають одним-двома рядками.

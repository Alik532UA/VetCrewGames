<script lang="ts">
	import { t, formatFont } from '$lib/i18n';
	import MemoryCard from '$lib/components/MemoryCard.svelte';
	import YouTag from '$lib/components/ui/YouTag.svelte';
	import PlayerBadge from '$lib/components/ui/PlayerBadge.svelte';
	import Flag from '$lib/components/ui/Flag.svelte';
	import Avatar from '$lib/components/ui/Avatar.svelte';
	import TimerBar from '$lib/components/ui/TimerBar.svelte';
	import type { PairsMatch } from '$lib/controllers/pairsMatch.svelte';

	/**
	 * Спільна партія «Знайди пару»: табло, дошка й підпис «чия черга».
	 *
	 * Компонент нічого не вирішує — навіть пауза перед перегортанням належить
	 * матчу, бо оголошує її ходом той, чия черга. Тут лишається показ і дотик.
	 */
	interface Props {
		match: PairsMatch;
		/** Хто я: підсвітити свій рядок у таблі. */
		me: string;
		/** Хто зараз на звʼязку. Присутність — окрема гілка бази. */
		online: string[];
		/** Нова партія; `undefined` — я не господар, і роздавати не мені. */
		onRematch?: () => void;
		/** Закрити кімнату назовсім. Так само лише господар. */
		onClose?: () => void;
		/**
		 * Забрати чергу в того, хто зник. `undefined` — ще не час або не мені.
		 *
		 * Кнопка з'являється лише коли межа очікування вийшла: доки суперник на
		 * звʼязку, нікого не підганяють.
		 */
		onYield?: () => void;
		/**
		 * Завершити партію, з якої суперник не вернувся. Умова та сама, що в
		 * `onYield`, — тож обидві кнопки зʼявляються разом, і людина вибирає, грати
		 * далі самій чи закінчити.
		 */
		onEnd?: () => void;
		/**
		 * Скільки лишилося ПОТОЧНОМУ ходові, у мілісекундах. `null` — ходу немає.
		 *
		 * Число приходить ГОТОВИМ, бо позначку часу знає контролер, а не екран.
		 * Рахується для будь-якого ходу, а не лише для чужого: смуга мусить іти в
		 * обох гравців, інакше вона зникає й зʼявляється на кожному ході.
		 */
		turnLeftMs?: number | null;
	}

	let { match, me, online, onRematch, onClose, onYield, onEnd, turnLeftMs = null }: Props =
		$props();

	/**
	 * Хто з гравців зник із гілки присутності.
	 *
	 * Себе тут не буде: власний запис живий доти, доки жива вкладка, — а якби він
	 * зник, цього екрана вже ніхто не бачив би.
	 */
	const away = $derived(match.players.filter((player) => !online.includes(player.uid)));


	/** Скільки пар зібрав кожен: рахунок живе в правилах, не в кімнаті. */
	const scoreOf = (uid: string) => match.game.players.find((p) => p.id === uid)?.score ?? 0;

	/**
	 * Хто переміг. `null` — нічия, і це не рідкість: пар парна кількість.
	 *
	 * Відповідь дає МАТЧ: те саме число потрібне ще й нарахуванню балів у кінці
	 * партії, а дві копії цієї арифметики розійшлися б непомітно.
	 */
	const winner = $derived(match.players.find((player) => player.uid === match.winnerUid) ?? null);

	const rows = $derived(Math.ceil(match.game.slots.length / match.game.cols));
</script>

<div class="board" style="--cols: {match.game.cols}; --rows: {rows}">
	<!--
		Підпис черги — головне, що людина шукає очима в спільній грі. Тому окремим
		ЧЕРГА БІЛЬШЕ НЕ ПИШЕТЬСЯ СЛОВАМИ НА ЕКРАНІ — але лишається для скрінрідера.

		Прохання автора: «навіщо "Хід: Сердитий Вовк", якщо видно, хто ходить…
		контейнер зайвий». Він має рацію про ОКО: обводка в таблі показує того, хто
		ходить, точніше за підпис — вона стоїть на самому гравці, а не називає його
		імʼя вдруге.

		Але скрінрідеру обводка не каже нічого, і колір теж (WCAG 1.4.1). Тому рядок
		лишився в розмітці під `.visually-hidden`: на екрані його немає, у живому
		регіоні він є, і зміна черги оголошується так само, як доти. Прибрати його
		цілком означало б зробити гру для незрячих нечитною — а це не те, про що
		просив автор.

		`formatFont` тут НЕ застосовується: він міняє кириличну «і» на латинську,
		щоб літера була у шрифті, — а це потрібно тому, що МАЛЮЄТЬСЯ. Те, що читає
		машина, від такої підміни вимовляється покручем (див. AGENTS.md).

		Гілки «партія скінчилася» тут немає, і це попереднє прохання автора: підсумок
		нижче каже «Нічия» й показує кнопку «Зіграти ще», тобто містить те саме з
		подробицями. Разом із гілкою на підсумок переїхав і `role="status"`.
	-->
	{#if !match.over}
		<p class="visually-hidden" role="status" data-testid="pairs-turn-status">
			{#if match.myTurn}
				{t('pairs.yourTurn')}
			{:else}
				{t('pairs.waitingFor')}: {match.actor?.name ?? '—'}
			{/if}
		</p>
	{/if}

	<!--
		СМУГА ЧАСУ ХОДУ — та сама, що у вікторині (`ui/TimerBar.svelte`).

		Прохання автора: «краще додай таймер, який вже реалізований в вікторині».
		Замінює вона рядок «Забрати хід можна за 0:43», який стояв окремою панеллю й
		зʼявлявся на початку кожного чужого ходу: «гра постійно стрибає через рядок».

		Смуга йде на КОЖНОМУ ході, а не лише на чужому, і це головне рішення тут.
		Показувати її тільки тоді, коли можна забрати чергу, означало б повернути те
		саме стрибання, просто тонше на шість пікселів. Заодно вона правдива: межа
		стосується й мого ходу — просто діяти за нею може суперник, а не я.
	-->
	{#if turnLeftMs !== null}
		<!--
			Смуга завужена до ДОШКИ, а не до сторінки. `.board` розтягнутий на всю
			ширину, тобто смуга на `width: 100%` йшла б від краю до краю над дошкою в
			півтора рази вужчою — і читалася б як смужка сторінки, а не як час цієї
			партії. Ширина рахується тим самим виразом, що й дошка, з одного місця.
		-->
		<div class="board__timer">
			<TimerBar
				leftMs={turnLeftMs}
				limitMs={match.turnLimitMs}
				label={t('pairs.turnTimer')}
				testId="pairs-turn-progress"
			/>
		</div>
	{/if}

	{#if match.over}
		<!--
			Підсумок замість зникнення дошки: картки лишаються на місці, бо після
			партії на них дивляться — «а де ж була та друга сова».
		-->
		<!--
			`role="status"` тут не для повноти: доти кінець партії оголошував рядок
			черги словами «партія скінчилася», і саме той рядок прибрано як дубль. Роль
			переїхала разом із обовʼязком — тепер скрінрідер чує підсумок, а не
			повідомлення про те, що підсумок є.
		-->
		<div class="board__over text-panel" role="status" data-testid="pairs-result-panel">
			<!--
				ЯК партія скінчилася — окремим рядком, і він тут не для повноти.

				«Перемога: Аня 4:2» над тим, хто пішов на другому ході, — правда про
				рахунок і неправда про партію. Рядок називає причину, тож рахунок нікого
				не вводить в оману й нічого не приховує.
			-->
			{#if match.endedBy !== null}
				<span class="board__wait" data-testid="pairs-ended-early-hint">
					{@html formatFont(t('pairs.endedEarly'))}
				</span>
			{/if}
			<b data-testid="pairs-result-text">
				{#if winner}
					<!--
						«Перемога: Аня», а не «Аня перемогла»: імʼя тут вільний рядок, і роду
						ми не знаємо. Перша версія писала «Аня — переміг», тобто вгадувала —
						і вгадувала неправильно рівно в половині випадків.
					-->
					{@html formatFont(t('pairs.won'))}: {winner.name}{#if winner.uid === me}
						<YouTag />
					{/if}
				{:else}
					{@html formatFont(t('pairs.draw'))}
				{/if}
			</b>
			{#if onRematch}
				<button
					type="button"
					class="btn-primary"
					onclick={onRematch}
					data-testid="pairs-rematch-btn"
				>
					{@html formatFont(t('pairs.rematch'))}
				</button>
				<button type="button" class="chip" onclick={onClose} data-testid="pairs-close-btn">
					{@html formatFont(t('pairs.closeRoom'))}
				</button>
			{:else}
				<span class="board__wait">{@html formatFont(t('pairs.waitingHost'))}</span>
			{/if}
		</div>
	{/if}

	<!--
		КОЖЕН ГРАВЕЦЬ — У СВОЄМУ КОНТЕЙНЕРІ, і рахунок ходів теж.

		Прохання автора: «кожен гравець в окремому графічному контейнері (і Ходів
		теж), щоб візуально виглядало окремо». Доти всі троє лежали в одній панелі
		(`board__score.text-panel`), тобто рядок читався як одне речення: «Спритний
		Яструб (ви): 7 Величезний Синій Кит: 7 Ходів: 26». Де закінчується один
		гравець і починається другий, доводилося визначати по двокрапках.

		Сам рядок фону більше не має — його мають плитки. Тло на тлі дало б шов на
		межі й нічого більше.
	-->
	<div class="board__score">
		{#each match.players as player (player.uid)}
			<!--
				ПОЗНАЧКИ ПОПЕРЕДУ, а не в хвості рядка.

				Прохання автора дослівно: «статуси треба ставити на початку» — замість
				«Плавна Манта: 0 (немає звʼязку)» очікується «(немає звʼязку) Плавна
				Манта: 0». Причина не в смаку: у хвості позначка стоїть ПІСЛЯ рахунку,
				тобто щоб дізнатися стан гравця, доводиться дочитати плитку до кінця, а
				на вузькому екрані ще й після переносу. Попереду вона читається як мітка
				рядка — так само, як мітка теки стоїть перед назвою, а не після.

				Побічний виграш: `role="status"` на самій плитці. Доти «суперник зник»
				оголошувала панель застою, і саме той рядок прибрано як дубль; тепер
				оголошує плитка, у якій пілюля зʼявляється. Регіон живе з монтування, тож
				поява пілюлі — саме та зміна, яку скрінрідер читає (регіон, створений
				РАЗОМ із вмістом, не оголошує нічого).
			-->
			<span
				class="board__player text-panel"
				class:board__player--turn={player.uid === match.actor?.id}
				class:board__player--away={!online.includes(player.uid)}
				role="status"
				data-testid="pairs-player-{player.uid}-status"
			>
				{#if player.uid === me}<YouTag />{/if}
				<!--
					СТАН СЛОВАМИ, а не лише стилем.

					Доти «немає звʼязку» передавалося перекресленням і прозорістю — тобто
					скрінрідер не отримував нічого, а очима це читалося як «видалено» або
					«недоступно», хоч людина могла просто зайти в тунель. Тепер причина
					написана, а стиль лишається підказкою, а не єдиним джерелом.
				-->
				{#if !online.includes(player.uid)}
					<PlayerBadge tone="away">{@html formatFont(t('pairs.away'))}</PlayerBadge>
				{/if}
				<Flag code={match.members.find((m) => m.uid === player.uid)?.country} />
				<Avatar avatar={match.members.find((m) => m.uid === player.uid)?.avatar} />
				<!--
					ІМʼЯ, ДВОКРАПКА Й РАХУНОК — ОДИН елемент флексу, а не три.

					`.board__player` — це `inline-flex` із проміжком, а проміжок стосується
					КОЖНОЇ дитини. Доти позначка стояла в цьому ж потоці, і двокрапка
					відʼїжджала від неї на ті самі пʼять пікселів: «Дикий Манул ВИ : 0».
					Позначки звідси пішли, але обгортка лишається — вона й тримає інваріант,
					а не сподівається на те, що сусідні текстові вузли злипнуться самі.
				-->
				<span class="board__who">{player.name}: {scoreOf(player.uid)}</span>
			</span>
		{/each}
		<span class="board__moves text-panel" data-testid="pairs-moves-value">
			{@html formatFont(t('memory.moves'))}: {match.game.moves}
		</span>
	</div>

	<!--
		Колонки приходять із КІМНАТИ, а не з екрана: сітка, яку перебудовує ширина
		вікна, стирає запамʼятане — і в спільній грі ще й розводить двох гравців.
	-->
	<div class="board__deck" data-testid="pairs-deck-container">
		{#each match.game.slots as slot, index (slot.card.id)}
			<MemoryCard
				{slot}
				position={index + 1}
				disabled={!match.myTurn || match.over}
				waiting={!match.myTurn}
				onflip={() => match.flip(index)}
				testId="pairs-card-btn-{slot.card.id}"
			/>
		{/each}
	</div>

<!--
		«ЗАБРАТИ ХІД» — КНОПКА, А НЕ АВТОМАТИКА, і ця панель тільки про неї.

		Присутність гасне сама, і вона НЕ лежить у журналі ходів, отже не має права
		змінювати стан партії: інакше дошки розійшлися б залежно від того, чий сокет
		обірвався першим. Тому діяти замість того, хто стоїть, — це хід, який робить
		людина й однаково перевіряють усі.

		ДВІ ЗМІНИ, І ОБИДВІ ПРОТИ СТРИБАННЯ ДОШКИ.

		Перша — умова показу. Тут стояло «межа застосовна», тобто панель зʼявлялася
		на початку КОЖНОГО чужого ходу з відліком «Забрати хід можна за 1:02», і
		зникала на кожному своєму. Автор сказав: «гра постійно стрибає через рядок» і
		«навіщо взагалі ця інформація з самого початку ходу?». Ні для чого:
		дізнаватися про межу на першій секунді ходу нема потреби. Тепер умова — сама
		ДІЯ (`onYield`), тобто панель є лише тоді, коли є що натиснути. Час, що
		спливає, показує смуга вище, і вона з місця не рухається.

		Друга — місце. Панель стоїть ПІД дошкою, а не над нею: зʼявляючись зверху,
		вона зсувала вниз усі картки, тобто людина цілила в картку, а тицяла в іншу.
		Знизу її поява нічого не зсуває.
	-->
	{#if !match.over && onYield}
		<div class="board__stall text-panel" role="status" data-testid="pairs-stall-panel">
			{#if away.length === 0}
				<!--
					Присутність є, а ходу немає: людина сидить у вкладці й не грає. Пілюлі
					«немає звʼязку» в таблі в цьому разі НЕМА (вона від присутності), тож
					причину каже панель — інакше дві кнопки стояли б без пояснення.
				-->
				<span data-testid="pairs-stall-idle-text">
					{@html formatFont(t('pairs.opponentGone'))}
				</span>
			{/if}

			<button type="button" class="chip" onclick={onYield} data-testid="pairs-yield-btn">
				{@html formatFont(t('pairs.takeTurn'))}
			</button>
			{#if onEnd}
				<button type="button" class="chip" onclick={onEnd} data-testid="pairs-end-btn">
					{@html formatFont(t('pairs.endMatch'))}
				</button>
			{/if}
		</div>
	{/if}
</div>


// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * КІНЕЦЬ ТАЙМЕРА НАТИСКАЄ «ПЕРЕВІРИТИ» ЗАМІСТЬ ГРАВЦЯ.
 *
 * ## Що це стереже
 *
 * Скарга автора: «фіксується відповідь, що була на момент закінчення таймера…
 * щоб гравець, який відповів на питання, але забув чи не встиг натиснути кнопку
 * „ПЕРЕВІРИТИ“, отримав бали за поточну свою відповідь». Доти такий гравець
 * діставав нуль за те, що знав.
 *
 * ## Чому саме ці пункти, і чому по джерелах
 *
 * Сама фіксація — це `$effect` у компоненті над пʼятьма контролерами ігор;
 * перевірити її поведінкою означало б підняти Svelte-рантайм із годинником. Тому
 * правила, які живуть у КОНТРОЛЕРАХ, перевірені там, де їх видно
 * (`populationGame.svelte.test.ts`, розділ «час вийшов»), а тут — три рішення
 * обвʼязки, кожне з яких ламається одним словом і жодного з них не видно в грі:
 *
 *  1. **не в нулі, а ЗА триста мілісекунд до нього.** Фаза раунду рахується з того
 *     самого годинника, що й залишок: у мить, коли `leftMs` доходить до нуля,
 *     `QuizRound` знімає дошку тим самим оновленням, і ефект знищеного компонента
 *     не запуститься. «Зафіксувати в нулі» означає «не зафіксувати» — і зламати це
 *     можна, «спростивши» умову до `<= 0`;
 *  2. **три гри, а не пʼять.** «Правда чи міф?» і «Хто з іншої родини?» фіксують
 *     відповідь самим натиском на варіант: незакінченого стану там немає. Дві дії —
 *     вибрати й підтвердити — лише в «Де живем?», «Хто численніший?» і «Роздай
 *     страви», і саме там гравець втрачав усе за незроблену другу;
 *  3. **умови «є що фіксувати» — ті самі, чим кнопки вмикаються для людини.**
 *     `canCheck` і `canFeed` не переписані тут іншими словами, тобто таймер може
 *     ровно те, що міг би зробити гравець. Виняток один і названий явно: у «Хто
 *     численніший?» таймер зараховує недороблений ряд (`check(true)`), бо
 *     витрачати раунд уже нічого.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — чотири, кожен червонив
 * рівно свій пункт: `AUTOCOMMIT_MS` зведено до нуля; умову `timeLeftMs > …`
 * прибрано; гілку `population` викинуто з `pendingCommit`; `canFeed` замінено на
 * `true`. Усі чотири зроблені.
 */

const BOARD = 'src/lib/components/quiz/QuizBoard.svelte';
const ROUND = 'src/lib/components/quiz/QuizRound.svelte';
const TRIAL = 'src/lib/components/reserve/ReserveTrial.svelte';

const read = (path: string) => readFileSync(path, 'utf8');

/** Коментарі цитують те, чого в коді немає, — знімаємо перед пошуком. */
const code = (path: string) =>
	read(path)
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:])\/\/.*/g, '$1 ');

describe('таймер натискає «Перевірити»', () => {
	const board = code(BOARD);

	it('перевірка жива: дошка знає залишок часу', () => {
		expect(board, 'пропа із залишком немає').toMatch(/timeLeftMs\?: number/);
		expect(code(ROUND), 'раунд не передає залишок дошці').toMatch(/timeLeftMs=\{leftMs\}/);
	});

	it('фіксує ДО нуля, а не в нулі', () => {
		/*
		 * У нулі дошки на екрані вже немає: фаза й залишок ідуть з одного годинника.
		 * Триста мілісекунд — три такти кімнати, тобто вікно не проскочить.
		 */
		expect(board, 'запасу немає — фіксація не встигне').toMatch(/AUTOCOMMIT_MS = 300/);
		expect(board, 'умова не дивиться на запас').toMatch(/timeLeftMs > AUTOCOMMIT_MS/);
	});

	it('фіксує РАЗ', () => {
		// `$effect` перезапускається на будь-якій зміні читаного стану, а після
		// фіксації стан гри змінюється — тобто без прапорця прохід був би другий.
		expect(board).toMatch(/autocommitted/);
		expect(board, 'прапорець не ставиться').toMatch(/autocommitted = true/);
	});

	it('накриває всі три гри з підтвердженням', () => {
		const fn = board.slice(board.indexOf('function pendingCommit'));
		const body = fn.slice(0, fn.indexOf('\n\t}'));
		expect(body, '«Де живем?» лишилася без фіксації').toMatch(/'habitat'[\s\S]*canCheck/);
		expect(body, '«Роздай страви» лишилася без фіксації').toMatch(/'feeding'[\s\S]*canFeed/);
		expect(body, '«Хто численніший?» лишилася без фіксації').toMatch(
			/'population'[\s\S]*check\(true\)/
		);
	});

	it('умови беруться в гри, а не переписуються тут', () => {
		/*
		 * Таймер може ровно те, що міг би гравець. Своя копія умови («вибрано хоч
		 * щось») розійшлася б із кнопкою на першій же правці правил гри.
		 */
		const fn = board.slice(board.indexOf('function pendingCommit'));
		const body = fn.slice(0, fn.indexOf('\n\t}'));
		expect(body, 'умову «Де живем?» переписано власними словами').toContain('game.canCheck');
		expect(body, 'умову «Роздай страви» переписано власними словами').toContain('game.canFeed');
	});

	it('соло-темп таймера не має і не отримує', () => {
		/*
		 * Та сама дошка стоїть у перевірці заповідника, де темп задає гравець кнопкою
		 * «Далі». Проп там не передається, тобто `undefined`, і фіксація не спрацює
		 * жодного разу — інакше відповідь відбирали б у людини, яка нікуди не спішить.
		 */
		expect(code(TRIAL), 'перевірка заповідника почала передавати таймер').not.toContain(
			'timeLeftMs'
		);
		expect(board, 'відсутній таймер не відсіюється').toMatch(/timeLeftMs === undefined/);
	});
});

<script lang="ts">
	import { formatFont } from '$lib/i18n';
	import { slide } from 'svelte/transition';
	import { motionMs } from '$lib/utils/transitions';
	import type { QuizPhase } from '$lib/controllers/quizMatch.svelte';
	import type { QuizStep } from '$lib/config/quizOnline';
	import QuizBoard from './QuizBoard.svelte';
	import TimerBar from '$lib/components/ui/TimerBar.svelte';

	/**
	 * Один раунд спільної вікторини: таймер, дошка, табло між раундами.
	 *
	 * ## Чому окремим компонентом
	 *
	 * Сторінка кімнати вийшла за межу розміру (429 рядків при орієнтирі 400), і
	 * межу канон піднімати забороняє. Фаза раунду — природний розріз: усе, що
	 * всередині, залежить лише від фази, кроку й часу, і жодного мережевого стану
	 * не читає.
	 *
	 * ## Час приходить ЧИСЛАМИ, а не годинником
	 *
	 * `leftMs` і `limitMs` — це вже порахований стан із контролера, який виводить
	 * їх із СЕРВЕРНИХ позначок часу в журналі. Свій `setInterval` тут дав би
	 * другий годинник, і смуга в двох гравців розійшлася б саме тому, що кожен
	 * рахував би від власного `Date.now()`.
	 */
	interface Props {
		/**
		 * Перекладач вікторини: її рядки лежать у ЛІНИВОМУ чанку
		 * (`i18n/quiz`), бо головний словник вантажать усі відвідувачі.
		 */
		text: (key: string) => string;
		phase: QuizPhase;
		/** Крок програми для цього раунду. `null` — раунду ще немає. */
		step: QuizStep | null;
		/**
		 * Що показує СМУГА, мс. Застигає, щойно відповіли всі, — і це навмисно: інакше
		 * вона стрибала б із половини на майже нуль (див. `leftMs` у `QuizMatch`).
		 */
		leftMs: number;
		/**
		 * Скільки лишилося до самої МЕЖІ ЧАСУ, мс. Не застигає.
		 *
		 * Два схожі числа, бо питання різні: смуга показує час, а автовідповідь питає
		 * «скільки в мене лишилося, щоб підтвердити». Застигле число дало б їй
		 * спрацювати не тоді, коли час вийшов, а тоді, коли хтось відповів.
		 */
		limitLeftMs: number;
		/** Скільки триває раунд, мс. Нуль — раунду немає; `NO_LIMIT` — межі немає. */
		limitMs: number;
		/** Чи я вже відповів у цьому раунді. */
		answered: boolean;
		/**
		 * Я глядач: дошку видно (грати подумки ніхто не забороняє), але відповідь не
		 * йде нікуди — і про це сказано, а не мовчки.
		 */
		watching?: boolean;
		onanswer: (correct: number) => void;
	}

	let {
		text,
		phase,
		step,
		leftMs,
		limitLeftMs,
		limitMs,
		answered,
		watching = false,
		onanswer
	}: Props = $props();
</script>

<!--
	ДОШКА ЖИВЕ Й НА ТАБЛІ — розбором під рахунком (прохання автора 2026-09-28: «між раундами
	оновлений рахунок, а нижче пояснення відповідей минулого раунду»). Той самий `{#key}` на
	зерні кроку, тож на табло переходить ТОЙ САМИЙ екземпляр дошки, з відповіддю гравця.
	Крок під час табла ще той, що скінчився: наступний оголошує ведучий уже після нього.
-->
{#if (phase === 'round' || phase === 'reveal') && step}
	{@const settled = phase === 'reveal'}
	<!--
		Смуга таймера. Ширина рахується від СЕРВЕРНОГО старту раунду, тож у двох
		гравців вона в одному місці, а не в кожного своя.

		БЕЗ МЕЖІ СМУГИ НЕМАЄ, а на її місці — рядок. Частка від нескінченності — це
		`NaN`, тобто смуга стала б або повною, або порожньою, і обидва стани брешуть:
		повна обіцяє, що час іде, порожня — що він вийшов. Рядок стоїть на тому самому
		місці, щоб гість, який не бачив налаштувань лобі, знав, чому таймера нема.
	-->
	{#if settled}
		<!-- Смуги раунду на таблі немає: у табла своя — до наступного раунду. -->
	{:else if Number.isFinite(limitMs)}
		<div class="round__timer" transition:slide={{ duration: motionMs(300) }}>
			<TimerBar {leftMs} {limitMs} label={text('quiz.roundTimer')} testId="quiz-round-progress" />
		</div>
	{:else}
		<p
			class="round__free text-panel"
			transition:slide={{ duration: motionMs(300) }}
			data-testid="quiz-round-unlimited-text"
		>
			{@html formatFont(text('quiz.roundUnlimited'))}
		</p>
	{/if}

	<!--
		ДОШКА ЛИШАЄТЬСЯ ПІСЛЯ ВІДПОВІДІ, і це виправлення, а не смак.

		Тут стояло `{#if answered}` навколо дошки, тобто відповівши, гравець бачив
		замість неї один рядок: питання, власна відповідь і розбір зникали разом.
		Автор сказав це прямо: «нічого не зникає, а на місці „далі“ ставимо
		„чекаємо на решту“».

		Змінити відповідь це не дає: `QuizMatch.answer()` відкидає повторну
		(`iAnswered`), і правило журналу — теж (один хід на раунд). Тобто заборона
		тримається журналом, а не тим, що дошку прибрали з екрана.

		`{#key}` на зерні раунду: контролер гри тримає стан, і наступний раунд для
		нього — нова партія на один раунд, а не продовження.
	-->
	{#key step.seed}
		<!--
			`timeLeftMs` — щоб таймер міг натиснути «Перевірити» за гравця, який вибрав
			відповідь і не встиг підтвердити. Проп саме тут, а не в дошці своїм
			годинником: час у цій партії один, серверний, і другий годинник розвів би
			двох гравців. На таблі його немає: раунд у журналі закрито, і натиснути
			«Перевірити» за гравця там уже не можна.
		-->
		<QuizBoard {text} {step} {onanswer} timeLeftMs={settled ? undefined : limitLeftMs} {settled} />
	{/key}

	{#if settled}
		<!-- Рядки «чекаємо» — про раунд, а він скінчився. -->
	{:else if watching}
		<p
			class="round__wait text-panel"
			transition:slide={{ duration: motionMs(300) }}
			data-testid="quiz-watching-text"
		>
			{@html formatFont(text('quiz.watching'))}
		</p>
	{:else if answered}
		<!-- На місце кнопки «Далі», яку в кімнаті ховає сама дошка (`hideNext`). -->
		<p
			class="round__wait text-panel"
			transition:slide={{ duration: motionMs(300) }}
			data-testid="quiz-answered-text"
		>
			{@html formatFont(text('quiz.answered'))}
		</p>
	{/if}
{/if}

<!--
	РАХУНОК ТАБЛА — НЕ ТУТ: його малює `QuizReveal`, панель над цією дошкою. Тут стояв рядок

<script lang="ts">
	import type { Member } from '$lib/net/roomTypes';
	import Flag from '$lib/components/ui/Flag.svelte';
	import Avatar from '$lib/components/ui/Avatar.svelte';
	import YouTag from '$lib/components/ui/YouTag.svelte';

	/**
	 * Смуга гравців над дошкою вікторини: хто в партії, хто вже відповів, кого немає.
	 *
	 * ## Це і є «спільна» частина раунду
	 *
	 * Дошки в кожного своя (усі відповідають одночасно), тож єдине, що всі бачать
	 * однаково під час раунду, — склад і те, хто вже відповів. Рахунку тут немає
	 * навмисно: цифри поруч із питанням тягнуть увагу саме тоді, коли вона потрібна
	 * на питанні. Рахунок і місця — на таблі між раундами й у фіналі (`QuizReveal`).
	 */
	interface Props {
		players: Member[];
		/** Хто вже відповів у поточному раунді. Саме ФАКТ, без правильності. */
		answered: string[];
		/**
		 * КОГО НЕМАЄ ОНЛАЙН — за uid.
		 *
		 * Вимога автора: «гравець який відключився виглядає на 50% ч/б та на сірому
		 * фоні, бо чітко видно було хто дізконект». Доти відсутній виглядав рівно як
		 * присутній: єдиною ознакою було вікно очікування над дошкою, тобто зв'язок
		 * «хто саме зник» доводилося тримати в голові.
		 *
		 * Порожньо — усі на місці; так само поводиться соло-режим, де присутності
		 * немає взагалі.
		 */
		away?: string[];
		me: string;
	}

	let { players, answered, away = [], me }: Props = $props();

	/*
	 * Порядок — за ВХОДОМ, стабільний і нічого не виказує. Сортування за очками
	 * переставляло б рядки просто від того, що хтось відповів, — тобто показувало б
	 * те, що під час раунду навмисно ховається. Рахунок і місця — на таблі між
	 * раундами й у фіналі (`QuizReveal`); окремої підсумкової таблиці тут більше
	 * немає (прохання автора 2026-09-26: фінал — великим, а не дрібним табло).
	 */
	const ranked = $derived([...players].sort((a, b) => a.order - b.order));
</script>

<!--
	КОЖЕН ГРАВЕЦЬ — У СВОЇЙ ПЛИТЦІ, а не всі в одній панелі.

	Прохання автора: «окремі візуальні контейнери (як в грі з „знайти пару“)». Доти
	`text-panel` стояв на самому переліку, тобто двоє гравців лежали на одному тлі й
	читалися як один блок: де закінчується перший і починається другий, доводилося
	визначати по прапорах.

	Тло тепер мають плитки, а не перелік: фон на фоні дав би шов на межі й нічого
	більше. Це та сама правка, що вже зроблена в таблі «Знайди пару», і зроблена
	однаково навмисно — два вигляди того самого рядка розійшлися б на першій же
	правці.
-->
<ul class="scores" data-testid="quiz-scores-list">
	{#each ranked as player (player.uid)}
		<!--
			ФОН РЯДКА — ЦЕ Й Є «ВІН УЖЕ ВІДПОВІВ».
			
			Саме факт, без правильності: показати «правильно» до кінця раунду
			означало б підказати відповідь тим, хто ще думає. Автор попросив рівно
			це — «просто сам факт відповіді, наприклад інший фон контейнеру».
		-->
		<li
			class="scores__row text-panel"
			class:scores__row--answered={answered.includes(player.uid)}
			class:player-away={away.includes(player.uid)}
			data-testid="quiz-score-{player.uid}-item"
		>
			<!--
				ПОЗНАЧКА ПОПЕРЕДУ, а не в хвості імені — так само, як у таблі «Знайди
				пару». Прохання автора там було дослівне: «статуси треба ставити на
				початку», і причина та сама: у хвості позначку видно, лише дочитавши рядок,
				а на вузькому екрані ще й після переносу.
			-->
			{#if player.uid === me}<YouTag />{/if}
			<span class="scores__who">
				<Flag code={player.country} />
				<Avatar avatar={player.avatar} />
				{player.name}
			</span>
		</li>
	{/each}
</ul>

<style>
	/*
	 * Сам перелік — лише розкладка: фон і відступи мають плитки всередині.
	 * `padding` тут був відступом ПАНЕЛІ, а панелі більше немає — лишившись, він
	 * додав би плиткам порожню рамку, якої ніхто не просив.
	 */
	.scores {
		display: flex;
		flex-flow: row wrap;
		justify-content: center;
		gap: var(--space-xs) var(--space-sm);
		margin: 0;
		padding: 0;
		list-style: none;
		box-sizing: border-box;
	}

	/*
	 * СМУГА — рядок, що переноситься, а не стовпець (правила вище).
	 *
	 * Стовпцем табло росло вниз на кожного гравця й відсувало дошку — на четвертому
	 * учаснику питання виїжджало за екран. `flex-wrap` лишає це чесним і на вузькому
	 * екрані: краще другий рядок, ніж обрізані підписи. Проміжок `--space-sm`, а не
	 * `--space-md`: межу між гравцями тримає край плитки, а не порожнє місце. І без
	 * `width: 100%`: кнопка паузи — сусід переліку в тому самому рядку — інакше
	 * щоразу переносилася б на свій рядок («не займати зайвий рядок»).
	 */

	/*
	 * Підкладка «відповів» — домішка АКЦЕНТУ до тла, а не свій колір: у чотирьох
	 * темах акцент різний, і власне значення тут розійшлося б із трьома з них.
	 *
	 * ПЕРЕКРИВАЄ `.text-panel`, і це навмисно, а не нічия порядку правил: плитка
	 * тепер має власне тло, а «він уже відповів» мусить бути видно ПОВЕРХ нього.
	 * Скоупований селектор із двома класами специфічніший за глобальний з одним, тож
	 * відповідь не залежить від того, як бандлер поскладав файли
	 * (SVELTE-UI-v8 § 3.6). `border-radius` лишається свій: `--radius-md` панелі на
	 * плитці висотою в рядок виглядає завеликим.
	 */
	.scores__row--answered {
		background: color-mix(in srgb, var(--color-accent), transparent 82%);
	}

	/*
	 * Вигляд відсутнього — глобальний `.player-away` (`global.css`): переліків
	 * гравців три, і правило мусить бути одне. Він гасить ПРОЗОРІСТЮ, а не тлом, тож
	 * із власним тлом плитки не воює: гасне вся плитка разом із підкладкою «він
	 * відповів». Той, хто відповів і потім зник, — найважливіший випадок, і саме
	 * так він і читається: приглушено, а не «усе гаразд».
	 *
	 * Плитки вужчі за `.text-panel`: та розрахована на абзац, а тут рядок із
	 * прапором і числом. Скоупований селектор специфічніший за глобальний, тож
	 * перекриття навмисне (SVELTE-UI-v8 § 3.6) — так само, як у таблі «Знайди пару».
	 */
	.scores__row {
		display: flex;
		padding: 4px var(--space-sm);
		border-radius: var(--radius-sm);
		flex: 0 1 auto;
		align-items: center;
		gap: var(--space-sm);
		font-size: var(--font-size-sm);
	}

	.scores__who {
		display: flex;
		align-items: center;
		gap: 6px;
		min-width: 0;
		overflow: hidden;
		text-overflow: ellipsis;
		white-space: nowrap;
	}
</style>

	 * вибраного». Спільний клас тримає те саме рішення для всіх виборів одразу.
	 *
	 * Курсор `aria-disabled` — теж там: клік доходить (інакше не показався б `title`
	 * про останню гру), але нічого не робить.
	 */
</style>

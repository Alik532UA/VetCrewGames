// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';

/**
 * СОРОЧКА КАРТКИ КАЖЕ, ЧИЙ ХІД.
 *
 * ## Що це стереже
 *
 * Прохання автора: «лапка кольорова тільки коли мій хід, а коли інший гравець
 * ходить, то сірий колір». Доти сорочка була однакова завжди, і те, що дошка не
 * клікається, повідомлялося лише курсором — тобто дізнатися можна було, тицьнувши.
 *
 * ## Чому саме ці пункти
 *
 * Кожен ламається одним словом і жоден не видно з коду:
 *
 *  * **окремий проп, а не `disabled`.** Спокуса очевидна: `disabled` в онлайні й
 *    так дорівнює «не мій хід». Але в одиночній грі він стоїть, поки лежать дві
 *    відкриті картки, — тобто всі сорочки блимали б сірим двічі на хід. Тому
 *    сірість питається окремо, і типово її немає;
 *  * **сірий від токена, а не літерал.** Тем чотири; зашитий `#888` в одній
 *    зникне у тлі, у другій стане плямою. Побачити це можна лише перемкнувши всі
 *    чотири, і саме тому це перевірка, а не пильність;
 *  * **колір лишається кольором на своєму ході.** Правило, що застосується
 *    завжди, «виправляє» скаргу, прибравши акцент зовсім.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — три, кожен червонив рівно
 * свій пункт: `waiting` замінено на `disabled` у виклику з `OnlineRoom`; сірий
 * замінено на `#8a8a8a`; `.card--waiting` знято з умови, тобто правило стало
 * безумовним. Усі три зроблені.
 */

const CARD = 'src/lib/components/MemoryCard.svelte';
const ROOM = 'src/lib/components/pairs/OnlineRoom.svelte';
const SOLO = 'src/routes/[[lang=lang]]/game-memory/+page.svelte';

const read = (path: string) => readFileSync(path, 'utf8');

/** Коментар цитує те, чого в коді немає, — знімаємо перед пошуком. */
const code = (path: string) =>
	read(path)
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:])\/\/.*/g, '$1 ');

describe('сорочка картки', () => {
	const card = code(CARD);

	it('перевірка жива: сорочка малює лапку й має свій колір', () => {
		expect(card, 'лапки на сорочці немає').toContain('<PawPrint');
		expect(card, 'у сорочки немає власного кольору').toMatch(/\.card__face--back\s*\{[^}]*color:/);
	});

	it('сірість — окремий проп, а не `disabled`', () => {
		/*
		 * `disabled` відповідає на «чи можна перевернути ЦЮ картку», а не на «чи мій
		 * хід». В одиночній грі він стоїть на кожному погляді на дві відкриті.
		 */
		expect(card, 'пропа немає — сірість звідкись іще').toMatch(/waiting\?: boolean/);
		expect(card, 'типово сіро — одиночна гра теж посіріла').toMatch(/waiting = false/);
		expect(code(ROOM), 'кімната не каже картці, чий хід').toMatch(/waiting=\{!match\.myTurn\}/);
		expect(code(SOLO), 'одиночна гра почала питати про черги').not.toContain('waiting=');
	});

	it('сірий рахується від токена теми', () => {
		const rule = card.slice(card.indexOf('.card--waiting'));
		const body = rule.slice(0, rule.indexOf('}'));
		expect(body, 'правила для чужого ходу немає').toMatch(/color:/);
		expect(body, 'сірий зашито літералом — у якійсь із чотирьох тем він зламається').toMatch(
			/var\(--color-text\)/
		);
	});

	it('на своєму ході лапка лишається кольоровою', () => {
		// Інакше скарга «виправляється» тим, що акцент зникає зовсім.
		expect(card, 'акцент із сорочки зник').toMatch(
			/\.card__face--back\s*\{[^}]*var\(--color-accent\)/
		);
		expect(card, 'сірість застосовується без умови').toContain('.card--waiting .card__face--back');
	});
});

/**
 * ЗІБРАНА ПАРА: напівпрозора Й МЕНША.
 *
 * Прохання автора: «напівпрозорі і розмір 80% від розміру». Прозорість була, а
 * розмір лишався тим самим.
 *
 * ## Чому саме `transform`, і чому це варто стерегти
 *
 * Зменшити картку властивістю розкладки (`width`, `aspect-ratio`, `scale`) —
 * найочевидніша правка, і вона зламала б головне в цій грі: клітинка сітки
 * зменшилася б разом із карткою, а сусідні поїхали б туди, де їх запамʼятали.
 * Місце на дошці і є те, що гравець тримає в голові. `transform` у розкладку не
 * входить зовсім.
 *
 * Друге — повільний хвіст. Три секунди тут не випадкові: швидкий стрибок у 80%
 * читається як «картку прибрали», а роздивитися, ЩО саме збіглося, треба встигнути.
 * Тому зменшення йде тією ж кривою, що й згасання, і про `prefers-reduced-motion`
 * дбає глобальне правило.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — три, кожен червонив рівно
 * свій пункт: `transform: scale(0.8)` замінено на `width: 80%`; прибрано
 * `transform` із переходу, тобто стрибок замість хвоста; прибрано `opacity`.
 * Усі три зроблені.
 */
describe('зібрана пара', () => {
	const card = code(CARD);
	const rule = (() => {
		const at = card.indexOf('.card--taken {');
		return card.slice(at, card.indexOf('}', at));
	})();

	it('перевірка жива: правило для зібраної пари знайдено', () => {
		expect(rule, 'правила `.card--taken` в компоненті немає').toContain('.card--taken');
	});

	it('менша — і саме на 80%', () => {
		expect(rule, 'зібрана пара того самого розміру').toMatch(/transform:\s*scale\(0\.8\)/);
	});

	it('розмір міняється НЕ розкладкою', () => {
		/*
		 * `width`/`height`/`aspect-ratio`/`scale` тут зсунули б сусідні картки з місць,
		 * які гравець запамʼятав, — тобто зламали б саму гру, а не вигляд.
		 */
		expect(rule, 'розмір міняється властивістю розкладки — сусідні картки поїдуть').not.toMatch(
			/\b(width|height|aspect-ratio|scale|padding|margin)\s*:/
		);
	});

	it('прозорість лишилася, і обидві зміни під тим самим хвостом', () => {
		expect(rule, 'зібрана пара перестала блякнути').toMatch(/opacity:\s*0\.25/);
		expect(rule, 'зменшення без переходу — стрибок замість хвоста').toMatch(
			/transition:[\s\S]*transform 3s ease-out/
		);
		expect(rule, 'згасання втратило свій повільний хвіст').toMatch(
			/transition:[\s\S]*opacity 3s ease-out/
		);
	});
});

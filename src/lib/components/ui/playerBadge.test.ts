// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * ПОЗНАЧКИ БІЛЯ ІМЕНІ — ПІЛЮЛІ, А НЕ ТЕКСТ У ДУЖКАХ.
 *
 * ## Що це стереже
 *
 * Скарга автора: «мітка (ви) (немає зʼязку) — актуальний результат: звичайна
 * текстова; очікуваний: стильна графічна», зі взірцем із сусіднього `MindStep`.
 * І друга, про той самий рядок: «кожен гравець в окремому графічному контейнері
 * (і Ходів теж), щоб візуально виглядало окремо».
 *
 * Обидва дефекти повертаються ОДНАКОВО легко й однаково непомітно: хтось
 * дописує третю позначку звичайним `<span>({t(...)})</span>` — і вона виглядає
 * правильною сама по собі, поки не стане поруч із пілюлею. Або згортає табло
 * назад в одну панель, бо «так менше рядків CSS».
 *
 * ## Чому по джерелах
 *
 * Вигляд перевіряється оком, і він перевірений: знімки табла в двох темах, у
 * стані «онлайн» і «немає звʼязку». Тут — інваріанти, які око НЕ ловить:
 * скільком місцям належить один і той самий вигляд і чи не зрослися плитки
 * назад.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — три, кожен червонив рівно
 * свій пункт: дописано другу пілюлю власними правилами в `OnlineRoom`;
 * повернуто `text-panel` на `.board__score`; `.board__who` переведено на
 * `inline-flex`, тобто рядкового потоку знову немає. Усі три зроблені.
 */

const BADGE = 'src/lib/components/ui/PlayerBadge.svelte';
const YOU = 'src/lib/components/ui/YouTag.svelte';
const ROOM = 'src/lib/components/pairs/OnlineRoom.svelte';

const read = (path: string) => readFileSync(path, 'utf8');

/** Коментар може цитувати те, чого в коді немає, — знімаємо перед пошуком. */
const code = (path: string) =>
	read(path)
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:])\/\/.*/g, '$1 ');

function svelteFiles(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) svelteFiles(full, out);
		else if (entry.endsWith('.svelte')) out.push(full.split(String.fromCharCode(92)).join('/'));
	}
	return out;
}

describe('позначки гравця', () => {
	it('перевірка жива: пілюля існує і має два тони', () => {
		const badge = code(BADGE);
		expect(badge).toMatch(/tone: 'me' \| 'away'/);
		expect(badge, 'нейтральний тон').toContain('.badge--me');
		expect(badge, 'тон попередження').toContain('.badge--away');
	});

	it('позначка лишається СЛОВОМ, а не самим лише кольором', () => {
		/*
		 * WCAG 1.4.1: колір і форма не бувають єдиним носієм. Пілюля — підсилення,
		 * і текст усередині обовʼязковий, тож `children` тут не для гнучкості.
		 */
		expect(code(BADGE)).toMatch(/children: Snippet/);
		expect(code(YOU), 'позначка «це ви» без тексту').toContain("t('pairs.you')");
		expect(code(ROOM), 'позначка «немає звʼязку» без тексту').toContain("t('pairs.away')");
	});

	it('вигляд пілюлі живе в ОДНОМУ місці', () => {
		/*
		 * Друга копія того самого вигляду розійшлася б із першою на першій же
		 * правці, і розійшлася б непомітно. Тому клас `badge` оголошує рівно один
		 * файл, а всі, кому потрібна позначка, беруть компонент.
		 */
		const owners = svelteFiles('src').filter((file) => /^\t*\.badge[-\s{]/m.test(code(file)));
		expect(owners, 'правила пілюлі оголошено більш ніж в одному файлі').toEqual([BADGE]);
	});

	it('табло — не спільна панель: у кожного блоку своя', () => {
		/*
		 * Прохання автора дослівно. Доти всі троє лежали в одній панелі, і рядок
		 * читався як одне речення: де закінчується один гравець і починається
		 * другий, доводилося визначати по двокрапках.
		 */
		const room = code(ROOM);
		expect(room, 'табло знову спільна панель').not.toMatch(/class="board__score text-panel"/);
		expect(room, 'у гравця немає своєї плитки').toMatch(/class="board__player text-panel/);
		expect(room, 'у рахунку ходів немає своєї плитки').toMatch(/class="board__moves text-panel"/);
	});

	it('двокрапка не відʼїжджає від імені', () => {
		/*
		 * `.board__player` — це `inline-flex` із проміжком (прапор і аватар інакше
		 * злітають на базову лінію), а проміжок стосується КОЖНОЇ дитини. Без
		 * рядкового потоку навколо імені виходило «Дикий Манул ВИ : 0».
		 */
		expect(code(ROOM), 'імʼя, двокрапка й рахунок не в одному потоці').toMatch(
			/class="board__who"/
		);
		expect(code(ROOM)).toMatch(/\.board__who\s*\{[^}]*display:\s*inline;/);
	});

	it('позначки стоять НА ПОЧАТКУ плитки, а не в хвості', () => {
		/*
		 * Прохання автора дослівно: «статуси треба ставити на початку». У хвості
		 * позначка стоїть після рахунку — тобто стан гравця видно, лише дочитавши
		 * плитку до кінця, а на вузькому екрані ще й після переносу.
		 *
		 * Перевіряється ПОРЯДКОМ у джерелі, бо саме він і є порядком у DOM: жоден
		 * `order` чи `row-reverse` тут не задіяний, і саме тому вставити позначку
		 * назад у хвіст — правка на один рядок.
		 */
		const room = code(ROOM);
		const each = room.slice(room.indexOf('{#each match.players'));
		const chip = each.slice(0, each.indexOf('{/each}'));
		const you = chip.indexOf('<YouTag');
		const away = chip.indexOf('<PlayerBadge');
		const flag = chip.indexOf('<Flag');
		expect(you, 'позначки «ви» в плитці немає').toBeGreaterThan(-1);
		expect(away, 'позначки «немає звʼязку» в плитці немає').toBeGreaterThan(-1);
		expect(you, 'позначка «ви» після прапора').toBeLessThan(flag);
		expect(away, 'позначка «немає звʼязку» після прапора').toBeLessThan(flag);
	});

	it('слово написано правильно: «звʼязку», а не «зʼязку»', () => {
		/*
		 * Не орфографічна причепка: рядок так і поїхав у продакшн, і в слові бракувало
		 * «в» — на екрані стояв покруч, якого в мові немає. Перевіряється саме
		 * українська: в решти мов це «no connection» і подібні, там ламатися нічому.
		 */
		const uk = read('src/lib/i18n/translations/uk/ui.ts');
		const line = uk.split('\n').find((row) => row.includes("'pairs.away'")) ?? '';
		expect(line, 'ключа pairs.away в українських рядках немає').toContain('pairs.away');
		expect(line, 'у слові «звʼязку» пропала «в»').toContain('звʼязку');
	});
});

/**
 * ШАПКА ПАРТІЇ НЕ ПЕРЕКАЗУЄ САМУ СЕБЕ.
 *
 * ## Що це стереже
 *
 * Скарга автора: «дублююча інформація, що створює шум». Два приклади, і обидва
 * точні: рядок черги казав «Партія скінчилася» над підсумком, який казав «Нічия»
 * і показував кнопку «Зіграти ще»; панель застою казала «немає звʼязку: Ім'я»
 * над таблом, де те саме стояло пілюлею біля самого імені.
 *
 * ## Чому це вертається саме тихо
 *
 * Три блоки шапки вирішують говорити НЕЗАЛЕЖНО, трьома `{#if}`, і жоден із них не
 * бачить решти. Кожен окремо виглядає правильним — саме тому шум і накопичився:
 * ніхто не додавав його навмисно. Наступний такий рядок додасться так само.
 *
 * Головне, що тут закріплено, — умова показу панелі застою. Вона стала «межу
 * забрати хід застосовно» замість «когось немає»; після партії `actor` дорівнює
 * `null`, отже межі немає, отже панель вироджувалася в панель ДІЙ без жодної дії.
 *
 * ## І чому роль живого регіону тут теж інваріант
 *
 * Кінець партії оголошував скрінрідеру саме рядок черги — той, що прибрано. Без
 * `role="status"` на підсумку найважливіша подія партії перестала б оголошуватися
 * взагалі, і побачити це неможливо ні оком, ні знімком.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — чотири, кожен червонив
 * рівно свій пункт: повернуто гілку `match.over` в рядок черги; умову панелі
 * замінено назад на `away.length > 0 || onYield`; знято `role="status"` з
 * підсумку; позначку «ви» пересунуто після прапора. Усі чотири зроблені.
 */
describe('шапка партії', () => {
	const room = code(ROOM);

	it('перевірка жива: усі три блоки шапки на місці', () => {
		expect(room).toContain('data-testid="pairs-turn-status"');
		expect(room).toContain('data-testid="pairs-stall-panel"');
		expect(room).toContain('data-testid="pairs-result-panel"');
	});

	it('рядок черги мовчить, коли партія скінчилася', () => {
		expect(room, 'рядок черги не питає, чи партія триває').toMatch(
			/\{#if !match\.over\}\s*<p class="board__turn/
		);
		expect(room, 'рядок черги знову оголошує кінець партії').not.toContain("t('pairs.over')");
	});

	it('панель застою існує лише там, де є ДІЯ', () => {
		/*
		 * `onYield || countdown` — це і є «межа застосовна»: обидва виводяться з
		 * `yieldReadyAt`, який після партії `null`. Умова «когось немає» давала панель
		 * без кнопок і без відліку.
		 */
		expect(room, 'панель застою показується не за дією').toMatch(
			/\{#if !match\.over && \(onYield \|\| countdown\)\}/
		);
	});

	it('панель застою не називає того, хто вже позначений у таблі', () => {
		// Ім'я відсутнього каже пілюля біля самого імені. Другий раз — це і є шум.
		expect(room, 'панель застою знову перелічує імена').not.toMatch(/away\.map\(/);
	});

	it('підсумок оголошується сам, а не через рядок черги', () => {
		expect(room, 'кінець партії перестав оголошуватися скрінрідеру').toMatch(
			/class="board__over text-panel" role="status"/
		);
	});
});

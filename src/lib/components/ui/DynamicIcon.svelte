<script lang="ts">
	import type { IconProps, Sun } from 'lucide-svelte';
	import { hydrated } from '$lib/services/hydration.svelte';

	/**
	 * ЗНАЧОК, ВИБРАНИЙ ПІД ЧАС ВИКОНАННЯ, — лише так, і гейт `src/hydration-safe.test.ts`
	 * інших шляхів не пропускає.
	 *
	 * ## Дефект, від якого це захищає: той самий двічі
	 *
	 * 2026-09-13 у кнопці теми після перезавантаження у «Сонячному саду» був шлях МІСЯЦЯ з
	 * пререндера плюс вісім променів сонця — без кола. 2026-09-27 у плитці аватарки
	 * (`pairs-avatar-toggle-btn`) замість тулуба пташки стояла голова силуету: коло з
	 * пререндера, на яке дописано чужий `d`. Першого разу виправлено одну кнопку, і клас
	 * дефекту лишився — тому тепер виправлено МІСЦЕ, через яке він проходить.
	 *
	 * ## Механізм
	 *
	 * Пререндер кладе в HTML значок для ТИПОВОГО стану (темна тема, силует без аватарки), а
	 * клієнт читає своє зі сховища вже в конструкторах і під час гідрації хоче інший значок.
	 * lucide-`Icon` малює його як `{#each iconNode}` із `svelte:element this={tag}`, і під
	 * час гідрації `svelte:element` бере наявний вузол, НЕ звіряючи тег, та розкладає на
	 * нього атрибути нового значка, не прибираючи старих; бракує вузлів — дописує, зайві —
	 * прибирає. Тексти й атрибути гідрація виправляє, а форму — ні: виходить суміш двох
	 * значків. Без повного завантаження дефекту немає — гідрація одна, на старті.
	 *
	 * ## Чому ключ за прапорцем гідрації, а не «чотири значки й `hidden`»
	 *
	 * «Усі варіанти в розмітці, видимий один» працювало в кнопці теми, але це рішення для
	 * одного місця: вісімнадцять значків аватарки в кожному рядку кожного списку так не
	 * намалюєш, і наступне місце про нього не знало б. Тут значок після гідрації
	 * перестворюється з нуля (`{#key hydrated()}`), тобто в DOM лишається свіжий клієнтський
	 * рендер, і що саме лежало в пререндері — байдуже. Зіпсований вузол до першого кадру не
	 * доживає: `onMount` і перестворення йдуть мікрозадачами, раніше, ніж браузер малює.
	 * Зміна значка вже потім — звичайна заміна компонента, без гідрації й без суміші.
	 *
	 * Звіряє кожен значок кожної сторінки з його ж `iconNode` e2e `tests/icon-hydration.spec.ts`.
	 */
	interface Props extends IconProps {
		/** Будь-який значок lucide: усі вони оголошені однаково, тож тип одного — тип кожного. */
		icon: typeof Sun;
	}

	let { icon: Icon, ...rest }: Props = $props();
</script>


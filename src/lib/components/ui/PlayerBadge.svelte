<script lang="ts">
	import type { Snippet } from 'svelte';

	/**
	 * ПОЗНАЧКА БІЛЯ ІМЕНІ ГРАВЦЯ: «це ви», «немає звʼязку».
	 *
	 * ## Що було не так
	 *
	 * Обидві позначки були звичайним текстом у дужках: «Спритний Яструб (ви): 7
	 * Величезний Синій Кит: 7 (немає звʼязку)». Автор сказав про це прямо —
	 * «актуальний результат: звичайна текстова; очікуваний: стильна графічна», і
	 * показав взірець: `<span class="badge me">YOU</span>` із сусіднього
	 * `MindStep`.
	 *
	 * Причина, чому це не смак: у рядку з двох імен, двох рахунків і трьох дужок
	 * усе має однакову вагу. Позначка, яка виглядає як частина імені, і
	 * читається як частина імені — тобто «Величезний Синій Кит немає звʼязку»
	 * доводиться розбирати очима.
	 *
	 * ## Чому один компонент на дві позначки
	 *
	 * Взято будову, а не код: пілюля дрібним великим шрифтом. Але живе вона в
	 * ОДНОМУ місці, і це головне — «ви» стоїть у пʼятьох місцях (склад лобі, табло
	 * партії, рядок переможця, табло вікторини, підсумок), а «немає звʼязку» в
	 * табло. Дві копії того самого вигляду розійшлися б на першій же правці, і
	 * розійшлися б непомітно: кожна виглядала б правильною окремо.
	 *
	 * ## Чому не колір як єдиний носій
	 *
	 * Позначка лишається СЛОВОМ. Пілюля — це підсилення, а не заміна: колір і
	 * форма нічого не кажуть скрінрідеру й зникають для тих, хто не розрізняє
	 * відтінків (WCAG 1.4.1). Тому текст усередині обовʼязковий, а `tone` міняє
	 * лише тло й рамку.
	 *
	 * Колір тексту НЕ задається зовсім (`inherit`): тло тут — тонке підмішування в
	 * панель, тож звичайний текст на ньому лишається таким самим контрастним, як
	 * поруч. Свій колір довелося б міряти окремо в кожній із чотирьох тем, а
	 * `color-mix` гейт контрасту й так не бачить.
	 */
	interface Props {
		/**
		 * `me` — нейтральна, це просто орієнтир «де я».
		 * `away` — попередження: гравець тут, але звʼязку немає.
		 */
		tone: 'me' | 'away';
		children: Snippet;
	}

	let { tone, children }: Props = $props();
</script>

<span class="badge badge--{tone}">{@render children()}</span>

<style>
	/*
	 * Дрібно й великими літерами — так пілюля читається як ПОЗНАЧКА, а не як
	 * продовження імені. Кегль числом, а не токеном: усі токени кеглю тут завеликі
	 * (найдрібніший `--font-size-xs` дорівнює основному тексту мінус крапля), а
	 * позначка мусить бути помітно дрібнішою за імʼя поруч.
	 */
	.badge {
		display: inline-flex;
		align-items: center;
		flex-shrink: 0;
		padding: 1px 6px;
		border-radius: var(--radius-sm);
		font-size: 10px;
		font-weight: var(--font-weight-bold);
		line-height: 1.6;
		letter-spacing: 0.06em;
		text-transform: uppercase;
		white-space: nowrap;
		/*
		 * Усередині рядкового потоку `inline-flex` сідає на базову лінію, тобто
		 * пілюля висіла б нижче за імʼя поруч. У флексі це властивість не діє
		 * взагалі, тож рядок безпечний і там, де позначка стоїть елементом флексу.
		 */
		vertical-align: middle;
		/* Колір тексту — панелі. Причина в докблоці: контраст лишається зміряним. */
		color: inherit;
	}

	/* «Це ви» — тиха: вона орієнтир, а не новина. */
	.badge--me {
		background: color-mix(in srgb, var(--color-text), transparent 88%);
		border: 1px solid color-mix(in srgb, var(--color-text), transparent 78%);
	}

	/*
	 * «Немає звʼязку» — попередження, і саме тому рамка повна, а тло підмішане:
	 * помітно, але не кричить. Гравець нікуди не подівся, його рахунок у силі.
	 */
	.badge--away {
		background: color-mix(in srgb, var(--color-warning), transparent 82%);
		border: 1px solid var(--color-warning);
	}
</style>

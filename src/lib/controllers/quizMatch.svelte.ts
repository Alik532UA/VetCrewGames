/**
 * Скільки разів боротися за номер у журналі, перш ніж здатися.
 *
 * ШІСТНАДЦЯТЬ, а не чотири, і число тепер виведене. Кожна спроба розводить
 * щонайменше одного суперника за той самий номер, тож N одночасних записів
 * гарантовано розходяться за N спроб. Стеля складу — 12 гравців (правило
 * `order`), автопідтвердження стріляє в усіх в ту саму серверну мить, отже
 * чотирьох вистачало лише на кімнату до пʼяти (аудит 2026-09-23: пʼятий
 * одночасний запис губився мовчки). Решта — запас на ходи, що не є відповіддю.
 *
 * Верхня межа потрібна не через мережу, а через нескінченний цикл: якщо база
 * відмовляє з причини, не пов'язаної з номером, спроби мусять закінчитися — і
 * закінчуються вони помилкою, а не тишею (див. `answer`).
 */
const APPEND_TRIES = 16;

/**
 * Спільна вікторина: РАУНД як одиниця, рахунок як чиста функція від журналу.
 *
 * ## Чим це відрізняється від `PairsMatch`
 *
 * Той відтворює ДОШКУ: усі застосовують ті самі ходи й бачять те саме поле. Тут
 * дошки в кожного своя — усі відповідають одночасно, — але СПІЛЬНИМ став час:
 * раунд починається одним ходом господаря, і від цієї позначки кожен рахує свій
 * дедлайн.
 *
 * ## Чому старт раунду — хід, а не поле в `info`
 *
 * У `info` вміщається лише ТЕПЕРІШНІЙ раунд. Щойно він змінюється, час початку
 * попереднього зникає — і перерахувати за нього очки вже нічим. У журналі ж
 * лишається все: `at` кожного ходу ставить сервер (правило `moves/$seq` вимагає
 * позначку у вікні пʼяти секунд від `now`), тож і старт раунду, і кожна
 * відповідь мають ЧЕСНИЙ час назавжди.
 *
 * Звідси головна властивість: рахунок — чиста функція від журналу. Ніхто не
 * оголошує своїх очок; він оголошує лише «я відповів правильно», а швидкість
 * рахується з двох серверних позначок.
 *
 * ## Що лишається неперевірним
 *
 * Саме `correct`. Той, хто відкрив консоль, може написати одиницю, відповівши
 * хибно, і жоден учасник цього не виявить — дошки в нього немає. Це властивість
 * одночасної гри з приватними дошками: щоб перевіряти й це, дошка мусила б бути
 * спільною, тобто це була б інша гра.
 *
 * Половина, яку підробляли легше за все — множник за швидкість, — тепер закрита,
 * і це головна різниця з попередньою моделью, де в журнал їхало саме число очок.
 */
export class QuizMatch {
	/** Скільки ходів журналу вже врахували. */
	applied = $state(0);
	/**
	 * ЗАЙНЯТІ НОМЕРИ ЖУРНАЛУ, за зростанням. Наступний хід бере ПЕРШУ ДІРКУ.
	 *
	 * Спершу номер виводився з кількості ходів (`applied`), і дірка в журналі
	 * вказувала на зайнятий номер назавжди. Потім — з найбільшого номера плюс
	 * одиниця, і це відкрило іншу дірку: один хід із `seq: 1e17` (правило бази
	 * перевіряло лише, що це число) робив «наступний» номер недосяжним — `1e17 + 1`
	 * у числах із рухомою комою дорівнює `1e17`, і кожна спроба впиралася в той
	 * самий зайнятий номер. Кімната вікторини переставала приймати ходи (аудит
	 * 2026-09-23). Перша дірка від чужого далекого номера не залежить зовсім.
	 *
	 * Порядок ходів стану не міняє: `replayQuizLog` перепрогонює журнал цілком, а
	 * відповіді лежать за (раунд, гравець).
	 */
	#seqs: number[] = [];
	status = $state<'lobby' | 'playing' | 'over'>('lobby');
	members = $state<Member[]>([]);
	hostUid = $state('');
	/** Зерно кімнати. Із нього виводиться програма — однакова в усіх. */
	seed = $state(0);
	autoStart = $state(false);
	/** Кімната публічна (`RoomInfo.listed`). */
	listed = $state(false);
	/**
	 * КОД КІМНАТИ, У ЯКУ ГРА ПЕРЕЇХАЛА. `null` — нікуди.
	 *
	 * Прохання автора: після фіналу можна зіграти не лише в ту саму гру, а й в
	 * іншу — «господар створює кімнату іншої гри, а решті в старій кімнаті
	 * зʼявляється кнопка „перейти“ з її кодом».
	 *
	 * Кімната й далі знає одну гру: це не зміна гри тут, а вказівник на нову. Тому
	 * поле живе в `info`, а не в журналі ходів — воно не про партію, яка вже
	 * скінчилася.
	 */
	nextCode = $state<string | null>(null);
	countdownAt = $state<number | null>(null);
	/** Які ігри вибрані в кімнаті. Порожньо — ще не приїхав знімок. */
	games = $state<string[]>([]);
	/**
	 * ШВИДКІСТЬ КІМНАТИ: час на раунд (зокрема «не обмежений») і час на перегляд
	 * відповіді.
	 *
	 * Шкали дві незалежні, бо це різні потреби: часу на раунд бракує тому, хто читає
	 * повільно, а часу на розбір — тому, хто хоче зрозуміти, чому відповідь така.
	 * Один рівень на партію змушував би платити другим за перший.
	 *
	 * Одним обʼєктом, а не полями поруч: `setConfig` пише налаштування цілком, і
	 * кожне окреме поле — ще одне, яке кожен виклик мусить не забути (див.
	 * `RoomPace`). `raw`, бо обʼєкт не правлять — його замінює кожен знімок.
	 *
	 * Читається з `info.config` як числа: конверт кімнати нічого, крім чисел, у
	 * налаштуваннях не приймає, і саме тому нова редакція ПРАВИЛ бази для цього не
	 * потрібна — а редакція правил ГРИ потрібна, див. `RULES_VERSION` на сторінці.
	 */
	pace = $state.raw<RoomPace>(DEFAULT_ROOM_PACE);

	/**
	 * ХТО ЗАРАЗ ОНЛАЙН — приходить іззовні, з `presence`.
	 *
	 * Не з журналу й не зі складу кімнати: `members` не прибираються ніколи (їх
	 * пише кожен про себе й лише про себе), а `presence` гасне сама —
	 * `onDisconnect` знімає запис, коли вкладка зникла.
	 *
	 * Порожній список означає «присутність ще НЕ ПРИЇХАЛА», а не «нікого немає»:
	 * підписка встає за такт після входу, і за цей такт раунд не мусить вважатися
	 * закінченим. Тому нижче порожнеча трактується як «чекаємо всіх».
	 */
	present = $state<string[]>([]);

	/** Серверний час початку кожного раунду. Ключ — номер раунду. */
	startedAt = $state<Record<number, number>>({});
	/** Голоси «граємо далі» за раундами. Порожньо — ніхто не голосував. */
	#goOnVotes = $state<Record<number, string[]>>({});
	/** Відповіді: раунд → гравець → коли й наскільки правильно. */
	answers = $state<Record<number, Record<string, QuizAnswer>>>({});

	readonly #me: string;
	readonly #transport: RoomTransport;
	/** Множник часу: у `dev` раунд довший. Передається, а не читається тут. */
	readonly #factor: number;

	constructor(me: string, transport: RoomTransport, factor = 1) {
		this.#me = me;
		this.#transport = transport;
		this.#factor = factor;
	}

	/** Кімнати більше немає: господар її закрив або прибрав збирач. */
	gone = $state(false);

	listen(): () => void {
		return this.#transport.watch(
			(snapshot) => this.#apply(snapshot),
			() => (this.gone = true)
		);
	}

	get players(): Member[] {
		return playersOf(this.members);
	}

	/** Програма партії — список раундів. Порожня, доки не приїхало зерно. */
	get programme(): QuizStep[] {
		if (this.seed === 0) return [];
		return quizProgramme(this.seed, this.games);
	}

	/**
	 * Номер поточного раунду — найбільший, який оголосив господар.
	 *
	 * `-1` означає «партія почалася, але жодного раунду ще не оголошено». Це
	 * законний стан, а не помилка: господар пише перший раунд окремим ходом, і між
	 * `status: playing` та цим ходом проходить мить.
	 */
	get round(): number {
		const numbers = Object.keys(this.startedAt).map(Number);
		return numbers.length === 0 ? -1 : Math.max(...numbers);
	}

	/** Крок програми для поточного раунду. `null` — раунду ще немає. */
	get step(): QuizStep | null {
		return this.programme[this.round] ?? null;
	}

	/** Скільки триває поточний раунд. Нуль — раунду немає; `NO_LIMIT` — межі немає. */
	get limitMs(): number {
		const step = this.step;
		return step === null ? 0 : roundLimitFor(step.game, this.pace, this.#factor);
	}

	/** Хто вже відповів у поточному раунді. Саме ФАКТ, без правильності. */
	get answered(): string[] {
		return Object.keys(this.answers[this.round] ?? {});
	}

	/** Чи відповів я в поточному раунді. */
	get iAnswered(): boolean {
		return this.answered.includes(this.#me);
	}

	/**
	 * Гравці, чиєї відповіді партія справді чекає.
	 *
	 * Доти чекали ВСІХ зі складу — і партія через це замерзала назавжди: той, хто
	 * закрив вкладку, лишається в `members` (їх ніхто не прибирає), відповіді від
	 * нього не буде ніколи, тож «усі відповіли» не ставало правдою й кожен
	 * наступний раунд крутив таймер до кінця. Автор сказав це прямо: «при виході
	 * одного з гравців немає вікна очікування».
	 *
	 * Дві порожнечі трактуються як «чекаємо всіх», і обидві — навмисно:
	 * присутність, яка ще не приїхала, і кімната, у якій за мить не стало нікого.
	 * Інакше раунд закінчувався б сам собою на порожньому списку.
	 */
	get awaited(): Member[] {
		const players = this.players;
		if (this.present.length === 0) return players;
		const here = players.filter((player) => this.present.includes(player.uid));
		return here.length > 0 ? here : players;
	}

	/**
	 * Гравці, яких чекають, а вони не онлайн. Для вікна очікування.
	 *
	 * Порожньо, поки присутність не приїхала: показати «немає зв'язку» в перший
	 * такт означало б написати це про кожного, включно з собою.
	 */
	get away(): Member[] {
		if (this.present.length === 0) return [];
		return this.players.filter((player) => !this.present.includes(player.uid));
	}

	/**
	 * ТІ САМІ ЗНИКЛІ, АЛЕ БЕЗ МЕНЕ — для екрана.
	 *
	 * Без звʼязку SDK сам виконує МІЙ `onDisconnect` у місцевій копії, тобто
	 * прибирає мене з присутності в мене ж. Доти через це людина без мережі бачила
	 * на весь екран «Чекаємо: <її власне імʼя>» поверх смуги «немає звʼязку», а
	 * господар без мережі за пʼятнадцять секунд отримував кнопку «Прибрати» САМОГО
	 * СЕБЕ — і, натиснувши, лишався присутнім, але не учасником: раунди більше не
	 * оголошувались, а перехопити ведення не міг ніхто, бо господар «на звʼязку»
	 * (аудит 2026-09-24).
	 *
	 * Сама пауза при цьому РАХУЄ і мене (`away`): партія стоїть і в мене, поки мене
	 * немає, — тож і дедлайн, і відлік у мене ті самі, що в тих, хто чекає.
	 */
	get awayOthers(): Member[] {
		return this.away.filter((player) => player.uid !== this.#me);
	}

	/** Чи відповіли всі, кого чекають. */
	get everyoneAnswered(): boolean {
		const awaited = this.awaited;
		return awaited.length > 0 && awaited.every((player) => this.answered.includes(player.uid));
	}

	/**
	 * ВЕСЬ РАХУНОК — В ОДНОМУ МІСЦІ, і це місце не тут.
	 *
	 * Арифметика переїхала в `utils/quizScore.ts`. Контролер і доти оголошував
	 * «рахунок — чиста функція від журналу», але тримав саму функцію всередині
	 * класу: перевіряти її можна було лише через транспорт і підписку. Тепер це
	 * видно з підпису — на вхід журнал, на вихід числа.
	 *
	 * Тут лишається складання того самого журналу в один обʼєкт. Межу раунду
	 * віддаємо ФУНКЦІЄЮ, бо її знає лише контролер: тривалість виводиться з гри
	 * раунду, гра — з програми, програма — із зерна кімнати й набору ігор.
	 */
	get #log(): QuizLogView {
		return {
			answers: this.answers,
			startedAt: this.startedAt,
			players: this.players.map((player) => player.uid),
			limitOf: (round) => {
				const game = this.programme[round]?.game;
				return game === undefined ? undefined : roundLimitFor(game, this.pace, this.#factor);
			}
		};
	}

	get scores(): Record<string, number> {
		return totalScores(this.#log);
	}

	/** Скільки очок дав САМЕ ЦЕЙ раунд — кожному. Табло між раундами показує приріст. */
	get roundGains(): Record<string, number> {
		return roundGains(this.#log, this.round);
	}

	/** Мої результати по зіграних раундах — для смужок прогресу в таблі. */
	get myRounds(): RoundStatus[] {
		return roundOutcomes(this.answers, this.round, this.#me);
	}

	/**
	 * ЧАС, ВІДДАНИЙ ЗА ЧЕКАННЯ: пауза плюс надбавка після неї.
	 *
	 * Вікно очікування перекриває питання, тож поки воно висить, раунд не мусить
	 * витрачатися. Пауза тут — не спинений таймер, а зсув дедлайну: у цьому
	 * контролері немає жодного таймера навмисно (час приходить аргументом, інакше
	 * перевірка мусила б чекати справжні секунди).
	 *
	 * ЧОМУ ЦЕ РАХУЄТЬСЯ МІСЦЕВО, а не журналом. Умова паузи вже місцева: хто
	 * присутній — це присутність, і на ній тримається і вікно очікування, і кінець
	 * раунду по `awaited`. Писати паузу в журнал означало б новий тип ходу з
	 * власним правилом бази, а заразом і те, що пауза не станеться взагалі, якщо в
	 * господаря обірвався зв'язок — тобто рівно тоді, коли вона потрібна.
	 *
	 * МЕЖА ЧЕСНОСТІ: розбіжність між гравцями обмежена дрижанням присутності
	 * (RTDB віддає її за секунду-дві). Хто саме оголошує наступний раунд, це не
	 * зачіпає — оголошує господар, і його рішення лишається єдиним.
	 */
	/**
	 * Пауза, ЗАПИСАНА В ЖУРНАЛ, за раундами. Одне число на всіх.
	 *
	 * Доти пауза жила лише в памʼяті кожного клієнта, і саме це й був дефект, який
	 * автор побачив: той, кого не було, паузи не бачив, тож надбавки в нього не
	 * з'являлося — і дедлайн у нього ставав інший. «Розбіжність на дрижання
	 * присутності», яку я записав як межу, насправді означала різні дедлайни.
	 *
	 * Пишеться, коли пауза ЗАКІНЧИЛАСЯ: тоді її тривалість уже відома числом, а
	 * число в журналі однакове в усіх — включно з тим, хто повернувся. Пише КОЖЕН
	 * гравець, у кого чекання скінчилося, а перепрогін бере найбільше
	 * (`utils/quizReplay.ts`, `countHolds`). Доти писав лише господар — і пауза
	 * губилася саме тоді, коли зникав ВІН (аудит 2026-09-24).
	 */
	#heldByRound = $state<Record<number, number>>({});
	/** Поточне чекання — облік у `utils/quizHold.ts` (основа, проміжки, автор паузи). */
	#hold = new QuizHold();
	/**
	 * Пауза, яку я вже відпустив, але хід про неї ще не приїхав — ЗА РАУНДАМИ.
	 *
	 * Без цього рядка смуга часу СТРИБАЛА Б НАЗАД на мить між відпусканням і
	 * приходом ходу: місцева пауза вже нуль, а журнальної ще немає.
	 *
	 * ## Чому саме перелік за раундами, а не одне число
	 *
	 * Одним числом воно тут і стояло, і це був дефект, який автор побачив:
	 * «таймер візуально не працює і прогружає оновлений стан тільки після вибору
	 * відповіді».
	 *
	 * `heldMs` порівнювала це число з журнальним `#heldByRound[round]` — тобто
	 * ОДНЕ на партію проти ОДНОГО НА РАУНД. Журнал тоді писав лише господар і лише свою
	 * виміряну паузу; у гостя вона майже завжди довша, бо присутність доїжджає до
	 * двох клієнтів у різні миті. Отже `log.held[round] >= pending` у гостя не
	 * ставало правдою ніколи, число не скидалося — і додавалося до дедлайну
	 * КОЖНОГО наступного раунду.
	 *
	 * Наслідків два, і оба видно на екрані. `leftMs` перевищувала `limitMs`, тож
	 * смуга отримувала ширину понад 100% і СТОЯЛА повною. А `nextDue` був
	 * відсунутий на ту саму зайву паузу, тож господар не оголошував наступний
	 * раунд — і партія рухалася лише тоді, коли відповіли всі.
	 *
	 * Тепер число належить своєму раундові й у чужий не потрапляє. Старі записи
	 * не прибираються навмисно: їх щонайбільше стільке, скільки раундів, а
	 * прибирання додало б місце, де можна помилитися ключем.
	 */
	#pending = $state<Record<number, number>>({});
	/**
	 * Хто веде партію — з журналу (`replayQuizLog`). Спершу господар; хід `lead`
	 * передає роль тому, хто підхопив партію, коли господаря не стало.
	 */
	leader = $state('');
	/** Скільки пільги вже витратив кожен — із журналу. */
	#graceSpent = $state<Record<string, number>>({});
	/** Хто поставив паузу в кожному раунді. Знята пауза — знову `undefined`. */
	#pausedBy = $state<Record<number, string>>({});
	/** Коли поставили — серверний час ходу. */
	#pausedAt = $state<Record<number, number>>({});
	/** Коли гравець останній раз ЗНІМАВ паузу — для хвилинної витримки. */
	#pauseUsedAt = $state<Record<string, number>>({});
	/** Витрачена пільга за раундами — із журналу; на ній нарощує свій запис чекання. */
	#spentByRound = $state<Record<number, Record<string, number>>>({});

	/**
	 * Увімкнути або зняти паузу очікування.
	 *
	 * Кличе екран: умова («когось немає І він ще не відповів І пільговий час не
	 * вичерпано») складається з присутності й пільги, а їх тримає сторінка.
	 * Зняття паузи додає надбавку — один раз на кожне чекання, а не на секунду.
	 */
	setHold(active: boolean, now: number): void {
		if (active) {
			const round = this.round;
			const away = this.away.map((member) => member.uid);
			const spentBase = this.#spentByRound[round] ?? {};
			this.#hold.hold(now, round, this.#settledMs(round), spentBase, away, this.pausedBy);
			return;
		}
		/*
		 * СУКУПНО ЗА РАУНД — поверх ОСНОВИ, узятої на початку чекання
		 * (`utils/quizHold.ts`): записи різних гравців про те саме чекання дають
		 * близькі числа, і перепрогін бере найбільше, а не суму.
		 */
		const released = this.#hold.release(now);
		if (!released) return;
		// Під номером ТОГО раунду, у якому чекання й було: у наступному воно нічого
		// не означає, і саме через це число колись переїжджало далі.
		this.#pending = { ...this.#pending, [released.round]: released.total };

		// Пише КОЖЕН ГРАВЕЦЬ (див. `#heldByRound`); запис глядача перепрогін не рахує.
		if (this.players.some((player) => player.uid === this.#me)) {
			void this.#writeHeld(released);
		}
	}

	/** Скільки раунд уже простояв, поки чекання немає: журнал або своє, більше. */
	#settledMs(round: number): number {
		return Math.max(this.#heldByRound[round] ?? 0, this.#pending[round] ?? 0);
	}

	/** Скільки часу вже віддано за чекання, разом із поточною паузою. */
	heldMs(now: number): number {
		const settled = this.#settledMs(this.round);
		/*
		 * Поки чекаю — від СВОЄЇ основи. Чужий запис про те саме чекання, що приїхав
		 * раніше за моє відпускання, не додається до мого, а лише не дає смузі
		 * показати менше, ніж уже в журналі.
		 */
		const holding = this.#hold.heldNow(now, this.round);
		return holding === null ? settled : Math.max(holding, settled);
	}

	/**
	 * ХТО ПОСТАВИВ ПАУЗУ — і `null`, якщо паузи немає.
	 *
	 * Легального способу спинити партію доти не існувало, і це не «забули кнопку»:
	 * пауза в грі БУЛА, але дістатися до неї можна було лише закривши вкладку —
	 * тобто зникнувши. Автор назвав це прямо: «гравець може вийти, щоб зупинити
	 * гру».
	 *
	 * Тому пауза — той самий стан, що зникнення, лише з іншою причиною: ті самі
	 * п'ятнадцять секунд, той самий накопичувальний запас, те саме вікно поверх
	 * гри. Різниця одна: автор паузи може зняти її САМ і одразу, а решта — коли
	 * відлік вичерпано.
	 */
	get pausedBy(): string | null {
		return this.#pausedBy[this.round] ?? null;
	}

	/**
	 * Коли паузу поставили — СЕРВЕРНИМ часом ходу.
	 *
	 * Не «коли я це побачив»: інакше відлік у кожного свій, а він показує спільну
	 * межу. Той самий принцип, що з початком раунду.
	 */
	get pausedAt(): number {
		return this.#pausedAt[this.round] ?? 0;
	}

	/**
	 * Коли цьому гравцеві знову можна ставити паузу (серверний час).
	 *
	 * ХВИЛИНА ПІСЛЯ ЗНЯТТЯ — вимога автора, і вона не про запас часу, а про
	 * настирливість: без неї можна тиснути паузу знову й знову, і партія
	 * перетворюється на смикання, навіть коли пільги вже нуль.
	 */
	pauseReadyAt(uid: string): number {
		return this.#pauseUsedAt[uid] === undefined ? 0 : this.#pauseUsedAt[uid] + PAUSE_COOLDOWN_MS;
	}

	/**
	 * ЗМІНИТИ НАБІР ІГОР — господар, і тільки в лобі.
	 *
	 * Чому не хід у журналі, як пауза: набір не подія партії, а її УМОВА. Програма
	 * раундів — чиста функція від (зерна, набору), тож набір мусить бути відомий до
	 * першого раунду й однаковий для всіх; ходом він приїжджав би ПІСЛЯ того, як
	 * хтось уже дивиться на перше питання.
	 *
	 * `status === 'lobby'` — не обережність, а те саме: зміна набору посеред партії
	 * перемалювала б уже зіграні раунди, бо програма перерахувалася б від нового
	 * набору. Кнопки в партії немає (`QuizGamePicker` там не показується), але
	 * перевірка стоїть ТУТ, бо саме тут вона правда для всіх викликів.
	 *
	 * Тихо не робить нічого, коли не дозволено: це кнопка, якої в такому стані не
	 * мусить бути видно, а не дія, що може не вдатися.
	 */
	async setGames(games: readonly string[]): Promise<void> {
		if (this.hostUid !== this.#me || this.status !== 'lobby') return;
		await this.#transport.setConfig(quizConfig(games, this.pace));
	}

	/**
	 * Змінити швидкість кімнати. Умови ті самі, що в набору ігор, і не випадково.
	 *
	 * ЛИШЕ ГОСПОДАР І ЛИШЕ В ЛОБІ. Друга половина тут важливіша за першу: очки
	 * залежать від того, скільки тривав раунд, і рахунок перепрогонюється з журналу
	 * ЦІЛКОМ на кожному знімку. Зміна швидкості посеред партії перерахувала б уже
	 * зіграні раунди за новою межею — тобто минуле змінилося б заднім числом.
	 *
	 * Набір ігор передається разом, бо `setConfig` пише обʼєкт повністю: інакше
	 * зміна швидкості стерла б вибір ігор. Швидкість приходить ЦІЛКОМ, обома
	 * шкалами, — з тієї самої причини.
	 */
	async setPace(pace: RoomPace): Promise<void> {
		if (this.hostUid !== this.#me || this.status !== 'lobby') return;
		await this.#transport.setConfig(quizConfig(this.games, pace));
	}

	/** Поставити паузу. Дозволено будь-кому, хто в партії. */
	async pause(): Promise<void> {
		if (this.round < 0 || this.pausedBy !== null) return;
		await this.#append({
			by: this.#me,
			type: 'pause',
			payload: { round: this.round }
		});
	}

	/**
	 * Зняти свою паузу. Чужу зняти цим не можна — для цього є голосування.
	 *
	 * Перевірка тут, а не в правилі бази: правило не знає, хто ставив паузу, і
	 * дізнатися це може лише перепрогін. Тому «зняв не той» — це хід, який
	 * ПЕРЕПРОГІН не зараховує, а не запис, який відкидає база.
	 */
	async resume(): Promise<void> {
		if (this.pausedBy !== this.#me) return;
		await this.#append({
			by: this.#me,
			type: 'resume',
			payload: { round: this.round }
		});
	}

	/** Скільки пільгового часу цей гравець уже витратив за партію. */
	graceSpent(uid: string): number {
		return this.#graceSpent[uid] ?? 0;
	}

	/**
	 * Записати паузу й витрачену пільгу — СУКУПНО за раунд.
	 *
	 * Пільга рахується тим самим числом: гравець, якого не було три секунди,
	 * витратив три секунди — і наступного разу відлік почнеться з решти. Саме це й
	 * ламало гру доти: відлік починався з повних п'ятнадцяти щоразу, тож зникати на
	 * чотирнадцять секунд можна було безкінечно. Витрачене теж — поверх журнального
	 * числа за цей раунд, узятого на початку чекання, з тієї самої причини, що й пауза.
	 *
	 * `uid` у payload вміщається: рядок там до 32 знаків, а uid Firebase — 28.
	 */
	async #writeHeld({ round, total, spent }: ReleasedHold): Promise<void> {
		// Як складаються ходи — `utils/awayWait.ts` (`heldPayloads`).
		for (const payload of heldPayloads(round, total, spent)) {
			await this.#append({ by: this.#me, type: 'held', payload });
		}
	}

	/**
	 * Коли поточний раунд мусить закінчитися, за серверним часом.
	 *
	 * Дві причини закінчитися, і ближча перемагає: вийшов час або відповіли всі
	 * (тоді ще секунда, щоб останній побачив власну відповідь на дошці).
	 * `null` — раунду немає.
	 *
	 * `now` потрібен саме для паузи: поки вона триває, дедлайн їде разом із часом,
	 * тобто стоїть на місці на екрані.
	 */
	/*
	 * УСЕ ПРО ЧАС — В ОДНОМУ МІСЦІ, і це місце не тут (`utils/quizClock.ts`).
	 *
	 * Контролер уже оголошував: таймера в ньому немає навмисно, час приходить
	 * аргументом, інакше перевірка мусила б чекати справжні секунди. Виніс — логічне
	 * завершення тієї самої думки: якщо час лише аргумент, то й усі відповіді про
	 * час — чисті функції.
	 *
	 * КОНТРОЛЕР ВІДДАЄ СЕБЕ (`this`), а не складений обʼєкт: усі поля знімка в нього
	 * вже публічні, тож адаптер лише переписував би їхні імена — п'ятнадцять рядків,
	 * які нічого не вирішують і при кожній правці розходяться з інтерфейсом.
	 *
	 * Три числа нижче РІЗНІ, і сплутати їх легко: `limitLeftMs` — до межі часу (на
	 * нього дивиться автовідповідь), `leftMs` — що показує смуга (застигає, щойно
	 * відповіли всі), `deadlineAt` — коли раунд справді кінчається.
	 */
	/**
	 * Скільки чекати після останньої відповіді, перш ніж показати табло.
	 *
	 * Похідне, а не константа: цим і налаштовується «час на перегляд відповіді».
	 * Множник той самий, що в табла, — інакше налаштування міняло б половину.
	 */
	get settleMs(): number {
		return SETTLE_MS * REVEAL_PACE[this.pace.reveal];
	}

	/** Скільки видно табло між раундами. Той самий множник. */
	get revealMs(): number {
		return REVEAL_MS * REVEAL_PACE[this.pace.reveal];
	}

	/** Коли поточний раунд мусить закінчитися, за серверним часом. */
	deadlineAt(now = 0): number | null {
		return deadlineAt(this, now);
	}

	/** Що показувати ЗАРАЗ. Час передається, а не читається з годинника. */
	phase(now: number): QuizPhase {
		// «Скінчилася» — не висновок про час: годинник цього не бачить, тому питаємо тут.
		return this.over ? 'over' : phaseAt(this, now);
	}

	/** Що показує смуга таймера. Застигає, щойно відповіли всі. */
	leftMs(now: number): number {
		return barLeftMs(this, now);
	}

	/** Скільки лишилося до самої МЕЖІ ЧАСУ. На це дивиться автовідповідь. */
	limitLeftMs(now: number): number {
		return limitLeftMs(this, now);
	}

	/** Чи час господареві оголошувати наступний раунд. */
	nextDue(now: number): boolean {
		return nextDue(this, now);
	}
	/** Скільки лишилося таблу між раундами — для смуги на ньому. */
	revealLeftMs(now: number): number {
		return revealLeftMs(this, now);
	}

	/**
	 * ПАРТІЯ СКІНЧИЛАСЯ — з двох причин, і обидві тут.
	 *
	 * Раундів більше немає (програма дограна) АБО кімната в стані `over`.
	 *
	 * Доти друга умова жила окремо, у `phase()`, — тобто «скінчилася» означало
	 * різне залежно від того, кого спитати: екран підсумку питав `over`, а фаза
	 * перевіряла ще й статус. ДЕФЕКТУ З ЦЬОГО ПОКИ НЕ ВИХОДИЛО: у вікторині
	 * `setStatus('over')` не кличе ніщо — перевірено пошуком. Тобто це не
	 * виправлення, а прибирання другого джерела правди, поки воно ще нікого не
	 * розвело: варто комусь колись закрити партію статусом, і два читання
	 * розійшлися б — а розійшлися б тихо, бо кожне виглядає правильним окремо.
	 */
	get over(): boolean {
		if (this.status === 'over') return true;
		return this.programme.length > 0 && this.round >= this.programme.length;
	}

	/**
	 * Оголосити свою відповідь.
	 *
	 * Номер раунду їде РАЗОМ із відповіддю, а не мається на увазі: два ходи, що
	 * приїхали не в тому порядку, інакше зарахувалися б як відповіді на різні
	 * раунди. Повторна відповідь на той самий раунд відкидається при застосуванні.
	 */
	/**
	 * ДОПИСАТИ ХІД, ПОБОРОВШИСЬ ЗА НОМЕР.
	 *
	 * Тут виправляється дефект, який автор побачив так: «двоє вибрали і не
	 * натиснули кнопку „підтвердити“ — бали нарахувалися тільки одному».
	 *
	 * Причина не в автовідповіді, а в тому, що вона зробила рідке звичайним. Хід —
	 * окрема дитина `moves/{seq}`, і створити її можна лише раз: другий запис того
	 * самого номера відкидає БАЗА. Доти номер брався один раз і на відмову ніхто не
	 * зважав — у «Знайди пару» це правильно (відмова означає «суперник устиг
	 * першим», і журнал справді головніший за наш намір), а у вікторині гравці
	 * відповідають ОДНОЧАСНО, і відмова означає просто втрачену відповідь.
	 *
	 * Двоє людей рідко тицяють у той самий проміжок; двоє таймерів, що рахують від
	 * тієї самої серверної позначки, — завжди. Тобто збіг перестав бути рідкістю, і
	 * саме тому потрібна боротьба, а не сподівання.
	 *
	 * Номер перечитується на КОЖНІЙ спробі (`+ attempt` лише щоб спроби не стояли
	 * на місці, коли знімок ще не приїхав), і дірка, якщо лишиться, нічого не
	 * ламає — див. докблок `#topSeq`.
	 */
	async #append(move: Omit<Move, 'seq'>): Promise<boolean> {
		for (let attempt = 0; attempt < APPEND_TRIES; attempt += 1) {
			// `attempt` вільних номерів пропускається: якщо знімок із номером
			// суперника ще не приїхав, наступна спроба не мусить битися в той самий.
			if (await this.#transport.append({ ...move, seq: freeSeq(this.#seqs, attempt) })) return true;
		}
		return false;
	}

	/**
	 * Оголосити свою відповідь.
	 *
	 * КИДАЄ, якщо номер так і не вдалося взяти: відповідь, що не лягла в журнал,
	 * не рахується ніде, і людина мусить про це почути (сторінка показує
	 * «не вдалося»), а не дивитися на табло без своїх очок.
	 */
	async answer(correct: number): Promise<void> {
		if (this.iAnswered || this.round < 0) return;
		const saved = await this.#append({
			by: this.#me,
			type: 'answer',
			payload: { round: this.round, correct }
		});
		if (!saved) throw new Error('answer-not-saved');
	}

	/**
	 * ГОЛОС «ГРАЄМО ДАЛІ БЕЗ НЬОГО» — звичайний хід у журналі.
	 *
	 * Правил бази правити не довелося: конверт ходу вже дозволяє свій тип (рядок до
	 * 16 знаків) і числа в payload, підпис перевіряє сама база (`by == auth.uid`),
	 * час ставить сервер, а повторний запис того самого номера відкидається. Тобто
	 * голосування вкладається в наявну модель ЦІЛКОМ.
	 *
	 * Номер раунду їде разом із голосом: чекання буває в кожному раунді, і голос за
	 * попередній не має права зняти паузу в наступному.
	 */
	async voteGoOn(): Promise<void> {
		if (this.round < 0 || this.goOn.includes(this.#me)) return;
		await this.#append({
			by: this.#me,
			type: 'goon',
			payload: { round: this.round }
		});
	}

	/** Хто вже проголосував «граємо далі» в ЦЬОМУ раунді. */
	get goOn(): string[] {
		return this.#goOnVotes[this.round] ?? [];
	}

	/**
	 * ПІДХОПИТИ ПАРТІЮ, коли господаря немає (`controllers/takeLead.ts`). Умову
	 * «його немає» перевіряє правило бази, тож тут лише спроба.
	 */
	async takeLead(): Promise<boolean> {
		if (this.leader === this.#me) return true;
		return takeLead(this.#transport, this.#me, this.hostUid, this.#seqs);
	}

	/** Оголосити початок раунду. Пише лише господар. */
	async startRound(round: number): Promise<void> {
		if (this.startedAt[round] !== undefined) return;
		await this.#append({
			by: this.#me,
			type: 'round',
			payload: { round }
		});
	}

	#apply(snapshot: RoomSnapshot): void {
		this.members = snapshot.members;
		this.status = snapshot.info.status;
		this.hostUid = snapshot.info.hostUid;
		if (snapshot.info.seed !== this.seed) {
			// Нова партія (реванш): власна незакомічена пауза минулої їй не належить —
			// інакше той самий номер раунду отримував би чужу надбавку часу.
			this.#pending = {};
			this.#hold.reset();
		}
		this.seed = snapshot.info.seed;
		this.autoStart = snapshot.info.autoStart === true;
		this.listed = snapshot.info.listed === true;
		this.nextCode = snapshot.info.nextCode ?? null;
		this.countdownAt = snapshot.info.countdownAt ?? null;
		this.games = configToGames(snapshot.info.config);
		this.pace = paceOf(snapshot.info.config);

		const log = replayQuizLog(snapshot, { limitOf: this.#log.limitOf });

		this.startedAt = log.startedAt;
		this.answers = log.answers;
		this.#goOnVotes = log.goOn;
		this.#heldByRound = log.held;
		this.#graceSpent = log.graceSpent;
		this.#spentByRound = log.spentByRound;
		this.#pausedBy = log.pausedBy;
		this.#pausedAt = log.pausedAt;
		this.#pauseUsedAt = log.pauseUsedAt;
		this.leader = log.leader;
		/*
		 * Хід приїхав — оптимістичне число більше не потрібне.
		 *
		 * Порівнюється ЗА ТИМ САМИМ раундом, що й записується: одне число проти
		 * переліку за раундами й було тим дефектом, через який пауза переїжджала в
		 * наступні раунди.
		 */
		const mine = this.#pending[this.round] ?? 0;
		if (mine > 0 && (log.held[this.round] ?? 0) >= mine) {
			this.#pending = { ...this.#pending, [this.round]: 0 };
		}
		this.applied = snapshot.moves.length;
		// Зайняті номери, а не кількість чи найбільший: причина — у докблоці `#seqs`.
		this.#seqs = snapshot.moves.map((move) => move.seq).sort((a, b) => a - b);
	}
}

import type { LobbyRoom } from '$lib/net/lobby';
import type { OwnRoom } from '$lib/net/ownRooms';
import { friendUids } from '$lib/net/follows';
import { logService } from '$lib/services/logService.svelte';

/**
 * ПЕРЕЛІК КІМНАТ І СВОЇ ПАРТІЇ — одне джерело для всіх спільних ігор.
 *
 * ## Чому контролер, а не по копії на сторінку
 *
 * Це перша частина боргу, названого в `quiz/online/+page.svelte`: дві сторінки
 * спільної гри («Знайди пару» і «Вікторина») тримали однакову обв'язку переліку —
 * чотири поля стану, дві підписки й похідну «зайняті імена». Сорок рядків, які
 * розійшлися б на першій же правці, і розійшлися б непомітно: кожна копія
 * виглядала б правильною окремо.
 *
 * Тут лишилося рівно те, що НЕ залежить від гри. Усе, що залежить (вхід у
 * кімнату, присутність, матч), лишається на сторінці — його загальна форма
 * вимагає фабрики матчу, і це наступний крок того самого боргу.
 *
 * ## Чому підписка ПОВЕРТАЄ прибирання, а не прибирає сама
 *
 * Життя підписки визначає сторінка: вона знає, коли форма входу видна, а коли її
 * заступив матч. Контролер, який вирішував би це сам, мусив би знати про матч —
 * тобто про гру.
 */
export class LobbyFeed {
	/** Відкриті кімнати. Порожньо і поки не підписалися, і коли їх немає. */
	rooms = $state<LobbyRoom[]>([]);

	/** Чи лишилося щось за межею запиту: обрізку треба показати, а не сховати. */
	hasMore = $state(false);

	/**
	 * Перелік не читається — майже завжди «правила ще не викладені».
	 *
	 * Окремо від «кімнат немає»: порожній список і недоступний список — різні
	 * повідомлення, і друге не мусить читатися як перше. Перша редакція цього не
	 * розрізняла, і «правила не викладені» виглядало як «ніхто не створив
	 * кімнату».
	 */
	unavailable = $state(false);

	/**
	 * Мої партії, які вже йдуть. Джерело — приватний індекс `myRooms/{uid}`.
	 *
	 * Окремо від `rooms` навмисно: у переліку лежить те, куди можна ЗАЙТИ, а тут —
	 * те, куди можна ВЕРНУТИСЯ.
	 */
	own = $state<OwnRoom[]>([]);

	/**
	 * `uid` моїх друзів — тих, із кимось підписка ВЗАЄМНА.
	 *
	 * Потрібні переліку, щоб закріпити їхні кімнати зверху. Саме `uid`, а не
	 * профілі: у рядку кімнати й так стоїть імʼя господаря, а читати профілі
	 * заради сортування означало б стільком запитів, скільком підписок.
	 *
	 * Порожньо — або друзів немає, або акаунта немає зовсім. Обидва випадки
	 * дають той самий результат: список без закріплених рядків, тобто рівно
	 * те, що було до появи підписок.
	 */
	friends = $state<string[]>([]);

	/**
	 * Імена, уже видані тим, хто зараз онлайн.
	 *
	 * Це підписи господарів ВІДКРИТИХ кімнат, а не всіх людей у грі, — і межа
	 * названа навмисно: решти клієнт не бачить і не має права бачити (`presence`
	 * живе під кодом кімнати, а перелічити `rooms` правила забороняють).
	 */
	get takenNames(): string[] {
		return this.rooms.map((room) => room.hostName);
	}

	/**
	 * Підписка на перелік. Кличеться з `$effect`; повертає прибирання.
	 *
	 * `onRooms` дає сторінці нагоду зробити те, що знає лише вона, — наприклад
	 * перекинути підставлене імʼя, якщо воно виявилося зайнятим.
	 */
	watch(onRooms: (names: string[]) => void): () => void {
		let stop: (() => void) | null = null;
		let dead = false;

		void (async () => {
			try {
				const list = await import('$lib/net/lobby');
				const off = await list.watchLobby({
					onRooms: (next, more) => {
						this.rooms = next;
						this.hasMore = more;
						this.unavailable = false;
						onRooms(next.map((room) => room.hostName));
					},
					onUnavailable: () => {
						this.rooms = [];
						this.hasMore = false;
						this.unavailable = true;
					}
				});
				// Ефект міг зникнути, поки йшов імпорт і вхід: тоді підписку треба
				// знімати одразу, інакше вона живе довше за сторінку.
				if (dead) off();
				else stop = off;
			} catch (error) {
				this.unavailable = true;
				logService.warn('network', 'lobby subscription failed', { reason: String(error) });
			}
		})();

		return () => {
			dead = true;
			stop?.();
		};
	}

	/**
	 * Свої розпочаті партії — ОДИН запит, а не підписка.
	 *
	 * Вони не з'являються самі: з'являються тоді, коли я сам зайшов у кімнату, — а
	 * після цього сторінка вже показує партію, не форму. Підписка платила б
	 * трафіком за зміни, яких у цей момент не буває.
	 */
	load(): () => void {
		let dead = false;

		void (async () => {
			const own = await import('$lib/net/ownRooms');
			/*
			 * Одним `Promise.all`, а не двома чеканнями поспіль: обидві відповіді
			 * потрібні тому самому списку, і послідовні запити подвоїли б час до
			 * першого показу без жодної вигоди.
			 *
			 * Жодна з них не кидає: це довідки, і їхня відсутність лишає список
			 * таким, яким він був до появи рядків «продовжити» й «кімнати друзів».
			 */
			const [rooms, friends] = await Promise.all([own.listOwnRooms(), friendUids()]);
			if (dead) return;
			this.own = rooms;
			this.friends = friends;
		})();

		return () => {
			dead = true;
		};
	}
}

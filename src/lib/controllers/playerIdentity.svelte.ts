import { randomCrewName } from '$lib/config/crewNames';
import { DEFAULT_AVATAR, isAvatar } from '$lib/config/avatars';
import { NAME_KEY, initialName, rerollIfTaken } from '$lib/config/playerName';
import { crewTranslate, loadCrewNames } from '$lib/i18n/crew';
import { storage } from '$lib/services/storage';
import { preferredCountry, rememberCountry } from '$lib/services/countryPref';
import { profileName, pushName } from '$lib/services/nameSync';
import { playerAvatar } from '$lib/services/playerAvatar.svelte';
import { pushAvatar } from '$lib/services/avatarSync';

/**
 * ХТО Я В КІМНАТІ: підпис, прапор і аватар (останній — лише гетер над спільним
 * `playerAvatar`, див. `avatar`).
 *
 * ## Чому імʼя й прапор разом
 *
 * Це одна відповідь на одне питання — «як мене видно іншим». Обидва
 * памʼятаються між заходами, обидва їдуть у кімнату одним записом складу,
 * обидва підставляються самі й міняються людиною. Розділені на два
 * контролери, вони дали б два майже однакових файли й дві копії роботи зі
 * сховищем.
 *
 * ## Чому окремий контролер, а не поля сторінки
 *
 * Це вже не одне поле. Тут зійшлися чотири речі: збережений вибір людини,
 * підставлене нами імʼя, ДОВАНТАЖУВАНИЙ словник імен (окремий чанк — див.
 * `i18n/crew/index.ts`) і перелік імен, уже зайнятих тими, хто онлайн. Розсипані
 * по сторінці, вони давали три різні місця, кожне з яких могло переписати поле, —
 * і сторінка через це двічі виходила за власну межу розміру файлу.
 *
 * ## Що тут головне
 *
 * Межа «наше/людське». Підставлене нами імʼя ми маємо право перекинути, коли
 * виявиться, що воно вже зайняте; введене людиною — ні. Помилка в цій межі не
 * падає й не видна на тесті: вона виглядає як «поле саме перескочило», і
 * побачить її лише той, хто саме друкував. Тримають її чисті функції в
 * `config/playerName.ts`, а тут — руни, сховище й завантаження.
 *
 * ## Чому джерело випадковості ПЕРЕДАЄТЬСЯ
 *
 * Той самий підпис, що в `crewNames.ts` і `pickOne`: `Math.random()` усередині
 * робить поведінку неперевірною точно, а лише ймовірно.
 */
export class PlayerIdentity {
	/** Що стоїть у полі. Двобічне: форма прив'язується просто до нього. */
	value = $state('');

	/**
	 * Словник імен для поточної мови. Порожній, поки не приїхав чанк.
	 *
	 * До його приїзду підставляти НІЧИМ: перекладач на невідомому ключі віддає
	 * сам ключ, тобто в полі стояло б «pairs.crew.owl».
	 */
	#dict = $state<Record<string, string>>({});

	/** Що з поля ВИГАДАЛИ ми. Порожньо — імʼя прийшло не з кубика. */
	#assigned = '';

	/**
	 * Що ми в поле ПОСТАВИЛИ — байдуже, звідки: кубик, сховище чи профіль.
	 *
	 * Два прапорці, і різниця між ними робоча:
	 *
	 *  • `#assigned` відповідає «чи можна це перекинути, коли імʼя виявилось
	 *    зайнятим» — перекидати можна лише СВОЮ вигадку;
	 *  • `#shown` відповідає «чи людина торкалася поля» — якщо значення й далі те,
	 *    що ми поставили, то ні, і профільне імʼя має право його замінити.
	 *
	 * Без другого прапорця імʼя зі сховища не відрізнити від набраного руками:
	 * `initialName` віддає збережене з порожнім `assigned`, тобто як «вибір
	 * людини». Саме через це профіль не міг перебити випадкове імʼя, яке колись
	 * потрапило у сховище при вході в кімнату.
	 */
	#shown = '';

	/**
	 * Код країни для прапора. Порожньо — «без прапора», і це ВІДПОВІДЬ.
	 *
	 * Не `null`: відсутність прапора тут не «ще не знаємо», а свідомий вибір
	 * зі списку («Без прапора» стоїть у ньому першим пунктом). Стан
	 * «ще не питали» відрізняється інакше — його немає у сховищі.
	 */
	country = $state('');

	readonly #random: () => number;

	constructor(random: () => number) {
		this.#random = random;
	}

	/**
	 * Аватар — рядок `значок:колір`, і ДЖЕРЕЛО В НЬОГО ОДНЕ: `playerAvatar`.
	 *
	 * Доти контролер читав сховище сам, у конструкторі, — тобто третьою копією
	 * поруч із шапкою й профілем, і вибір, зроблений після відкриття сторінки, сюди
	 * не доходив. Тепер вибір є й тут, у формі входу (прохання автора 2026-09-26), і
	 * дві копії розійшлися б на першому ж натиску: плитка в полі одна, а в кімнату
	 * їхала б інша. Тому тут лише ГЕТЕР над спільним станом.
	 *
	 * Порожньо (нічого не вибирали) і типовий дають ту саму плитку: «без аватара» не
	 * буває, порожнє місце читалося б як дефект. Підписи вибору («Кіт», «Синій»)
	 * лежать у лінивому чанку `i18n/account`, і форма входу довантажує його, лише
	 * коли вибір відкривають (`AvatarChooser`).
	 */
	get avatar(): string {
		return playerAvatar.value || DEFAULT_AVATAR;
	}

	/**
	 * Вибрали аватар у формі входу — і для цього пристрою, і для профілю.
	 *
	 * Спільний стан пишеться одразу (шапка й плитка в полі міняються разом), профіль
	 * — у фоні й лише коли він є (`pushAvatar`): вибір не мусить чекати на мережу.
	 */
	chooseAvatar(next: string): void {
		if (!isAvatar(next)) return;
		playerAvatar.set(next);
		void pushAvatar(next);
	}

	/** Перекладач над уже завантаженим словником. */
	get text() {
		return crewTranslate(this.#dict);
	}

	/**
	 * Довантажити словник для мови й підставити перше імʼя. Кличеться з `$effect`
	 * сторінки, бо залежить від `settings.locale`.
	 *
	 * Перше імʼя ставиться ЛИШЕ в порожнє поле: після перемикання мови ефект
	 * перезапускається, і підпис, який людина вже бачить, мінятися не мусить —
	 * інакше вибір злітав би від дотику до перемикача мов.
	 */
	async load(locale: string, taken: readonly string[]): Promise<void> {
		this.#dict = await loadCrewNames(locale);
		/*
		 * ІМʼЯ З ПРОФІЛЮ ТЯГНЕТЬСЯ ПАРАЛЕЛЬНО, а не перед підстановкою.
		 *
		 * Порядок тут вирішує, чи блимне поле порожнім: спершу ставимо те, що є під
		 * рукою (сховище або кубик), і лише потім, коли приїде, замінюємо профільним.
		 * Чекати на мережу до першої підстановки означало б порожнє поле на весь час
		 * запиту — на повільному звʼязку це секунди.
		 *
		 * Виклик безпечний при кожному перезапуску ефекту: профіль читається раз на
		 * сесію (`services/nameSync` кешує), а `adopt` не чіпає того, що людина
		 * встигла набрати.
		 */
		void profileName().then((name) => this.adopt(name));

		if (this.value !== '') return;
		const chosen = initialName(storage.get(NAME_KEY), this.text, this.#random, taken);
		this.value = chosen.name;
		this.#assigned = chosen.assigned;
		this.#shown = chosen.name;
	}

	/**
	 * ПРИЙНЯТИ ІМʼЯ З ПРОФІЛЮ — але не поверх того, що людина набрала.
	 *
	 * Профіль головніший за сховище: він на сервері, один для всіх пристроїв і
	 * заповнений свідомо. Тому він перебиває і кубик, і збережене — усе, що в поле
	 * поставили МИ.
	 *
	 * Чого він не перебиває — набраного в цьому сеансі. Якщо значення розійшлося з
	 * `#shown`, значить людина щось надрукувала, і поле, яке «саме перескочило»
	 * посеред набору, — це найгірший різновид цієї помилки: він видний лише тому,
	 * хто саме друкував.
	 *
	 * Кеш сховища наздоганяє профіль ТУТ: інакше наступне відкриття сторінки знову
	 * почалося б зі старого імені, і профіль перебивав би його щоразу заново.
	 */
	adopt(name: string): void {
		if (name === '' || name === this.value) return;
		if (this.value !== '' && this.value !== this.#shown) return;

		this.value = name;
		this.#shown = name;
		// Не наша вигадка, тож перекидати його як «зайняте» не можна.
		this.#assigned = '';
		storage.set(NAME_KEY, name);
	}

	/**
	 * Прапор: збережений вибір, а якщо його немає — ПІДКАЗКА за IP.
	 *
	 * Порядок тут і є вся суть. Спершу сховище: вибір людини головніший за
	 * будь-яке визначення, і перезаписати його означало б щоразу вертати
	 * прапор, який вона вже змінила. Запит до сторонньої служби йде ЛИШЕ
	 * коли у сховищі немає нічого — тобто один раз, на першому відкритті.
	 *
	 * Порожній рядок у сховищі — це «без прапора», і він теж лічиться
	 * вибором: `null` від `storage.get` означає «не питали», а `''` —
	 * «питали, відповіли: не показувати».
	 *
	 * Чому IP лише підказка, а не факт, розписано в `net/country.ts`.
	 */
	async loadCountry(): Promise<void> {
		// Три правила («вибір головніший за підказку», «служба питається раз»,
		// «відповідь памʼятається») живуть у `services/countryPref`: та сама
		// відповідь потрібна й сторінці акаунта, а дві копії розійшлися б.
		this.country = await preferredCountry();
	}

	/**
	 * Кубик: інше імʼя, і воно теж НАШЕ — отже, його можна буде перекинути, коли
	 * виявиться зайнятим. Виключаються і зайняті, і поточне.
	 */
	reroll(taken: readonly string[]): void {
		this.value = randomCrewName(this.text, this.#random, [...taken, this.value.trim()]);
		this.#assigned = this.value;
		this.#shown = this.value;
	}

	/**
	 * Перелік кімнат приїхав — перекинути СВОЄ імʼя, якщо воно виявилося зайнятим.
	 *
	 * Кличеться з обробника підписки, а не з `$effect`: імʼя підставляється до
	 * приїзду переліку, а ефект, що читає й пише те саме значення, довелося б
	 * стерегти від самозапуску.
	 */
	settle(taken: readonly string[]): void {
		const swap = rerollIfTaken(this.value, this.#assigned, this.text, this.#random, taken);
		if (swap === null) return;
		this.value = swap;
		this.#assigned = swap;
		this.#shown = swap;
	}

	/**
	 * Імʼя для входу в кімнату — і запамʼятати його.
	 *
	 * Порожнє поле означає «хай буде будь-яке»: людина стерла підставлене й не
	 * вписала свого. Вигадувати за неї нікому, тож беремо зі списку.
	 */
	forEntry(taken: readonly string[]): string {
		const who = this.value.trim() || randomCrewName(this.text, this.#random, taken);
		storage.set(NAME_KEY, who);
		/*
		 * І В ПРОФІЛЬ — саме тут, а не при кожній зміні поля.
		 *
		 * Це мить, коли імʼя вперше стає публічним, і мить, коли мережа в коді вже є.
		 * Нічого не робить для того, хто акаунта не має, і не кидає: невдача лишає
		 * профіль позаду на одне імʼя, а не ламає вхід у кімнату.
		 */
		void pushName(who);
		// Прапор памʼятається ТУТ, а не при кожній зміні списку: запис у сховище
		// має сенс тоді, коли вибір уже поїхав у кімнату. Через `rememberCountry`,
		// бо «без прапора» — теж вибір, і записати його мусить те саме місце.
		rememberCountry(this.country);
		return who;
	}

	/**
	 * Аватар для запису в кімнату. Порожньо — поля в базі не буде зовсім.
	 *
	 * Типовий аватар НЕ пишеться: він і так підставляється на показі, а зайве
	 * поле в `members/$uid` пишеться на КОЖЕН вхід у кімнату.
	 */
	forRoom(): string | undefined {
		return playerAvatar.forRoom();
	}
}

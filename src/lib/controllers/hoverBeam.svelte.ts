/**
 * ЧУЖЕ НАВЕДЕННЯ НА КАРТКУ: підписка, надсилання, затримка — в одному місці.
 *
 * ## Що це таке
 *
 * Прохання автора: «наведення на картку — бачать усі в грі». Показує це дошка, а
 * везе — присутність у базі (`net/presence.ts`): наведення стану партії не змінює,
 * тож у журналі ходів йому не місце.
 *
 * ## Чому окремим контролером
 *
 * Сторінка кімнати стоїть на межі розміру (400 рядків), і підсвітка вийшла за неї.
 * Але розріз тут не через межу: на сторінці зійшлися три різні речі — підписка,
 * канал надсилання й затримка проти сплеску. Разом вони читаються як «щось про
 * курсор», а окремо кожна проста. Тут вони одна одиниця з одним обовʼязком, і
 * затримку нарешті можна перевірити тестом, а не оком.
 *
 * ## Затримка — проти ОДНОГО випадку
 *
 * Джерело сигналу — `pointerenter`/`pointerleave`, тобто ПОДІЯ, а не рух. Це
 * поправка автора: «не треба кожний рух курсора записувати, а тільки саму подію
 * наведення — навіщо знати, що гравець водить по картці курсором, і забивати
 * трафік». Записів виходить кілька на хід.
 *
 * Затримка все одно потрібна, і рівно проти курсора, проведеного через усю колоду:
 * двадцять чотири «заходи» підряд. Останнє значення перемагає, тобто в базу їде та
 * картка, на якій курсор спинився.
 */

/** Скільки чекати, перш ніж повідомити про наведення. */
export const HOVER_QUIET_MS = 150;

export class HoverBeam {
	/**
	 * На що дивляться ІНШІ: uid → індекс картки. Свого тут не буває.
	 *
	 * Своє наведення гравець і так бачить курсором, а друга рамка поверх читалася б
	 * як інший, незрозумілий стан. Прибирає себе сам `watchHovers`.
	 */
	seen = $state<Record<string, number>>({});

	/** Куди надсилати. `null` — поза кімнатою, тобто в нікуди. */
	#send: ((card: number | null) => void) | null = null;
	#timer: ReturnType<typeof setTimeout> | null = null;
	readonly #quietMs: number;

	constructor(quietMs = HOVER_QUIET_MS) {
		this.#quietMs = quietMs;
	}

	/**
	 * Стати на звʼязок: слухати чужі наведення й уміти надсилати своє.
	 *
	 * Повертає функцію відписки, яка ще й ГАСИТЬ власну підсвітку: інакше остання
	 * наведена картка лишилася б підсвіченою в суперника доти, доки присутність не
	 * зникне сама.
	 */
	async listen(code: string): Promise<() => void> {
		const live = await import('$lib/net/presence');
		const off = await live.watchHovers(code, (byUid) => (this.seen = byUid));
		this.attach((card) => void live.setHover(code, card));
		return () => {
			this.clear();
			this.attach(null);
			off();
		};
	}

	/**
	 * Приєднати канал надсилання. `null` — відʼєднати.
	 *
	 * Окремо від `listen`, і не заради гнучкості: затримка — єдине, що тут можна
	 * зробити неправильно, і саме її треба перевіряти. Через `listen` це вимагало б
	 * мережі, а без явного шва — каста до приватного поля, тобто перевірки, яка
	 * зеленіє, не діставши до коду.
	 */
	attach(send: ((card: number | null) => void) | null): void {
		this.#send = send;
	}

	/** Курсор зайшов на картку (`index`) або пішов із неї (`null`). */
	point(card: number | null): void {
		if (this.#timer !== null) clearTimeout(this.#timer);
		this.#timer = setTimeout(() => {
			this.#timer = null;
			this.#send?.(card);
		}, this.#quietMs);
	}

	/**
	 * Погасити НЕГАЙНО, не чекаючи затримки.
	 *
	 * Потрібне на зміну черги: своя скінчилася — підсвітка мусить зникнути, не
	 * чекаючи, доки гравець ворухне мишею. Заразом скасовує те, що вже намічено:
	 * інакше згасання перемогла б відкладена картка.
	 */
	clear(): void {
		if (this.#timer !== null) clearTimeout(this.#timer);
		this.#timer = null;
		this.#send?.(null);
	}
}

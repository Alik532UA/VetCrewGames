import type { GoneReason, Member, RoomStatus, RosterEntry } from '$lib/net/roomTypes';
import type { RoomEnvelope } from '$lib/utils/roomEnvelope';

/**
 * СПІЛЬНИЙ СТАН КІМНАТИ ОБОХ МАТЧІВ — один клас, а не дві копії полів.
 *
 * Доти ці поля стояли в `PairsMatch` і `QuizMatch` рядок у рядок, разом із
 * докблоками, і кожне нове поле кімнати мусило не забутися двічі: `avatarSwaps`
 * (2026-09-26) правилося в чотирьох місцях. Шостий аудит назвав це прямо, а межа
 * розміру контролера (обидва стояли на 295–299 рядках із 300) не лишала місця навіть
 * на виправлення. Розклад знімка на ці поля — `envelopeOf` (`utils/roomEnvelope.ts`),
 * тут — лише реактивні комірки для нього, спільні `gone` і `refused`, і зерно.
 *
 * Матчі лишаються окремими класами: роздача, журнал і правила партії в кожної гри
 * свої. Спільне — лише те, що кімната каже про себе.
 */
export abstract class RoomEnvelopeState implements RoomEnvelope {
	/** Стан кімнати: доки не `playing`, партії немає. */
	status = $state<RoomStatus>('lobby');
	/** Склад з УНІКАЛЬНИМИ аватарками (`utils/roomAvatars` через `envelopeOf`). */
	members = $state<Member[]>([]);
	/** Кого замінено через повтор аватарки: uid → показана пара (`RoomEnvelope`). */
	avatarSwaps = $state<Record<string, string>>({});
	/** Заморожений склад партії (`RoomInfo.roster`); `null` — лобі або кімната старша за поле. */
	roster = $state.raw<readonly RosterEntry[] | null>(null);
	/**
	 * Хто господар — з КІМНАТИ, а не з порядку у списку. Спершу сторінка рахувала
	 * господаря як «перший у складі» — і кнопка «Почати» зникала в нього, щойно
	 * заходив хтось із «меншим» `uid`: база віддає склад за алфавітом ключів.
	 */
	hostUid = $state('');
	/**
	 * Зерно кімнати. Змінюється на «зіграти ще», тобто це і є «яка це партія»:
	 * нагорода за партію рахується один раз на зерно, а вікторина виводить із нього
	 * програму — однакову в усіх.
	 */
	seed = $state(0);
	/**
	 * Серверний час початку відліку до автостарту; `null` — відліку немає. Матч його
	 * лише передає: «пора починати» вирішує господар.
	 */
	countdownAt = $state<number | null>(null);
	/**
	 * Режим початку партії: сама чи за підтвердженням. Відсутнє поле = виключено —
	 * безпечніший бік: партія, що почалася сама без прохання, гірша за партію, яку
	 * треба почати кнопкою.
	 */
	autoStart = $state(false);
	/** Кімната публічна (`RoomInfo.listed`). */
	listed = $state(false);
	/**
	 * КОД КІМНАТИ, У ЯКУ ГРА ПЕРЕЇХАЛА («зіграти в іншу гру»); `null` — нікуди.
	 * Кімната й далі знає одну гру: це вказівник на НОВУ, тому він живе в `info`, а не
	 * в журналі, — він не про партію, яка вже скінчилася.
	 */
	nextCode = $state<string | null>(null);
	/** Коли кімнату створено — з неї мітка запису в переліку. */
	createdAt = $state<number | null>(null);
	/**
	 * Кімнати більше немає: господар її закрив або прибрав збирач (`closed`), або
	 * читати її мені вже не дають (`lost`). `null` — кімната є.
	 */
	gone = $state<GoneReason | null>(null);
	/** Скільки ходів база не прийняла (`RoomMatch.refused`). */
	refused = $state(0);
}

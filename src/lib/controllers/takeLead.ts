import type { RoomTransport } from '$lib/net/roomTypes';
import { freeSeq } from '$lib/utils/journalSeq';

/**
 * Скільки номерів спробувати, перш ніж визнати, що ведення не взяти.
 *
 * Три, а не шістнадцять, як у відповіді: відмова тут найчастіше означає не
 * «номер зайнятий», а «господар на місці» або «ведення вже підхопив інший», і
 * повтор цього не змінить — лише додасть марних записів.
 */
const LEAD_TRIES = 3;

/**
 * ПІДХОПИТИ ВЕДЕННЯ ПАРТІЇ, коли господаря немає.
 *
 * ## Навіщо
 *
 * Аудит 2026-09-23: у вікторині раунди оголошує лише господар, тож коли він
 * закривав вкладку, партія стояла в усіх назавжди. Автоматичне просування за часом
 * тут не годиться — вікно очікування свідомо не має стелі (рішення автора,
 * `utils/awayWait.ts`). Тому роль ПЕРЕДАЄТЬСЯ: хтось із присутніх гравців називає
 * господарем себе, і з цієї миті перепрогін рахує його раунди.
 *
 * ## Хто вирішує
 *
 * Не клієнт, а правило бази: воно пускає запис лише гравцеві кімнати, який сам на
 * звʼязку, і лише коли нинішнього господаря в присутності НЕМАЄ. Тут — тільки
 * спроба й номер ходу.
 *
 * Окремим модулем, а не методом контролера: те саме знадобиться «Знайди пару»
 * (реванш і дії лідера теж належать господареві), а контролер вікторини стоїть на
 * межі розміру.
 *
 * @param from той, хто господар ЗАРАЗ, — правило вимагає назвати саме його
 * @param seqs зайняті номери журналу, за зростанням
 * @returns `true` — ведення тепер моє
 */
export async function takeLead(
	transport: RoomTransport,
	me: string,
	from: string,
	seqs: readonly number[]
): Promise<boolean> {
	for (let attempt = 0; attempt < LEAD_TRIES; attempt += 1) {
		const taken = await transport.takeLead({
			seq: freeSeq(seqs, attempt),
			by: me,
			type: 'lead',
			payload: { from }
		});
		if (taken) return true;
	}
	return false;
}

import type { Move } from '$lib/net/roomTypes';

/**
 * Межа очікування чужого ходу — єдине правило спільної партії, яке залежить від
 * часу. Тому воно живе окремо й чистою функцією.
 *
 * **Чому це не в матчі.** Правило дороге не обчисленням, а тим, скільком речам
 * воно мусить одночасно відповідати: не дати забрати чергу зарано, не дати
 * забрати СВОЮ чергу (це був би спосіб пропустити невигідний хід), не дати
 * глядачеві втручатися, не зламатися від підробленого часу й дійти до
 * однакового висновку в усіх учасників. Окремою функцією його видно цілком, і
 * перевіряється воно без кімнати, без транспорту й без гри.
 *
 * **Час приходить аргументом.** Ні тут, ні в матчі немає `Date.now()`: правило,
 * що залежить від справжнього годинника, або чекає реальні секунди в тесті, або
 * зеленіє випадково. Усі позначки часу приходять із журналу, і ставить їх сервер.
 */

/**
 * Скільки чекати на чужий хід, перш ніж чергу можна забрати.
 *
 * Це не «таймер ходу»: доки суперник на звʼязку, ніхто нікого не підганяє —
 * межа просто мовчить. Вона існує рівно для одного випадку: суперник зник, і без
 * неї партія висить назавжди. Півтори хвилини — це «встиг вийти й повернутися»,
 * а не «замислився».
 */
export const TURN_LIMIT_MS = 90_000;

export interface TurnState {
	/** Хто зараз ходить. `undefined` — партія не почалася або скінчилася. */
	actorId: string | undefined;
	/** Гравці партії. Глядачі сюди не входять — вони в черзі не стоять. */
	playerIds: readonly string[];
	/**
	 * Серверна позначка, від якої йде відлік поточної черги: `at` останнього
	 * ходу, що щось змінив, а на початку партії — `startedAt` кімнати. `null`
	 * означає «межі ще немає».
	 */
	turnSince: number | null;
}

/**
 * Чи має право `uid` забрати чергу — без огляду на час.
 *
 * Три умови, і кожна закриває свій спосіб зловживання: свою чергу віддати не
 * можна (пропуск невигідного ходу), глядач не втручається (він у черзі не
 * стоїть), і партія на двох мусить справді бути на двох.
 */
function mayYield(uid: string, state: TurnState): boolean {
	if (state.actorId === undefined || uid === state.actorId) return false;
	if (!state.playerIds.includes(uid)) return false;
	return state.playerIds.length >= 2;
}

/**
 * Коли чергу можна буде забрати — серверним часом. `null` — не можна взагалі.
 */
export function yieldReadyAt(uid: string, state: TurnState): number | null {
	if (state.turnSince === null) return null;
	if (!mayYield(uid, state)) return null;
	return state.turnSince + TURN_LIMIT_MS;
}

/**
 * Чи законний цей `yield` у журналі.
 *
 * Викликається при ЗАСТОСУВАННІ ходу, тобто в кожного учасника окремо — і
 * відповідь мусить збігтися в усіх. Через це рішення спирається лише на журнал:
 * `at` самого ходу проти позначки, від якої йшов відлік. Обидві ставить сервер, і
 * правило бази не дає записати хід із часом поза вікном навколо серверного, тож
 * підробити відповідь неможливо.
 */
export function isYieldLegal(move: Move, state: TurnState): boolean {
	if (!mayYield(move.by, state)) return false;
	if (state.turnSince === null || move.at === undefined) return false;
	return move.at - state.turnSince >= TURN_LIMIT_MS;
}

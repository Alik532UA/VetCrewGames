import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { HoverBeam } from './hoverBeam.svelte';

/**
 * ПІДСВІТКА ЧУЖОГО НАВЕДЕННЯ: перевіряється затримка, а не вигляд.
 *
 * Прохання автора: «наведення на картку — бачать усі в грі», з поправкою — «не
 * треба кожний рух курсора записувати, а тільки саму подію наведення». Джерело
 * сигналу справді подія (`pointerenter`/`pointerleave`), тобто кілька записів на
 * хід. Але один випадок усе одно дає сплеск: курсор, проведений через усю колоду,
 * — двадцять чотири «заходи» підряд.
 *
 * ## Що саме тут стережеться
 *
 *  * **сплеск стискається в один запис.** Без цього кожен рух через дошку — двадцять
 *    чотири звернення до бази за ту саму інформацію;
 *  * **перемагає ОСТАННЄ значення.** Стиснути сплеск можна й неправильно: узявши
 *    перше. Тоді в базу поїде картка, з якої курсор почав, а не та, на якій
 *    спинився, — і суперник дивився б не туда;
 *  * **згасання негайне.** Своя черга скінчилася — підсвітка мусить зникнути, не
 *    чекаючи, доки гравець ворухне мишею;
 *  * **згасання скасовує намічене.** Інакше відкладена картка спрацювала б ПІСЛЯ
 *    згасання, і чужа підсвітка лишилася б висіти;
 *  * **поза кімнатою не пише нікуди.** Виклик після виходу не має права ні кинути,
 *    ні розбудити мережу.
 *
 * Час тут підмінений (`vi.useFakeTimers`): перевірка, яка чекає справжні сто
 * пʼятдесят мілісекунд, або довга, або зеленіє випадково.
 *
 * Зворотні експерименти (AI-AGENT-PITFALLS-v8 § 1.1) — чотири, кожен червонив рівно
 * свій пункт: `clearTimeout` прибрано з `point` (сплеск летить весь); у `point`
 * значення заморожено першим викликом; `clear` перестав гасити негайно; `clear`
 * перестав скасовувати намічене. Усі чотири зроблені.
 */

const QUIET = 150;

/** Канал, який лише записує те, що йому дали. */
function sink() {
	const sent: Array<number | null> = [];
	const beam = new HoverBeam(QUIET);
	// Той самий шов, яким користується `listen()`: підписка тягла б мережевий
	// модуль, а перевіряється тут затримка, а не мережа.
	beam.attach((card) => void sent.push(card));
	return { beam, sent };
}

beforeEach(() => vi.useFakeTimers());
afterEach(() => vi.useRealTimers());

describe('підсвітка наведення', () => {
	it('перевірка жива: одне наведення доходить', () => {
		const { beam, sent } = sink();
		beam.point(3);
		expect(sent, 'до затримки нічого не летить').toEqual([]);
		vi.advanceTimersByTime(QUIET);
		expect(sent).toEqual([3]);
	});

	it('сплеск стискається в ОДИН запис, і це останній', () => {
		const { beam, sent } = sink();
		// Курсор через усю колоду: заходи йдуть швидше за затримку.
		for (const card of [0, 1, 2, 3, 4, 5]) {
			beam.point(card);
			vi.advanceTimersByTime(QUIET - 20);
		}
		vi.advanceTimersByTime(QUIET);

		expect(sent, 'сплеск полетів увесь').toHaveLength(1);
		expect(sent[0], 'узято першу картку замість тієї, на якій спинилися').toBe(5);
	});

	it('пауза між наведеннями дає два записи', () => {
		// Без цього пункту попередній нічого не вартий: канал, який пише раз і
		// замовкає, теж «стискає сплеск».
		const { beam, sent } = sink();
		beam.point(1);
		vi.advanceTimersByTime(QUIET);
		beam.point(2);
		vi.advanceTimersByTime(QUIET);
		expect(sent).toEqual([1, 2]);
	});

	it('згасання НЕГАЙНЕ й скасовує намічене', () => {
		const { beam, sent } = sink();
		beam.point(4);
		beam.clear();

		expect(sent, 'згасання чекає на затримку').toEqual([null]);
		vi.advanceTimersByTime(QUIET * 2);
		expect(sent, 'намічена картка спрацювала ПІСЛЯ згасання').toEqual([null]);
	});

	it('поза кімнатою не пише нікуди й не кидає', () => {
		const beam = new HoverBeam(QUIET);
		expect(() => {
			beam.point(2);
			vi.advanceTimersByTime(QUIET);
			beam.clear();
		}).not.toThrow();
	});

	it('чужі наведення починаються з порожнечі', () => {
		// Порожнеча — «ще не приїхало», і дошка мусить малювати нуль підсвіток, а не
		// вгадувати.
		expect(new HoverBeam().seen).toEqual({});
	});
});

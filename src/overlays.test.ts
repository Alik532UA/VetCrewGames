// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/**
 * ПОЯВА ПОВЕРХ УСЬОГО — СПРАВА ПЛАТФОРМИ, А НЕ ЧОТИРЬОХ САМОРОБОК
 * (UI-ELEMENTS-v8 § 1A.2, `UIE-POPOVER`).
 *
 * ## Що це за клас дефектів
 *
 * Випадайка, написана вручну, тягне за собою чотири окремі механізми: власний
 * `z-index`, власний обробник `Escape`, власний клік по тлу і власне повернення
 * фокуса. Кожен із них окремо працює; ламаються вони СТИКАМИ.
 *
 * У цьому проєкті обидва стики вже спрацювали:
 *
 *  * **Гонка чисел.** Панель вибору країни показувалася НЕ поверх усього —
 *    автор написав це дослівно: «перекривається деякими елементами». Ліки тоді
 *    були черговим числом (9500 між смугою прокрутки 8000 і меню шапки 9501),
 *    тобто виграшем у гонці, а не її скасуванням. Сходи 7000/7500/8000/9000/
 *    9500/9501/9999/10000 у цьому репозиторії — це і є та гонка в записі.
 *  * **Повторний натиск.** Клік по тлу закривав панель, а `click`, що доходив до
 *    кнопки, відкривав її знову. Дефект був у `HeaderMenu` і описаний у
 *    коментарях `CountryPicker`.
 *
 * `popover="auto"` знімає обидва: верхній шар вище за будь-яке число, а
 * `popovertarget` робить кнопку відомою браузерові, тож другого відкриття він не
 * робить.
 *
 * ## Чому облік, а не заборона
 *
 * Той самий взірець, що в `container-queries.test.ts` і `eslint-baseline.test.ts`:
 * перевести всі накладки одним рухом означало б змінити поведінку шести
 * компонентів без нагоди подивитися на кожен очима. Тому борг названий
 * поіменно, список лише СКОРОЧУЄТЬСЯ, і нова саморобна накладка валить прогін.
 *
 * ## Що саме перевіряється
 *
 * 1. Перевірка жива: у проєкті є хоч один справжній `popover`.
 * 2. Канонічний інваріант: файл із `popover` не має ВЛАСНОГО закривача на
 *    `Escape`. Два закривачі закривають два шари одним натиском.
 * 3. Файл із `popover` не призначає `z-index`: верхній шар його не питає, а
 *    залишене число повертає гонку через рік, коли причину вже забуто.
 * 4. Борг: перелік саморобних накладок лише коротшає.
 *
 * Зворотний експеримент (AI-AGENT-PITFALLS-v8 § 1.1) описаний у кожному пункті
 * окремо — і зроблений.
 */

function svelteFiles(dir: string, out: string[] = []): string[] {
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) svelteFiles(full, out);
		else if (entry.endsWith('.svelte')) out.push(full.split(String.fromCharCode(92)).join('/'));
	}
	return out;
}

/**
 * Коментарі знімаються ПЕРЕД пошуком, і це не дрібниця.
 *
 * `InfoPopover` пояснює у власному докблоці, що `Escape` тепер вбудований, —
 * тобто містить це слово рівно тому, що саморобки більше не має. Пошук по
 * сирому тексту звинуватив би єдиний правильний файл у проєкті. Той самий
 * дефект уже був у переліку медіазапитів, де докблок із прибраним запитом
 * роздував число.
 */
function code(text: string): string {
	return text
		.replace(/\/\*[\s\S]*?\*\//g, ' ')
		.replace(/<!--[\s\S]*?-->/g, ' ')
		.replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
}

/** Власний закривач: рядок 'Escape' у КОДІ, а не в поясненні. */
const OWN_ESCAPE = /['"]Escape['"]/;

const files = svelteFiles('src').map((path) => ({
	path,
	raw: readFileSync(path, 'utf8')
}));

/**
 * Саморобні накладки, які ще не переведені на платформу.
 *
 * Список іменний, а не числовий: тут важить не «скільки рядків», а «які саме
 * накладки лишилися» — кожну доведеться дивитися очима після переведення.
 *
 * Погашений рядок прибирається — його стереже четверта перевірка. Перший такий
 * уже є: `ui/InfoPopover` переведено на `popover="auto"` з CSS-якорями, і саме
 * тому його тут немає.
 *
 * `HeaderControls` у списку окремо від `HeaderMenu`: перший тримає, яке з трьох
 * меню шапки відкрите, другий — клавіатуру всередині відкритого. Переводити їх
 * доведеться разом, але це дві різні правки.
 *
 * `CountryPicker` тут НЕМАЄ, хоч накладку малює саме він: клавіатуру, разом із
 * `Escape`, тримає його `CountryMenu`, і переводитиметься накладка звідти. Рядок
 * тут спершу стояв — і четверта перевірка одразу сказала, що він бреше.
 */
const OWN_OVERLAYS = [
	'src/lib/components/HeaderControls.svelte',
	'src/lib/components/HeaderMenu.svelte',
	'src/lib/components/ScrollbarContextMenu.svelte',
	'src/lib/components/reserve/ReserveHud.svelte',
	'src/lib/components/ui/CountryMenu.svelte'
];

describe('накладки: платформа замість саморобки', () => {
	const withPopover = files.filter((f) => /\spopover=/.test(code(f.raw)));

	it('перевірка жива: у проєкті є справжній popover', () => {
		/*
		 * Без цього пункту весь файл проходив би на порожньому місці: у проєкті без
		 * жодного `popover` пункти 2 і 3 істинні бездоганно й безглуздо. Це та сама
		 * пастка, через яку гейт гарячих клавіш спершу шукав ІМʼЯ захисту й знаходив
		 * його в рядку `import`.
		 */
		const info = withPopover.find((f) => f.path.endsWith('ui/InfoPopover.svelte'));
		expect(info, 'довідка на платформі').toBeDefined();
		expect(code(info!.raw), 'саме auto, а не manual').toMatch(/popover="auto"/);
		// `popovertarget` — те, що знімає пастку повторного натиску по кнопці.
		expect(
			withPopover.some((f) => /popovertarget=/.test(code(f.raw))),
			'кнопка мусить бути викликачем, а не власним onclick'
		).toBe(true);
	});

	it('файл із popover не тримає ВЛАСНОГО закривача на Escape', () => {
		/*
		 * Реверсний експеримент: повернуто `if (event.key === 'Escape')` в
		 * `InfoPopover` — пункт червоніє.
		 *
		 * Канон називає причину прямо: два закривачі дають закриття двох шарів одним
		 * натиском. Той, хто відкрив довідку поверх меню, втратив би обидва.
		 */
		const guilty = withPopover.filter((f) => OWN_ESCAPE.test(code(f.raw))).map((f) => f.path);
		expect(guilty, 'Escape уже вбудований у popover').toEqual([]);
	});

	it('файл із popover не призначає z-index', () => {
		/*
		 * Реверсний експеримент: додано `z-index: 9500` у `.info__panel` — пункт
		 * червоніє.
		 *
		 * Число тут не «зайве», а шкідливе: воно виглядає як робоче, тож наступна
		 * панель підбиратиме своє відносно нього — і гонка, яку верхній шар щойно
		 * скасував, відродиться вже без причини.
		 */
		const guilty = withPopover.filter((f) => /z-index\s*:/.test(code(f.raw))).map((f) => f.path);
		expect(guilty, 'верхній шар вище за будь-яке число').toEqual([]);
	});

	it('борг саморобних накладок лише коротшає', () => {
		/*
		 * Реверсні експерименти: додано `onkeydown` з `'Escape'` у сьомий компонент —
		 * червоніє «нових саморобок немає»; прибрано `ScrollbarContextMenu` зі
		 * списку, лишивши обробник у файлі, — червоніє той самий пункт; прибрано
		 * обробник із `ReserveHud`, не чіпаючи списку, — червоніє «список
		 * актуальний».
		 */
		const actual = files
			.filter((f) => OWN_ESCAPE.test(code(f.raw)))
			.map((f) => f.path)
			.sort();

		const added = actual.filter((path) => !OWN_OVERLAYS.includes(path));
		expect(added, 'нова накладка пишеться на popover, а не вручну').toEqual([]);

		const stale = OWN_OVERLAYS.filter((path) => !actual.includes(path));
		expect(stale, 'переведене прибирається зі списку, інакше він бреше').toEqual([]);
	});
});
